        static void EnsureBaseline()
        {
            if (_base != null) return;
            _staged = new Staged[Cells];
            _base = new Outcome[Cells][];
            _baseForm = new string[Cells];
            for (var i = 0; i < _minds.Length; i++)
            for (var wi = 0; wi < Wants.Length; wi++)
            for (var ci = 0; ci < 2; ci++)
            {
                var cell = Cell(i, wi, ci);
                _staged[cell] = Stage(_rules, _minds[i], Moment(i, ci), Wants[wi]);
                _base[cell] = Decide(_staged[cell]);
                var f = Form(_rules, _minds[i], Moment(i, ci), Wants[wi]);
                _baseForm[cell] = f.Intent;
                if (f.Intent != _base[cell][Sum].Winner) _formWinnerMismatch++;
                else if (f.Intent != null && !f.Weight.Equals(_base[cell][Sum].Score)) _formWeightMismatch++;
            }
        }

