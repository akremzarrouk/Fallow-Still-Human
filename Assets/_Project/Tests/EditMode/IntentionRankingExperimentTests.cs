        {
            yield return Make(c, c.Id + "_base", scalers: new List<Scaler>());
            for (var k = 0; k < c.ScaledBy.Count; k++)
                yield return Make(c, c.Id + "_term" + k, baseWeight: 0.0, scalers: new[] { c.ScaledBy[k] });
        }

