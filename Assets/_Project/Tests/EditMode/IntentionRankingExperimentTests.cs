        [Test, Order(8), Timeout(3600000)]
        public void H_RepresentationInvariance()
        {
            EnsureTransforms();
            var sb = new StringBuilder();
            sb.AppendLine("## H. Representation invariance");
            sb.AppendLine();
            sb.AppendLine("Each transformation rewrites the rule file without changing anything about any person. The count is of cells, over all " + Cells
                          + ", whose intention changed; for a per-rule transformation it is summed over the ten rules. In brackets, how many of those changes were in a cell where the top two were within 1e-9 of each other before or after: a tie in the real numbers, decided by the alphabet or by rounding.");
            sb.AppendLine();
            sb.AppendLine("| | Transformation | Should it preserve the conclusion? | " + string.Join(" | ", Family.Select(a => a.Name)) + " |");
            sb.AppendLine("|---|---|---|" + string.Concat(Enumerable.Repeat("---|", Family.Length)));

            string Cellf(int changed, int atTie) => changed == 0 ? "0" : "**" + changed + "**" + (atTie > 0 ? " (" + atTie + ")" : "");
            var rows = new List<Tuple<string, string, string, int[], int[]>>();
            for (var t = 0; t < WholeTransforms.Length; t++)
                rows.Add(Tuple.Create(WholeTransforms[t].Key, WholeTransforms[t].Label, WholeTransforms[t].Should,
                    _whole[t].Select(x => x.Changed).ToArray(), _whole[t].Select(x => x.AtTie).ToArray()));
            for (var t = 0; t < PerRuleTransforms.Length; t++)
                rows.Add(Tuple.Create(PerRuleTransforms[t].Key, PerRuleTransforms[t].Label, PerRuleTransforms[t].Should,
                    Enumerable.Range(0, Family.Length).Select(a => _perRule[t].Sum(r => r[a].Changed)).ToArray(),
                    Enumerable.Range(0, Family.Length).Select(a => _perRule[t].Sum(r => r[a].AtTie)).ToArray()));
            foreach (var row in rows.OrderBy(r => int.Parse(r.Item1.Substring(1))))
                sb.AppendLine("| " + row.Item1 + " | " + row.Item2 + " | " + row.Item3 + " | "
                              + string.Join(" | ", Enumerable.Range(0, Family.Length).Select(a => Cellf(row.Item4[a], row.Item5[a]))) + " |");
            sb.AppendLine();

            sb.AppendLine("### Preserved or violated, counting only changes that are not ties");
            sb.AppendLine();
            sb.AppendLine("| | " + string.Join(" | ", Family.Select(a => a.Name)) + " |");
            sb.AppendLine("|---|" + string.Concat(Enumerable.Repeat("---|", Family.Length)));
            var clear = new Dictionary<string, int[]>();
            foreach (var row in rows.OrderBy(r => int.Parse(r.Item1.Substring(1))))
            {
                clear[row.Item1] = Enumerable.Range(0, Family.Length).Select(a => row.Item4[a] - row.Item5[a]).ToArray();
                sb.AppendLine("| " + row.Item1 + " | " + string.Join(" | ", clear[row.Item1].Select(c => c == 0 ? "P" : "**V**")) + " |");
            }
            sb.AppendLine();

            sb.AppendLine("### Monotonicity: where a duplicate sends the answer");
            sb.AppendLine();
            sb.AppendLine("Adding a copy of a reason for X should never make X lose. Changes from T4, by where they went:");
            sb.AppendLine();
            sb.AppendLine("| Aggregator | Toward the duplicated rule's intention | **Away from it** | Between two others | In a cell where the rule is not compatible |");
            sb.AppendLine("|---|---|---|---|---|");
            for (var a = 0; a < Family.Length; a++)
            {
                var toward = _perRule[T4].Sum(r => r[a].Toward);
                var away = _perRule[T4].Sum(r => r[a].Away);
                var changed = _perRule[T4].Sum(r => r[a].Changed);
                var outside = PerRuleTransforms.Indices().Sum(t => _perRule[t].Sum(r => r[a].Outside));
                sb.AppendLine("| " + Family[a].Name + " | " + toward + " | " + (away == 0 ? "0" : "**" + away + "**") + " | " + (changed - toward - away) + " | " + outside + " |");
            }
            sb.AppendLine();

            sb.AppendLine("### Splitting by term, rule by rule, under the sum");
            sb.AppendLine();
            sb.AppendLine("| Rule | Changed | At a tie |");
            sb.AppendLine("|---|---|---|");
            for (var ri = 0; ri < _rules.Count; ri++)
                sb.AppendLine("| `" + _rules[ri].Id + "` | " + _perRule[T8][ri][Sum].Changed + " | " + _perRule[T8][ri][Sum].AtTie + " |");
            sb.AppendLine();

            var impossible = Enumerable.Range(0, Family.Length).Where(a => clear["T4"][a] == 0 && clear["T6"][a] == 0 && clear["T9"][a] > 0).ToList();
            sb.AppendLine("### The impossibility, checked");
            sb.AppendLine();
            sb.AppendLine("No aggregator of anonymous contributions can be invariant to duplication (T4) and to proportional splitting (T6) and still respond to weight (T9). Aggregators here that show all three: **"
                          + (impossible.Count == 0 ? "none" : string.Join(", ", impossible.Select(a => Family[a].Name))) + "**.");
            sb.AppendLine();
            sb.AppendLine("| Aggregator | T4 duplicate | T6 split | T9 scale x 2 | Gives up |");
            sb.AppendLine("|---|---|---|---|---|");
            for (var a = 0; a < Family.Length; a++)
            {
                var gives = new List<string>();
                if (clear["T4"][a] > 0) gives.Add("duplication");
                if (clear["T6"][a] > 0) gives.Add("splitting");
                if (clear["T9"][a] == 0) gives.Add("**weight**");
                sb.AppendLine("| " + Family[a].Name + " | " + (clear["T4"][a] == 0 ? "P" : "V") + " | " + (clear["T6"][a] == 0 ? "P" : "V") + " | "
                              + (clear["T9"][a] == 0 ? "no response" : "responds") + " | " + string.Join(", ", gives) + " |");
            }
            Record("H", sb.ToString());

            Assert.IsEmpty(impossible, "the theorem: no aggregator of anonymous contributions keeps duplication and splitting and responds to weight");
            Assert.AreEqual(0, PerRuleTransforms.Indices().Sum(t => _perRule[t].Sum(r => r.Sum(x => x.Outside))),
                "locality: rewriting a rule can only change cells where it is compatible");
        }

