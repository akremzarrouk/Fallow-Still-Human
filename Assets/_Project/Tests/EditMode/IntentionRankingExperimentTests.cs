        static int[] _dupFlipsPerCell;         // under the sum: how many single-rule duplications reverse this cell
        static int[] _dupFlipsPerWant;
        static int _dupFlipsEverySeventh;

        static readonly string[] Representations = { "W", "2 x W/2", "4 x W/4", "2W", "W + W" };

        static void EnsureTransforms()
        {
            if (_perRule != null) return;
            EnsureBaseline();

            _perRule = PerRuleTransforms.Select(_ => _rules.Select(__ => Family.Select(___ => new Tally()).ToArray()).ToArray()).ToArray();
            _formChanged = PerRuleTransforms.Select(_ => new int[_rules.Count]).ToArray();
            _pairwise = _rules.Select(_ => Family.Select(__ => new int[10]).ToArray()).ToArray();
            _dupFlipsPerCell = new int[Cells];
            _dupFlipsPerWant = new int[Wants.Length];
            var formChecked = new[] { T4, T6, T7, T9 };

            for (var ri = 0; ri < _rules.Count; ri++)
            {
                var rule = _rules[ri];
                var sets = PerRuleTransforms.Select(t => t.Build(rule)).ToArray();
                for (var i = 0; i < _minds.Length; i++)
                for (var wi = 0; wi < Wants.Length; wi++)
                for (var ci = 0; ci < 2; ci++)
                {
                    var cell = Cell(i, wi, ci);
                    var p = Moment(i, ci);
                    var exposed = CompatibleIn(rule, wi, ci);
                    var outs = new Outcome[sets.Length][];
                    for (var t = 0; t < sets.Length; t++)
                    {
                        outs[t] = Decide(Stage(sets[t], _minds[i], p, Wants[wi]));
                        for (var a = 0; a < Family.Length; a++)
                        {
                            var was = _base[cell][a];
                            var now = outs[t][a];
                            if (was.Winner == now.Winner) continue;
                            var tally = _perRule[t][ri][a];
                            tally.Changed++;
                            if (was.Margin < Tie || now.Margin < Tie) tally.AtTie++;
                            if (now.Winner == rule.Intent) tally.Toward++;
                            else if (was.Winner == rule.Intent) tally.Away++;
                            if (!exposed) tally.Outside++;
                            if (t == T4 && a == Sum)
                            {
                                _dupFlipsPerCell[cell]++;
                                _dupFlipsPerWant[wi]++;
                            }
                        }
                    }

                    foreach (var t in formChecked)
                    {
                        var f = Form(sets[t], _minds[i], p, Wants[wi]);
                        if (f.Intent != outs[t][Sum].Winner) _formMismatch++;
                        if (f.Intent != _baseForm[cell])
                        {
                            _formChanged[t][ri]++;
                            if (t == T4 && i % 7 == 0) _dupFlipsEverySeventh++;
                        }
                    }

                    // C: the five representations of one rule's weight, compared pairwise.
                    var rep = new[] { _base[cell], outs[T6], outs[T7], outs[T9], outs[T4] };
                    for (var a = 0; a < Family.Length; a++)
                    {
                        var k = 0;
                        for (var x = 0; x < rep.Length; x++)
                        for (var y = x + 1; y < rep.Length; y++, k++)
                            if (rep[x][a].Winner != rep[y][a].Winner) _pairwise[ri][a][k]++;
                    }
                }
            }

            _whole = WholeTransforms.Select(_ => Family.Select(__ => new Tally()).ToArray()).ToArray();
            for (var t = 0; t < WholeTransforms.Length; t++)
            {
                var set = WholeTransforms[t].Build();
                for (var i = 0; i < _minds.Length; i++)
                for (var wi = 0; wi < Wants.Length; wi++)
                for (var ci = 0; ci < 2; ci++)
                {
                    var cell = Cell(i, wi, ci);
                    var outs = Decide(Stage(set, _minds[i], Moment(i, ci), Wants[wi]), WholeTransforms[t].Unrename);
                    for (var a = 0; a < Family.Length; a++)
                    {
                        var was = _base[cell][a];
                        if (was.Winner == outs[a].Winner) continue;
                        _whole[t][a].Changed++;
                        if (was.Margin < Tie || outs[a].Margin < Tie) _whole[t][a].AtTie++;
                    }
                }
            }
        }

