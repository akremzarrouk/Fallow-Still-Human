    /// <summary>
    /// What must an intention-selection mechanism satisfy to be a causal
    /// mechanism rather than a numerical ranking, and which of those properties
    /// does the current one have?
    ///
    /// The ten candidate rules stay frozen and hashed, and `IntentionSelector`
    /// is not touched. The selector is taken apart into the five stages it
    /// already has, so that they can be measured separately:
    ///
    ///   availability   a rule lists the want               (the want)
    ///   compatibility  its `when` matches the moment        (the circumstance)
    ///   support        base + factor x level, by ScalerEval (the person)
    ///   preference     an intention's score from its rules  (the aggregation)
    ///   selection      the highest score, ties by name      (the alphabet)
    ///
    /// Every alternative rule set is built in memory, and every alternative
    /// aggregator is a pure function in this file and nowhere else. They are
    /// instruments for asking which invariants a way of ranking keeps, not
    /// candidates for production, and none of them has a parameter to tune.
    ///
    /// No production change of any kind. Writes
    /// `Docs/experiments/intention-ranking/measurements.md`.
    /// </summary>
    public class IntentionRankingExperimentTests
