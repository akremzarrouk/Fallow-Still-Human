        sealed class Move
        {
            public int Attribute;
            public string Description;
            public Mind Mind;
        }

        static readonly string[] Attributes =
        {
            "trait anxious", "trait cautious", "trait dominant", "trait empathetic", "trait honest", "trait impulsive", "trait proud",
            "value ranks 1 <-> 2", "value ranks 2 <-> 3", "value ranks 3 <-> 4", "value ranks 4 <-> 5", "value ranks 5 <-> 6",
            "belief role_claim", "belief answerable_for"
        };

        /// <summary>
        /// The 21 single-attribute moves of one sweep profile: each trait to each
        /// of its other two levels, each adjacent pair of value ranks swapped,
        /// each belief toggled between absent and its sweep confidence.
        /// </summary>
        static List<Move> Moves(int i)
        {
            var m = _minds[i];
            var moves = new List<Move>();
            for (var t = 0; t < _sweepTraits.Count; t++)
                foreach (var level in _levels)
                {
                    var was = m.Profile.Trait(_sweepTraits[t]);
                    if (level.Equals(was)) continue;
                    var traits = TraitsOf(m);
                    traits[_sweepTraits[t]] = level;
                    moves.Add(new Move
                    {
                        Attribute = Array.IndexOf(Attributes, "trait " + _sweepTraits[t]),
                        Description = _sweepTraits[t] + " " + F(was) + " -> " + F(level),
                        Mind = Person(m.Id, traits, m.Profile.Values, Seeds(m))
                    });
                }
            for (var k = 0; k < m.Profile.Values.Count - 1; k++)
            {
                var values = m.Profile.Values.ToList();
                var swap = values[k];
                values[k] = values[k + 1];
                values[k + 1] = swap;
                moves.Add(new Move
                {
                    Attribute = Array.IndexOf(Attributes, "value ranks " + (k + 1) + " <-> " + (k + 2)),
                    Description = values[k + 1] + " and " + values[k] + " swap ranks " + (k + 1) + " and " + (k + 2),
                    Mind = Person(m.Id, TraitsOf(m), values, Seeds(m))
                });
            }
            foreach (var (predicate, second, confidence) in new[] { ("role_claim", "leads_family", 0.80), ("answerable_for", "missing_can", 0.90) })
            {
                var seeds = Seeds(m);
                var held = seeds.Any(b => b.Predicate == predicate);
                seeds = held
                    ? seeds.Where(b => b.Predicate != predicate).ToList()
                    : seeds.Concat(new[] { new BeliefSeed(predicate, new[] { m.Id, second }, confidence) }).ToList();
                moves.Add(new Move
                {
                    Attribute = Array.IndexOf(Attributes, "belief " + predicate),
                    Description = predicate + (held ? " dropped" : " taken up at " + F(confidence)),
                    Mind = Person(m.Id, TraitsOf(m), m.Profile.Values, seeds)
                });
            }
            return moves;
        }

        static int[][][] _pairs;            // [group][attribute][aggregator]  all pairs (same for every aggregator)
        static int[][][] _moved;            // [group][attribute][aggregator]  winner changed
        static int[][] _fixedPairs;         // [group][attribute]              candidate set (supported) identical
        static int[][][] _fixedMoved;       // [group][attribute][aggregator]  ... and the winner changed
        static int _compatibleChanged;
        static int _supportedChanged;
        static int _supportedChangedByDiscard;
        static readonly List<string> _examples = new List<string>();

        static bool SameSet(IEnumerable<string> a, IEnumerable<string> b)
            => new HashSet<string>(a, StringComparer.Ordinal).SetEquals(b);

        static void EnsurePerturbations()
        {
            if (_pairs != null) return;
            EnsureBaseline();
            var groups = Wants.Length * 2;
            _pairs = Enumerable.Range(0, groups).Select(_ => Attributes.Select(__ => new int[Family.Length]).ToArray()).ToArray();
            _moved = Enumerable.Range(0, groups).Select(_ => Attributes.Select(__ => new int[Family.Length]).ToArray()).ToArray();
            _fixedPairs = Enumerable.Range(0, groups).Select(_ => new int[Attributes.Length]).ToArray();
            _fixedMoved = Enumerable.Range(0, groups).Select(_ => Attributes.Select(__ => new int[Family.Length]).ToArray()).ToArray();
            var exampleFor = new HashSet<int>();

            for (var i = 0; i < _minds.Length; i++)
                foreach (var move in Moves(i))
                    for (var wi = 0; wi < Wants.Length; wi++)
                    for (var ci = 0; ci < 2; ci++)
                    {
                        var g = Group(wi, ci);
                        var cell = Cell(i, wi, ci);
                        var before = _staged[cell];
                        var after = Stage(_rules, move.Mind, Moment(i, ci), Wants[wi]);
                        var outs = Decide(after);

                        if (!SameSet(before.Compatible, after.Compatible)) _compatibleChanged++;
                        var fixedSet = SameSet(before.Supported, after.Supported);
                        if (!fixedSet)
                        {
                            _supportedChanged++;
                            var differ = new HashSet<string>(before.Supported, StringComparer.Ordinal);
                            differ.SymmetricExceptWith(after.Supported);
                            var discarded = before.Contributions.Concat(after.Contributions)
                                .Where(c => c.Weight <= 0.0).Select(c => c.Rule.Intent);
                            if (differ.IsSubsetOf(discarded)) _supportedChangedByDiscard++;
                        }
                        else _fixedPairs[g][move.Attribute]++;

                        for (var a = 0; a < Family.Length; a++)
                        {
                            _pairs[g][move.Attribute][a]++;
                            if (outs[a].Winner == _base[cell][a].Winner) continue;
                            _moved[g][move.Attribute][a]++;
                            if (fixedSet) _fixedMoved[g][move.Attribute][a]++;
                        }

                        if (fixedSet && before.Compatible.Count >= 2 && outs[Sum].Winner != _base[cell][Sum].Winner && exampleFor.Add(g))
                            _examples.Add("| " + GroupName(g) + " | p" + i + " | " + move.Description + " | "
                                          + _base[cell][Sum].Line + " | " + outs[Sum].Line + " |");
                    }
        }

        // ============================================================ structure: what can win at all

        /// <summary>
        /// A rule's contribution as a linear function of what it reads. Every
        /// level lies in 0..1, so its range over all possible people is the
        /// constant plus the positive coefficients, or plus the negative ones.
        /// </summary>
        sealed class Linear
        {
            public double Const;
            public readonly Dictionary<string, double> Coef = new Dictionary<string, double>(StringComparer.Ordinal);

            public void Add(Linear o, double sign)
            {
                Const += sign * o.Const;
                foreach (var kv in o.Coef)
                {
                    Coef.TryGetValue(kv.Key, out var c);
                    Coef[kv.Key] = c + sign * kv.Value;
                }
            }

            public double Highest => Const + Coef.Values.Sum(v => Math.Max(0.0, v));
            public double Lowest => Const + Coef.Values.Sum(v => Math.Min(0.0, v));
        }

        static string VarKey(Scaler s)
            => s.Kind == ScalerKind.Belief ? "belief " + s.Predicate : s.Kind + " " + s.Name;

        static Linear LinearOf(Candidate c)
        {
            var l = new Linear { Const = c.Base };
            foreach (var s in c.ScaledBy)
            {
                l.Coef.TryGetValue(VarKey(s), out var v);
                l.Coef[VarKey(s)] = v + s.Factor;
            }
            return l;
        }

        /// <summary>
        /// An upper bound, over every person in the unit box, on how far X can
        /// outscore Y under the sum. A rule of X that can fall to zero may be
        /// discarded, so both cases are bounded. Y's discards only raise Y.
        /// Relaxing value ranks to independent weights only widens the box, so a
        /// negative bound is a proof that X never beats Y.
        /// </summary>
        static double BestMargin(IReadOnlyList<Candidate> x, IReadOnlyList<Candidate> y)
        {
            var sure = x.Where(r => LinearOf(r).Lowest > 0.0).ToList();
            var fragile = x.Where(r => LinearOf(r).Lowest <= 0.0).ToList();
            var best = double.NegativeInfinity;
            for (var mask = 0; mask < 1 << fragile.Count; mask++)
            {
                var kept = sure.Concat(fragile.Where((r, k) => (mask & (1 << k)) != 0)).ToList();
                if (kept.Count == 0) continue;
                var d = new Linear();
                foreach (var r in kept) d.Add(LinearOf(r), +1);
                foreach (var r in y) d.Add(LinearOf(r), -1);
                best = Math.Max(best, d.Highest);
            }
            return best;
        }

        sealed class Standing
        {
            public int Group;
            public string Intent;
            public bool Witnessed;
            public string DominatedBy;
            public double Margin;
        }

        static List<Candidate> CompatibleRules(int wi, int ci, string intent = null)
            => _rules.Where(r => CompatibleIn(r, wi, ci) && (intent == null || r.Intent == intent)).ToList();

        static List<Standing> Standings()
        {
            EnsureBaseline();
            var list = new List<Standing>();
            for (var wi = 0; wi < Wants.Length; wi++)
            for (var ci = 0; ci < 2; ci++)
            {
                var intents = CompatibleRules(wi, ci).Select(r => r.Intent).Distinct().ToList();
                if (intents.Count < 2) continue;
                var winners = new HashSet<string>(Enumerable.Range(0, _minds.Length)
                    .Select(i => _base[Cell(i, wi, ci)][Sum].Winner), StringComparer.Ordinal);
                foreach (var x in intents)
                {
                    var st = new Standing { Group = Group(wi, ci), Intent = x, Witnessed = winners.Contains(x), Margin = double.PositiveInfinity };
                    foreach (var y in intents.Where(y => y != x))
                    {
                        var m = BestMargin(CompatibleRules(wi, ci, x), CompatibleRules(wi, ci, y));
                        if (m < -Tie && m < st.Margin) { st.Margin = m; st.DominatedBy = y; }
                    }
                    list.Add(st);
                }
            }
            return list;
        }

