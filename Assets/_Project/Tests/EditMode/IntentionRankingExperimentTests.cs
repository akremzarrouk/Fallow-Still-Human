        /// <summary>
        /// One rule per (want, intention, circumstance): every set of rules that
        /// are compatible together is merged, base added to base and scalers
        /// concatenated. Equivalent to the frozen set in the two circumstances
        /// tested, and in no others.
        /// </summary>
        static List<Candidate> Merged()
        {
            var list = new List<Candidate>();
            for (var wi = 0; wi < Wants.Length; wi++)
            for (var ci = 0; ci < 2; ci++)
            {
                var p = Moment(0, ci);
                var gate = ci == 0 ? new SituationCondition { OthersPresentMin = 1 } : new SituationCondition { Alone = true };
                var compatible = _rules.Where(r => r.Motives.Contains(Wants[wi], StringComparer.Ordinal) && r.When.Matches(p)).ToList();
                foreach (var intent in compatible.Select(r => r.Intent).Distinct().ToList())
                {
                    var parts = compatible.Where(r => r.Intent == intent).ToList();
                    var b = 0.0;
                    foreach (var r in parts) b += r.Base;
                    list.Add(Make(parts[0], Wants[wi] + "_" + ci + "_" + intent, motives: new[] { Wants[wi] }, when: gate,
                        baseWeight: b, scalers: parts.SelectMany(r => r.ScaledBy).ToList()));
                }
            }
            return list;
        }

