        sealed class Contribution
        {
            public Candidate Rule;
            public double Weight;
        }

        /// <summary>What each stage let through, for one want in one moment of one person.</summary>
        sealed class Staged
        {
            public readonly List<string> Available = new List<string>();
            public readonly List<string> Compatible = new List<string>();
            public readonly List<Contribution> Contributions = new List<Contribution>();

            public IEnumerable<string> Supported
                => Contributions.Where(c => c.Weight > 0.0).Select(c => c.Rule.Intent).Distinct();
        }

        /// <summary>
        /// Stages 1 to 3, done exactly as `IntentionSelector.Form` does them and
        /// in the same order, so that the sum over what comes out is bit for bit
        /// the selector's own. That is checked on every cell, not assumed.
        /// </summary>
        static Staged Stage(IReadOnlyList<Candidate> rules, Mind mind, Percept p, string want)
        {
            var s = new Staged();
            var motive = Want(want);
            var ctx = new DecisionContext(p, mind.Id, motive.TargetId, _content.Morning.Day,
                _content.Rules.Deciding.RecallHalfLife);
            foreach (var c in rules)
            {
                if (!c.Motives.Contains(want, StringComparer.Ordinal)) continue;
                if (!s.Available.Contains(c.Intent)) s.Available.Add(c.Intent);
                if (!c.When.Matches(p)) continue;
                if (!s.Compatible.Contains(c.Intent)) s.Compatible.Add(c.Intent);
                var terms = ScalerEval.Evaluate(c.ScaledBy, mind, ctx);
                s.Contributions.Add(new Contribution { Rule = c, Weight = c.Base + terms.Sum(t => t.Amount) });
            }
            return s;
        }

        static IntentionSelector.Formed Form(IReadOnlyList<Candidate> rules, Mind mind, Percept p, string want)
            => IntentionSelector.Form(rules, mind, p, Want(want), _content.Morning.Day, _content.Rules.Deciding.RecallHalfLife);

        /// <summary>Stages 4 and 5 under one aggregator.</summary>
        sealed class Outcome
        {
            public string Winner;
            public double Score;
            public string RunnerUp;
            public double RunnerUpScore;
            public int Supported;

            public double Margin => RunnerUp == null ? double.PositiveInfinity : Score - RunnerUpScore;
            public string Line => Winner == null ? "none"
                : Winner + " " + F(Score) + (RunnerUp == null ? "" : " over " + RunnerUp + " " + F(RunnerUpScore));
        }

        sealed class Aggregator
        {
            public string Name;
            public string Definition;
            public Func<IReadOnlyList<Contribution>, double> Score;
        }

        /// <summary>
        /// The family, fixed in the predictions before anything ran. Each scores
        /// one intention from its positive contributions in rule order. Ties
        /// break by name for all six, as they do now, so that only the
        /// aggregation varies.
        /// </summary>
        static readonly Aggregator[] Family =
        {
            new Aggregator
            {
                Name = "sum", Definition = "the sum of its positive contributions; the current mechanism",
                Score = cs => { var t = 0.0; foreach (var c in cs) t += c.Weight; return t; }
            },
            new Aggregator
            {
                Name = "max", Definition = "its largest contribution",
                Score = cs => { var m = double.NegativeInfinity; foreach (var c in cs) if (c.Weight > m) m = c.Weight; return m; }
            },
            new Aggregator
            {
                Name = "mean", Definition = "the mean of its positive contributions",
                Score = cs => { var t = 0.0; foreach (var c in cs) t += c.Weight; return t / cs.Count; }
            },
            new Aggregator
            {
                Name = "normalized max", Definition = "the largest contribution / that rule's own attainable maximum",
                Score = cs => { var m = double.NegativeInfinity; foreach (var c in cs) { var v = c.Weight / Ceiling(c.Rule); if (v > m) m = v; } return m; }
            },
            new Aggregator
            {
                Name = "noisy-OR", Definition = "1 - product(1 - normalized contribution)",
                Score = cs => { var miss = 1.0; foreach (var c in cs) miss *= 1.0 - c.Weight / Ceiling(c.Rule); return 1.0 - miss; }
            },
            new Aggregator
            {
                Name = "deduplicated sum", Definition = "the sum, counting rules identical in all but their id once",
                Score = cs =>
                {
                    var seen = new HashSet<string>(StringComparer.Ordinal);
                    var t = 0.0;
                    foreach (var c in cs) if (seen.Add(ContentKey(c.Rule))) t += c.Weight;
                    return t;
                }
            },
        };

        const int Sum = 0;
        const int Max = 1;

        static bool Beats(double s1, string n1, double s2, string n2)
            => s1 > s2 || (s1 == s2 && string.CompareOrdinal(n1, n2) < 0);

        /// <summary>
        /// Rank the supported intentions under every aggregator. A contribution at
        /// or below zero is discarded before aggregation, as the selector does.
        /// </summary>
        static Outcome[] Decide(Staged s, Func<string, string> unrename = null)
        {
            var order = new List<string>();
            var by = new Dictionary<string, List<Contribution>>(StringComparer.Ordinal);
            foreach (var c in s.Contributions)
            {
                if (c.Weight <= 0.0) continue;
                if (!by.TryGetValue(c.Rule.Intent, out var list))
                {
                    by[c.Rule.Intent] = list = new List<Contribution>();
                    order.Add(c.Rule.Intent);
                }
                list.Add(c);
            }

            var outcomes = new Outcome[Family.Length];
            for (var a = 0; a < Family.Length; a++)
            {
                var o = new Outcome { Supported = order.Count };
                foreach (var intent in order)
                {
                    var score = Family[a].Score(by[intent]);
                    if (o.Winner == null || Beats(score, intent, o.Score, o.Winner))
                    {
                        o.RunnerUp = o.Winner;
                        o.RunnerUpScore = o.Score;
                        o.Winner = intent;
                        o.Score = score;
                    }
                    else if (o.RunnerUp == null || Beats(score, intent, o.RunnerUpScore, o.RunnerUp))
                    {
                        o.RunnerUp = intent;
                        o.RunnerUpScore = score;
                    }
                }
                if (unrename != null)
                {
                    o.Winner = o.Winner == null ? null : unrename(o.Winner);
                    o.RunnerUp = o.RunnerUp == null ? null : unrename(o.RunnerUp);
                }
                outcomes[a] = o;
            }
            return outcomes;
        }

        /// <summary>The same sum without the discard: a non-positive contribution counts as what it is.</summary>
        static string DecideWithoutDiscard(Staged s)
        {
            var totals = new Dictionary<string, double>(StringComparer.Ordinal);
            var order = new List<string>();
            foreach (var c in s.Contributions)
            {
                if (!totals.ContainsKey(c.Rule.Intent)) { totals[c.Rule.Intent] = 0.0; order.Add(c.Rule.Intent); }
                totals[c.Rule.Intent] += c.Weight;
            }
            string best = null;
            foreach (var i in order)
                if (best == null || Beats(totals[i], i, totals[best], best)) best = i;
            return best;
        }

        static readonly Dictionary<Candidate, double> _ceilings = new Dictionary<Candidate, double>();
        static readonly Dictionary<Candidate, string> _keys = new Dictionary<Candidate, string>();

        /// <summary>
        /// The most a rule could ever weigh for anybody. Every level it reads
        /// (trait, value weight, belief confidence, feeling) lies in 0..1.
        /// </summary>
        static double Ceiling(Candidate c)
        {
            if (_ceilings.TryGetValue(c, out var v)) return v;
            v = c.Base;
            foreach (var s in c.ScaledBy) v += Math.Max(0.0, s.Factor);
            _ceilings[c] = v;
            return v;
        }

        static string R(double v) => v.ToString("R", CultureInfo.InvariantCulture);

        /// <summary>Everything about a rule except its id.</summary>
        static string ContentKey(Candidate c)
        {
            if (_keys.TryGetValue(c, out var k)) return k;
            var w = c.When;
            var sb = new StringBuilder();
            sb.Append(c.Intent).Append('|').Append(string.Join(",", c.Motives)).Append('|')
              .Append(w.Alone).Append(',').Append(w.InOwnRoom).Append(',').Append(w.InSomebodyElsesRoom).Append(',')
              .Append(w.RoomHoldsFood).Append(',').Append(w.SearchedThisRoomMyself).Append(',').Append(w.OthersPresentMin)
              .Append('|').Append(R(c.Base));
            foreach (var s in c.ScaledBy)
                sb.Append('|').Append(s.Kind).Append(':').Append(s.Name).Append(':').Append(s.Predicate).Append(':')
                  .Append(string.Join(",", s.Args ?? new List<string>())).Append(':').Append(s.Entry).Append(':')
                  .Append(s.About).Append(':').Append(s.Topic).Append(':').Append(s.By).Append(':').Append(s.Target).Append(':')
                  .Append(string.Join(",", s.Until ?? new List<string>())).Append(':').Append(R(s.Factor));
            _keys[c] = k = sb.ToString();
            return k;
        }

