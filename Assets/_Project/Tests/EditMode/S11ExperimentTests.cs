        [Test]
        public void WhetherItReachesBehaviourAboveTheNoise()
        {
            // A behaviour difference means nothing without knowing how different
            // two sets of mornings are when nothing at all has changed. Each
            // comparison is between twenty-seed pools from disjoint seeds.
            var sb = new StringBuilder();
            sb.AppendLine("| Condition | Who | Night vs no night | No night vs no night | Night vs night | Above the noise |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var anyAbove = false;

            foreach (var (variant, who) in Culprits)
            {
                Dictionary<string, double> Pool(bool treatment, ulong from)
                {
                    var counts = new Dictionary<string, double>(StringComparer.Ordinal);
                    var total = 0;
                    for (var seed = from; seed < from + 20; seed++)
                    {
                        var run = Scenario001.PrepareWith(_content, variant, treatment ? Night(variant) : new List<WorldEvent>(), seed);
                        run.Morning.Run(_content.Morning.Minutes);
                        foreach (var a in run.Result.By(who))
                        {
                            counts.TryGetValue(a.Action.KindName, out var n);
                            counts[a.Action.KindName] = n + 1;
                            total++;
                        }
                    }
                    return counts.ToDictionary(c => c.Key, c => c.Value / Math.Max(1, total), StringComparer.Ordinal);
                }

                var t1 = Pool(true, 1); var t2 = Pool(true, 21);
                var c1 = Pool(false, 1); var c2 = Pool(false, 21);

                var effect = (BatchRunner.HowDifferent(t1, c2) + BatchRunner.HowDifferent(t2, c1)) / 2;
                var noiseC = BatchRunner.HowDifferent(c1, c2);
                var noiseT = BatchRunner.HowDifferent(t1, t2);
                var above = effect > Math.Max(noiseC, noiseT) * 1.5;
                anyAbove |= above;

                sb.AppendLine("| " + variant + " | " + who + " | " + effect.ToString("0.000") + " | " + noiseC.ToString("0.000") +
                              " | " + noiseT.ToString("0.000") + " | " + (above ? "yes" : "no") + " |");
            }

            sb.AppendLine();
            sb.AppendLine("Above the noise means the night-versus-no-night difference is more than one and a half times the larger of the two same-condition differences.");
            Record("E. Behaviour against the noise floor", sb.ToString());
            TestContext.WriteLine("any condition above the noise: " + anyAbove);
        }

        [Test]
        public void WhetherTheBehaviourEffectRepeatsOnSeedsNeverUsedBefore()
        {
            // Written after the test above was widened from ten-seed pools to
            // twenty, which it was because the ten-seed result was null. Widening
            // a sample after seeing a null is how a false positive gets made, so
            // the positive result is checked here on seeds 41 to 80, which no test
            // had used when this was written. The gate is unchanged, and was
            // stated before these seeds were run: Mara must clear it.
            var sb = new StringBuilder();
            sb.AppendLine("| Condition | Who | Night vs no night | No night vs no night | Night vs night | Above the noise |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var maraAbove = false;

            foreach (var (variant, who) in new[] { ("mara_ate_it", "mara"), ("elena_fed_mara", "elena") })
            {
                Dictionary<string, double> Pool(bool treatment, ulong from)
                {
                    var counts = new Dictionary<string, double>(StringComparer.Ordinal);
                    var total = 0;
                    for (var seed = from; seed < from + 20; seed++)
                    {
                        var run = Scenario001.PrepareWith(_content, variant, treatment ? Night(variant) : new List<WorldEvent>(), seed);
                        run.Morning.Run(_content.Morning.Minutes);
                        foreach (var a in run.Result.By(who))
                        {
                            counts.TryGetValue(a.Action.KindName, out var n);
                            counts[a.Action.KindName] = n + 1;
                            total++;
                        }
                    }
                    return counts.ToDictionary(c => c.Key, c => c.Value / Math.Max(1, total), StringComparer.Ordinal);
                }

                var t1 = Pool(true, 41); var t2 = Pool(true, 61);
                var c1 = Pool(false, 41); var c2 = Pool(false, 61);

                var effect = (BatchRunner.HowDifferent(t1, c2) + BatchRunner.HowDifferent(t2, c1)) / 2;
                var noiseC = BatchRunner.HowDifferent(c1, c2);
                var noiseT = BatchRunner.HowDifferent(t1, t2);
                var above = effect > Math.Max(noiseC, noiseT) * 1.5;
                if (who == "mara") maraAbove = above;

                sb.AppendLine("| " + variant + " | " + who + " | " + effect.ToString("0.000") + " | " + noiseC.ToString("0.000") +
                              " | " + noiseT.ToString("0.000") + " | " + (above ? "yes" : "no") + " |");
            }

            Record("E. Behaviour against the noise floor, fresh seeds 41 to 80", sb.ToString());
            Assert.IsTrue(maraAbove, "the behaviour effect did not repeat on seeds that were never used to find it");
        }

