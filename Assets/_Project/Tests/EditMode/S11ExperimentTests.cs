        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# S1.1 experiment results");
            sb.AppendLine();
            sb.AppendLine("Generated by `S11ExperimentTests`. Design conditions only; the held-out");
            sb.AppendLine("condition is reported separately. Every comparison is paired on the seed.");
            sb.AppendLine();
            foreach (var pair in _findings) sb.AppendLine("## " + pair.Key + Environment.NewLine + Environment.NewLine + pair.Value);

            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "slices", "S1.1");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "experiment-results.md"), sb.ToString());
