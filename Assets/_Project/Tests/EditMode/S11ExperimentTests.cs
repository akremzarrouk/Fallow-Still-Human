        static Scenario001Content WithTrait(string who, string trait, double level)
        {
            var cast = new Dictionary<string, Profile>(StringComparer.Ordinal);
            foreach (var pair in _content.Cast) cast[pair.Key] = pair.Value;

            var p = _content.Cast[who];
            var traits = p.Traits.ToDictionary(t => t.Key, t => t.Value, StringComparer.Ordinal);
            traits[trait] = level;
            cast[who] = new Profile(p.Id, p.DisplayName, p.Age, p.FamilyRole, traits, p.Values,
                p.Perceptiveness, p.AttentionWeights, p.InitialBeliefs, p.Expressiveness, p.HungerRate);

            return new Scenario001Content(_content.Vocabulary, cast, _content.Backstory, _content.Morning, _content.Rules);
        }

        [Test]
        public void D_ChangingOneTraitChangesHowTheSameNightLands()
        {
            const string variant = "mara_ate_it";
            const string who = "mara";

            (double start, double morning, string meaning, double fear) Measure(Scenario001Content content)
            {
                var starts = new List<double>();
                var mornings = new List<double>();
                for (ulong seed = 1; seed <= Seeds; seed++)
                {
                    var p = Pair(variant, seed, content: content).People[who];
                    starts.Add(p.ShiftAtStart("avoid_exposure"));
                    mornings.Add(p.ShiftOverMorning("avoid_exposure"));
                }

                var probe = Scenario001.Prepare(content, variant, 1);
                var search = new WorldEvent("probe-d", _content.Morning.Day, 5000, EventKind.Action, "leo", null,
                    null, "search_belongings", "missing_can", "neutral", "direct", "neutral", null, "Leo searches.",
                    new[] { who }, new string[0], new List<LedgerEffect>(), null, 10);
                var o = probe.Simulation.Apply(search).ByCharacter[who];
                var fear = o.Emotions.Where(e => e.Type == "fear").Select(e => e.Intensity).DefaultIfEmpty(0).Max();

                return (starts.Average(), mornings.Average(), o.Meaning, fear);
            }

            var asShe = Measure(_content);
            var calm = Measure(WithTrait(who, "anxious", 0.20));
            var shameless = Measure(WithTrait(who, "honest", 0.10));

            Record("D. Same night, one trait changed", "`" + variant + "`, " + who + ", " + Seeds + " seeds." +
                   Environment.NewLine + Environment.NewLine +
                   "| Mara | `avoid_exposure` at start | over the morning | Reads a search as | Fear it stirs |" + Environment.NewLine +
                   "|---|---|---|---|---|" + Environment.NewLine +
                   "| as written (anxious 0.80, honest 0.55) | " + asShe.start.ToString("+0.000;-0.000") + " | " + asShe.morning.ToString("+0.000;-0.000") + " | " + asShe.meaning + " | " + asShe.fear.ToString("0.00") + " |" + Environment.NewLine +
                   "| anxious 0.20 | " + calm.start.ToString("+0.000;-0.000") + " | " + calm.morning.ToString("+0.000;-0.000") + " | " + calm.meaning + " | " + calm.fear.ToString("0.00") + " |" + Environment.NewLine +
                   "| honest 0.10 | " + shameless.start.ToString("+0.000;-0.000") + " | " + shameless.morning.ToString("+0.000;-0.000") + " | " + shameless.meaning + " | " + shameless.fear.ToString("0.00") + " |" + Environment.NewLine +
                   Environment.NewLine +
                   "The reading of the search comes from the belief and is the same in all three. What it does to her comes from her.");

            Assert.AreEqual(asShe.meaning, calm.meaning, "temperament should not change what she believes the search is about");
            Assert.Less(calm.fear, asShe.fear, "a calmer Mara is not less frightened by the same threat");
            Assert.Less(shameless.start, asShe.start, "a less honest Mara is not less troubled at the start by what she did");
        }

