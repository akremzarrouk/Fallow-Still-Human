    /// <summary>
    /// The S1.1 experiment: can something that happens to a person change what
    /// that person wants, through the pipeline, and not merely because they are a
    /// different person?
    ///
    /// Every comparison here is a counterfactual: two mornings on the same seed,
    /// same world, same people, differing in one cause. Only the design conditions
    /// are used. The held-out condition lives in its own file.
    ///
    /// Each test records what it measured into a report whether it passes or not.
    /// </summary>
    public class S11ExperimentTests
    {
        const double Changed = 0.02;
        const int Seeds = 10;

        static Scenario001Content _content;
        static readonly SortedDictionary<string, string> _findings = new SortedDictionary<string, string>(StringComparer.Ordinal);

        static readonly (string Variant, string Who)[] Culprits =
        {
            ("daniel_ate_it", "daniel"),
            ("mara_ate_it", "mara"),
            ("daniel_hid_it", "daniel"),
            ("elena_fed_mara", "elena")
        };

        [OneTimeSetUp]
