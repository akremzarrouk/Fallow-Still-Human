        [Test]
        public void NothingAddedInS11NamesAPersonACondition()
        {
            var problems = new List<string>();
            problems.AddRange(RuleSetValidator.ValidateNamesNobody(_content.Rules, _content.Cast.Keys));
            problems.AddRange(DecisionRuleValidator.ValidateNamesNobody(_content.Rules, _content.Cast.Keys));

            var forbidden = _content.Morning.Variants.Concat(_content.Morning.HeldOutVariants)
                .SelectMany(v => new[] { v.Id }.Concat(v.NightEvents.Select(e => e.Id)))
                .Concat(_content.Cast.Keys)
                .Distinct()
                .ToList();

            foreach (var file in Directory.GetFiles(TestPaths.CoreSources, "*.cs", SearchOption.AllDirectories))
            {
                var text = File.ReadAllText(file);
                foreach (var word in forbidden)
                    if (System.Text.RegularExpressions.Regex.IsMatch(text, "\"" + System.Text.RegularExpressions.Regex.Escape(word) + "\""))
                        problems.Add(Path.GetFileName(file) + " contains the string \"" + word + "\"");
            }

            foreach (var file in new[] { "rules.json", "decisions.json" })
            {
                var text = File.ReadAllText(Path.Combine(TestPaths.Rules, file));
                foreach (var v in _content.Morning.Variants.Concat(_content.Morning.HeldOutVariants))
                    if (text.Contains("\"" + v.Id + "\"")) problems.Add(file + " names the condition " + v.Id);
            }

            Assert.IsEmpty(problems, string.Join("\n", problems));
        }
