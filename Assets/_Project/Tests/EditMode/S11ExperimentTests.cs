        static IReadOnlyList<string> Motives => _content.Vocabulary.Set("motives").ToList();

        static IReadOnlyList<WorldEvent> Night(string variant) => _content.Morning.Variant(variant).NightEvents;
        static IReadOnlyList<string> Causes(string variant) => Night(variant).Select(e => e.Id).ToList();

        static Counterfactual.Pair Pair(string variant, ulong seed, int? minutes = null, Action<Simulation> intervene = null,
            IReadOnlyList<WorldEvent> treatment = null, Scenario001Content content = null)
            => Counterfactual.Run(content ?? _content, variant, new List<WorldEvent>(), treatment ?? Night(variant),
                Causes(variant), seed, minutes, intervene);

        static void Record(string key, string text)
        {
            _findings[key] = text;
            TestContext.WriteLine(text);
        }

        /// <summary>
        /// The scale to read a circumstance effect against: how far apart two
        /// different people's wants are at the same moment in the same world.
        /// </summary>
        static double PersonalityGapAtStart(Counterfactual.Pair pair)
        {
            var ids = pair.People.Keys.ToList();
            var gaps = new List<double>();
            for (var i = 0; i < ids.Count; i++)
            for (var j = i + 1; j < ids.Count; j++)
                gaps.Add(Motives.Average(m =>
                    Math.Abs(pair.People[ids[i]].ControlAtStart.Of(m) - pair.People[ids[j]].ControlAtStart.Of(m))));
            return gaps.Average();
        }

        // ---- A: a changed night changes the person it happened to ----

        [Test]
        public void A_AChangedNightChangesWhatThePersonItHappenedToWants()
        {
            var sb = new StringBuilder();
            sb.AppendLine("| Condition | Who | Start sensitivity | Morning sensitivity (mean of " + Seeds + " seeds) | Lasting share | `avoid_exposure` at start | `avoid_exposure` over morning | Attribution at start | Attribution over morning |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|");

            var best = 0.0;
            string bestCase = null;
            var gap = 0.0;

            foreach (var (variant, who) in Culprits)
            {
                var starts = new List<double>();
                var mornings = new List<double>();
                var avoidStart = 0.0;
                var avoidMorning = new List<double>();
                double? attrStart = null;
                var attrMorning = new List<double>();

                for (ulong seed = 1; seed <= Seeds; seed++)
                {
                    var pair = Pair(variant, seed);
                    var p = pair.People[who];
                    if (seed == 1) gap = PersonalityGapAtStart(pair);

                    starts.Add(p.SensitivityAtStart(Motives));
                    mornings.Add(p.SensitivityOverMorning(Motives));
                    avoidStart = p.ShiftAtStart("avoid_exposure");
                    avoidMorning.Add(p.ShiftOverMorning("avoid_exposure"));
                    attrStart = p.AttributionAtStart(Motives, Changed);
                    var am = p.AttributionOverMorning(Motives, Changed);
                    if (am.HasValue) attrMorning.Add(am.Value);
                }

                var start = starts.Average();
                var morning = mornings.Average();
                sb.AppendLine("| " + variant + " | " + who + " | " + start.ToString("0.000") + " | " + morning.ToString("0.000") +
                              " | " + (start < 0.01 ? "n/a (nothing at the start)" : (morning / start).ToString("P0")) +
                              " | " + avoidStart.ToString("+0.000;-0.000;0.000") + " | " + avoidMorning.Average().ToString("+0.000;-0.000;0.000") +
                              " | " + (attrStart.HasValue ? attrStart.Value.ToString("P0") : "nothing changed") +
                              " | " + (attrMorning.Count == 0 ? "nothing changed" : attrMorning.Average().ToString("P0")) + " |");

                if (morning > best) { best = morning; bestCase = variant + "/" + who; }
            }

            sb.AppendLine();
            sb.AppendLine("For scale: two different people in the same world differ at the start by a mean of **" +
                          gap.ToString("0.000") + "** per want.");
            sb.AppendLine("Strongest lasting effect: **" + bestCase + "**, " + best.ToString("0.000") +
                          " per want, " + (best / gap).ToString("P0") + " of the personality gap.");
            Record("A. A changed night, same person", sb.ToString());

            Assert.Greater(best, 0.0, "no condition changed its culprit's wants across the morning at all");
        }

        [Test]
        public void A_TheChangeAtTheStartCanAlwaysBeWalkedBackToTheNight()
        {
            var problems = new List<string>();
            foreach (var (variant, who) in Culprits)
            {
                var p = Pair(variant, 1, minutes: 0).People[who];
                foreach (var m in Motives.Where(m => Math.Abs(p.ShiftAtStart(m)) > Changed))
                    if (!(p.TreatmentAtStart.RestsOnCause.TryGetValue(m, out var yes) && yes))
                        problems.Add(variant + "/" + who + ": " + m + " moved " +
                                     p.ShiftAtStart(m).ToString("+0.000;-0.000") + " with no trace to the night");
            }

            Record("A. Attribution at the start", problems.Count == 0
                ? "Every want that moved by more than " + Changed + " at the start, in every design condition, has a reason that leads back to the night."
                : string.Join(Environment.NewLine, problems));

            Assert.IsEmpty(problems, string.Join("\n", problems));
        }

        [Test]
        public void A_ItSurvivesTheSeed()
        {
            // The main claim, on the condition with the largest lasting effect in
            // the sweep above, across twice as many seeds.
            const string variant = "mara_ate_it";
            const string who = "mara";
            const int seeds = 20;

            var shifts = new List<double>();
            for (ulong seed = 1; seed <= seeds; seed++)
                shifts.Add(Pair(variant, seed).People[who].ShiftOverMorning("avoid_exposure"));

            var positive = shifts.Count(s => s > 0);
            var mean = shifts.Average();
            var sd = Math.Sqrt(shifts.Sum(s => (s - mean) * (s - mean)) / (shifts.Count - 1));
            var se = sd / Math.Sqrt(shifts.Count);

            Record("A. Across seeds", "`" + variant + "`, " + who + ", `avoid_exposure` averaged over the morning, treatment minus control on the same seed, " + seeds + " seeds." +
                   Environment.NewLine + Environment.NewLine +
                   "- positive on " + positive + " of " + seeds + " seeds" + Environment.NewLine +
                   "- mean " + mean.ToString("+0.000;-0.000") + ", standard deviation " + sd.ToString("0.000") +
                   ", standard error " + se.ToString("0.000") + ", mean over standard error " + (mean / se).ToString("0.0") + Environment.NewLine +
                   "- per seed: " + string.Join(" ", shifts.Select(s => s.ToString("+0.00;-0.00"))));

            Assert.GreaterOrEqual(positive, 16, "the effect does not hold on most seeds");
            Assert.Greater(mean / se, 3.0, "the effect is not clearly distinguishable from zero across seeds");
        }

        // ---- B: remove the cause, and the effect goes with it ----

        [Test]
        public void B_RemovingTheNightRemovesEverythingItDid()
        {
            var problems = new List<string>();

            foreach (var (variant, _) in Culprits)
            for (ulong seed = 1; seed <= 3; seed++)
            {
                var removed = Pair(variant, seed, treatment: Counterfactual.Without(Night(variant), Causes(variant).ToArray()));

                foreach (var p in removed.People.Values)
                {
                    if (p.SensitivityOverMorning(Motives) != 0.0 || p.SensitivityAtStart(Motives) != 0.0)
                        problems.Add(variant + "/" + seed + "/" + p.CharacterId + " still differs from the control");
                    if (!p.ControlActions.SequenceEqual(p.TreatmentActions))
                        problems.Add(variant + "/" + seed + "/" + p.CharacterId + " still acts differently");
                }
            }

            Record("B. Removing the night", problems.Count == 0
                ? "With the originating event removed, every person in every design condition on seeds 1 to 3 has exactly the wants and exactly the actions of the control, every minute. There is no second path by which the night reaches anybody."
                : string.Join(Environment.NewLine, problems));

            Assert.IsEmpty(problems, string.Join("\n", problems));
        }

        [Test]
        public void B_TakingAwayTheBeliefTakesAwayMostOfWhatLasts()
        {
            // Mediation. Keep the night and everything it made the person feel;
            // take away only the belief it formed, right after the night. If the
            // belief is what carries the night into the morning, most of what
            // lasts should go, and what remains at the start should mostly stay.
            const string variant = "mara_ate_it";
            const string who = "mara";

            var withBelief = new List<double>();
            var withoutBelief = new List<double>();
            var startWith = 0.0;
            var startWithout = 0.0;

            for (ulong seed = 1; seed <= Seeds; seed++)
            {
                var full = Pair(variant, seed).People[who];
                var cut = Pair(variant, seed, intervene: sim =>
                {
                    var mind = sim.Minds[who];
                    var args = new[] { who, "missing_can" };
                    var id = sim.Trace.Add(Fallow.Core.Tracing.TraceKind.BeliefChange, who, null,
                        "EXPERIMENT: belief removed to test what it was carrying");
                    mind.Beliefs.Nudge("answerable_for", args, -1.0, id);
                }).People[who];

                withBelief.Add(full.ShiftOverMorning("avoid_exposure"));
                withoutBelief.Add(cut.ShiftOverMorning("avoid_exposure"));
                if (seed == 1)
                {
                    startWith = full.ShiftAtStart("avoid_exposure");
                    startWithout = cut.ShiftAtStart("avoid_exposure");
                }
            }

            var lasting = withBelief.Average();
            var lastingCut = withoutBelief.Average();
            var carried = lasting == 0 ? 0 : 1.0 - lastingCut / lasting;

            Record("B. Taking away the belief", "`" + variant + "`, " + who + ", `avoid_exposure` shift against the no-night control, " + Seeds + " seeds." +
                   Environment.NewLine + Environment.NewLine +
                   "| | At the start | Averaged over the morning |" + Environment.NewLine +
                   "|---|---|---|" + Environment.NewLine +
                   "| Night, with the belief it formed | " + startWith.ToString("+0.000;-0.000") + " | " + lasting.ToString("+0.000;-0.000") + " |" + Environment.NewLine +
                   "| Night, belief removed | " + startWithout.ToString("+0.000;-0.000") + " | " + lastingCut.ToString("+0.000;-0.000") + " |" + Environment.NewLine +
                   Environment.NewLine +
                   "Share of the lasting effect carried by the belief: **" + carried.ToString("P0") + "**.");

            Assert.Greater(carried, 0.5, "the belief is not what carries the night into the morning");
        }

        [Test]
        public void B_TakingSomebodyOutOfTheRoomTakesAwayOnlyTheirPart()
        {
            const string variant = "elena_fed_mara";

            var full = Pair(variant, 1, minutes: 0);
            var noWitness = Pair(variant, 1, minutes: 0, treatment: Counterfactual.WithoutWitness(Night(variant), "mara"));

            var maraBelief = noWitness.Treatment.Minds["mara"].Beliefs.Confidence("answerable_for", "elena", "missing_can");
            var maraSame = Motives.All(m => Math.Abs(noWitness.People["mara"].ShiftAtStart(m)) < 1e-12)
                           && noWitness.People["mara"].ControlFeelings[Scenario001.Stages.AfterOpening] ==
                              noWitness.People["mara"].TreatmentFeelings[Scenario001.Stages.AfterOpening];
            var elenaSame = Motives.All(m =>
                Math.Abs(noWitness.People["elena"].TreatmentAtStart.Of(m) - full.People["elena"].TreatmentAtStart.Of(m)) < 1e-12);

            Record("B. Taking one witness out of the room", "`" + variant + "` with Mara removed from the witnesses of the night: " +
                   "her belief about Elena " + maraBelief.ToString("0.00") + "; her feelings and wants identical to the control: " + maraSame +
                   "; Elena's wants identical to the full night: " + elenaSame + ".");

            Assert.AreEqual(0.0, maraBelief);
            Assert.IsTrue(maraSame, "Mara is still changed by a night she no longer saw");
            Assert.IsTrue(elenaSame, "taking Mara out of the room changed Elena, who was still there");
        }

