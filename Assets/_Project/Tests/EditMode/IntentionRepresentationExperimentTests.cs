        static void Compare(Tally t, Outcome was, Outcome now, bool exposed, string intent, int wasRecognised, int compatible)
        {
            if (now.Candidates != compatible) t.CandidateMismatch++;
            var detected = now.Recognised > wasRecognised;
            if (detected) t.Detected++;
            if (was.Token == now.Token) return;
            t.Changed++;
            if (!detected) t.ChangedUndetected++;
            if (was.Tie || now.Tie || was.Margin < Tie || now.Margin < Tie) t.AtTie++;
            if (intent != null && now.Winner == intent) t.Toward++;
            else if (intent != null && was.Winner == intent) t.Away++;
            if (!exposed) t.Outside++;
        }

