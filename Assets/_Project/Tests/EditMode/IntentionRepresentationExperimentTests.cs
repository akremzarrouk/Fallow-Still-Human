        /// <summary>What a representation made of one moment: a score per candidate, what it counted, and what it recognised as repeated.</summary>
        sealed class Scored
        {
            public readonly List<string> Candidates = new List<string>();
            public readonly Dictionary<string, double> Score = new Dictionary<string, double>(StringComparer.Ordinal);
            public readonly Dictionary<string, Dictionary<string, double>> Counted = new Dictionary<string, Dictionary<string, double>>(StringComparer.Ordinal);
            public int Restated;
            public int Conflicts;
        }

        static bool Same(double a, double b) => Math.Abs(a - b) < 1e-12;

        /// <summary>The strongest of several statements of one thing: the largest in magnitude, positive first on a tie.</summary>
        static double Strongest(IEnumerable<double> coefs)
            => coefs.OrderByDescending(Math.Abs).ThenByDescending(v => v).First();

        static void Count(Scored sc, string intent, string key, double amount)
        {
            if (!sc.Counted.TryGetValue(intent, out var m)) sc.Counted[intent] = m = new Dictionary<string, double>(StringComparer.Ordinal);
            m.TryGetValue(key, out var v);
            m[key] = v + amount;
        }

        static Scored Score(Rep rep, Staged s)
        {
            var sc = new Scored();
            switch (rep)
            {
                case Rep.A:
                case Rep.A0:
                    // The anonymous sum, rule by rule, in the selector's order. A
                    // discards a rule weighing nothing or less; A° counts it.
                    foreach (var r in s.Rules)
                    {
                        if (rep == Rep.A && r.Weight <= 0.0) continue;
                        if (!sc.Score.ContainsKey(r.Rule.Intent)) { sc.Score[r.Rule.Intent] = 0.0; sc.Candidates.Add(r.Rule.Intent); }
                        sc.Score[r.Rule.Intent] += r.Weight;
                        foreach (var st in r.Statements) Count(sc, r.Rule.Intent, st.Key, st.Amount);
                    }
                    break;

                case Rep.B:
                case Rep.BMean:
                {
                    // Evidence identity: per intention, one entry per evidence key.
                    // The same statement again is a restatement and counts once. A
                    // different statement of the same evidence is a conflict: B keeps
                    // the strongest, B-mean the mean, and both record it.
                    var stated = new Dictionary<string, Dictionary<string, List<Statement>>>(StringComparer.Ordinal);
                    foreach (var intent in s.Compatible) stated[intent] = new Dictionary<string, List<Statement>>(StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    foreach (var st in r.Statements)
                    {
                        var byKey = stated[r.Rule.Intent];
                        if (!byKey.TryGetValue(st.Key, out var list)) { byKey[st.Key] = new List<Statement> { st }; continue; }
                        if (list.Any(x => Same(x.Coef, st.Coef))) { sc.Restated++; continue; }
                        sc.Conflicts++;
                        list.Add(st);
                    }
                    foreach (var intent in s.Compatible)
                    {
                        sc.Candidates.Add(intent);
                        var total = 0.0;
                        foreach (var kv in stated[intent].OrderBy(x => x.Key, StringComparer.Ordinal))
                        {
                            var amount = rep == Rep.B
                                ? kv.Value.OrderByDescending(x => Math.Abs(x.Coef)).ThenByDescending(x => x.Coef).First().Amount
                                : kv.Value.Average(x => x.Amount);
                            Count(sc, intent, kv.Key, amount);
                            total += amount;
                        }
                        sc.Score[intent] = total;
                    }
                    break;
                }

                case Rep.C:
                {
                    // Reason identity: a reason is its intention, its gate and the set
                    // of evidence it reads. The same reason again counts once, at the
                    // strongest of each statement if the numbers differ. Different
                    // reasons add, whatever evidence they share.
                    var reasons = new Dictionary<string, Dictionary<string, List<RuleEval>>>(StringComparer.Ordinal);
                    foreach (var intent in s.Compatible) reasons[intent] = new Dictionary<string, List<RuleEval>>(StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    {
                        var bySig = reasons[r.Rule.Intent];
                        if (!bySig.TryGetValue(r.Signature, out var list)) bySig[r.Signature] = list = new List<RuleEval>();
                        list.Add(r);
                    }
                    foreach (var intent in s.Compatible)
                    {
                        sc.Candidates.Add(intent);
                        var total = 0.0;
                        foreach (var kv in reasons[intent].OrderBy(x => x.Key, StringComparer.Ordinal))
                        {
                            var vectors = kv.Value.Select(Vector).ToList();
                            Dictionary<string, Tuple<double, double>> chosen;
                            if (vectors.Count == 1) chosen = vectors[0];
                            else
                            {
                                var canon = vectors.Select(Canonical).ToList();
                                if (canon.All(x => x == canon[0])) sc.Restated += vectors.Count - 1;
                                else sc.Conflicts += vectors.Count - 1;
                                chosen = new Dictionary<string, Tuple<double, double>>(StringComparer.Ordinal);
                                foreach (var key in vectors.SelectMany(v => v.Keys).Distinct())
                                    chosen[key] = vectors.Where(v => v.ContainsKey(key)).Select(v => v[key]).OrderByDescending(t => Math.Abs(t.Item1)).ThenByDescending(t => t.Item1).First();
                            }
                            var reasonTotal = 0.0;
                            foreach (var st in chosen.OrderBy(x => x.Key, StringComparer.Ordinal))
                            {
                                Count(sc, intent, st.Key, st.Value.Item2);
                                reasonTotal += st.Value.Item2;
                            }
                            total += reasonTotal;
                        }
                        sc.Score[intent] = total;
                    }
                    break;
                }
            }
            return sc;
        }

        /// <summary>A reason's statements, key by key: (coefficient, amount), summed within the one rule.</summary>
        static Dictionary<string, Tuple<double, double>> Vector(RuleEval r)
        {
            var v = new Dictionary<string, Tuple<double, double>>(StringComparer.Ordinal);
            foreach (var st in r.Statements)
                v[st.Key] = v.TryGetValue(st.Key, out var t) ? Tuple.Create(t.Item1 + st.Coef, t.Item2 + st.Amount) : Tuple.Create(st.Coef, st.Amount);
            return v;
        }

        static string Canonical(Dictionary<string, Tuple<double, double>> v)
            => string.Join(";", v.OrderBy(x => x.Key, StringComparer.Ordinal).Select(x => x.Key + "=" + x.Value.Item1.ToString("R", CultureInfo.InvariantCulture)));

        /// <summary>What was decided, under one representation.</summary>
        sealed class Outcome
        {
            public string Token;
            public string Winner;
            public bool Tie;
            public string Second;
            public double TopScore;
            public double SecondScore;
            public int Candidates;
            public int Recognised;
            public Scored Scored;

            public double Margin => Second == null ? double.PositiveInfinity : TopScore - SecondScore;
            public string Line => Token + (Winner == null ? "" : " " + F(TopScore)) + (Second == null ? "" : " over " + Second + " " + F(SecondScore));
        }

        static bool Beats(double s1, string n1, double s2, string n2)
            => s1 > s2 || (s1 == s2 && string.CompareOrdinal(n1, n2) < 0);

        /// <summary>
        /// A breaks a tie by the intention's name, as the selector does. Every
        /// other representation reports it: the outcome is the set of tied
        /// intentions, and nothing is chosen between them.
        /// </summary>
        static Outcome Decide(Rep rep, Staged s, Func<string, string> unrename = null)
        {
            var sc = Score(rep, s);
            var o = new Outcome { Candidates = sc.Candidates.Count, Recognised = sc.Restated + sc.Conflicts, Scored = sc };
            string N(string x) => unrename == null ? x : unrename(x);
            if (sc.Candidates.Count == 0) { o.Token = "none"; return o; }

            if (rep == Rep.A)
            {
                string best = null, second = null;
                double b = 0, sd = 0;
                foreach (var i in sc.Candidates)
                {
                    var v = sc.Score[i];
                    if (best == null || Beats(v, i, b, best)) { second = best; sd = b; best = i; b = v; }
                    else if (second == null || Beats(v, i, sd, second)) { second = i; sd = v; }
                }
                o.Winner = N(best);
                o.Token = o.Winner;
                o.TopScore = b;
                o.Second = second == null ? null : N(second);
                o.SecondScore = sd;
                return o;
            }

            var top = sc.Candidates.Max(i => sc.Score[i]);
            var tied = sc.Candidates.Where(i => sc.Score[i] >= top - Tie).Select(N).OrderBy(x => x, StringComparer.Ordinal).ToList();
            var rest = sc.Candidates.Where(i => sc.Score[i] < top - Tie).OrderByDescending(i => sc.Score[i]).ThenBy(N, StringComparer.Ordinal).ToList();
            o.TopScore = top;
            if (tied.Count > 1)
            {
                o.Tie = true;
                o.Token = "tie(" + string.Join("=", tied) + ")";
                o.Second = tied[1];
                o.SecondScore = top;
            }
            else
            {
                o.Winner = tied[0];
                o.Token = o.Winner;
                if (rest.Count > 0) { o.Second = N(rest[0]); o.SecondScore = sc.Score[rest[0]]; }
            }
            return o;
        }

        static Outcome[] DecideAll(Staged s, Func<string, string> unrename = null)
            => Battery.Select(r => Decide(r, s, unrename)).ToArray();

        // ============================================================ why: an outcome as person evidence

        /// <summary>
        /// Each piece of evidence's share of the winner's margin over the
        /// runner-up, in that representation's own arithmetic. Where there is
        /// no runner-up, its share of the winner's support.
        /// </summary>
        static List<KeyValuePair<string, double>> Why(Outcome o)
        {
            if (o.Winner == null) return new List<KeyValuePair<string, double>>();
            var sc = o.Scored;
            var w = sc.Counted.TryGetValue(o.Winner, out var wm) ? wm : new Dictionary<string, double>();
            var r = o.Second != null && sc.Counted.TryGetValue(o.Second, out var rm) ? rm : new Dictionary<string, double>();
            return w.Keys.Union(r.Keys)
                .Select(k => new KeyValuePair<string, double>(k, (w.TryGetValue(k, out var a) ? a : 0.0) - (r.TryGetValue(k, out var b) ? b : 0.0)))
                .OrderByDescending(x => x.Value).ThenBy(x => x.Key, StringComparer.Ordinal).ToList();
        }

        static List<string> PersonReasons(Outcome o, int n = 3)
            => Why(o).Where(x => !x.Key.StartsWith(CircumstancePrefix, StringComparison.Ordinal) && x.Value > 1e-12)
                .Take(n).Select(x => x.Key).ToList();

        static string Lead(Outcome o) => PersonReasons(o, 1).FirstOrDefault() ?? "none";

        /// <summary>Whether two outcomes for the same intention rest on the same person evidence, piece by piece and weight by weight.</summary>
        static bool SameSupport(Outcome x, Outcome y)
        {
            Dictionary<string, double> Of(Outcome o) =>
                o.Scored.Counted.TryGetValue(o.Winner, out var m)
                    ? m.Where(kv => !kv.Key.StartsWith(CircumstancePrefix, StringComparison.Ordinal)).ToDictionary(kv => kv.Key, kv => kv.Value)
