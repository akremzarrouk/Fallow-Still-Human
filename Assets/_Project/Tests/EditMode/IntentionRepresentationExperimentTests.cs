        // ============================================================ structure: linear forms, per representation

        /// <summary>
        /// An intention's score as a linear function of what is read. Every
        /// level lies in 0..1, so the most a difference of two forms can reach
        /// over every possible person is its constant plus its positive
        /// coefficients. Circumstance statements are constants.
        /// </summary>
        sealed class Linear
        {
            public double Const;
            public readonly Dictionary<string, double> Coef = new Dictionary<string, double>(StringComparer.Ordinal);

            public void Add(string key, double c)
            {
                if (key.StartsWith(CircumstancePrefix, StringComparison.Ordinal)) { Const += c; return; }
                Coef.TryGetValue(key, out var v);
                Coef[key] = v + c;
            }

            public Linear Minus(Linear o)
            {
                var d = new Linear { Const = Const - o.Const };
                foreach (var kv in Coef) d.Add(kv.Key, kv.Value);
                foreach (var kv in o.Coef) d.Add(kv.Key, -kv.Value);
                return d;
            }

            public double Highest => Const + Coef.Values.Sum(v => Math.Max(0.0, v));
            public double Lowest => Const + Coef.Values.Sum(v => Math.Min(0.0, v));
            public double Of(string key) => Coef.TryGetValue(key, out var v) ? v : 0.0;
        }

        static IEnumerable<KeyValuePair<string, double>> StatementsOf(Candidate c)
        {
            if (c.Base != 0.0) yield return new KeyValuePair<string, double>(CircumstancePrefix + GateKey(c.When), c.Base);
            foreach (var s in c.ScaledBy) yield return new KeyValuePair<string, double>(EvidenceKey(s), s.Factor);
        }

        /// <summary>The form an intention's compatible rules make under a representation. A's discard is handled by the caller.</summary>
        static Linear FormOf(Rep rep, IReadOnlyList<Candidate> rules)
        {
            var l = new Linear();
            switch (rep)
            {
                case Rep.A:
                case Rep.A0:
                    foreach (var r in rules) foreach (var st in StatementsOf(r)) l.Add(st.Key, st.Value);
                    break;
                case Rep.B:
                case Rep.BMean:
                    foreach (var g in rules.SelectMany(StatementsOf).GroupBy(x => x.Key))
                    {
                        var distinct = g.Select(x => x.Value).Aggregate(new List<double>(), (acc, v) => { if (!acc.Any(x => Same(x, v))) acc.Add(v); return acc; });
                        l.Add(g.Key, rep == Rep.B ? Strongest(distinct) : distinct.Average());
                    }
                    break;
                case Rep.C:
                    foreach (var sig in rules.GroupBy(r => r.Intent + "|" + GateKey(r.When) + "|" + string.Join(",", r.ScaledBy.Select(EvidenceKey).Distinct().OrderBy(x => x, StringComparer.Ordinal))))
                    {
                        var vectors = sig.Select(r => StatementsOf(r).GroupBy(x => x.Key).ToDictionary(x => x.Key, x => x.Sum(y => y.Value))).ToList();
                        foreach (var key in vectors.SelectMany(v => v.Keys).Distinct())
                            l.Add(key, Strongest(vectors.Where(v => v.ContainsKey(key)).Select(v => v[key])));
                    }
                    break;
            }
            return l;
        }

        /// <summary>
        /// An upper bound, over every person in the unit box, on how far X can
        /// outscore Y. Under A a rule of X that can weigh nothing may be
        /// discarded, so both cases are bounded. A negative bound proves X never
        /// beats Y.
        /// </summary>
        static double BestMargin(Rep rep, IReadOnlyList<Candidate> x, IReadOnlyList<Candidate> y)
        {
            if (rep != Rep.A) return FormOf(rep, x).Minus(FormOf(rep, y)).Highest;
            var sure = x.Where(r => FormOf(Rep.A0, new[] { r }).Lowest > 0.0).ToList();
            var fragile = x.Where(r => FormOf(Rep.A0, new[] { r }).Lowest <= 0.0).ToList();
            var best = double.NegativeInfinity;
            for (var mask = 0; mask < 1 << fragile.Count; mask++)
            {
                var kept = sure.Concat(fragile.Where((r, k) => (mask & (1 << k)) != 0)).ToList();
                if (kept.Count == 0) continue;
                best = Math.Max(best, FormOf(Rep.A0, kept).Minus(FormOf(Rep.A0, y)).Highest);
            }
            return best;
        }

        /// <summary>Compatible intentions that no rival dominates, under a representation.</summary>
        static List<string> Contenders(Rep rep, IReadOnlyList<Candidate> rules, int wi, int ci, Dictionary<string, string> dominatedBy = null)
        {
            var intents = CompatibleRules(rules, wi, ci).Select(r => r.Intent).Distinct().ToList();
            if (intents.Count < 2) return intents;
            var alive = new List<string>();
            foreach (var x in intents)
            {
                string by = null;
                foreach (var y in intents.Where(other => other != x))
                    if (BestMargin(rep, CompatibleRules(rules, wi, ci, x), CompatibleRules(rules, wi, ci, y)) < -Tie) { by = y; break; }
                if (by == null) alive.Add(x);
                else if (dominatedBy != null) dominatedBy[x] = by;
            }
            return alive;
        }

        enum Status { NotRead, Live, Cancelled, Idle }

        /// <summary>
        /// Whether a piece of evidence can decide anything in a group: live if
        /// two contenders weigh it differently; cancelled if every contender
        /// weighs it the same and some do read it; idle if only a dominated or
        /// a lone intention reads it.
        /// </summary>
        static Status StatusOf(Rep rep, IReadOnlyList<Candidate> rules, int wi, int ci, string key)
        {
            var intents = CompatibleRules(rules, wi, ci).Select(r => r.Intent).Distinct().ToList();
            var forms = intents.ToDictionary(x => x, x => FormOf(rep, CompatibleRules(rules, wi, ci, x)));
            if (!forms.Values.Any(f => f.Of(key) != 0.0)) return Status.NotRead;
            var contenders = Contenders(rep, rules, wi, ci);
            if (contenders.Count < 2) return Status.Idle;
            var coefs = contenders.Select(x => forms[x].Of(key)).ToList();
            if (coefs.Max() - coefs.Min() > 1e-12) return Status.Live;
            return coefs.Any(c => c != 0.0) ? Status.Cancelled : Status.Idle;
        }

