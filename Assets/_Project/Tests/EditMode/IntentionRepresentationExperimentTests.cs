        enum Rep { A, A0, B, C, BMean }

        static readonly Rep[] Battery = { Rep.A, Rep.A0, Rep.B, Rep.C };

        static string Name(Rep r)
        {
            switch (r)
            {
                case Rep.A: return "A";
