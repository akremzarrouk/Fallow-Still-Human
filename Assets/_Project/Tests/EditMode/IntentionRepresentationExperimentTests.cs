        /// <summary>
        /// The identity of what a scaler reads, from fields the rule file
        /// already has. Nothing is added: a trait is its name, a belief its
        /// predicate and argument tokens, a feeling its name and target token.
        /// </summary>
        static string EvidenceKey(Scaler s)
        {
            switch (s.Kind)
            {
                case ScalerKind.Trait: return "trait:" + s.Name;
                case ScalerKind.Value: return "value:" + s.Name;
                case ScalerKind.Belief: return "belief:" + s.Predicate + "(" + string.Join(",", s.Args ?? new List<string>()) + ")";
                case ScalerKind.Emotion: return "emotion:" + s.Name + "@" + (s.Target ?? "situation");
                default: return s.Kind + ":" + (s.Name ?? s.Predicate ?? s.Entry ?? "") + (s.About == null ? "" : "@" + s.About);
            }
        }

        static string GateKey(SituationCondition w)
        {
            var parts = new List<string>();
            if (w.Alone.HasValue) parts.Add(w.Alone.Value ? "alone" : "not alone");
            if (w.OthersPresentMin.HasValue) parts.Add("others>=" + w.OthersPresentMin.Value);
            if (w.InOwnRoom.HasValue) parts.Add(w.InOwnRoom.Value ? "own room" : "not own room");
            if (w.InSomebodyElsesRoom.HasValue) parts.Add(w.InSomebodyElsesRoom.Value ? "somebody else's room" : "not somebody else's room");
            if (w.RoomHoldsFood.HasValue) parts.Add(w.RoomHoldsFood.Value ? "food here" : "no food here");
            if (w.SearchedThisRoomMyself.HasValue) parts.Add(w.SearchedThisRoomMyself.Value ? "searched here" : "not searched here");
            return parts.Count == 0 ? "any" : string.Join(",", parts);
        }

        const string CircumstancePrefix = "circumstance:";

        /// <summary>
        /// Stages 1 to 3, in the selector's own order and with its own
        /// arithmetic, so that A over what comes out is the selector to the bit.
        /// </summary>
        static Staged Stage(IReadOnlyList<Candidate> rules, Mind mind, Percept p, string want, string target = null)
        {
            var s = new Staged();
            var motive = Want(want, target);
            var ctx = new DecisionContext(p, mind.Id, motive.TargetId, _content.Morning.Day,
                _content.Rules.Deciding.RecallHalfLife);
            foreach (var c in rules)
            {
                if (!c.Motives.Contains(want, StringComparer.Ordinal)) continue;
                if (!s.Available.Contains(c.Intent)) s.Available.Add(c.Intent);
                if (!c.When.Matches(p)) continue;
                if (!s.Compatible.Contains(c.Intent)) s.Compatible.Add(c.Intent);
                var terms = ScalerEval.Evaluate(c.ScaledBy, mind, ctx);
                if (terms.Count != c.ScaledBy.Count) throw new InvalidOperationException(c.Id + ": a scaler was not evaluated");
                var gate = GateKey(c.When);
                var statements = new List<Statement>();
                if (c.Base != 0.0) statements.Add(new Statement { Key = CircumstancePrefix + gate, Coef = c.Base, Amount = c.Base, IsBase = true });
                for (var k = 0; k < terms.Count; k++)
                    statements.Add(new Statement { Key = EvidenceKey(c.ScaledBy[k]), Coef = c.ScaledBy[k].Factor, Amount = terms[k].Amount });
                s.Rules.Add(new RuleEval
                {
                    Rule = c,
                    Weight = c.Base + terms.Sum(t => t.Amount),
                    Gate = gate,
                    Signature = c.Intent + "|" + gate + "|" + string.Join(",", c.ScaledBy.Select(EvidenceKey).Distinct().OrderBy(x => x, StringComparer.Ordinal)),
                    Statements = statements
                });
            }
            return s;
        }

        /// <summary>The same moment with every statement of one kind of evidence read at level zero.</summary>
        static Staged Zeroed(Staged s, string prefix)
        {
            var z = new Staged();
            z.Available.AddRange(s.Available);
            z.Compatible.AddRange(s.Compatible);
            foreach (var r in s.Rules)
            {
                var statements = r.Statements.Select(x => new Statement
                {
                    Key = x.Key, Coef = x.Coef, IsBase = x.IsBase,
                    Amount = !x.IsBase && x.Key.StartsWith(prefix, StringComparison.Ordinal) ? 0.0 : x.Amount
                }).ToList();
                z.Rules.Add(new RuleEval
                {
                    Rule = r.Rule, Gate = r.Gate, Signature = r.Signature, Statements = statements,
                    Weight = r.Rule.Base + statements.Where(x => !x.IsBase).Sum(x => x.Amount)
                });
            }
            return z;
        }

