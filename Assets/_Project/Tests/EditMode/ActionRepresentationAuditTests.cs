        [Test]
        public void D1_WhatEachActPutsIntoTheWorld()
        {
            var s = _primary;
            var sb = new StringBuilder();
            sb.AppendLine("## 1. What each act puts into the world");
            sb.AppendLine();
            sb.AppendLine(s.Mornings + " mornings, " + s.Acts.Count + " decisions, primary baseline. For each kind of act: how often it was chosen, for how many different leading wants, how many world events it produced, and every value each field of those events took.");
            sb.AppendLine();
            sb.AppendLine("| Act | Chosen | Leading wants (distinct) | Events | Acts with no event, and why (from the act's record) | Event fields seen (all values) | `intent` on any event |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (var k in Kinds)
            {
                var acts = s.Of(k).ToList();
                if (acts.Count == 0) { sb.AppendLine("| " + k + " | 0 | | | | | |"); continue; }
                var events = acts.SelectMany(a => a.Events).ToList();
                string Values(Func<WorldEvent, string> f) => string.Join("/", events.Select(f).Select(Or).Distinct().OrderBy(x => x, StringComparer.Ordinal));
                var fields = events.Count == 0 ? "none" :
                    "action " + Values(e => e.Action) + "; topic " + Values(e => e.Topic) + "; tone " + Values(e => e.Tone) + "; valence " + Values(e => e.Valence) + "; target " + Values(e => e.TargetId == null ? null : "a person");
                var none = acts.Where(a => a.Events.Count == 0).GroupBy(a => WhyNoEvent(a)).OrderByDescending(g => g.Count()).Select(g => g.Key + " " + g.Count());
                sb.AppendLine("| " + k + " | " + acts.Count + " (" + P(acts.Count, s.Acts.Count) + ") | " + acts.Select(a => a.LeadingName ?? "nothing").Distinct().Count() + " | " + events.Count + " | " + acts.Count(a => a.Events.Count == 0) + ": " + string.Join("; ", none) + " | " + fields + " | " + events.Count(e => e.Intent != null) + " of " + events.Count + " |");
            }
            sb.AppendLine();
            var all = s.Acts.SelectMany(a => a.Events).ToList();
            sb.AppendLine("Of " + all.Count + " world events the morning's acts produced, **" + all.Count(e => e.Intent != null) + "** carry an intent. Every field of every event is set in `SilentMorning.Complete`, `Walk` or `Happened` from the kind of act, its target, the room and the state of the house (the pantry's count decides a valence); none is taken from the decision.");
            Record("1", sb.ToString());

            Assert.AreEqual(0, all.Count(e => e.Intent != null), "no morning act carries an intent");
        }

