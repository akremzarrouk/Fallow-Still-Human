        [Test]
        public void D2_TheSameActForDifferentReasons()
        {
            var s = _primary;
            var sb = new StringBuilder();
            sb.AppendLine("## 2. The same act, for different reasons");
            sb.AppendLine();
            sb.AppendLine("For each kind of act, the events it produced grouped by everything an event carries except who, where and when (its *signature*). If the reason survived into the world, acts done for different leading wants would produce different signatures.");
            sb.AppendLine();
            sb.AppendLine("| Act | Acts with an event | Leading wants among them | Distinct signatures | Signatures produced for more than one leading want | Acts whose signature is shared with another want |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var shared = 0;
            var withEvent = 0;
            foreach (var k in Kinds)
            {
                var acts = s.Of(k).Where(a => a.Events.Count > 0).ToList();
                if (acts.Count == 0) continue;
                var bySig = acts.SelectMany(a => a.Events.Select(e => (Sig: Signature(e), Want: a.LeadingName ?? "nothing", Act: a)))
                    .GroupBy(x => x.Sig).ToList();
                var multi = bySig.Where(g => g.Select(x => x.Want).Distinct().Count() > 1).ToList();
                var sharedActs = multi.SelectMany(g => g.Select(x => x.Act)).Distinct().Count();
                shared += sharedActs;
                withEvent += acts.Count;
                sb.AppendLine("| " + k + " | " + acts.Count + " | " + string.Join(", ", acts.GroupBy(a => a.LeadingName ?? "nothing").OrderByDescending(g => g.Count()).Select(g => g.Key + " " + g.Count())) + " | " + bySig.Count + " | " + multi.Count + " | " + sharedActs + " (" + P(sharedActs, acts.Count) + ") |");
            }
            sb.AppendLine();
            sb.AppendLine("**" + shared + " of " + withEvent + " acts that produced an event (" + P(shared, withEvent) + ") produced exactly the event an act of the same kind produced for a different reason.**");
            sb.AppendLine();

            // Concrete pairs: the first two acts of a kind whose leading wants differ.
            sb.AppendLine("### Pairs, side by side");
            sb.AppendLine();
            foreach (var k in Kinds)
            {
                var acts = s.Of(k).Where(a => a.Events.Count > 0).ToList();
                Act first = null, second = null;
                foreach (var a in acts)
                {
                    if (first == null) { first = a; continue; }
                    if ((a.LeadingName ?? "nothing") != (first.LeadingName ?? "nothing") && Signature(a.Events[0]) == Signature(first.Events[0])) { second = a; break; }
                }
                if (first == null || second == null) continue;
                sb.AppendLine("**" + k + "**");
                sb.AppendLine();
                sb.AppendLine("| | " + Describe(first) + " | " + Describe(second) + " |");
                sb.AppendLine("|---|---|---|");
                sb.AppendLine("| Why, as deliberated | " + Why(first) + " | " + Why(second) + " |");
                sb.AppendLine("| World event | " + Signature(first.Events[0]) + " | " + Signature(second.Events[0]) + " |");
                sb.AppendLine("| Summary | " + first.Events[0].Summary + " | " + second.Events[0].Summary + " |");
                sb.AppendLine("| What the actor kept | " + Kept(first, true) + " | " + Kept(second, true) + " |");
                sb.AppendLine("| What the others kept | " + Kept(first, false) + " | " + Kept(second, false) + " |");
                sb.AppendLine("| Event's trace record rests on | " + (first.EventParents[first.Events[0].Id] == 0 ? "nothing" : first.EventParents[first.Events[0].Id] + " records") + " | " + (second.EventParents[second.Events[0].Id] == 0 ? "nothing" : second.EventParents[second.Events[0].Id] + " records") + " |");
                sb.AppendLine();
            }
            Record("2", sb.ToString());
        }

        static string Describe(Act a) => a.Who + ", " + a.Variant + " s" + a.Seed + " m" + a.Minute + ", " + a.Key + " in the " + a.Room;

        static string Why(Act a)
            => (a.Leading == null ? "led by nothing" : "led by **" + a.Leading + "** " + F(a.LeadingUrgency)) +
               (a.Credits.Count == 0 ? "" : "; credited by " + string.Join(", ", a.Credits.Select(c => c.Want + " via " + c.Proposal + " " + F(c.Amount))));

        static string Kept(Act a, bool actor)
        {
            var e = a.Events[0];
            var r = a.Readings.TryGetValue(e.Id, out var list) ? list : new List<(string, string, bool, string, string)>();
            var sel = r.Where(x => (x.Item1 == a.Who) == actor).ToList();
            if (sel.Count == 0) return actor ? "nothing" : "nobody else perceived it";
            return string.Join("; ", sel.Select(x => (actor ? "" : x.Item1 + ": ") + x.Item2 + (x.Item3 ? " (own intention)" : " (" + x.Item5 + ")") + ", felt " + x.Item4));
        }

