        /// <summary>One act, from the decision that chose it to what the house made of it.</summary>
        internal sealed class Act
        {
            public string Variant;
            public ulong Seed;
            public int Minute;
            public string Who;
            public string Room;
            public int Present;
            public bool FoodWithinReach;
            public bool FoodKeptHere;
            public int OthersWorthDoing;
            public int KindsWorthDoing;
            public string Kind;
            public string Key;
            public string Leading;
            public string LeadingName;
            public double LeadingUrgency;
            public string Because;
            public List<(string Want, string Name, string Proposal, double Amount)> Credits = new List<(string, string, string, double)>();
            public double Appeal, Cost, Score, Margin;
            public bool Ambiguous;
            public string Competitors;
            public List<(string Key, double U)> Raised = new List<(string, double)>();
            public string Holding;
            public string Commitment;
            public string Forms;
            public int DecisionTraceId;
            public string Outcome;
            public List<WorldEvent> Events = new List<WorldEvent>();

            /// <summary>For each event: perceiver -> (meaning, own intention, dominant feeling, access).</summary>
            public Dictionary<string, List<(string Who, string Meaning, bool Own, string Felt, string Access)>> Readings =
                new Dictionary<string, List<(string, string, bool, string, string)>>(StringComparer.Ordinal);

            public Dictionary<string, int> EventParents = new Dictionary<string, int>(StringComparer.Ordinal);
            public bool AnyReadingReachesTheDecision;

            public int WantsCrediting => Credits.Select(c => c.Want).Distinct().Count();
        }

        internal sealed class Survey
        {
            public string Label;
            public List<Act> Acts = new List<Act>();
            public int Mornings;

            public static Survey Run(Scenario001Content c, string label, int seeds)
            {
                var s = new Survey { Label = label };
                foreach (var v in c.Morning.Variants.Select(x => x.Id))
                for (ulong seed = 1; seed <= (ulong)seeds; seed++)
                {
                    var run = Scenario001.Prepare(c, v, seed);
                    var byDecision = new Dictionary<int, Act>();
                    run.Morning.Decided = m =>
                    {
                        var d = m.Decision;
                        var chosen = d.ChosenScored;
                        var lead = d.Leading;
                        var a = new Act
                        {
                            Variant = v, Seed = seed, Minute = m.Minute, Who = m.CharacterId, Room = m.Percept.Room?.Id,
                            Present = m.Percept.Present.Count, Kind = d.Chosen.KindName, Key = d.Chosen.Key,
                            FoodWithinReach = m.Percept.FoodWithinReach == true, FoodKeptHere = m.Percept.RoomHoldsFood,
                            OthersWorthDoing = d.Considered.Count(r => r.Score > 0.0 && !r.Option.SameAs(d.Chosen)),
                            KindsWorthDoing = d.Considered.Where(r => r.Score > 0.0).Select(r => r.Option.KindName).Distinct().Count(),
                            Leading = lead?.Key, LeadingName = lead?.Name, LeadingUrgency = lead?.Urgency ?? 0.0,
                            Because = lead?.Because,
                            Appeal = chosen.Appeal, Cost = chosen.Cost, Score = chosen.Score, Margin = d.Margin,
                            Ambiguous = d.Resolution == Resolution.Ambiguous,
                            Competitors = string.Join("; ", d.Considered.Where(r => !r.Option.SameAs(d.Chosen)).Take(3)
                                .Select(r => r.Option.Key + " " + r.Score.ToString("+0.000;-0.000", CultureInfo.InvariantCulture))),
                            Holding = d.Holding?.MotiveKey, Commitment = d.Commitment, Forms = d.Forms?.MotiveKey,
                            DecisionTraceId = d.TraceId
                        };
                        foreach (var x in chosen.Contributions.Where(x => x.Amount > 0.0))
                            a.Credits.Add((x.MotiveKey, x.MotiveName, x.ProposalId, x.Amount));
                        foreach (var w in m.Motives) a.Raised.Add((w.Key, w.Urgency));
                        byDecision[d.TraceId] = a;
                    };
                    run.Morning.Run(c.Morning.Minutes);
                    s.Mornings++;

                    var result = run.Result;
                    var acts = new List<Act>();
                    foreach (var record in result.Actions)
                    {
                        var a = byDecision[record.DecisionTraceId];
                        a.Outcome = record.Outcome;
                        acts.Add(a);
                    }

                    // Each event a person authored belongs to their latest decision before it.
                    var eventRecords = run.Trace.All.Where(r => r.Kind == TraceKind.Event && r.EventId != null)
                        .GroupBy(r => r.EventId).ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
                    foreach (var e in result.Events.Where(e => e.ActorId != null))
                    {
                        var owner = acts.Where(x => x.Who == e.ActorId && x.Minute < e.Minute).OrderBy(x => x.Minute).LastOrDefault();
                        if (owner == null) continue;
                        owner.Events.Add(e);
                        owner.EventParents[e.Id] = eventRecords.TryGetValue(e.Id, out var er) ? er.ParentIds.Count : -1;

                        var perceivers = new[] { e.ActorId }.Concat(e.Witnesses).Concat(e.Overhearers).Distinct().ToList();
                        var readings = new List<(string, string, bool, string, string)>();
                        foreach (var p in perceivers)
                        {
                            var x = run.Minds[p].Experiences.LastOrDefault(k => k.EventId == e.Id);
                            if (x == null) continue;
                            readings.Add((p, x.Meaning, x.FromOwnIntent, x.DominantEmotion ?? "nothing", x.Access.ToString().ToLowerInvariant()));

                            // Can what this person made of it be walked back to why it was done?
                            var chain = run.Trace.Chain(x.TraceId);
                            if (chain.Any(r => r.Id == owner.DecisionTraceId ||
                                               (r.CharacterId == e.ActorId && (r.Kind == TraceKind.Deliberation || r.Kind == TraceKind.Motive))))
                                owner.AnyReadingReachesTheDecision = true;
                        }
                        owner.Readings[e.Id] = readings;
                    }
                    s.Acts.AddRange(acts);
                }
                return s;
            }

            public IEnumerable<Act> Of(string kind) => Acts.Where(a => a.Kind == kind);
        }

        static readonly string[] Kinds = ActionOption.AllNames.ToArray();

        /// <summary>What the act's own record says, with names taken out.</summary>
        static string WhyNoEvent(Act a)
        {
            var o = a.Outcome;
            if (o == null) return "stopped part way, or the morning ended first";
            if (o.StartsWith("thought again", StringComparison.Ordinal)) return "thought again and carried on (the event is the later decision's)";
            if (o.Contains("had gone before")) return "the person had gone";
            if (o.StartsWith("went to", StringComparison.Ordinal)) return "walked, and nobody was there to see it";
            if (o.StartsWith("stayed", StringComparison.Ordinal)) return "stood still: no event by design";
            // A completion note on the record and no event of its own: it was
            // stopped, thought again and carried on, and the event it made
            // belongs to the decision that carried it on.
            if (o.StartsWith("found", StringComparison.Ordinal) || o.StartsWith("went through", StringComparison.Ordinal) ||
                o.StartsWith("sat with", StringComparison.Ordinal) || o.StartsWith("watched", StringComparison.Ordinal))
                return "completed after being carried on; the event is the later decision's";
            return "other: " + o;
        }

        static string Signature(WorldEvent e)
            => "action=" + Or(e.Action) + ", target=" + (e.TargetId == null ? "none" : "a person") + ", topic=" + Or(e.Topic) +
               ", tone=" + Or(e.Tone) + ", valence=" + Or(e.Valence) + ", intent=" + Or(e.Intent) + ", act=" + Or(e.Act);

