        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static string F(double v) => v.ToString("0.000", CultureInfo.InvariantCulture);
        static string P(double part, double whole) => whole == 0 ? "n/a" : (100.0 * part / whole).ToString("0.0", CultureInfo.InvariantCulture) + " %";

        // ------------------------------------------------------------------ the two events

        static WorldEvent Intrusion(int day, int minute, IReadOnlyList<string> witnesses)
            => new WorldEvent(
                "e-intrusion", day, 5000, EventKind.Action, "daniel", "mara",
                null, "search_belongings", "missing_can", "neutral", "direct", "neutral",
                null, "Daniel empties Mara's bag out while she is standing there.",
                witnesses, new List<string>(), new List<LedgerEffect>(), null, minute);

        static WorldEvent Watching(int day, int minute, IReadOnlyList<string> witnesses)
            => new WorldEvent(
                "e-watching", day, 6000, EventKind.Action, "daniel", "mara",
                null, "observe", null, "neutral", "direct", "neutral",
                null, "Daniel watches Mara across the room and says nothing.",
                witnesses, new List<string>(), new List<LedgerEffect>(), null, minute);

        // ------------------------------------------------------------------ watching a morning

        sealed class Moment
        {
            public int Minute;
            public string Who;
            public string Chosen;
            public string Leading;
            public string Feelings;
            public string Options;
            public bool Ambiguous;
            public Dictionary<string, double> Wants = new Dictionary<string, double>(StringComparer.Ordinal);

            public string Line => "m" + Minute + " " + Who + " " + Chosen + " for " + (Leading ?? "nothing");
            public string WantLine => string.Join(", ", Wants.OrderByDescending(x => x.Value).Select(x => x.Key + " " + F(x.Value)));
        }

        sealed class Episode
        {
            public string Condition;
            public string Variant;
            public ulong Seed;
            public bool Usable = true;
            public string Why;
            public int IntrusionAt = -1;
            public int WatchingAt = -1;
            public PerceptionOutcome HerIntrusion;
            public PerceptionOutcome HerWatching;
            public Dictionary<string, double> BeliefsAfter = new Dictionary<string, double>(StringComparer.Ordinal);
            public List<Moment> Decisions = new List<Moment>();
            public IReadOnlyList<ActionRecord> Actions;
            public IReadOnlyList<WorldEvent> Events;
            public IReadOnlyDictionary<string, Mind> Minds;
            public TraceLog Trace;
            public string Fingerprint;

            /// <summary>Whether what happened stopped her doing what she was doing.</summary>
            public bool StoppedHer;

            public IEnumerable<Moment> Hers => Decisions.Where(d => d.Who == "mara");
            public Moment HerNext(int after) => Hers.FirstOrDefault(d => d.Minute > after);
            public IEnumerable<ActionRecord> HerActs => Actions.Where(a => a.CharacterId == "mara");

            /// <summary>Times somebody sat with her, and who.</summary>
            public List<WorldEvent> SatWithHer => Events.Where(e => e.Action == "comfort" && e.TargetId == "mara").ToList();
            public List<WorldEvent> HerDistressShowing => Events.Where(e => e.Action == "show_distress" && e.TargetId == "mara").ToList();
            public int SheComfortedDaniel => Actions.Count(a => a.CharacterId == "mara" && a.Action.Key == "comfort:daniel");
        }

        static readonly string[] Watched = { "tendency(daniel,treats_me_like_a_child)", "tendency(daniel,does_not_respect_me)" };

        static double Belief(Mind mind, string key)
        {
            var open = key.IndexOf('(');
            var predicate = key.Substring(0, open);
            var args = key.Substring(open + 1, key.Length - open - 2).Split(',').Select(a => a.Trim()).ToList();
            return mind.Beliefs.Confidence(predicate, args);
        }

        static Episode RunEpisode(string variant, ulong seed, string condition, int intrusionAt, int watchingAt)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            var ep = new Episode { Condition = condition, Variant = variant, Seed = seed };
            run.Morning.Decided = m =>
            {
                var d = m.Decision;
                var mo = new Moment
                {
                    Minute = m.Minute, Who = m.CharacterId, Chosen = d.Chosen.Key, Leading = d.Leading?.Key,
                    Ambiguous = d.Resolution == Resolution.Ambiguous,
                    Options = string.Join("; ", d.Considered.Take(4).Select(r => r.Option.Key + " " + r.Score.ToString("+0.000;-0.000", CultureInfo.InvariantCulture))),
                    Feelings = string.Join(", ", m.Mind.Emotions.Live.OrderByDescending(e => e.Intensity)
                        .Select(e => e.Type + (e.TargetId == null ? "" : ":" + e.TargetId) + " " + F(e.Intensity)))
                };
                foreach (var x in m.Motives) mo.Wants[x.Key] = x.Urgency;
                ep.Decisions.Add(mo);
            };

            for (var i = 0; i < _content.Morning.Minutes; i++)
            {
                run.Morning.Step();
                var now = run.World.Minute;
                var together = run.World.RoomOf("daniel") == run.World.RoomOf("mara");

                // In every condition, her beliefs are read at the same minute,
                // so that the three are comparable.
                if (now == intrusionAt && condition == Never)
                    foreach (var k in Watched) ep.BeliefsAfter[k] = Belief(run.Minds["mara"], k);

                if (now == intrusionAt && condition != Never)
                {
                    if (!together) { ep.Usable = false; ep.Why = "they were not in the same room at minute " + now; }
                    else
                    {
                        var room = run.World.RoomOf("daniel");
                        var inTheRoom = run.World.InRoom(room).Where(id => id != "daniel").ToList();
                        var witnesses = condition == Saw ? inTheRoom : inTheRoom.Where(id => id != "mara").ToList();
                        var outcome = run.Morning.Happen(Intrusion(_content.Morning.Day, now, witnesses));
                        ep.IntrusionAt = now;
                        ep.HerIntrusion = outcome.ByCharacter["mara"];
                        foreach (var k in Watched) ep.BeliefsAfter[k] = Belief(run.Minds["mara"], k);
                    }
                }

                if (now == watchingAt)
                {
                    if (!together) { ep.Usable = false; ep.Why = "they were not in the same room at minute " + now; }
                    else
                    {
                        var room = run.World.RoomOf("daniel");
                        var witnesses = run.World.InRoom(room).Where(id => id != "daniel").ToList();
                        var outcome = run.Morning.Happen(Watching(_content.Morning.Day, now, witnesses));
                        ep.WatchingAt = now;
                        ep.HerWatching = outcome.ByCharacter["mara"];
                    }
                }
            }

            ep.StoppedHer = run.Morning.Interruptions.Any(i => i.CharacterId == "mara" && i.EventId == "e-intrusion");
            ep.Actions = run.Result.Actions;
            ep.Events = run.Result.Events;
            ep.Minds = run.Minds;
            ep.Trace = run.Trace;
            ep.Fingerprint = string.Join("\n", ep.Actions.Select(a => a.ToString()));
            if (ep.BeliefsAfter.Count == 0) foreach (var k in Watched) ep.BeliefsAfter[k] = Belief(run.Minds["mara"], k);
            return ep;
        }

        /// <summary>The minutes at which the two moments can happen, found in an untouched morning.</summary>
        static (int Intrusion, int Watching) Moments(string variant, ulong seed)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            var intrusion = -1;
            var watching = -1;
            for (var i = 0; i < _content.Morning.Minutes; i++)
            {
                run.Morning.Step();
                var now = run.World.Minute;
                var together = run.World.RoomOf("daniel") == run.World.RoomOf("mara");
                if (together && intrusion < 0 && now >= IntrusionFrom) intrusion = now;
                if (together && watching < 0 && now >= EncounterFrom) watching = now;
            }
            return (intrusion, watching);
        }

        static string Reading(PerceptionOutcome o)
        {
            if (o == null) return "-";
            if (o.Access == Access.None) return "nothing reached her";
            return o.Meaning + " (" + F(o.InterpretationWeight) + ")" +
                   (o.RunnerUpMeaning == null ? "" : ", next " + o.RunnerUpMeaning) +
                   "; stirred " + (o.Emotions.Count == 0 ? "nothing" : string.Join(", ", o.Emotions.Select(e => e.Type + " " + F(e.Intensity))));
        }

