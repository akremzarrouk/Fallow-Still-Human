        [Test, Timeout(1800000)]
        public void E2_TheSameEpisodeOverSeeds()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. The same episode over seeds and conditions");
            sb.AppendLine();
            sb.AppendLine("Seeds 1-" + Seeds + " of two conditions of the house: `daniel_ate_it`, in which Mara took nothing, and `mara_ate_it`, in which she is the one who took the can. A seed is used only if Daniel and Mara are in the same room at both moments, in every arm.");
            sb.AppendLine();

            foreach (var variant in new[] { "daniel_ate_it", "mara_ate_it" })
            {
                int usable = 0, readingDiffered = 0, weightDiffered = 0, feelingsDiffered = 0, wantsDiffered = 0,
                    actDiffered = 0, morningDiffered = 0, satWithHer = 0, satWithHerC = 0, showed = 0, showedC = 0,
                    sheSatWithDaniel = 0, sheSatWithDanielC = 0,
                    nowFeelings = 0, nowWants = 0, nowAct = 0, stopped = 0;
                var weights = new List<(double A, double C)>();
                var firstPartings = new List<string>();
                var rows = new List<string>();
                var gaps = new List<int>();
                var lasts = new List<int>();

                for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
                {
                    var at = Moments(variant, seed);
                    if (at.Intrusion < 0 || at.Watching < 0) continue;
                    var a = RunEpisode(variant, seed, Saw, at.Intrusion, at.Watching);
                    var c = RunEpisode(variant, seed, Missed, at.Intrusion, at.Watching);
                    if (!a.Usable || !c.Usable) continue;
                    usable++;

                    if (a.HerWatching != null && c.HerWatching != null)
                    {
                        if (a.HerWatching.Meaning != c.HerWatching.Meaning) readingDiffered++;
                        if (Math.Abs(a.HerWatching.InterpretationWeight - c.HerWatching.InterpretationWeight) > 1e-9) weightDiffered++;
                        weights.Add((a.HerWatching.InterpretationWeight, c.HerWatching.InterpretationWeight));
                    }

                    // Right after the intrusion.
                    var na = a.HerNext(at.Intrusion);
                    var nc = c.HerNext(at.Intrusion);
                    var nf = na != null && nc != null && na.Feelings != nc.Feelings;
                    var nw = na != null && nc != null && na.WantLine != nc.WantLine;
                    var nact = na != null && nc != null && (na.Chosen != nc.Chosen || na.Minute != nc.Minute);
                    if (a.StoppedHer) stopped++;
                    if (nf) nowFeelings++;
                    if (nw) nowWants++;
                    if (nact) nowAct++;

                    // An hour later, at the watching.
                    var ma = a.HerNext(at.Watching);
                    var mc = c.HerNext(at.Watching);
                    var lf = ma != null && mc != null && ma.Feelings != mc.Feelings;
                    var lw = ma != null && mc != null && ma.WantLine != mc.WantLine;
                    var lact = ma != null && mc != null && ma.Chosen != mc.Chosen;
                    if (lf) feelingsDiffered++;
                    if (lw) wantsDiffered++;
                    if (lact) actDiffered++;

                    var div = HerDivergence(a, c);
                    gaps.Add(at.Watching - at.Intrusion);
                    lasts.Add(div.Last);
                    rows.Add("| " + seed + " | " + at.Intrusion + " | " + at.Watching + " | " + (at.Watching - at.Intrusion) + " | " +
                             (nf ? "yes" : "no") + " | " + (nw ? "yes" : "no") + " | " + (nact ? "**yes**" : "no") + " | " +
                             (lf ? "yes" : "no") + " | " + (lw ? "yes" : "no") + " | " + (lact ? "**yes**" : "no") + " | " +
                             div.Differing + " of " + div.Total + " | " + (div.Last < 0 ? "-" : "m" + div.Last) + " |");
                    if (a.Fingerprint != c.Fingerprint)
                    {
                        morningDiffered++;
                        if (firstPartings.Count < 5) firstPartings.Add("seed " + seed + ", " + FirstParting(a, c));
                    }
                    if (a.SatWithHer.Any(e => e.Minute >= at.Intrusion)) satWithHer++;
                    if (c.SatWithHer.Any(e => e.Minute >= at.Intrusion)) satWithHerC++;
                    if (a.HerDistressShowing.Any(e => e.Minute >= at.Intrusion)) showed++;
                    if (c.HerDistressShowing.Any(e => e.Minute >= at.Intrusion)) showedC++;
                    sheSatWithDaniel += a.SheComfortedDaniel;
                    sheSatWithDanielC += c.SheComfortedDaniel;
                }

                sb.AppendLine("### " + variant);
                sb.AppendLine();
                sb.AppendLine("Seed by seed. \"Right after\" is her first decision after the intrusion; \"an hour later\" is her first decision after the watching. Her decisions are lined up by the minute she took them.");
                sb.AppendLine();
                sb.AppendLine("| Seed | Intrusion | Watching | Gap | Right after: feelings | wants | act | An hour later: feelings | wants | act | Her decisions differing | Last one |");
                sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (var r in rows) sb.AppendLine(r);
                sb.AppendLine();
                sb.AppendLine("| | A (she saw it) | C (she did not) |");
                sb.AppendLine("|---|---|---|");
                sb.AppendLine("| Seeds used | " + usable + " of " + Seeds + " | |");
