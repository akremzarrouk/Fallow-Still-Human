        [Test, Timeout(1800000)]
        public void E1_TheEpisodeOnOneMorning()
        {
            var variant = "daniel_ate_it";
            ulong seed = 0;
            (int Intrusion, int Watching) at = (-1, -1);
            for (ulong s = 1; s <= (ulong)Seeds && seed == 0; s++)
            {
                var m = Moments(variant, s);
                if (m.Intrusion > 0 && m.Watching > 0) { seed = s; at = m; }
            }
            Assert.Greater(seed, 0UL, "some seed has them in the same room twice");

            var runs = Conditions.ToDictionary(c => c, c => RunEpisode(variant, seed, c, at.Intrusion, at.Watching));
            foreach (var r in runs.Values) Assert.IsTrue(r.Usable, r.Condition + ": " + r.Why);
            var a = runs[Saw];
            var c = runs[Missed];
            var b = runs[Never];

            var sb = new StringBuilder();
            sb.AppendLine("## 1. The episode, one morning, minute by minute");
            sb.AppendLine();
            sb.AppendLine("`" + variant + "`, seed " + seed + ". Daniel goes through Mara's things at minute " + at.Intrusion + " (**SETUP**) and watches her at minute " + at.Watching + " (**SETUP**). Both were put in at the first minute after " + IntrusionFrom + " and " + EncounterFrom + " at which the two of them were in the same room, found in an untouched morning.");
            sb.AppendLine();
            sb.AppendLine("| | " + string.Join(" | ", Conditions) + " |");
            sb.AppendLine("|---|---|---|---|");
            sb.AppendLine("| **The intrusion**, as it reached her | " + Reading(a.HerIntrusion) + " | " + Reading(c.HerIntrusion) + " | it never happened |");
            foreach (var k in Watched)
                sb.AppendLine("| Her belief `" + k + "` just after | " + F(a.BeliefsAfter[k]) + " | " + F(c.BeliefsAfter[k]) + " | " + F(b.BeliefsAfter[k]) + " |");

