            sb.AppendLine("### Mara's morning in A, decision by decision");
            sb.AppendLine();
            sb.AppendLine("| Minute | She chose | For | Feeling | Wants at 0.10 or more |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var m in a.Hers)
                sb.AppendLine("| " + m.Minute + (m.Minute == a.IntrusionAt + 1 ? " (just after the intrusion)" : m.Minute == a.WatchingAt + 1 ? " (just after the watching)" : "") + " | " + m.Chosen + " | " + (m.Leading ?? "nothing") + " | " + (m.Feelings.Length == 0 ? "nothing" : m.Feelings) + " | " + string.Join(", ", m.Wants.Where(x => x.Value >= 0.1).OrderByDescending(x => x.Value).Select(x => x.Key + " " + F(x.Value))) + " |");
