            sb.AppendLine("### The same morning in C (she did not see it)");
            sb.AppendLine();
            sb.AppendLine("| Minute | She chose | For | Feeling |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var m in c.Hers)
                sb.AppendLine("| " + m.Minute + " | " + m.Chosen + " | " + (m.Leading ?? "nothing") + " | " + (m.Feelings.Length == 0 ? "nothing" : m.Feelings) + " |");
            Record("1", sb.ToString());

            Assert.AreEqual(Access.Witnessed, a.HerIntrusion.Access, "she was there for it in A");
            Assert.AreEqual(Access.None, c.HerIntrusion.Access, "and not in C");
        }

        /// <summary>
        /// Her own decisions, lined up by the minute she took them, since an
        /// event that stops somebody changes when they next decide as well as
        /// what they decide.
        /// </summary>
        static (int Differing, int Total, int Last) HerDivergence(Episode x, Episode y)
        {
            string Line(Moment m) => m == null ? "(no decision)" : m.Chosen + " for " + (m.Leading ?? "nothing");
            var a = x.Hers.ToDictionary(m => m.Minute, m => m);
            var b = y.Hers.ToDictionary(m => m.Minute, m => m);
            var minutes = a.Keys.Union(b.Keys).OrderBy(m => m).ToList();
            var differing = 0;
            var last = -1;
            foreach (var m in minutes)
            {
                a.TryGetValue(m, out var p);
                b.TryGetValue(m, out var q);
                if (Line(p) == Line(q)) continue;
                differing++;
                last = m;
            }
            return (differing, minutes.Count, last);
        }

        static string Different(Episode x, Episode y)
        {
            var n = 0;
            var p = x.Decisions.Select(d => d.Line).ToList();
            var q = y.Decisions.Select(d => d.Line).ToList();
            for (var i = 0; i < Math.Min(p.Count, q.Count); i++) if (p[i] != q[i]) n++;
            return (n + Math.Abs(p.Count - q.Count)) + " of " + p.Count;
        }

        static string FirstParting(Episode x, Episode y)
        {
            var p = x.Decisions.Select(d => d.Line).ToList();
            var q = y.Decisions.Select(d => d.Line).ToList();
            for (var i = 0; i < Math.Min(p.Count, q.Count); i++)
                if (p[i] != q[i]) return "at decision " + (i + 1) + ": `" + p[i] + "` against `" + q[i] + "`.";
            return "they never part.";
        }

        static bool SameForMara(Episode x, Episode y)
        {
            var p = x.Hers.Select(d => d.Line + " | " + d.Feelings).ToList();
            var q = y.Hers.Select(d => d.Line + " | " + d.Feelings).ToList();
            return p.SequenceEqual(q);
        }

