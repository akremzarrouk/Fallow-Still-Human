            var db = HerDivergence(a, b);
            sb.AppendLine("| **Her own** decisions differing from **A**, lined up by minute | - | " + dc.Differing + " of " + dc.Total + ", the last at minute " + dc.Last + " | " + db.Differing + " of " + db.Total + ", the last at minute " + db.Last + " |");
