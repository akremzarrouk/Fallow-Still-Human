            sb.AppendLine("| Her next decision after that | " + string.Join(" | ", afterWatching.Select(m => m == null ? "-" : "m" + m.Minute + " " + m.Chosen + " for " + (m.Leading ?? "nothing"))) + " |");
            sb.AppendLine("| What she was feeling there | " + string.Join(" | ", afterWatching.Select(m => m == null ? "-" : (m.Feelings.Length == 0 ? "nothing" : m.Feelings))) + " |");
