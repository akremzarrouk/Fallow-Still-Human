    /// <summary>
    /// One small episode of a life, run in a live morning: Daniel goes through
    /// Mara's things while she is standing there, and half an hour later he
    /// watches her across the room. Both are put into the morning by the
    /// experiment (SETUP) through the existing `SilentMorning.Happen`, which
    /// reaches people by exactly the route their own acts reach each other.
    /// Everything between and after is whatever the simulation does.
    ///
    /// Three conditions on the same seed and the same random streams: she was
    /// there and saw it; the same thing happened and she did not perceive it;
    /// and it never happened. Nothing is scripted about what she does next: no
    /// rule names this memory, and no rule was added or changed for this
    /// experiment.
    ///
    /// Writes `Docs/experiments/episode/measurements.md`.
    /// </summary>
    public class EpisodeExperimentTests
    {
        const int Seeds = 10;
        const string Saw = "A: she saw it";
        const string Missed = "C: she did not see it";
        const string Never = "B: it never happened";
        static readonly string[] Conditions = { Saw, Missed, Never };

        /// <summary>The morning is 90 minutes; the two moments are looked for from here.</summary>
        const int IntrusionFrom = 8;
        const int EncounterFrom = 38;

        static Scenario001Content _content;
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        [OneTimeSetUp]
        public void Load() => _content = Baselines.Primary();

        [OneTimeTearDown]
        public void Write()
        {
