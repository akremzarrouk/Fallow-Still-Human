            sb.AppendLine("# One episode: measurements");
            sb.AppendLine();
            sb.AppendLine("Generated by `EpisodeExperimentTests` on the primary baseline. Two events are put into a live morning by the experiment; everything else is the simulation. The three conditions share a seed, and the random stream is forked per person and minute, so it cannot shift between them.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "experiments", "episode");
