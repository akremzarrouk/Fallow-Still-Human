        [Test]
        public void D1_WhatSurvivesADayBoundary()
        {
            // One person, one earlier event they read as something, then days pass.
            // What of it is still readable by the machinery that raises wants?
            var sb = new StringBuilder();
            sb.AppendLine("## 1. What survives a day boundary");
            sb.AppendLine();
            sb.AppendLine("One person is shown one event on day 1 that they read as a slight. Then days pass with nothing happening. At each later day their wants are raised exactly as a morning would raise them, and the three things that could carry the event are read off: the memory, the belief it moved, and the feeling it stirred.");
            sb.AppendLine();
            sb.AppendLine("| Day the wants are raised | Memory of it recalled (`find_out` memory term) | Belief `treats_me_like_a_child` | Strongest feeling left |");
            sb.AppendLine("|---|---|---|---|");

            for (var day = 1; day <= 4; day++)
            {
                var trace = new TraceLog();
                var sim = new Simulation(_content.Cast, _content.Rules, trace) { FadeOnEachEvent = false };
                sim.Apply(S17.WentThroughTheirThings("daniel", "elena", 1, new List<string> { "elena" }));
                for (var d = 1; d < day; d++) sim.PassTime(1.0);

                var mind = sim.Minds["elena"];
                var percept = Bench.Standing("elena", present: new List<string> { "daniel" });
                var motives = new Motivator(_content.Rules).Raise(mind, percept, day, trace, 0);
                var findOut = motives.FirstOrDefault(m => m.Name == "find_out");
                var memoryTerm = findOut?.Terms
                    .Where(t => t.Kind == ScalerKind.Memory)
                    .Sum(t => t.Amount) ?? 0.0;
                var strongest = mind.Emotions.Live.OrderByDescending(e => e.Intensity).FirstOrDefault();

                sb.AppendLine("| " + day + (day == 1 ? " (the same day)" : "") + " | " + S17.F(memoryTerm) + " | " +
                              S17.F(mind.Beliefs.Confidence("tendency", new[] { "daniel", "treats_me_like_a_child" })) + " | " +
                              (strongest == null ? "nothing" : strongest.Type + " " + S17.F(strongest.Intensity)) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("A memory scaler only ever looks at the day being lived (`ScalerEval.Recall` filters on `x.Day == ctx.Today`), so a memory of an earlier day is kept and is never read by anything that raises a want. Feelings fade. **A belief is the only thing that crosses midnight with its strength intact**, and nothing anywhere decays one.");
            Record("1", sb.ToString());
        }

