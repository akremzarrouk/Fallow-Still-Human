        [Test]
        public void D2_TheLedgerIsAlmostEntirelyWriteOnly()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. The ledger is almost entirely write-only");
            sb.AppendLine();

            var written = new Dictionary<string, int>(StringComparer.Ordinal);
            var events = _content.Backstory.Events.ToList();
            if (_content.Morning.Opening != null) events.Add(_content.Morning.Opening);
            foreach (var v in _content.Morning.Variants.Concat(_content.Morning.HeldOutVariants)) events.AddRange(v.NightEvents);
            foreach (var e in events)
            foreach (var f in e.LedgerEffects)
            {
                written.TryGetValue(f.Entry, out var n);
                written[f.Entry] = n + 1;
            }

            var read = new HashSet<string>(StringComparer.Ordinal);
            foreach (var s in _content.Rules.Interpretation.SelectMany(r => r.ScaledBy)
                         .Concat(_content.Rules.Appraisal.SelectMany(r => r.ScaledBy))
                         .Concat(_content.Rules.BeliefNudges.SelectMany(r => r.ScaledBy))
                         .Concat(_content.Rules.Motivation.SelectMany(r => r.ScaledBy ?? new List<Scaler>()))
                         .Concat(_content.Rules.Costs.SelectMany(r => r.ScaledBy ?? new List<Scaler>())))
                if (s.Kind == ScalerKind.Ledger && s.Entry != null) read.Add(s.Entry);

            sb.AppendLine("| Ledger entry | Written by the scenario data | Read by any rule |");
            sb.AppendLine("|---|---|---|");
            foreach (var entry in _content.Vocabulary.LedgerEntries.OrderBy(e => e, StringComparer.Ordinal))
            {
                written.TryGetValue(entry, out var n);
                sb.AppendLine("| `" + entry + "` | " + (n == 0 ? "never" : n + " times") + " | " + (read.Contains(entry) ? "yes" : "**no**") + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Every one of those writes is an authored `ledger_effects` block on a hand-written event. **No rule anywhere produces a ledger entry from what an event meant**, so the record of what somebody did to somebody else is authored rather than simulated. " +
                          read.Count + " of " + _content.Vocabulary.LedgerEntries.Count + " entry kinds are read by anything at all.");
            Record("2", sb.ToString());

            Assert.IsFalse(read.Contains("searched_my_things"),
                "if this starts failing, going through somebody's things has become readable and the S1.7 argument should be revisited");
        }

