        [Test]
        public void D3_WhichBeliefsAreLearnableAndWhatReadsThemBack()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 3. Which beliefs are learnable, and what reads them back");
            sb.AppendLine();
            sb.AppendLine("A belief matters longitudinally only if something can write it from experience and something else reads it later. The two columns are what make a loop.");
            sb.AppendLine();
            sb.AppendLine("| Belief | Written from experience by | Read by interpretation | Read by motivation |");
            sb.AppendLine("|---|---|---|---|");

            var predicates = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var r in _content.Rules.BeliefNudges) predicates.Add(r.Predicate);
            foreach (var s in _content.Rules.Interpretation.SelectMany(r => r.ScaledBy).Where(s => s.Kind == ScalerKind.Belief)) predicates.Add(s.Predicate);
            foreach (var s in _content.Rules.Motivation.SelectMany(r => r.ScaledBy ?? new List<Scaler>()).Where(s => s.Kind == ScalerKind.Belief)) predicates.Add(s.Predicate);

            foreach (var p in predicates)
            {
                var writes = _content.Rules.BeliefNudges.Where(r => r.Predicate == p).Select(r => "`" + r.Id + "`").ToList();
                var interp = _content.Rules.Interpretation
                    .Where(r => r.ScaledBy.Any(s => s.Kind == ScalerKind.Belief && s.Predicate == p))
                    .Select(r => "`" + r.Id + "` -> " + r.Label).ToList();
                var motiv = _content.Rules.Motivation
                    .Where(r => (r.ScaledBy ?? new List<Scaler>()).Any(s => s.Kind == ScalerKind.Belief && s.Predicate == p))
                    .Select(r => "`" + r.Motive + "`").ToList();
                sb.AppendLine("| `" + p + "` | " + (writes.Count == 0 ? "**nothing**" : string.Join(", ", writes)) + " | " +
                              (interp.Count == 0 ? "-" : string.Join("; ", interp)) + " | " +
                              (motiv.Count == 0 ? "-" : string.Join(", ", motiv)) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Two shapes, and they behave nothing like each other. A belief read by a **motivation** rule moves a want directly, by any amount, at once. A belief read only by **interpretation** rules can only change what a later event comes to mean, and section 4 shows what that costs.");
            Record("3", sb.ToString());
        }

