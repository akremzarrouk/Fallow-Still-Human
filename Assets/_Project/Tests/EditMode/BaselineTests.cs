        [Test]
        public void B3_ModelBRaisesNoWantFromTraitsAndValuesAlone()
        {
            // A bench: each member of the cast, with their own traits and values
            // and nothing else. Nothing has happened to them, they believe
            // nothing, they are not hungry, and they are standing in a kitchen
            // with food in it, alone, and then with somebody.
            var sb = new StringBuilder();
            sb.AppendLine("## 3. No want from traits and values alone");
            sb.AppendLine();
            sb.AppendLine("**On the bench.** Each member of the cast with their own traits and values and nothing else: no memory, no belief, no feeling, not hungry, in a kitchen with food, alone and then with one other person.");
            sb.AppendLine();
            sb.AppendLine("| Person | Model A, alone | Model A, with somebody | Primary, alone | Primary, with somebody |");
            sb.AppendLine("|---|---|---|---|---|");

            var totalA = 0;
            foreach (var who in _primary.Cast.Keys.OrderBy(k => k, StringComparer.Ordinal))
            {
                var p = _primary.Cast[who];
                var bare = new Mind(new Profile(p.Id, p.DisplayName, p.Age, p.FamilyRole,
                    p.Traits, p.Values, p.Perceptiveness, new Dictionary<string, double>(), new List<BeliefSeed>()));
                var other = _primary.Cast.Keys.First(k => k != who);
                var alone = Bench.Standing(who);
                var company = Bench.Standing(who, present: new List<string> { other });

                string Wants(Scenario001Content c, Percept at)
                {
                    var ms = new Motivator(c.Rules).Raise(bare, at, _primary.Morning.Day, new TraceLog(), 0);
                    return ms.Count == 0 ? "nothing" : string.Join(", ", ms.Select(m => m.Key + " " + F(m.Urgency)));
                }

                var inA = new Motivator(_modelA.Rules).Raise(bare, company, _primary.Morning.Day, new TraceLog(), 0);
                totalA += inA.Count;
                Assert.IsEmpty(new Motivator(_primary.Rules).Raise(bare, alone, _primary.Morning.Day, new TraceLog(), 0), who + " alone");
                Assert.IsEmpty(new Motivator(_primary.Rules).Raise(bare, company, _primary.Morning.Day, new TraceLog(), 0), who + " with " + other);

                sb.AppendLine("| " + who + " | " + Wants(_modelA, alone) + " | " + Wants(_modelA, company) + " | " + Wants(_primary, alone) + " | " + Wants(_primary, company) + " |");
            }
            Assert.Greater(totalA, 0, "Model A does raise wants from traits and values alone, which is the difference");

            // In real mornings: every want the primary baseline raises has
            // something other than a trait or a value behind it.
            var wants = 0;
            var onDispositionsAlone = 0;
            var unsupported = 0;
            var unsupportedA = 0;
            var wantsA = 0;
            foreach (var (c, isA) in new[] { (_primary, false), (_modelA, true) })
            foreach (var v in Design)
            {
                var run = Scenario001.Prepare(c, v, 1);
                run.Morning.Decided = m =>
                {
                    foreach (var w in m.Motives)
                    {
                        var behind = w.Terms.Where(t => t.Amount > 0.0).ToList();
                        var onlyDispositions = behind.Count > 0 && behind.All(t => MotivationSources.SourceOf(t) == Source.Disposition);
                        var support = MotivationSources.Of(w).Class;
                        if (isA)
                        {
                            wantsA++;
                            if (support == Support.Unsupported) unsupportedA++;
                        }
                        else
                        {
                            wants++;
                            if (onlyDispositions) onDispositionsAlone++;
                            if (support == Support.Unsupported) unsupported++;
                        }
                    }
                };
                run.Morning.Run(c.Morning.Minutes);
            }
            Assert.AreEqual(0, onDispositionsAlone, "a want on traits and values alone");

            sb.AppendLine();
            sb.AppendLine("**In real mornings** (the five design conditions, seed 1): of " + wants + " wants the primary baseline raised, **" + onDispositionsAlone + "** rest on traits and values alone, and " + unsupported +
                          " (" + (100.0 * unsupported / Math.Max(1, wants)).ToString("0.0", CultureInfo.InvariantCulture) + " %) have nothing that happened behind them (a belief written into the character file, such as Daniel's that he leads, is the rest). Model A on the same mornings: " +
                          unsupportedA + " of " + wantsA + " (" + (100.0 * unsupportedA / Math.Max(1, wantsA)).ToString("0.0", CultureInfo.InvariantCulture) + " %).");
            Record("3", sb.ToString());
        }

