        [Test]
        public void B5_TheLivedDayIsNotRememberedAsTimeless()
        {
            // Nobody, at the end of any morning, holds a memory of the lived day
            // with no minute on it: S1.6's stale memory cannot come back through
            // the scripted events.
            var untimedB = 0;
            var untimedA = 0;
            foreach (var v in Design)
            {
                var b = Scenario001.Run(_primary, v, 1);
                var a = Scenario001.Run(_modelA, v, 1);
                untimedB += b.Minds.Values.Sum(m => m.Experiences.Count(x => x.Day == _primary.Morning.Day && x.Minute < 0));
                untimedA += a.Minds.Values.Sum(m => m.Experiences.Count(x => x.Day == _primary.Morning.Day && x.Minute < 0));
            }
            Assert.AreEqual(0, untimedB, "a memory of the lived day with no minute");
            Assert.Greater(untimedA, 0, "Model A keeps them untimed, which is the difference");

            // And so a want resting on them fades: Leo's wish to find out, over
            // the morning, first ten minutes against the last ten (S1.6 P3).
            (double first, double last) FindOut(Scenario001Content c)
            {
                double f = 0, l = 0; int nf = 0, nl = 0;
                for (ulong seed = 1; seed <= 10; seed++)
                {
                    var run = Scenario001.Prepare(c, "daniel_ate_it", seed);
                    run.Morning.Decided = m =>
                    {
                        if (m.CharacterId != "leo") return;
                        var u = m.Motives.FirstOrDefault(x => x.Name == "find_out")?.Urgency ?? 0.0;
                        if (m.Minute < 10) { f += u; nf++; }
                        if (m.Minute >= c.Morning.Minutes - 10) { l += u; nl++; }
                    };
                    run.Morning.Run(c.Morning.Minutes);
                }
                return (f / Math.Max(1, nf), l / Math.Max(1, nl));
            }

            var inB = FindOut(_primary);
            var inAWithRespond = FindOut(S15.Mode(_modelA, DispositionMode.Respond));
            Assert.Less(inB.last, 0.5 * inB.first, "Leo's wish to find out fades over the morning");

            var sb = new StringBuilder();
            sb.AppendLine("## 5. The stale memory is not reintroduced");
            sb.AppendLine();
            sb.AppendLine("Memories of the lived day with no minute, held by anybody at the end of the five design mornings (seed 1): Model A **" + untimedA + "**, primary **" + untimedB + "**.");
            sb.AppendLine();
            sb.AppendLine("Leo's wish to find out, mean urgency over his decisions, first ten minutes against the last ten (`daniel_ate_it`, seeds 1-10): primary " + F(inB.first) + " -> " + F(inB.last) +
                          "; the same dispositions with the events untimed (S1.6's B) " + F(inAWithRespond.first) + " -> " + F(inAWithRespond.last) + ". S1.6 reported 0.38 -> 0.09 under M1 on its design seeds.");
            Record("5", sb.ToString());
        }

