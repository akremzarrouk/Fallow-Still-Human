        [Test]
        public void B2_ModelAIsStillThereAndDiffersInExactlyThoseThreeThings()
        {
            // Printed first, and for the raw load too: run on the data as it was
            // committed before the change, the raw load is Model A, and that is
            // where the constant above came from.
            var fingerprint = Fingerprint(_modelA, 3);
            TestContext.WriteLine("fingerprint of Model A as selected: " + fingerprint);
            TestContext.WriteLine("fingerprint of the data as loaded: " + Fingerprint(_primary, 3));

            Assert.AreEqual(DispositionMode.Standing, _modelA.Rules.Deciding.Dispositions);
            Assert.AreEqual(MeansMode.Want, _modelA.Rules.Deciding.Means);
            foreach (var e in LivedDayScript(_modelA)) Assert.AreEqual(-1, e.Minute, e.Id + " is untimed in Model A");

            // Everything else about the two is the same object or the same value.
            var a = _modelA.Rules.Deciding;
            var b = _primary.Rules.Deciding;
            Assert.AreEqual(b.AmbiguityBand, a.AmbiguityBand);
            Assert.AreEqual(b.InterruptIntensity, a.InterruptIntensity);
            Assert.AreEqual(b.VisibleDistress, a.VisibleDistress);
            Assert.AreEqual(b.HungerPerMinute, a.HungerPerMinute);
            Assert.AreEqual(b.PortionRelief, a.PortionRelief);
            Assert.AreEqual(b.LowPortions, a.LowPortions);
            Assert.AreEqual(b.ComfortSettling, a.ComfortSettling);
            Assert.AreEqual(b.UrgencyKnee, a.UrgencyKnee);
            Assert.AreEqual(b.RecallHalfLife, a.RecallHalfLife);
            Assert.AreEqual(b.WatchingGoesStaleAfter, a.WatchingGoesStaleAfter);
            Assert.AreSame(b.ActionMinutes, a.ActionMinutes);
            Assert.AreSame(b.DistressShows, a.DistressShows);
            Assert.AreSame(b.ComfortSettles, a.ComfortSettles);
            Assert.AreSame(_primary.Rules.Motivation, _modelA.Rules.Motivation);
            Assert.AreSame(_primary.Rules.Proposals, _modelA.Rules.Proposals);
            Assert.AreSame(_primary.Rules.Costs, _modelA.Rules.Costs);
            Assert.AreSame(_primary.Rules.Interpretation, _modelA.Rules.Interpretation);
            Assert.AreSame(_primary.Rules.Appraisal, _modelA.Rules.Appraisal);
            Assert.AreSame(_primary.Cast, _modelA.Cast);
            Assert.AreEqual(_primary.Backstory.Events.Count, _modelA.Backstory.Events.Count);
            for (var i = 0; i < _primary.Backstory.Events.Count; i++)
            {
                var p = _primary.Backstory.Events[i];
                var q = _modelA.Backstory.Events[i];
                Assert.AreEqual(p.Id, q.Id);
                if (p.Day != _primary.Morning.Day) Assert.AreSame(p, q, p.Id + " is not on the lived day and is untouched");
            }

            // Model A can be run, and it is its own runtime rather than a label.
            var ranA = Scenario001.Run(_modelA, "daniel_ate_it", 1);
