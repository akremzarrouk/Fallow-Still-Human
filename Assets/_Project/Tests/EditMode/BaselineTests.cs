            sb.AppendLine();
            sb.AppendLine("Generated by `BaselineTests`. The primary experimental baseline is the shipped data: Model B (`dispositions: respond`) with both S1.6 fixes (`means: end`, and `minute: 0` on the four scripted events of the lived day). Model A is selected by `Baselines.ModelA()`, which restores the three settings the data had before, and nothing else.");
