            CollectionAssert.AreNotEqual(
                ranA.Result.Actions.Select(x => x.ToString()).ToArray(),
                ranB.Result.Actions.Select(x => x.ToString()).ToArray());

            // And it is the runtime that shipped before the change, decision for decision.
            Assert.AreEqual(ModelAFingerprintBeforeTheChange, fingerprint,
                "Model A as selected runs every decision of 15 mornings exactly as the data committed before the change did");

            var sb = new StringBuilder();
            sb.AppendLine("## 2. Model A is still there");
            sb.AppendLine();
            sb.AppendLine("`Baselines.ModelA()` differs from the shipped content in the three settings above and nothing else: every other decision number, rule list, profile and event is the same object or the same value. It runs (" + ranA.Result.Actions.Count + " decisions on `daniel_ate_it` seed 1, against " + ranB.Result.Actions.Count + " under the primary baseline, and not the same ones).");
            sb.AppendLine();
            sb.AppendLine("**It is the runtime that shipped before the change, decision for decision.** Every decision of 15 mornings (the five design conditions, seeds 1-3: minute, person, act, room, leading want, urgency, resolution and margin) hashes to `" + fingerprint + "`, the value the same fingerprint took on the data as committed at `dd9065c`, loaded directly. Every test written before the change now selects Model A explicitly (34 fixtures), so every document they generate is expected to regenerate byte-identical.");
            Record("2", sb.ToString());
        }

        /// <summary>A hash of every decision in the design conditions, seeds 1..n.</summary>
        internal static string Fingerprint(Scenario001Content c, int seeds)
        {
            ulong h = 1469598103934665603UL;
            void Mix(string s)
            {
                foreach (var ch in s) { h ^= ch; h *= 1099511628211UL; }
                h ^= '\n'; h *= 1099511628211UL;
            }

            foreach (var v in c.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)seeds; seed++)
            {
                var run = Scenario001.Run(c, v, seed);
                foreach (var a in run.Result.Actions)
                    Mix(v + "/" + seed + " " + a + " | " + a.LeadingMotive + " " + a.LeadingUrgency.ToString("R", CultureInfo.InvariantCulture) +
                        " | " + a.Resolution + " " + a.Margin.ToString("R", CultureInfo.InvariantCulture));
            }
            return h.ToString("x16", CultureInfo.InvariantCulture);
        }

