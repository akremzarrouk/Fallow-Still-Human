        /// </summary>
        const string ModelAFingerprintBeforeTheChange = "3e544cc8f2be569d";

        static IReadOnlyList<string> Design => _primary.Morning.Variants.Select(v => v.Id).ToList();

        [OneTimeSetUp]
        public void Load()
        {
