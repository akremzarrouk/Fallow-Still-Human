        [Test, Timeout(1800000)]
        public void B4_TheMeansEndCheckIsActive()
        {
            var walksB = S16.Walks(_primary, Design, 1, 3);
            var walksA = S16.Walks(_modelA, Design, 1, 3);
            var pointlessB = walksB.Count(w => !w.Foreseen.WorthIt);
            var pointlessA = walksA.Count(w => !w.Foreseen.WorthIt);

            // Every walk credited to a want was foreseen worth it first, and the
            // deliberation says so; some walks are refused on the record.
            var credited = 0;
            var creditedAndForeseen = 0;
            var refusals = 0;
            string example = null;
            var run = Scenario001.Prepare(_primary, "daniel_ate_it", 1);
            run.Morning.Decided = m =>
            {
                var r = run.Trace.Get(m.Decision.TraceId);
                r.Data.TryGetValue("foresaw", out var foresaw);
                foreach (var walk in m.Decision.Ranked.Where(o => o.Option.Kind == ActionKind.GoTo && o.Appeal > 0.0))
                {
                    credited++;
                    if (foresaw != null && foresaw.Split(';').Any(s => s.Trim().StartsWith(walk.Option.Key + " for ", StringComparison.Ordinal)
                                                                        && !s.Contains("not worth walking for") && !s.Contains("nothing there serves it")))
                        creditedAndForeseen++;
                }
                if (foresaw != null && foresaw.Contains("not worth walking for"))
                {
                    refusals++;
                    example = example ?? m.CharacterId + " at minute " + m.Minute + ": " + foresaw.Split(';').First(s => s.Contains("not worth walking for")).Trim();
                }
            };
            run.Morning.Run(_primary.Morning.Minutes);
            var runA = Scenario001.Run(_modelA, "daniel_ate_it", 1);
            var foresightInA = runA.Result.Actions.Count(a => runA.Trace.Get(a.DecisionTraceId).Data.ContainsKey("foresaw"));

            Assert.AreEqual(0, pointlessB, "no walk is set out on whose end was foreseeably not worth doing");
            Assert.Greater(pointlessA, 0, "Model A does set out on such walks, which is the difference");
            Assert.Greater(credited, 0);
            Assert.AreEqual(credited, creditedAndForeseen, "every walk credited to a want was foreseen worth doing, on the record");
            Assert.Greater(refusals, 0, "some walk was refused credit because its end was not worth it");
            Assert.AreEqual(0, foresightInA, "Model A weighs no walk by its end");

            var sb = new StringBuilder();
            sb.AppendLine("## 4. The means-end check is active");
            sb.AppendLine();
            sb.AppendLine("Measured with S1.6's foresight instrument (`S16.Walks`), which imagines the destination from what the walker knows and weighs it with the deliberator itself, on the five design conditions, seeds 1-3.");
            sb.AppendLine();
            sb.AppendLine("| | Model A | Primary |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Walks set out on | " + walksA.Count + " | " + walksB.Count + " |");
            sb.AppendLine("| ... whose end was foreseeably not worth doing | " + pointlessA + " | **" + pointlessB + "** |");
            sb.AppendLine("| ... given up on arrival | " + walksA.Count(w => w.Lapsed) + " | " + walksB.Count(w => w.Lapsed) + " |");
            sb.AppendLine("| ... given up with somebody in the room | " + walksA.Count(w => w.Lapsed && w.PresentOnArrival > 0) + " | " + walksB.Count(w => w.Lapsed && w.PresentOnArrival > 0) + " |");
            sb.AppendLine("| Walks credited to a want, and foreseen worth it on the record (daniel_ate_it seed 1) | no foresight recorded (" + foresightInA + " decisions) | " + creditedAndForeseen + " of " + credited + " |");
            sb.AppendLine("| Decisions refusing a walk credit because its end was not worth it (same morning) | - | " + refusals + " |");
            sb.AppendLine();
            if (example != null) sb.AppendLine("A walk refused on the record: `" + example + "`.");
            Record("4", sb.ToString());
        }

