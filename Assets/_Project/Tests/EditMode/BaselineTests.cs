        [Test, Timeout(1800000)]
        public void B6_ThePrimaryBaselineIsS16sBothFixesDecisionForDecision()
        {
            // S1.6 measured its recommendation as a condition built in code from
            // the content (`B timed end`). The shipped data is now that condition.
            // Built from Model A, the way S1.6 built it, it must run every
            // decision of every morning exactly as the shipped data does.
            var s16 = S16.Conditions.Single(x => x.Label == "B timed end").Make(_modelA);
            var mornings = 0;
            var decisions = 0;
            foreach (var v in Design)
            for (ulong seed = 1; seed <= 5; seed++)
            {
                var shipped = Scenario001.Run(_primary, v, seed);
                var built = Scenario001.Run(s16, v, seed);
                string Line(ActionRecord a) => a + " | " + a.LeadingMotive + " " + a.LeadingUrgency.ToString("R", CultureInfo.InvariantCulture) +
                                              " | " + a.Resolution + " " + a.Margin.ToString("R", CultureInfo.InvariantCulture);
                CollectionAssert.AreEqual(
                    built.Result.Actions.Select(Line).ToArray(),
                    shipped.Result.Actions.Select(Line).ToArray(), v + " seed " + seed);
                Assert.AreEqual(built.World.Portions, shipped.World.Portions);
                mornings++;
                decisions += shipped.Result.Actions.Count;
            }

            // Same seed, same morning.
            var again = Scenario001.Run(_primary, "daniel_ate_it", 11);
            var once = Scenario001.Run(_primary, "daniel_ate_it", 11);
            CollectionAssert.AreEqual(once.Result.Actions.Select(x => x.ToString()).ToArray(), again.Result.Actions.Select(x => x.ToString()).ToArray());

            var sb = new StringBuilder();
            sb.AppendLine("## 6. S1.6's behaviour is reproduced exactly");
            sb.AppendLine();
            sb.AppendLine("S1.6 measured its recommendation as a condition built in code, `B timed end` (`S16.Conditions`). Built from Model A the way S1.6 built it, it runs **every decision of " + mornings + " mornings (" + decisions + " decisions) identically** to the shipped data: the same act, minute, room, leading want and urgency, resolution and margin to the last bit, and the same portions left. The same seed gives the same morning. S1.6's own experiment and held-out tests go on building their six conditions from Model A, so their documents and numbers are unchanged.");
            Record("6", sb.ToString());
        }
