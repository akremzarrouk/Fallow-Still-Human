        static void Compare(Tally t, Outcome was, Outcome now, bool exposed, string intent, int compatible)
        {
            if (now.Candidates != compatible) t.CandidateMismatch++;
            if (now.Scored.Suspicious > was.Scored.Suspicious) t.Suspicious++;
            if (was.Token == now.Token) return;
            t.Changed++;
            if (now.Recognised <= was.Recognised && now.Scored.Suspicious <= was.Scored.Suspicious) t.ChangedUnflagged++;
            if (intent != null && now.Winner == intent) t.Toward++;
            else if (intent != null && was.Winner == intent) t.Away++;
            if (!exposed) t.Outside++;
        }

