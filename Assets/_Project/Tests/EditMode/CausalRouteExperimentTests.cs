        static bool Same(double a, double b) => Math.Abs(a - b) < 1e-12;

        static Statement Strongest(IEnumerable<Statement> xs)
            => xs.OrderByDescending(x => Math.Abs(x.Coef)).ThenByDescending(x => x.Coef).First();

        static void Count(Scored sc, string intent, string key, double amount)
        {
            if (!sc.Counted.TryGetValue(intent, out var m)) sc.Counted[intent] = m = new Dictionary<string, double>(StringComparer.Ordinal);
            m.TryGetValue(key, out var v);
            m[key] = v + amount;
        }

        static string Content(IEnumerable<Statement> xs)
            => string.Join(";", xs.OrderBy(x => x.Key, StringComparer.Ordinal).Select(x => x.Key + ":" + x.Coef.ToString("R", CultureInfo.InvariantCulture)));

        static Scored Score(Rep rep, Staged s, Declared d)
        {
            var sc = new Scored();
            string Canon(string route) => route != null && d.Rename.TryGetValue(route, out var r) ? r : route;
            switch (rep)
            {
                case Rep.A:
                {
                    var parts = new Dictionary<string, List<string>>(StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    {
                        if (r.Weight <= 0.0) continue;
                        var i = r.R.C.Intent;
                        if (!sc.Score.ContainsKey(i)) { sc.Score[i] = 0.0; sc.Candidates.Add(i); parts[i] = new List<string>(); }
                        sc.Score[i] += r.Weight;
                        parts[i].Add(r.Gate + "{" + Content(r.Statements) + "}=" + F9(r.Weight));
                        foreach (var st in r.Statements) Count(sc, i, st.Key, st.Amount);
                    }
                    foreach (var kv in parts) sc.Trace[kv.Key] = string.Join(" + ", kv.Value.OrderBy(x => x, StringComparer.Ordinal));
                    break;
                }

                case Rep.B:
                case Rep.G:
                {
                    var stated = s.Compatible.ToDictionary(i => i, i => new Dictionary<string, List<Statement>>(StringComparer.Ordinal), StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    foreach (var st in r.Statements)
                    {
                        var byKey = stated[r.R.C.Intent];
                        if (!byKey.TryGetValue(st.Key, out var list)) { byKey[st.Key] = new List<Statement> { st }; continue; }
                        if (list.Any(x => Same(x.Coef, st.Coef))) { sc.Restated++; continue; }
                        sc.Conflicts++;
                        list.Add(st);
                    }
                    var kept = stated.ToDictionary(kv => kv.Key, kv => kv.Value.ToDictionary(x => x.Key, x => Strongest(x.Value), StringComparer.Ordinal), StringComparer.Ordinal);
                    if (rep == Rep.G)
                    {
                        // The negative control: each fact is given to one intention only,
                        // the one that states it most strongly.
                        var keys = kept.Values.SelectMany(m => m.Keys).Where(k => !k.StartsWith(CircumstancePrefix, StringComparison.Ordinal)).Distinct().ToList();
                        foreach (var key in keys)
                        {
                            var holders = kept.Where(kv => kv.Value.ContainsKey(key)).ToList();
                            if (holders.Count < 2) continue;
                            var owner = holders.OrderByDescending(h => Math.Abs(h.Value[key].Coef)).ThenBy(h => h.Key, StringComparer.Ordinal).First().Key;
                            foreach (var h in holders.Where(h => h.Key != owner)) h.Value.Remove(key);
                        }
                    }
                    foreach (var i in s.Compatible)
                    {
                        sc.Candidates.Add(i);
                        var total = 0.0;
                        foreach (var kv in kept[i].OrderBy(x => x.Key, StringComparer.Ordinal)) { total += kv.Value.Amount; Count(sc, i, kv.Key, kv.Value.Amount); }
                        sc.Score[i] = total;
                        sc.Trace[i] = string.Join(";", kept[i].OrderBy(x => x.Key, StringComparer.Ordinal).Select(x => x.Key + "=" + F9(x.Value.Amount)));
                    }
                    break;
                }

                case Rep.C:
                {
                    var reasons = s.Compatible.ToDictionary(i => i, i => new Dictionary<string, List<RuleEval>>(StringComparer.Ordinal), StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    {
                        var bySig = reasons[r.R.C.Intent];
                        if (!bySig.TryGetValue(r.Signature, out var list)) bySig[r.Signature] = list = new List<RuleEval>();
                        list.Add(r);
                    }
                    foreach (var i in s.Compatible)
                    {
                        sc.Candidates.Add(i);
                        var total = 0.0;
                        var parts = new List<string>();
                        foreach (var kv in reasons[i].OrderBy(x => x.Key, StringComparer.Ordinal))
                        {
                            var vectors = kv.Value.Select(Vector).ToList();
                            var chosen = vectors[0];
                            if (vectors.Count > 1)
                            {
                                var canon = vectors.Select(v => string.Join(";", v.OrderBy(x => x.Key, StringComparer.Ordinal).Select(x => x.Key + "=" + x.Value.Item1.ToString("R", CultureInfo.InvariantCulture)))).ToList();
                                if (canon.All(x => x == canon[0])) sc.Restated += vectors.Count - 1;
                                else sc.Conflicts += vectors.Count - 1;
                                chosen = new Dictionary<string, Tuple<double, double>>(StringComparer.Ordinal);
                                foreach (var key in vectors.SelectMany(v => v.Keys).Distinct())
                                    chosen[key] = vectors.Where(v => v.ContainsKey(key)).Select(v => v[key]).OrderByDescending(t => Math.Abs(t.Item1)).ThenByDescending(t => t.Item1).First();
                            }
                            var reasonTotal = 0.0;
                            foreach (var st in chosen.OrderBy(x => x.Key, StringComparer.Ordinal)) { reasonTotal += st.Value.Item2; Count(sc, i, st.Key, st.Value.Item2); }
                            total += reasonTotal;
                            parts.Add(kv.Key + "=" + F9(reasonTotal));
                        }
                        sc.Score[i] = total;
                        sc.Trace[i] = string.Join(" + ", parts);
                    }
                    break;
                }

                default:
                {
                    // D: per intention, per declared route, per piece of evidence. The same
                    // statement again within a route counts once; a different strength for
                    // the same fact within a route is a conflict, flagged. Different routes
                    // keep their own statements. Routes combine by their declared relation.
                    var stated = s.Compatible.ToDictionary(i => i, i => new Dictionary<string, Dictionary<string, List<Statement>>>(StringComparer.Ordinal), StringComparer.Ordinal);
                    foreach (var r in s.Rules)
                    foreach (var st in r.Statements)
                    {
                        if (st.RuleId == null || st.Route == null) sc.ProvenanceGaps++;
                        if ((st.Role == "driver" && st.Coef < 0.0) || (st.Role == "inhibitor" && st.Coef > 0.0)) sc.RoleMismatch++;
                        var byRoute = stated[r.R.C.Intent];
                        if (!byRoute.TryGetValue(st.Route, out var byKey)) byRoute[st.Route] = byKey = new Dictionary<string, List<Statement>>(StringComparer.Ordinal);
                        if (!byKey.TryGetValue(st.Key, out var list)) { byKey[st.Key] = new List<Statement> { st }; continue; }
                        if (list.Any(x => Same(x.Coef, st.Coef))) { sc.Restated++; continue; }
                        sc.Conflicts++;
                        list.Add(st);
                    }
                    foreach (var i in s.Compatible)
                    {
                        sc.Candidates.Add(i);
                        var totals = new Dictionary<string, double>(StringComparer.Ordinal);
                        var contents = new Dictionary<string, string>(StringComparer.Ordinal);
                        var parts = new List<string>();
                        foreach (var route in stated[i].OrderBy(x => x.Key, StringComparer.Ordinal))
                        {
                            var kept = route.Value.ToDictionary(x => x.Key, x => Strongest(x.Value), StringComparer.Ordinal);
                            var inactive = rep == Rep.DEnablers && kept.Values.Any(x => x.Role == "enabler" && x.Amount == 0.0);
                            if (inactive) sc.InactiveRoutes++;
                            var total = 0.0;
                            foreach (var kv in kept.OrderBy(x => x.Key, StringComparer.Ordinal))
                            {
                                var amount = inactive ? 0.0 : kv.Value.Amount;
                                total += amount;
                                Count(sc, i, kv.Key, amount);
                            }
                            totals[route.Key] = total;
                            contents[route.Key] = Content(kept.Values);
                            parts.Add(Canon(route.Key) + "{" + string.Join(";", kept.OrderBy(x => x.Key, StringComparer.Ordinal)
                                .Select(x => x.Key + "=" + F9(inactive ? 0.0 : x.Value.Amount))) + "}");
                        }
                        // Two different routes for one intention that state exactly the same
                        // evidence at exactly the same strengths: not merged, flagged.
                        var routeList = contents.Keys.ToList();
                        for (var a = 0; a < routeList.Count; a++)
                            for (var b = a + 1; b < routeList.Count; b++)
                                if (contents[routeList[a]] == contents[routeList[b]]) sc.Suspicious++;
                        var alternatives = rep == Rep.DAlt || d.Alternatives.Count > 0 ? d.Alternatives : new List<List<string>>();
                        var inGroup = new HashSet<string>(alternatives.SelectMany(g => g), StringComparer.Ordinal);
                        var score = 0.0;
                        foreach (var kv in totals.OrderBy(x => x.Key, StringComparer.Ordinal))
                            if (!inGroup.Contains(kv.Key)) score += kv.Value;
                        foreach (var g in alternatives)
                        {
                            var present = g.Where(totals.ContainsKey).ToList();
                            if (present.Count > 0) score += present.Max(r => totals[r]);
                        }
                        sc.Score[i] = score;
                        sc.RouteTotals[i] = totals.ToDictionary(kv => Canon(kv.Key), kv => kv.Value, StringComparer.Ordinal);
                        sc.Trace[i] = string.Join(" + ", parts.OrderBy(x => x, StringComparer.Ordinal));
                    }
                    break;
                }
            }
            return sc;
        }

        static Dictionary<string, Tuple<double, double>> Vector(RuleEval r)
        {
            var v = new Dictionary<string, Tuple<double, double>>(StringComparer.Ordinal);
            foreach (var st in r.Statements)
                v[st.Key] = v.TryGetValue(st.Key, out var t) ? Tuple.Create(t.Item1 + st.Coef, t.Item2 + st.Amount) : Tuple.Create(st.Coef, st.Amount);
            return v;
        }

        sealed class Outcome
        {
            public string Token;
            public string Winner;
            public bool Tie;
            public string Second;
            public double TopScore;
            public double SecondScore;
            public int Candidates;
            public Scored Scored;
            public string Trace;

            public int Recognised => Scored.Restated + Scored.Conflicts;
            public double Margin => Second == null ? double.PositiveInfinity : TopScore - SecondScore;
            public double Support(string intent) => Scored.Score.TryGetValue(intent, out var v) ? v : double.NaN;
        }

        static bool Beats(double s1, string n1, double s2, string n2)
            => s1 > s2 || (s1 == s2 && string.CompareOrdinal(n1, n2) < 0);

        static Outcome Decide(Rep rep, Staged s, Declared d, Func<string, string> unrename = null)
        {
            var sc = Score(rep, s, d);
            string N(string x) => unrename == null ? x : unrename(x);
            var o = new Outcome
            {
                Candidates = sc.Candidates.Count, Scored = sc,
                Trace = string.Join(" | ", sc.Trace.OrderBy(kv => N(kv.Key), StringComparer.Ordinal).Select(kv => N(kv.Key) + ": " + kv.Value))
            };
            if (sc.Candidates.Count == 0) { o.Token = "none"; return o; }
            if (rep == Rep.A)
            {
                string best = null, second = null;
                double b = 0, sd = 0;
                foreach (var i in sc.Candidates)
                {
                    var v = sc.Score[i];
                    if (best == null || Beats(v, i, b, best)) { second = best; sd = b; best = i; b = v; }
                    else if (second == null || Beats(v, i, sd, second)) { second = i; sd = v; }
                }
                o.Winner = N(best);
                o.Token = o.Winner;
                o.TopScore = b;
                o.Second = second == null ? null : N(second);
                o.SecondScore = sd;
                return o;
            }
            var top = sc.Candidates.Max(i => sc.Score[i]);
            var tied = sc.Candidates.Where(i => sc.Score[i] >= top - Tie).Select(N).OrderBy(x => x, StringComparer.Ordinal).ToList();
            var rest = sc.Candidates.Where(i => sc.Score[i] < top - Tie).OrderByDescending(i => sc.Score[i]).ThenBy(N, StringComparer.Ordinal).ToList();
            o.TopScore = top;
            if (tied.Count > 1)
            {
                o.Tie = true;
                o.Token = "tie(" + string.Join("=", tied) + ")";
                o.Second = tied[1];
                o.SecondScore = top;
            }
            else
            {
                o.Winner = tied[0];
                o.Token = o.Winner;
                if (rest.Count > 0) { o.Second = N(rest[0]); o.SecondScore = sc.Score[rest[0]]; }
            }
            return o;
        }

        static Outcome[] DecideAll(Staged s, Declared d, IReadOnlyList<Rep> reps, Func<string, string> unrename = null)
            => reps.Select(r => Decide(r, s, d, unrename)).ToArray();

        /// <summary>D's why at the level of routes: the winner's routes, strongest first.</summary>
        static string LeadRoute(Outcome o)
            => o.Winner == null || !o.Scored.RouteTotals.TryGetValue(o.Winner, out var t) || t.Count == 0
                ? "none" : t.OrderByDescending(kv => kv.Value).ThenBy(kv => kv.Key, StringComparer.Ordinal).First().Key;

        static bool SameSupport(Outcome x, Outcome y)
        {
            Dictionary<string, double> Of(Outcome o) =>
                o.Winner != null && o.Scored.Counted.TryGetValue(o.Winner, out var m)
                    ? m.Where(kv => !kv.Key.StartsWith(CircumstancePrefix, StringComparison.Ordinal)).ToDictionary(kv => kv.Key, kv => kv.Value)
                    : new Dictionary<string, double>();
            var a = Of(x);
            var b = Of(y);
            return a.Keys.Union(b.Keys).All(k => Math.Abs((a.TryGetValue(k, out var u) ? u : 0.0) - (b.TryGetValue(k, out var v) ? v : 0.0)) <= 1e-9);
        }

