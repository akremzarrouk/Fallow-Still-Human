        static Declared FrozenDeclared()
        {
            if (_frozenDeclared != null) return _frozenDeclared;
            _frozenRouteOf = new Dictionary<string, string>(StringComparer.Ordinal);
            _frozenMeans = new Dictionary<string, string>(StringComparer.Ordinal);
            var roles = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
            foreach (var r in (JArray)_routesJson["frozen"]["routes"])
            {
                var id = r["rule"].Value<string>();
                _frozenRouteOf[id] = r["route"].Value<string>();
                _frozenMeans[r["route"].Value<string>()] = r["means"].Value<string>();
                roles[id] = (r["roles"] as JObject)?.Properties().ToDictionary(p => p.Name, p => p.Value.Value<string>(), StringComparer.Ordinal)
                            ?? new Dictionary<string, string>();
            }
            _frozenDeclared = new Declared { Rules = _frozen.Select(c => Uniform(c, _frozenRouteOf[c.Id], roles[c.Id])).ToList() };
            return _frozenDeclared;
        }

