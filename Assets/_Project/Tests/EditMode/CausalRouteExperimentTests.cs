        /// <summary>
        /// One rule per (want, intention, circumstance), holding every statement
        /// its co-compatible rules made, each still in its own route. A base goes
        /// in as a constant scaler named for its gate, so that it keeps its route.
        /// </summary>
        static Declared Merged(Declared d)
        {
            var list = new List<RouteRule>();
            for (var wi = 0; wi < Wants.Length; wi++)
            for (var ci = 0; ci < 2; ci++)
            {
                var gate = ci == 0 ? new SituationCondition { OthersPresentMin = 1 } : new SituationCondition { Alone = true };
                var compatible = d.Rules.Where(r => CompatibleIn(r.C, wi, ci)).ToList();
                foreach (var intent in compatible.Select(r => r.C.Intent).Distinct().ToList())
                {
                    var parts = compatible.Where(r => r.C.Intent == intent).ToList();
                    var scalers = new List<Scaler>();
                    var routes = new List<string> { parts[0].Routes[0] };
                    var roles = new List<string> { null };
                    foreach (var p in parts)
                    {
                        if (p.C.Base != 0.0)
                        {
                            scalers.Add(new Scaler { Kind = ScalerKind.Constant, Name = GateKey(p.C.When), Factor = p.C.Base });
                            routes.Add(p.Routes[0]);
                            roles.Add(null);
                        }
                        for (var k = 0; k < p.C.ScaledBy.Count; k++)
                        {
                            scalers.Add(p.C.ScaledBy[k]);
                            routes.Add(p.Routes[k + 1]);
                            roles.Add(p.Roles[k + 1]);
                        }
                    }
                    list.Add(new RouteRule
                    {
                        C = Make(parts[0].C, Wants[wi] + "_" + ci + "_" + intent, motives: new[] { Wants[wi] }, when: gate, baseWeight: 0.0, scalers: scalers),
                        Routes = routes.ToArray(),
                        Roles = roles.ToArray()
                    });
                }
            }
            return d.With(list);
        }

