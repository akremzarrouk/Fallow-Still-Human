        static string EvidenceKey(Scaler s)
        {
            switch (s.Kind)
            {
                case ScalerKind.Trait: return "trait:" + s.Name;
                case ScalerKind.Value: return "value:" + s.Name;
                case ScalerKind.Belief: return "belief:" + s.Predicate + "(" + string.Join(",", s.Args ?? new List<string>()) + ")";
                case ScalerKind.Emotion: return "emotion:" + s.Name + "@" + (s.Target ?? "situation");
                case ScalerKind.Constant: return CircumstancePrefix + (s.Name ?? "any");
                default: return s.Kind + ":" + (s.Name ?? s.Predicate ?? s.Entry ?? "");
            }
        }

        static string GateKey(SituationCondition w)
        {
            var parts = new List<string>();
            if (w.Alone.HasValue) parts.Add(w.Alone.Value ? "alone" : "not alone");
            if (w.OthersPresentMin.HasValue) parts.Add("others>=" + w.OthersPresentMin.Value);
            if (w.InOwnRoom.HasValue) parts.Add(w.InOwnRoom.Value ? "own room" : "not own room");
            if (w.InSomebodyElsesRoom.HasValue) parts.Add(w.InSomebodyElsesRoom.Value ? "somebody else's room" : "not somebody else's room");
            if (w.RoomHoldsFood.HasValue) parts.Add(w.RoomHoldsFood.Value ? "food here" : "no food here");
            if (w.SearchedThisRoomMyself.HasValue) parts.Add(w.SearchedThisRoomMyself.Value ? "searched here" : "not searched here");
            return parts.Count == 0 ? "any" : string.Join(",", parts);
        }

        const string CircumstancePrefix = "circumstance:";

        static RouteRule Uniform(Candidate c, string route, IDictionary<string, string> roles = null)
            => new RouteRule
            {
                C = c,
                Routes = Enumerable.Repeat(route, c.ScaledBy.Count + 1).ToArray(),
                Roles = new[] { (string)null }.Concat(c.ScaledBy.Select(s => roles != null && roles.TryGetValue(EvidenceKey(s), out var r) ? r : null)).ToArray()
            };

