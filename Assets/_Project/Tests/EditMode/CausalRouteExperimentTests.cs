        static Dictionary<string, Declared> _variants;
        static string _synthWant;

        static Dictionary<string, Declared> Variants()
        {
            if (_variants != null) return _variants;
            var syn = (JObject)_routesJson["synthetic"];
            _synthWant = syn["want"].Value<string>();
            var fd = FrozenDeclared();
            var rivals = ((JArray)syn["rivals"]).Select(x => x.Value<string>()).Select(id => fd.Rules.First(r => r.C.Id == id)).ToList();
            var relations = syn["variant_relations"] as JObject ?? new JObject();
            var renamings = syn["renamings"] as JObject ?? new JObject();
            _variants = new Dictionary<string, Declared>(StringComparer.Ordinal);
            foreach (var v in ((JObject)syn["variants"]).Properties())
            {
                var d = new Declared();
                foreach (var c in (JArray)v.Value)
                    d.Rules.Add(Uniform(ParseRule(c, new[] { _synthWant }), c["route"].Value<string>()));
                d.Rules.AddRange(rivals);
                if (relations[v.Name] is JArray rel)
                    foreach (var g in rel.Where(x => x["type"].Value<string>() == "alternative"))
                        d.Alternatives.Add(((JArray)g["routes"]).Select(x => x.Value<string>()).ToList());
                if (renamings[v.Name] is JObject map)
                    foreach (var p in map.Properties()) d.Rename[p.Name] = p.Value.Value<string>();
                _variants[v.Name] = d;
            }
            return _variants;
        }

