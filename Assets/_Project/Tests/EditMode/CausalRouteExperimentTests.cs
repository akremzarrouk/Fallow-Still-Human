        static double Fleiss(IReadOnlyList<Dictionary<string, int>> counts, IReadOnlyList<string> categories)
        {
            var n = counts[0].Values.Sum();
            var pi = counts.Select(c => (c.Values.Sum(x => x * (x - 1.0))) / (n * (n - 1.0))).Average();
            var pj = categories.Select(cat => counts.Sum(c => c.TryGetValue(cat, out var v) ? v : 0) / (double)(counts.Count * n)).ToList();
            var pe = pj.Sum(p => p * p);
            return Math.Abs(1.0 - pe) < 1e-12 ? double.NaN : (pi - pe) / (1.0 - pe);
        }

        [Test, Order(5)]
        public void E_TheBlindAnnotation()
        {
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "experiments", "causal-routes", "annotation");
            var itemsJson = JObject.Parse(File.ReadAllText(Path.Combine(dir, "items.json")));
            var items = ((JArray)itemsJson["items"]).ToList();
            var key = (JObject)itemsJson["answer_key"];
            var neutral = items.Select((it, k) => new { Id = it["id"].Value<string>(), N = "item-" + (k + 1).ToString("00") }).ToDictionary(x => x.N, x => x.Id);
            var files = Directory.GetFiles(Path.Combine(dir, "responses"), "reviewer-*.json").OrderBy(f => f, StringComparer.Ordinal).ToList();
            var reviewers = files.Select(f => JObject.Parse(File.ReadAllText(f))).ToList();

            string Judgment(JToken a)
            {
                var q1 = a?["q1"]?.Value<string>();
                var q2 = a?["q2"]?.Value<string>();
                if (q1 == "yes" && q2 == "no") return "restatement";
                if (q1 == "no" && q2 == "yes") return "different";
                return "unclear";
            }
            string Combine(JToken a)
            {
                var q3 = a?["q3"]?.Value<string>();
                return q3 == "both" || q3 == "one_or_other" ? q3 : "unclear";
            }
            JToken AnswerOf(JObject r, string itemId) => ((JArray)r["answers"]).FirstOrDefault(x => neutral[x["id"].Value<string>()] == itemId);

            var sb = new StringBuilder();
            sb.AppendLine("## 5. The blind annotation");
            sb.AppendLine();
            sb.AppendLine(reviewers.Count + " reviewers (" + string.Join(", ", reviewers.Select(r => "#" + r["reviewer"] + " " + r["model"])) + "), each a fresh subagent shown only the items, in the rotated and swapped order the protocol fixes, under neutral ids. **They are language models, not people.** Agreement below is evidence about whether the distinctions are legible and reproducible, and says nothing about whether they are true.");
            sb.AppendLine();
            sb.AppendLine("| Item | Source | Declared | Judgments (restatement / different / unclear) | Majority | Matches the key | Q3 (both / one or other / unclear) | Declared Q3 |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            var judgmentCounts = new List<Dictionary<string, int>>();
            var combineCounts = new List<Dictionary<string, int>>();
            var matches = 0;
            var pairItems = 0;
            var q3Matches = 0;
            var q3Items = new List<string>();
            foreach (var it in items)
            {
                var id = it["id"].Value<string>();
                if (it["single"]?.Value<bool>() == true) continue;
                pairItems++;
                var j = reviewers.Select(r => Judgment(AnswerOf(r, id))).ToList();
                var q3 = reviewers.Select(r => Combine(AnswerOf(r, id))).ToList();
                var jc = new[] { "restatement", "different", "unclear" }.ToDictionary(c => c, c => j.Count(x => x == c));
                var qc = new[] { "both", "one_or_other", "unclear" }.ToDictionary(c => c, c => q3.Count(x => x == c));
                judgmentCounts.Add(jc);
                var majority = jc.OrderByDescending(kv => kv.Value).First();
                var declared = key[id]["judgment"].Value<string>();
                var declaredQ3 = key[id]["combine"].Value<string>();
                if (majority.Key == declared) matches++;
                if (declared == "different")
                {
                    combineCounts.Add(qc);
                    var q3Majority = qc.OrderByDescending(kv => kv.Value).First().Key;
                    if (q3Majority == declaredQ3) q3Matches++;
                    else q3Items.Add("`" + id + "` (declared " + declaredQ3 + ", majority " + q3Majority + " " + qc[q3Majority] + " of " + reviewers.Count + ")");
                }
                sb.AppendLine("| `" + id + "` | " + it["source"].Value<string>() + " | " + declared + " | " + jc["restatement"] + " / " + jc["different"] + " / " + jc["unclear"]
                              + " | " + majority.Key + " (" + majority.Value + " of " + reviewers.Count + ")" + " | " + (majority.Key == declared ? "yes" : "**no**")
                              + " | " + (declared == "different" ? qc["both"] + " / " + qc["one_or_other"] + " / " + qc["unclear"] : "-") + " | " + (declared == "different" ? declaredQ3 : "-") + " |");
            }
            sb.AppendLine();
            var role = items.First(it => it["single"]?.Value<bool>() == true);
            var q5 = reviewers.Select(r => AnswerOf(r, role["id"].Value<string>())?["q5"]?.Value<string>() ?? "missing").ToList();
            var kJ = Fleiss(judgmentCounts, new[] { "restatement", "different", "unclear" });
            var kQ3 = Fleiss(combineCounts, new[] { "both", "one_or_other", "unclear" });
            var q3Agree = combineCounts.Select(c => c.Values.Max() / (double)reviewers.Count).Average();
            sb.AppendLine("| | |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| Majority judgment matches the key | **" + matches + " of " + pairItems + "** two-reason items |");
            sb.AppendLine("| Fleiss' kappa, judgment (restatement / different / unclear), " + pairItems + " items | **" + F(kJ) + "** |");
            sb.AppendLine("| Fleiss' kappa, Q3 (both / one or other / unclear), the " + combineCounts.Count + " items declared different | **" + F(kQ3) + "**; mean share agreeing with the item's majority " + Pc(q3Agree, 1.0) + " |");
            sb.AppendLine("| Q3 majority matches the declared relation | **" + q3Matches + " of " + combineCounts.Count + "** items declared different. Not matching: " + (q3Items.Count == 0 ? "none" : string.Join("; ", q3Items)) + " |");
            sb.AppendLine("| Q5, the role item (`" + role["id"] + "`): precondition / contributing / unclear | " + q5.Count(x => x == "precondition") + " / " + q5.Count(x => x == "contributing") + " / " + q5.Count(x => x == "unclear") + " (declared: precondition) |");
            sb.AppendLine();
            sb.AppendLine("### Q4, verbatim: what an explanation would need to show");
            sb.AppendLine();
            foreach (var it in items)
            {
                var id = it["id"].Value<string>();
                sb.AppendLine("**`" + id + "`**");
                sb.AppendLine();
                foreach (var r in reviewers)
                    sb.AppendLine("- #" + r["reviewer"] + " " + r["model"] + ": " + (AnswerOf(r, id)?["q4"]?.Value<string>() ?? "(missing)"));
                sb.AppendLine();
            }
            Record("5", sb.ToString());
        }

