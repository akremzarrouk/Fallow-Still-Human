        /// <summary>
        /// Stages 1 to 3, in the selector's own order and arithmetic. A constant
        /// scaler named for a gate is a base carried inside a merged rule, and is
        /// read as that base.
        /// </summary>
        static Staged Stage(Declared d, Mind mind, Percept p, string want, string target = null)
        {
            var s = new Staged();
            var motive = Want(want, target);
            var ctx = new DecisionContext(p, mind.Id, motive.TargetId, _content.Morning.Day, _content.Rules.Deciding.RecallHalfLife);
            foreach (var rr in d.Rules)
            {
                var c = rr.C;
                if (!c.Motives.Contains(want, StringComparer.Ordinal)) continue;
                if (!s.Available.Contains(c.Intent)) s.Available.Add(c.Intent);
                if (!c.When.Matches(p)) continue;
                if (!s.Compatible.Contains(c.Intent)) s.Compatible.Add(c.Intent);
                var terms = ScalerEval.Evaluate(c.ScaledBy, mind, ctx);
                if (terms.Count != c.ScaledBy.Count) throw new InvalidOperationException(c.Id + ": a scaler was not evaluated");
                var gate = GateKey(c.When);
                var statements = new List<Statement>();
                if (c.Base != 0.0)
                    statements.Add(new Statement { Key = CircumstancePrefix + gate, Coef = c.Base, Amount = c.Base, IsBase = true, Route = rr.Routes[0], RuleId = c.Id });
                for (var k = 0; k < terms.Count; k++)
                {
                    var sc = c.ScaledBy[k];
                    var isBase = sc.Kind == ScalerKind.Constant;
                    statements.Add(new Statement
                    {
                        Key = EvidenceKey(sc), Coef = sc.Factor, Amount = terms[k].Amount, IsBase = isBase,
                        Route = rr.Routes[k + 1], Role = rr.Roles[k + 1], RuleId = c.Id
                    });
                }
                s.Rules.Add(new RuleEval
                {
                    R = rr,
                    Weight = c.Base + terms.Sum(t => t.Amount),
                    Gate = gate,
                    Signature = c.Intent + "|" + gate + "|" + string.Join(",", statements.Where(x => !x.IsBase).Select(x => x.Key).Distinct().OrderBy(x => x, StringComparer.Ordinal)),
                    Statements = statements
                });
            }
            return s;
        }

