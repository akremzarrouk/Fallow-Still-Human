        // ---- circumstances and diagnostic rule sets ----

        /// <summary>DIAGNOSTIC ONLY, never shipped: the same rules with nothing priced against eating.</summary>
        internal static Scenario001Content PriceRemoved(Scenario001Content c)
        {
            var r = c.Rules;
            var rules = new RuleSet
            {
                Interpretation = r.Interpretation, BeliefNudges = r.BeliefNudges, Appraisal = r.Appraisal, Dynamics = r.Dynamics,
                Motivation = r.Motivation, Proposals = r.Proposals, Costs = r.Costs.Where(x => x.Action != "eat").ToList(), Deciding = r.Deciding
            };
            return new Scenario001Content(c.Vocabulary, c.Cast, c.Backstory, c.Morning, rules);
        }

        /// <summary>
        /// A circumstance, not a rule: more food in the pantry, and optionally an
        /// opening count that does not come up short, so nobody learns the
        /// shelf is short.
        /// </summary>
        internal static Scenario001Content Plenty(Scenario001Content c, int portions, bool countComesUpShort)
        {
            var m = c.Morning;
            var o = m.Opening;
            var opening = countComesUpShort
                ? o
                : new WorldEvent(o.Id, o.Day, o.Order, o.Kind, o.ActorId, o.TargetId, o.Act, o.Action, "supplies", o.Tone, o.Directness,
                    "neutral", o.Intent, "Elena counts the pantry with everyone standing there. There is enough.",
                    o.Witnesses, o.Overhearers, o.LedgerEffects, o.BeliefEffects, o.Minute);
            var morning = new MorningScenario(m.Id, m.Description, m.Day, m.Minutes, m.House, portions, m.StartRooms, m.StartHunger,
                opening, m.Variants, m.HeldOutVariants);
            return new Scenario001Content(c.Vocabulary, c.Cast, c.Backstory, morning, c.Rules);
        }

        /// <summary>Everyone else out of the kitchen, and this person as hungry as the scale allows.</summary>
        internal static void StarvingAlone(Scenario001Run run, string who, double hunger = 0.99)
        {
            run.World.Place(who, "kitchen");
            foreach (var id in run.World.Inhabitants.Where(i => i != who).ToList()) run.World.Place(id, "back_room");
            run.World.SetHunger(who, hunger);
        }

        static IReadOnlyList<Motive> Wants(Scenario001Run run, string who, TraceLog scratch = null)
            => new Motivator(_content.Rules).Raise(run.Minds[who], run.Morning.See(who), _content.Morning.Day, scratch ?? new TraceLog(), 0);

        // ---- 1. how hunger is raised and represented ----

        [Test]
        public void D1_HowHungerIsRaisedAndWhatTheWantRestsOn()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 1. How hunger is raised, and how it becomes a want");
            sb.AppendLine();
            sb.AppendLine("`mara_ate_it`, seed 1, shipped rules. Hunger is world state: a start level from the scenario, plus");
            sb.AppendLine("`hunger_per_minute` " + _content.Rules.Deciding.HungerPerMinute + " times the person's metabolism, every minute, clamped to 1.");
            sb.AppendLine("The want is raised by the rule `a_body_that_has_not_eaten`: `get_food` = hunger x 1.0, through the urgency knee at " + _content.Rules.Deciding.UrgencyKnee + ".");
            sb.AppendLine();
            sb.AppendLine("| Who | Metabolism | Hunger at 0 / 30 / 60 / 90 | `get_food` at 90 | Records the hunger term rests on |");
            sb.AppendLine("|---|---|---|---|---|");

            var run = Scenario001.Prepare(_content, "mara_ate_it", 1);
            var levels = People.ToDictionary(p => p, p => new List<double> { run.World.HungerOf(p) });
            for (var i = 1; i <= 90; i++)
            {
                run.Morning.Step();
                if (i % 30 == 0) foreach (var p in People) levels[p].Add(run.World.HungerOf(p));
            }

            foreach (var p in People)
            {
                var want = Wants(run, p).FirstOrDefault(m => m.Name == "get_food");
                var term = want?.Terms.FirstOrDefault(t => t.Description.StartsWith("hunger", StringComparison.Ordinal));
                sb.AppendLine("| " + p + " | " + run.Minds[p].Profile.HungerRate + " | " + string.Join(" / ", levels[p].Select(F)) + " | " +
                              (want == null ? "not raised" : F(want.Urgency)) + " | " + (term == null ? "n/a" : term.Drew.Count.ToString()) + " |");
            }

            sb.AppendLine();
            sb.AppendLine("Every other kind of term a want can rest on names the records it read (a feeling's causes, a memory, a belief's evidence). The hunger term names none: nothing in the trace can say why somebody is as hungry as they are.");
            Record("1", sb.ToString());
        }

        // ---- 2. the price of eating ----

        [Test]
        public void D2_WhatEatingCostsEachOfThemAndWhetherItCanEverBeWorthIt()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. What eating costs each of them, and whether it can ever be worth it");
            sb.AppendLine();
            sb.AppendLine("Shipped rules, `mara_ate_it`, seed 1, just after the opening count. Eating is worth exactly the urgency of `get_food`, which cannot exceed 1.");
            sb.AppendLine("The highest it can reach this morning is the knee applied to start hunger plus ninety minutes of that person's metabolism.");
            sb.AppendLine("Price alone is measured with everyone else moved out of the kitchen; watched, with the whole house there.");
            sb.AppendLine();
            sb.AppendLine("| Who | Price alone | ... of which | Price watched | Best `get_food` this morning | Best score alone | Best score watched | Standing still alone, same moment |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");

            foreach (var p in People)
            {
                var run = Scenario001.Prepare(_content, "mara_ate_it", 1);
                run.World.Place(p, "kitchen");
                var watched = Price(run, p);

                StarvingAlone(run, p, run.World.HungerOf(p));
                var alone = Price(run, p);
                var d = new Deliberator(_content.Rules).Decide(run.Minds[p], run.Morning.See(p), Wants(run, p), _content.Morning.Day, new Rng(1), new TraceLog(), 0);
                var wait = d.Ranked.First(r => r.Option.Kind == ActionKind.Wait);

                var start = _content.Morning.StartHunger[p];
                var reach = Accumulate.Knee(Math.Min(1.0, start + 90 * _content.Rules.Deciding.HungerPerMinute * run.Minds[p].Profile.HungerRate), _content.Rules.Deciding.UrgencyKnee);

                sb.AppendLine("| " + p + " | " + F(alone.cost) + " | " + string.Join("; ", alone.prices) + " | " + F(watched.cost) + " | " + F(reach) + " | " +
                              F(reach - alone.cost) + " | " + F(reach - watched.cost) + " | " + F(wait.Score) + " (" +
                              string.Join(", ", wait.Contributions.Select(c => c.ProposalId + " " + F(c.Amount))) + ") |");
            }

            sb.AppendLine();
            sb.AppendLine("The same, at the top of the hunger scale (1.0, worth " + F(Accumulate.Knee(1.0, _content.Rules.Deciding.UrgencyKnee)) + " after the knee), is the column of best scores shifted up by the difference.");
            sb.AppendLine();
            sb.AppendLine("The same price, alone, where the count did not come up short and there is plenty (nobody believes supplies are short), against the top of the hunger scale:");
            sb.AppendLine();
            sb.AppendLine("| Who | Price alone, nothing short | Best score alone at hunger 1.0 |");
            sb.AppendLine("|---|---|---|");
            foreach (var p in People)
            {
                var run = Scenario001.Prepare(Plenty(_content, 10, false), "mara_ate_it", 1);
                StarvingAlone(run, p, 1.0);
                var price = Price(run, p).cost;
                sb.AppendLine("| " + p + " | " + F(price) + " | " + F(Accumulate.Knee(1.0, _content.Rules.Deciding.UrgencyKnee) - price) + " |");
            }
            Record("2", sb.ToString());
        }

        static (double cost, List<string> prices) Price(Scenario001Run run, string who)
        {
            var d = new Deliberator(_content.Rules).Decide(run.Minds[who], run.Morning.See(who), new List<Motive>(), _content.Morning.Day, new Rng(1), new TraceLog(), 0);
            var eat = d.Ranked.First(r => r.Option.Kind == ActionKind.Eat);
            return (eat.Cost, eat.Prices.Select(x => x.Split('(')[0].Trim()).ToList());
        }

