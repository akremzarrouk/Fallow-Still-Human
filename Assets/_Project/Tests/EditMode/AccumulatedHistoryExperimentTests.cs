        [Test, Timeout(1800000)]
        public void H2_WhatChangesWithTheReading()
        {
            // Where the label flips, what does it take with it? The three levels
            // the brief asks for, side by side, for both subjects.
            var sb = new StringBuilder();
            sb.AppendLine("## 2. No history, small history, accumulated history");
            sb.AppendLine();
            sb.AppendLine("The same later event (he goes through her things), the same room, the same company, the same hunger, and she believes she is answerable for the missing can. Only the number of earlier times differs.");
            sb.AppendLine();

            foreach (var subject in new[] { "elena", "mara" })
            {
                var arms = new[] { 0, 1, 12 }.Select(n => (N: n, C: S17.Run(_content, Arm(subject, n, S17.Search, true)))).ToList();
                sb.AppendLine("### " + subject);
                sb.AppendLine();
                sb.AppendLine("| | none (N=0) | small (N=1) | accumulated (N=12) |");
                sb.AppendLine("|---|---|---|---|");
                sb.AppendLine("| Her belief `treats_me_like_a_child`, before it | " + string.Join(" | ", arms.Select(a => F(a.C.Belief("tendency(daniel,treats_me_like_a_child)")))) + " |");
                sb.AppendLine("| Her belief `does_not_respect_me`, before it | " + string.Join(" | ", arms.Select(a => F(a.C.Belief("tendency(daniel,does_not_respect_me)")))) + " |");
                sb.AppendLine("| ... of which seeded by her character file | " + string.Join(" | ", arms.Select(a => subject == "mara" ? "0.550 of the first" : "none")) + " |");
                sb.AppendLine("| Memories of him going through her things | " + string.Join(" | ", arms.Select(a => a.C.Mind.Experiences.Count(x => x.ActorId == "daniel" && x.Topic == "missing_can").ToString())) + " |");
                sb.AppendLine("| **She read it as** | " + string.Join(" | ", arms.Select(a => "**" + a.C.Meaning + "** " + F(a.C.Weight))) + " |");
                sb.AppendLine("| Next reading | " + string.Join(" | ", arms.Select(a => (a.C.RunnerUp ?? "none") + " " + F(a.C.RunnerUpWeight))) + " |");
                sb.AppendLine("| The rules that read it | " + string.Join(" | ", arms.Select(a => a.C.RulesDetail ?? "-")) + " |");
                sb.AppendLine("| It stirred | " + string.Join(" | ", arms.Select(a => a.C.Stirring.Length == 0 ? "nothing" : a.C.Stirring)) + " |");
                sb.AppendLine("| She was left feeling | " + string.Join(" | ", arms.Select(a => string.Join(", ", a.C.Emotions.OrderByDescending(x => x.Value).Take(4).Select(x => x.Key + " " + F(x.Value))))) + " |");
                sb.AppendLine("| She wanted | " + string.Join(" | ", arms.Select(a => string.Join(", ", a.C.Wants.OrderByDescending(x => x.Value).Take(4).Select(x => x.Key + " " + F(x.Value))))) + " |");
                sb.AppendLine("| She chose | " + string.Join(" | ", arms.Select(a => a.C.Chosen + " for " + a.C.LeadingWant + ", " + a.C.Resolution)) + " |");
                sb.AppendLine("| Everything downstream, identical to N=0? | - | " + string.Join(" | ", arms.Skip(1).Select(a => a.C.Downstream == arms[0].C.Downstream ? "identical" : "**different**")) + " |");
                sb.AppendLine();
            }

            // Controls: she was not there for them; and taking the history away again.
            sb.AppendLine("### Controls");
            sb.AppendLine();
            sb.AppendLine("| | elena | mara |");
            sb.AppendLine("|---|---|---|");
            foreach (var (label, make) in new (string, Func<string, S17Chain>)[]
            {
                ("N=0, run twice: identical", s => S17.Run(_content, Arm(s, 0, S17.Search, true))),
                ("N=12 but she was never there to see them", s => S17.Run(_content, Arm(s, 12, S17.Search, true, sees: false))),
                ("N=12, then the history taken away again (N=0)", s => S17.Run(_content, Arm(s, 0, S17.Search, true)))
            })
            {
                sb.AppendLine("| " + label + " | " + string.Join(" | ", new[] { "elena", "mara" }.Select(s =>
                {
                    var baseline = S17.Run(_content, Arm(s, 0, S17.Search, true));
                    var arm = make(s);
                    return arm.Meaning + " " + F(arm.Weight) + (arm.Downstream == baseline.Downstream ? ", downstream identical to N=0" : ", downstream differs from N=0");
                })) + " |");
            }
            Record("2", sb.ToString());

            // The unseen history must leave her exactly as no history does.
            foreach (var s in new[] { "elena", "mara" })
            {
                var none = S17.Run(_content, Arm(s, 0, S17.Search, true));
                var unseen = S17.Run(_content, Arm(s, 12, S17.Search, true, sees: false));
                Assert.AreEqual(none.Meaning, unseen.Meaning, s + ": history she never saw must change nothing");
                Assert.AreEqual(none.Downstream, unseen.Downstream, s + ": downstream");
            }
        }

