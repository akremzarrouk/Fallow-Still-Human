        [Test, Timeout(3600000)]
        public void H3_TheSameQuestionInALiveMorning()
        {
            // The same later event, put into a live morning at the same minute,
            // with the history written into the days before it.
            var sb = new StringBuilder();
            sb.AppendLine("## 3. The same question in a live morning");
            sb.AppendLine();
            sb.AppendLine("The history is written into the backstory (S1.7's `WithHistory`), so the morning starts with her already carrying it. The same later event is put into the morning at the same minute in every arm, at the first minute after 10 at which she and Daniel are in the same room in the no-history run. Her circumstances at that moment are checked, because the history may already have changed her morning.");
            sb.AppendLine();
            sb.AppendLine("Each subject is run in the condition of the house where she has reason to believe she is answerable for the missing can (`mara_ate_it` for Mara, `elena_fed_mara` for Elena), so that the later event has a competing reading for history to overtake.");
            sb.AppendLine();
            sb.AppendLine("| Subject | Seed | Probe at | Her morning up to then, identical to N=0 | N=0 read it as | N=1 | N=12 | Her next act, N=0 | N=12 | Her reason, N=0 -> N=12 |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|");

            var skipped = new List<string>();
            var labelChanged = 0;
            var weightChanged = 0;
            var actChanged = 0;
            var reasonChanged = 0;
            var comparable = 0;
            var total = 0;

            foreach (var subject in new[] { "elena", "mara" })
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var minute = ProbeMinute(_content, subject, seed);
                if (minute < 0) { skipped.Add(subject + " seed " + seed); continue; }
                total++;

                var arms = new[] { 0, 1, 12 }.Select(n =>
                {
                    var content = n == 0 ? _content : S17.WithHistory(_content, n, "daniel", subject);
                    return (N: n, Run: RunWithProbe(content, subject, seed, minute));
                }).ToList();

                // Comparable only if nothing about her had already diverged: same
                // circumstances and the same decisions all morning up to then.
                var same = arms.All(a => a.Run.Circumstance == arms[0].Run.Circumstance && a.Run.Before == arms[0].Run.Before);
                if (same) comparable++;
                if (same && arms[2].Run.Label != arms[0].Run.Label) labelChanged++;
                if (same && Math.Abs(arms[2].Run.Weight - arms[0].Run.Weight) > 1e-9) weightChanged++;
                if (same && arms[2].Run.NextAct != arms[0].Run.NextAct) actChanged++;
                if (same && arms[2].Run.NextAct == arms[0].Run.NextAct && arms[2].Run.NextReason != arms[0].Run.NextReason) reasonChanged++;

                sb.AppendLine("| " + subject + " | " + seed + " | m" + minute + " | " + (same ? "yes" : "**no**") + " | " +
                              arms[0].Run.Label + " " + F(arms[0].Run.Weight) + " | " + arms[1].Run.Label + " " + F(arms[1].Run.Weight) + " | " +
                              arms[2].Run.Label + " " + F(arms[2].Run.Weight) + " | " + arms[0].Run.NextAct + " | " +
                              (arms[2].Run.NextAct == arms[0].Run.NextAct ? "the same" : "**" + arms[2].Run.NextAct + "**") + " | " +
                              arms[0].Run.NextReason + " -> " + (arms[2].Run.NextReason == arms[0].Run.NextReason ? "the same" : "**" + arms[2].Run.NextReason + "**") + " |");
            }

            sb.AppendLine();
            if (skipped.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("**" + skipped.Count + " runs could not be used**, because the two of them were never in the same room after minute 10, so the later event could not happen to her at all: " + string.Join(", ", skipped) + ".");
            }
            sb.AppendLine();
            sb.AppendLine("Of " + total + " runs, **" + comparable + "** had identical circumstances at the moment of the later event in all three arms. Among those: the **label** differed between no history and accumulated history in **" + labelChanged + "**, the **weight** in **" + weightChanged + "**, and the **act she then chose** in **" + actChanged + "**, and the act was the same but her **reason** for it differed in **" + reasonChanged + "**.");
            Record("3", sb.ToString());
        }

        sealed class Probed
        {
            public string Circumstance;
            public string Label;
            public double Weight;
            public string NextAct;
            public string NextReason;
            /// <summary>Her own decisions before the later event, to tell a cascade from the event.</summary>
            public string Before = "";
        }

        /// <summary>
        /// The condition of the house in which this subject has reason to believe
        /// she is answerable for the missing can, so that the later event has a
        /// competing reading for history to overtake.
        /// </summary>
        static string VariantFor(string subject) => subject == "mara" ? "mara_ate_it" : "elena_fed_mara";

        /// <summary>The first minute after 30 at which the subject and Daniel are in the same room, with no history.</summary>
        static int ProbeMinute(Scenario001Content content, string subject, ulong seed)
        {
            var run = Scenario001.Prepare(content, VariantFor(subject), seed);
            for (var i = 0; i < content.Morning.Minutes; i++)
            {
                run.Morning.Step();
                if (run.World.Minute >= 10 && run.World.RoomOf(subject) == run.World.RoomOf("daniel")) return run.World.Minute;
            }
            return -1;
        }

        static Probed RunWithProbe(Scenario001Content content, string subject, ulong seed, int minute)
        {
            var run = Scenario001.Prepare(content, VariantFor(subject), seed);
            var probed = new Probed { Label = "-", NextAct = "-", NextReason = "-" };
            var seen = false;
            var before = new List<string>();
            run.Morning.Decided = m =>
            {
                if (m.CharacterId != subject) return;
                if (!seen)
                {
                    before.Add("m" + m.Minute + " " + m.Decision.Chosen.Key + " for " + (m.Decision.Leading?.Key ?? "nothing"));
                    return;
                }
                if (probed.NextAct != "-") return;
                probed.NextAct = m.Decision.Chosen.Key;
                probed.NextReason = m.Decision.Leading?.Key ?? "nothing";
            };

            for (var i = 0; i < content.Morning.Minutes; i++)
            {
                run.Morning.Step();
                if (run.World.Minute != minute) continue;
                var room = run.World.RoomOf(subject);
                probed.Circumstance = "room " + room + "; with " + string.Join(",", run.World.WithMe(subject).OrderBy(x => x, StringComparer.Ordinal)) +
                                      "; hunger " + F(run.World.HungerOf(subject));
                if (run.World.RoomOf("daniel") != room) { probed.Label = "not in the same room"; return probed; }

                var witnesses = run.World.InRoom(room).Where(id => id != "daniel").ToList();
                var probe = S17.Probe(S17.Search, "daniel", subject, content.Morning.Day, witnesses);
                var outcome = run.Morning.Happen(probe);
                var hers = outcome.ByCharacter[subject];
                probed.Label = hers.Meaning;
                probed.Weight = hers.InterpretationWeight;
                probed.Before = string.Join(" | ", before);
                seen = true;
            }
            return probed;
        }
