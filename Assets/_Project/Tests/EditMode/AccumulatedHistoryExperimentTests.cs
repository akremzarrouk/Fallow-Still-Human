    /// <summary>
    /// Whether what somebody has done to you before changes what they do to you
    /// now, using only the shipped mechanisms.
    ///
    /// N earlier times Daniel goes through her things, each on its own day and
    /// each perceived by her; then long enough that nothing is still felt; then
    /// one later event built identically in every arm. The only difference
    /// between arms is how many times it happened before. Built on S1.7's
    /// harness (`S17`), which is ordinary scenario data: no rule, number or line
    /// of `Fallow.Core` was added or changed for this experiment.
    ///
    /// Writes `Docs/experiments/accumulated-history/measurements.md`.
    /// </summary>
    public class AccumulatedHistoryExperimentTests
    {
        static readonly int[] Curve = { 0, 1, 2, 3, 4, 6, 8, 10, 12, 16 };
        const int Seeds = 10;

        /// <summary>Long enough that nothing the earlier events stirred is still felt (S1.7).</summary>
        const double Settled = 40.0;

        static Scenario001Content _content;
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        [OneTimeSetUp]
        public void Load() => _content = Baselines.Primary();

        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Accumulated interpersonal history: measurements");
            sb.AppendLine();
            sb.AppendLine("Generated by `AccumulatedHistoryExperimentTests` on the primary baseline, using S1.7's harness. Each arm lives N earlier times of the same thing, then waits until nothing is felt, then meets one later event built identically in every arm. Nothing in `Fallow.Core` or the data was changed.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "experiments", "accumulated-history");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "measurements.md"), sb.ToString());
        }

        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static string F(double v) => v.ToString("0.000", CultureInfo.InvariantCulture);

        static double Belief(Mind mind, string predicate, params string[] args)
            => mind.Beliefs.Confidence(predicate, args.ToList());

        static S17Arm Arm(string subject, int priors, string probe, bool answerable, bool sees = true)
            => new S17Arm
            {
                Label = "N=" + priors,
                Subject = subject,
                Other = "daniel",
                PriorSlights = priors,
                SubjectSeesPriors = sees,
                Answerable = answerable,
                LagFades = Settled,
                ProbeKind = probe,
                Room = "back_room",
                Present = new List<string> { "daniel" },
                Hunger = 0.50
            };

        // ------------------------------------------------------------------ 1

        [Test, Timeout(1800000)]
        public void H1_WhatTheSameEventMeansAfterNTimes()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 1. What the same event means, after it has happened N times before");
            sb.AppendLine();
            sb.AppendLine("Every arm: the subject in the back room with Daniel, hunger 0.50, " + Settled + " units of fading since the last earlier time, then the same later event. **Label** is the winning reading; **weight** is what it won with; **margin** is how far ahead of the next reading it was.");
            sb.AppendLine();

            foreach (var subject in new[] { "elena", "mara" })
            foreach (var probe in new[] { S17.Search, S17.Observe })
            foreach (var answerable in new[] { true, false })
            {
                sb.AppendLine("### " + subject + ", " + (probe == S17.Search ? "he goes through her things again" : "he watches her") +
                              ", " + (answerable ? "and she believes she is answerable for the missing can" : "and she is not answerable"));
                sb.AppendLine();
                sb.AppendLine("Beliefs are as they stood **before** the later event. What she starts with at N=0 is whatever her character file seeds: Mara's says she already believes Daniel treats her like a child (0.55); Elena's says nothing of the kind.");
                sb.AppendLine();
                sb.AppendLine("| Earlier times | `treats_me_like_a_child` | `does_not_respect_me` | `answerable_for` | Label | Weight | Runner-up | Margin | Stirred | Chose |");
                sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|");

                string firstLabel = null;
                var labels = new List<string>();
                foreach (var n in Curve)
                {
                    var c = S17.Run(_content, Arm(subject, n, probe, answerable));
                    // As they stood BEFORE the later event: the event itself
                    // nudges them, and that is not what this column is about.
                    var child = c.Belief("tendency(daniel,treats_me_like_a_child)");
                    var respect = c.Belief("tendency(daniel,does_not_respect_me)");
                    var answer = Belief(c.Mind, "answerable_for", subject, "missing_can");
                    firstLabel = firstLabel ?? c.Meaning;
                    labels.Add(c.Meaning);
                    sb.AppendLine("| " + n + " | " + F(child) + " | " + F(respect) + " | " + F(answer) + " | " +
                                  (c.Meaning == firstLabel ? c.Meaning : "**" + c.Meaning + "**") + " | " + F(c.Weight) + " | " +
                                  (c.RunnerUp ?? "none") + " " + F(c.RunnerUpWeight) + " | " + F(c.Weight - c.RunnerUpWeight) + " | " +
                                  (c.Stirring.Length == 0 ? "nothing" : c.Stirring) + " | " + c.Chosen + " |");
                }
                sb.AppendLine();
                var flipped = labels.Distinct().Count() > 1;
                sb.AppendLine(flipped
                    ? "**The reading changes**: " + string.Join(" -> ", labels.Select((l, i) => Curve[i] + ": " + l).Where((l, i) => i == 0 || labels[i] != labels[i - 1]))
                    : "**The reading never changes**: " + labels[0] + " at every number of earlier times.");
                sb.AppendLine();
            }
            Record("1", sb.ToString());
        }

