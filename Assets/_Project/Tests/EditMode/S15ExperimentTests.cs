        [Test]
        public void E8_OneWantUnderBTracedBackToWhatHappened()
        {
            var content = S15.Mode(_content, DispositionMode.Respond);
            var run = Scenario001.Prepare(content, "daniel_ate_it", 1);
            string found = null;
            run.Morning.Decided = m =>
            {
                if (found != null || m.CharacterId != "elena") return;
                var want = m.Motives.FirstOrDefault(x => x.Name == "keep_peace" && x.Terms.Any(t => t.Description.Contains("in response to")));
                if (want == null) return;
                found = "Minute " + m.Minute + ", Elena, chose " + m.Decision.Chosen + ":" + Environment.NewLine + Environment.NewLine +
                        "```" + Environment.NewLine + run.Trace.Why(want.TraceId) + Environment.NewLine + "```";
            };
            run.Morning.Run(content.Morning.Minutes);
            Record("8", "## 8. One want under B, traced" + Environment.NewLine + Environment.NewLine + (found ?? "none found") + Environment.NewLine);
            Assert.IsNotNull(found);
            StringAssert.Contains("Event", found);
        }
