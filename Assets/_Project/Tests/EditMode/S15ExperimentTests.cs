        [Test, Timeout(3600000)]
        public void E3_TheSamePersonWithAndWithoutTheNight()
        {
            var culprits = new[] { ("daniel_ate_it", "daniel"), ("mara_ate_it", "mara"), ("daniel_hid_it", "daniel"), ("elena_fed_mara", "elena") };
            var sb = new StringBuilder();
            sb.AppendLine("## 3. The same person, with and without the night");
            sb.AppendLine();
            sb.AppendLine("The S1.1 measure: behaviour with the night against without it, against two same-condition pools (seeds 1 to 20 and 21 to 40). Above the noise means more than 1.5 times the larger noise.");
            sb.AppendLine();
            sb.AppendLine("| Condition | Who | Mode | Night vs no night | No night vs no night | Night vs night | Effect / noise | Above |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (var (variant, who) in culprits)
            foreach (var (label, mode) in Modes.Where(m => m.Mode != DispositionMode.Gated))
            {
                var (effect, c, t) = S15.NightEffect(S15.Mode(_content, mode), variant, who, 1);
                var noise = Math.Max(c, t);
                sb.AppendLine("| " + variant + " | " + who + " | " + label + " | " + S15.F(effect) + " | " + S15.F(c) + " | " + S15.F(t) + " | " +
                              (noise == 0 ? "n/a" : (effect / noise).ToString("0.0")) + " | " + (effect > noise * 1.5 ? "yes" : "no") + " |");
            }
            Record("3", sb.ToString());
        }

