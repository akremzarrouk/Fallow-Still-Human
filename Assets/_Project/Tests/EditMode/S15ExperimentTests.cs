        [Test, Timeout(3600000)]
        public void E2_WhatPeopleDo()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. What people do");
            sb.AppendLine();
            sb.AppendLine("Behaviour from the S1 batch (seeds 1 to " + BatchSeeds + ", 200 mornings); decisions, walks and decisive rates from the S1.2 audit (seeds 1 to " + AuditSeeds + ").");
            sb.AppendLine();
            sb.AppendLine(Header("Measure"));
            sb.AppendLine(Row("Standing still, share of choices (batch)", m => S15.P(m.WaitShare)));
            sb.AppendLine(Row("Standing still on top (audit)", m => S15.P(m.WaitOnTopShare)));
            sb.AppendLine(Row("Sitting with somebody, share of choices", m => S15.P(m.SittingShare)));
            foreach (var want in new[] { "look_after", "keep_peace", "guard_supplies", "find_out", "get_food", "restore_standing", "avoid_exposure" })
                sb.AppendLine(Row("`" + want + "` decisive", m => S15.P(m.Decisive(want))));
            sb.AppendLine(Row("Walks completed and followed by a decision", m => m.Audit.WalksWithAPurpose.ToString()));
            sb.AppendLine(Row("... followed by something the walk's want did not serve", m => S15.P(m.AbandonedWalks)));
            sb.AppendLine(Row("Pacing, mean per person per morning (audit)", m => m.MeanPacing.ToString("0.00")));
            sb.AppendLine(Row("Worst pacing (batch)", m => m.WorstPacing + " (" + m.WorstPacingWho + ")"));
            sb.AppendLine(Row("Different people, mean gap", m => S15.F(m.MeanGap)));
            sb.AppendLine(Row("Weakest condition, mean gap", m => S15.F(m.WorstConditionMean)));
            sb.AppendLine(Row("Closest pair", m => S15.F(m.ClosestPair) + " (" + m.ClosestWho + ")"));
            sb.AppendLine(Row("Ties between genuinely different actions (batch)", m => S15.P(m.RealTies)));
            sb.AppendLine(Row("Settled by the seed, between different kinds (audit)", m => S15.P(m.GenuineTies)));
            sb.AppendLine(Row("Interruptions per morning", m => (m.Audit.Interruptions / (double)Math.Max(1, m.Audit.Mornings)).ToString("0.0")));
            sb.AppendLine(Row("Meals (batch)", m => m.Meals.ToString()));
            sb.AppendLine(Row("Walks to the food given up on arrival (audit)", m => m.Audit.CommitmentsByWant.TryGetValue("get_food: " + Commitment.NotWorthIt, out var n) ? n.ToString() : "0"));
            sb.AppendLine();
            foreach (var (label, _) in Modes)
            {
                var m = Measured()[label];
                sb.AppendLine("**" + label + "**, what each person did across every condition:");
                sb.AppendLine();
                sb.AppendLine(S15.Profiles(m));
                sb.AppendLine("What was chosen, by the support of the want that added most: " +
