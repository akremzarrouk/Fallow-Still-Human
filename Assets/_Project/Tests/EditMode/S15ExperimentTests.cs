            var moved = new StringBuilder();
            moved.AppendLine("How far each person's morning moved from A (the total difference between action profiles):");
            moved.AppendLine();
            moved.AppendLine("| Who | A to B | A to B0 |");
            moved.AppendLine("|---|---|---|");
            foreach (var p in S15.People)
                moved.AppendLine("| " + p + " | " + S15.F(BatchRunner.HowDifferent(Measured()["A standing"].ProfileByPerson[p], Measured()["B respond"].ProfileByPerson[p])) +
