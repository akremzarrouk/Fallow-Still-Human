        [Test, Timeout(3600000)]
        public void E4_RemovingACircumstance_NobodysDistressCanBeSeen()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 4. Removing a circumstance: nobody's distress can be seen");
            sb.AppendLine();
            sb.AppendLine("Seeds 1 to 10. `visible_distress` set out of reach, so nobody ever sees anybody go to pieces or come right.");
            sb.AppendLine();
            sb.AppendLine("| Mode | World | Mornings | Distress seen | `look_after` raised | ... per decision | ... unsupported | ... with no history behind it | ... on history alone | Sittings | ... for `look_after` |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|");
            var counts = new Dictionary<string, S15.WorldCounts>();
            foreach (var (label, mode) in Modes.Where(m => m.Mode != DispositionMode.Gated))
            foreach (var (world, content) in new[] { ("as written", S15.Mode(_content, mode)), ("distress never seen", S15.DistressNeverShows(S15.Mode(_content, mode))) })
            {
                var w = S15.Count(content, _variants, 1, AuditSeeds);
                counts[label + "/" + world] = w;
                sb.AppendLine("| " + label + " | " + world + " | " + w.Mornings + " | " + w.ShowDistress + " | " + w.LookAfterRaised + " | " +
                              (w.LookAfterRaised / (double)Math.Max(1, w.Decisions)).ToString("0.00") + " | " + w.LookAfterUnsupported + " | " +
                              w.LookAfterWithoutHistory + " | " + w.LookAfterOnHistoryOnly + " | " + w.Comfort + " | " + w.ComfortForLookAfter + " |");
            }
            sb.AppendLine();
            var aw = counts["A standing/as written"]; var ar = counts["A standing/distress never seen"];
            var bw = counts["B respond/as written"]; var br = counts["B respond/distress never seen"];
            sb.AppendLine("Sittings left when distress cannot be seen: A " + ar.Comfort + " of " + aw.Comfort + " (" + S15.P(ar.Comfort / (double)Math.Max(1, aw.Comfort)) +
                          "), B " + br.Comfort + " of " + bw.Comfort + " (" + S15.P(br.Comfort / (double)Math.Max(1, bw.Comfort)) + ").");
            Record("4", sb.ToString());

            Assert.AreEqual(0, ar.ShowDistress + br.ShowDistress, "the circumstance was removed");
            Assert.AreEqual(0, br.LookAfterUnsupported, "under B, looking after somebody always stands on something that happened");
            Assert.AreEqual(ar.PeoplePresentAtDecisions, ar.LookAfterRaised, "under A it is raised about everybody present at every decision, whatever happens");
        }

