    /// <summary>
    /// S1.5: traits and values as standing wants (A, as shipped) against traits and
    /// values as dispositions that scale a response (B), with the gate (B0) as an
    /// ablation for attribution. Design conditions only. Everything is recorded
    /// whichever way it comes out; the assertions check the mechanism, never a
    /// behavioural number. Writes Docs/slices/S1.5/experiment-results.md.
    /// </summary>
    public class S15ExperimentTests
    {
        const int AuditSeeds = 10;
        const int BatchSeeds = 40;

        static Scenario001Content _content;
        static IReadOnlyList<string> _variants;
        static Dictionary<string, S15Measured> _measured;
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        static readonly (string Label, string Mode)[] Modes =
        {
            ("A standing", DispositionMode.Standing),
            ("B respond", DispositionMode.Respond),
            ("B0 gated", DispositionMode.Gated)
        };

        [OneTimeSetUp]
        public void Load()
        {
            _content = Scenario001Content.Load(TestPaths.DataRoot);
            _variants = _content.Morning.Variants.Select(v => v.Id).ToList();
        }

        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# S1.5 experiment results");
            sb.AppendLine();
            sb.AppendLine("Generated by `S15ExperimentTests`. The five design conditions. **A** is the shipped rules (`standing`). **B** is traits and values as dispositions (`respond`): `urgency = C x (1 + D)`. **B0** is the gate, an ablation for attribution only (`gated`). Nothing else differs between them.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "slices", "S1.5");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "experiment-results.md"), sb.ToString());
        }

        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static Dictionary<string, S15Measured> Measured()
        {
            if (_measured != null) return _measured;
            _measured = new Dictionary<string, S15Measured>(StringComparer.Ordinal);
            foreach (var (label, mode) in Modes)
                _measured[label] = S15.Measure(S15.Mode(_content, mode), label, _variants, AuditSeeds, BatchSeeds);
            return _measured;
        }

        static string Row(string name, Func<S15Measured, string> value)
            => "| " + name + " | " + string.Join(" | ", Modes.Select(m => value(Measured()[m.Label]))) + " |";

        static string Header(string first) => "| " + first + " | " + string.Join(" | ", Modes.Select(m => m.Label)) + " |" + Environment.NewLine +
                                             "|---|" + string.Join("|", Modes.Select(_ => "---")) + "|";

