        [Test, Timeout(3600000)]
        public void E1_WhereWantsComeFrom()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 1. Where wants come from");
            sb.AppendLine();
            sb.AppendLine("Decisions from seeds 1 to " + AuditSeeds + ".");
            sb.AppendLine();
            sb.AppendLine(Header("Measure"));
            sb.AppendLine(Row("Decisions", m => m.Audit.Decisions.ToString()));
            sb.AppendLine(Row("Wants raised", m => m.Sources.Raised.ToString()));
            sb.AppendLine(Row("... from circumstance", m => S15.P(m.Sources.Share(Support.FromCircumstance))));
            sb.AppendLine(Row("... mostly disposition", m => S15.P(m.Sources.Share(Support.MostlyDisposition))));
            sb.AppendLine(Row("... unsupported", m => S15.P(m.Sources.Share(Support.Unsupported))));
            sb.AppendLine(Row("... raised on traits and values alone", m => MotivationSources.P(m.Sources.OnTraitsAndValuesAlone, m.Sources.Raised)));
            sb.AppendLine(Row("... standing on history alone (evidence, ledger)", m => MotivationSources.P(m.Sources.StandingWithReasons, m.Sources.Raised)));
            foreach (Source s in Enum.GetValues(typeof(Source)))
                sb.AppendLine(Row("Urgency from " + s, m => S15.P(m.Sources.ShareOfUrgency(s))));
            sb.AppendLine(Row("Wants resting on something that happened (trace)", m => MotivationSources.P(m.Sources.WantsTraced, m.Sources.Raised)));
            sb.AppendLine(Row("Urgency resting on something that happened (trace)", m => MotivationSources.P(m.Sources.UrgencyTraced, m.Sources.UrgencyTraced + m.Sources.UrgencyUntraced)));
            sb.AppendLine(Row("Decisions with nothing wanted at all", m => MotivationSources.P(m.Sources.NothingWanted, m.Sources.Decisions)));
            sb.AppendLine(Row("Decisions changed by taking out unsupported wants", m => MotivationSources.P(m.DecidedByUnsupportedWants, m.Audit.Decisions)));
            sb.AppendLine(Row("Decisions changed by taking out the trait and value part of wants", m => MotivationSources.P(m.DecidedByTraitsAndValuesInWants, m.Audit.Decisions)));
            sb.AppendLine();
            foreach (var (label, _) in Modes)
            {
                sb.AppendLine("### " + label);
                sb.AppendLine();
                sb.AppendLine(Measured()[label].Sources.ToMarkdown());
            }
            Record("1", sb.ToString());

            var b = Measured()["B respond"];
            Assert.AreEqual(0, b.Sources.OnTraitsAndValuesAlone, "under B nothing may be raised on traits and values alone");
            Assert.Greater(Measured()["A standing"].Sources.OnTraitsAndValuesAlone, 0, "the instrument sees standing wants where they exist");
        }

