        [Test, Timeout(1800000)]
        public void D5_WhenNothingIsWanted()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 5. When nothing is wanted");
            sb.AppendLine();
            sb.AppendLine("| World | Decisions | With no want at all | ... chose | Led by no want (\"nothing pressing\") | ... chose | ... settled by the seed | ... between |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (var (label, content) in new[] { ("as written", _b), ("nothing missing", S15.NothingMissing(_b)) })
            {
                var decisions = 0; var none = 0; var unled = 0; var unledAmbiguous = 0;
                var noneChose = new Dictionary<string, int>(StringComparer.Ordinal);
                var unledChose = new Dictionary<string, int>(StringComparer.Ordinal);
                var unledTied = new Dictionary<string, int>(StringComparer.Ordinal);
                foreach (var v in _variants)
                for (ulong seed = 1; seed <= Seeds; seed++)
                {
                    var run = Scenario001.Prepare(content, v, seed);
                    run.Morning.Decided = m =>
                    {
                        decisions++;
                        var kind = m.Decision.Chosen.KindName;
                        if (m.Motives.Count == 0)
                        {
                            none++;
                            noneChose.TryGetValue(kind, out var n); noneChose[kind] = n + 1;
                        }
                        if (m.Decision.Leading == null)
                        {
                            unled++;
                            unledChose.TryGetValue(kind, out var n); unledChose[kind] = n + 1;
                            if (m.Decision.Resolution == Resolution.Ambiguous)
                            {
                                unledAmbiguous++;
                                var tied = string.Join(", ", m.Decision.Tied.Select(t => t.KindName).Distinct().OrderBy(k => k, StringComparer.Ordinal));
                                unledTied.TryGetValue(tied, out var t); unledTied[tied] = t + 1;
                            }
                        }
                    };
                    run.Morning.Run(content.Morning.Minutes);
                }
                sb.AppendLine("| " + label + " | " + decisions + " | " + none + " | " + Kinds(noneChose) + " | " + unled + " | " + Kinds(unledChose) + " | " + unledAmbiguous + " | " + Kinds(unledTied) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("A decision led by no want is one where nothing added to what was chosen: every option was worth nothing or less, and the cheapest won. With every appeal at zero, any act whose price is inside the ambiguity band of standing still ties with it, and the seed decides.");
            Record("5", sb.ToString());
        }

        static string Kinds(Dictionary<string, int> d)
            => d.Count == 0 ? "-" : string.Join(", ", d.OrderByDescending(k => k.Value).Select(k => k.Key + " " + k.Value));
    }
