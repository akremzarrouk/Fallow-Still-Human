        [Test, Timeout(1800000)]
        public void D4_WhatAWalkGivenUpLeavesBehind()
        {
            var lapsed = Walks().Where(w => w.Commitment == Commitment.NotWorthIt).ToList();
            var meanings = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (var w in lapsed)
            foreach (var m in (w.ExperienceMeanings ?? "").Split(new[] { ", " }, StringSplitOptions.RemoveEmptyEntries))
            {
                meanings.TryGetValue(m, out var n); meanings[m] = n + 1;
            }

            var sb = new StringBuilder();
            sb.AppendLine("## 4. What a walk given up leaves behind");
            sb.AppendLine();
            sb.AppendLine("For the " + lapsed.Count + " walks given up on arrival as not worth what it costs there, what the walker had by the time they decided that they did not have when they set out:");
            sb.AppendLine();
            sb.AppendLine("| Left behind | Total | Walks with any |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Experiences (things perceived on the way or on arrival) | " + lapsed.Sum(w => w.ExperiencesGained) + " | " + lapsed.Count(w => w.ExperiencesGained > 0) + " |");
            sb.AppendLine("| Beliefs moved | " + lapsed.Sum(w => w.BeliefsMoved) + " | " + lapsed.Count(w => w.BeliefsMoved > 0) + " |");
            sb.AppendLine("| Outcomes recorded (S1.3: only for wants that read a need) | " + lapsed.Sum(w => w.OutcomesRecorded) + " | " + lapsed.Count(w => w.OutcomesRecorded > 0) + " |");
            sb.AppendLine();
            sb.AppendLine("What the experiences meant to them: " + (meanings.Count == 0 ? "nothing" : string.Join(", ", meanings.OrderByDescending(k => k.Value).Select(k => k.Key + " " + k.Value))) + ".");
            sb.AppendLine();
            sb.AppendLine("The want the walk was for, on arrival against departure: mean change " + S16.F(lapsed.Average(w => w.WantUrgencyOnArrival - w.WantUrgencyAtDeparture)) +
                          ", higher on arrival in " + lapsed.Count(w => w.WantUrgencyOnArrival > w.WantUrgencyAtDeparture + 1e-9) + ", lower in " + lapsed.Count(w => w.WantUrgencyOnArrival < w.WantUrgencyAtDeparture - 1e-9) + ", the same in " + lapsed.Count(w => Math.Abs(w.WantUrgencyOnArrival - w.WantUrgencyAtDeparture) <= 1e-9) + ".");
            sb.AppendLine();
            sb.AppendLine("Nothing that could make the same walk less worth proposing next time is written anywhere the next deliberation reads: the want is raised again from the same state, and the walk is worth what the want is worth.");
            Record("4", sb.ToString());
        }

