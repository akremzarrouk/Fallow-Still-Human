        [Test]
        public void D3_LeoSettingOutAndArriving()
        {
            var run = Scenario001.Prepare(_b, "daniel_ate_it", 9);
            var sb = new StringBuilder();
            sb.AppendLine("## 3. Leo, `daniel_ate_it` seed 9: setting out at minute 25, arriving at minute 29");
            sb.AppendLine();
            string foresight = null;
            run.Morning.Decided = m =>
