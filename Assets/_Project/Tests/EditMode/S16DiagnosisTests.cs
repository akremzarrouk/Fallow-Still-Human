        [Test, Timeout(1800000)]
        public void D2_WhetherTheWalkerCouldHaveForeseenTheLapse()
        {
            var walks = Walks();
            var arrived = walks.Where(w => w.Arrived).ToList();
            var lapsedNotWorthIt = arrived.Where(w => w.Commitment == Commitment.NotWorthIt).ToList();
            var held = arrived.Where(w => w.Held).ToList();

            var sb = new StringBuilder();
            sb.AppendLine("## 2. Could the walker have foreseen the lapse?");
            sb.AppendLine();
            sb.AppendLine(walks.Count + " walks set out on for a want. " + arrived.Count + " arrived and decided with the intention carried in (the rest were stopped on the way or the morning ended). What became of the intention on arrival, against what the walker could have foreseen when they set out:");
            sb.AppendLine();
            sb.AppendLine("| On arrival | Walks | Foreseen worth doing | Foreseen not worth doing | Foreseen: nothing there serves it |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var group in arrived.GroupBy(w => w.Commitment).OrderBy(g => g.Key, StringComparer.Ordinal))
                sb.AppendLine("| " + group.Key + " | " + group.Count() + " | " + group.Count(w => w.Foreseen.WorthIt) + " | " +
                              group.Count(w => w.Foreseen.Possible && !w.Foreseen.WorthIt) + " | " + group.Count(w => !w.Foreseen.Possible) + " |");
            sb.AppendLine();

            var foreseeable = lapsedNotWorthIt.Where(w => !w.Foreseen.WorthIt).ToList();
            var surprises = lapsedNotWorthIt.Where(w => w.Foreseen.WorthIt).ToList();
            sb.AppendLine("**Given up as not worth what it costs there: " + lapsedNotWorthIt.Count + ".** Foreseeable at departure: " + foreseeable.Count + " (" + S16.P(foreseeable.Count, lapsedNotWorthIt.Count) + "). " +
                          "Not foreseeable: " + surprises.Count + ", of which somebody was in the room on arrival in " + surprises.Count(w => w.PresentOnArrival > 0) +
                          ", and the want was lower on arrival than at departure in " + surprises.Count(w => w.WantUrgencyOnArrival < w.WantUrgencyAtDeparture - 1e-9) + ".");
            sb.AppendLine();
            sb.AppendLine("**Held: " + held.Count + ".** Foreseen worth doing: " + held.Count(w => w.Foreseen.WorthIt) + " (" + S16.P(held.Count(w => w.Foreseen.WorthIt), held.Count) + "). " +
                          "Foreseen not worth doing but held anyway: " + held.Count(w => !w.Foreseen.WorthIt) + ", of which somebody was in the room on arrival in " + held.Count(w => !w.Foreseen.WorthIt && w.PresentOnArrival > 0) + ".");
            sb.AppendLine();

            sb.AppendLine("By want, walks that arrived:");
            sb.AppendLine();
            sb.AppendLine("| Want | Walks | Held | Given up | ... foreseeable | Mean worth of the walk to the want | Mean foreseen worth of the end |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (var group in arrived.GroupBy(w => w.Want.Split(':')[0]).OrderByDescending(g => g.Count()))
            {
                var lapsed = group.Where(w => w.Lapsed).ToList();
                var possible = group.Where(w => w.Foreseen.Possible).ToList();
                sb.AppendLine("| `" + group.Key + "` | " + group.Count() + " | " + group.Count(w => w.Held) + " | " + lapsed.Count + " | " +
                              lapsed.Count(w => !w.Foreseen.WorthIt) + " | " + S16.F(group.Average(w => w.WalkWorth)) + " | " +
                              (possible.Count == 0 ? "-" : S16.F(possible.Average(w => w.Foreseen.Score))) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Walks whose end was foreseeably not worth doing, as a share of every walk set out on: " + S16.P(walks.Count(w => !w.Foreseen.WorthIt), walks.Count) + " (" + walks.Count(w => !w.Foreseen.WorthIt) + " of " + walks.Count + ").");
            sb.AppendLine();
            sb.AppendLine("Where the foreseeably pointless walks went, by want and destination:");
            sb.AppendLine();
            sb.AppendLine("| Want | To | Walks | Foreseen best there |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var group in walks.Where(w => !w.Foreseen.WorthIt).GroupBy(w => w.Want.Split(':')[0] + " -> " + w.To).OrderByDescending(g => g.Count()).Take(10))
            {
                var sample = group.First();
                sb.AppendLine("| `" + group.Key.Split(' ')[0] + "` | " + sample.To + " | " + group.Count() + " | " + string.Join("; ", group.Select(w => w.Foreseen.Best?.Option.Key ?? "nothing").Distinct().Take(3)) + " |");
            }
            Record("2", sb.ToString());

            Assert.Greater(lapsedNotWorthIt.Count, 0, "the instrument saw the walks S1.5 counted");
        }

