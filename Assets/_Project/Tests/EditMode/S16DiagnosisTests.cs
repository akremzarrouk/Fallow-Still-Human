        [Test, Timeout(1800000)]
        public void D1_TheMemoryOfTheOpeningCountNeverFades()
        {
            var opening = _content.Morning.Opening;
            var sb = new StringBuilder();
            sb.AppendLine("## 1. The memory of the opening count");
            sb.AppendLine();
            sb.AppendLine("`find_out` is carried by the memory of the count coming up short (concern and threat about `missing_can`). A memory presses at salience x freshness, and freshness halves over the recall half life (" + _content.Rules.Deciding.RecallHalfLife + " minutes) from the minute the event happened. The opening event `" + opening.Id + "` is scripted and carries minute " + opening.Minute + ".");
            sb.AppendLine();

            // Mean find_out per person per ten minutes.
            sb.AppendLine("Mean `find_out` urgency per person, by ten minutes of the morning (B, seeds 1 to " + Seeds + "):");
            sb.AppendLine();
            sb.AppendLine(S16.Timeline(_b, _variants, 1, Seeds, "find_out"));

            // Every memory of today that carries no minute, and what the strongest
            // memory term behind find_out drew on, with its freshness at the end.
            var timeless = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
            var freshness = new Dictionary<string, List<double>>(StringComparer.Ordinal);
            var restsOnTimeless = new Dictionary<string, int>(StringComparer.Ordinal);
            var restsOnTimed = new Dictionary<string, int>(StringComparer.Ordinal);
            var drewOn = new Dictionary<string, int>(StringComparer.Ordinal);
            var wantsSeen = 0;
            foreach (var p in S16.People) { freshness[p] = new List<double>(); timeless[p] = new Dictionary<string, string>(StringComparer.Ordinal); restsOnTimeless[p] = 0; restsOnTimed[p] = 0; }

            foreach (var v in _variants)
            for (ulong seed = 1; seed <= Seeds; seed++)
            {
                var run = Scenario001.Prepare(_b, v, seed);
                run.Morning.Decided = m =>
                {
                    foreach (var x in m.Mind.Experiences.Where(x => x.Day == _content.Morning.Day && x.Minute < 0))
                        timeless[m.CharacterId][x.EventId] = x.Meaning + " (salience " + x.Salience.ToString("0.00") + ")";

                    var want = m.Motives.FirstOrDefault(x => x.Name == "find_out");
                    if (want == null) return;
                    wantsSeen++;
                    var memoryTerms = want.Terms.Where(t => t.Kind == ScalerKind.Memory && t.Amount > 0.0).ToList();
                    if (memoryTerms.Count == 0) return;
                    var strongest = memoryTerms.OrderByDescending(t => t.Amount).First();
                    var kept = strongest.Drew.Select(id => m.Mind.Experiences.FirstOrDefault(x => x.TraceId == id)).FirstOrDefault(x => x != null);
                    if (kept == null) return;

                    var e = run.Result.Events.FirstOrDefault(x => x.Id == kept.EventId);
                    var key = (e == null ? kept.EventId + " (scripted, minute " + kept.Minute + ")" : e.Action + " (this morning)") + ", read as " + kept.Meaning;
                    drewOn.TryGetValue(key, out var n); drewOn[key] = n + 1;
                    if (kept.Minute < 0) restsOnTimeless[m.CharacterId]++; else restsOnTimed[m.CharacterId]++;

                    if (m.Minute < _content.Morning.Minutes - 10 || kept.Minute >= 0 || kept.Salience <= 0.0) return;
                    freshness[m.CharacterId].Add(strongest.Level / kept.Salience);
                };
                run.Morning.Run(_content.Morning.Minutes);
            }

            sb.AppendLine("Memories of today that carry no minute, by person (every one is scripted: the three day-4 events of the backstory and the opening):");
            sb.AppendLine();
            sb.AppendLine("| Who | Event: what it was kept as |");
            sb.AppendLine("|---|---|");
            foreach (var p in S16.People)
                sb.AppendLine("| " + p + " | " + (timeless[p].Count == 0 ? "none" : string.Join("; ", timeless[p].OrderBy(k => k.Key, StringComparer.Ordinal).Select(k => "`" + k.Key + "` " + k.Value))) + " |");
            sb.AppendLine();
            sb.AppendLine("What the strongest memory term behind `find_out` drew on, over " + wantsSeen + " wants raised: " +
                          string.Join("; ", drewOn.OrderByDescending(k => k.Value).Select(k => k.Key + " " + k.Value)) + ".");
            sb.AppendLine();
            sb.AppendLine("| Who | `find_out` resting on a memory with no minute | ... on a memory of this morning | Freshness of the no-minute memory in the last ten minutes (level / salience) |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var p in S16.People)
                sb.AppendLine("| " + p + " | " + restsOnTimeless[p] + " | " + restsOnTimed[p] + " | " +
                              (freshness[p].Count == 0 ? "-" : freshness[p].Min().ToString("0.000") + " to " + freshness[p].Max().ToString("0.000") + " over " + freshness[p].Count + " decisions") + " |");
            sb.AppendLine();

            // Leo's find_out at the end of the worst morning, walked back.
            var worst = Scenario001.Prepare(_b, "daniel_ate_it", 9);
            string why = null;
            worst.Morning.Decided = m =>
            {
                if (m.CharacterId != "leo" || m.Minute < 85) return;
                var want = m.Motives.FirstOrDefault(x => x.Name == "find_out");
                if (want != null && why == null) why = "Leo, minute " + m.Minute + ":" + Environment.NewLine + Environment.NewLine + "```" + Environment.NewLine + worst.Trace.Why(want.TraceId) + "```";
            };
            worst.Morning.Run(_content.Morning.Minutes);
            sb.AppendLine("Leo's `find_out` at the end of `daniel_ate_it` seed 9, walked back:");
            sb.AppendLine();
            sb.AppendLine(why ?? "not raised");
            Record("1", sb.ToString());

            Assert.AreEqual(-1, opening.Minute, "the opening event carries no minute");
            foreach (var p in S16.People)
            {
                Assert.IsTrue(timeless[p].ContainsKey(opening.Id), p + " remembers the opening with no minute");
                Assert.IsTrue(freshness[p].All(f => Math.Abs(f - 1.0) < 1e-9), p + ": a memory with no minute is still fully fresh at the end of the morning");
            }
            Assert.Greater(S16.People.Sum(p => freshness[p].Count), 0, "somebody's find_out rests on a memory with no minute at the end of the morning");
        }

