        /// <summary>
        /// A person as the scenario starts them: their real profile, their real
        /// seeded beliefs, and nothing that a morning has yet done to them.
        /// </summary>
        static Mind Fresh(string who)
        {
            var mind = new Mind(_content.Cast[who]);
            foreach (var s in _content.Cast[who].InitialBeliefs) mind.Beliefs.Seed(s);
            return mind;
