            public string Competing;
            public string Beliefs;
            public string Feelings;
            public string Memories;
            public string Room;
            public double Answerable;
            public IReadOnlyList<string> Present;
        }

        sealed class MorningRun
        {
            public string Fingerprint;
            public string IntentLine;
            public List<Act> Acts = new List<Act>();
            public IReadOnlyList<WorldEvent> Events;
        }

        /// <summary>
        /// A whole morning with the selector installed on the intent hook. The
        /// intention is formed from the circumstances at the moment the person
        /// decided, not the moment the act finished, because that is when a
        /// person forms one.
        /// </summary>
        static MorningRun RunWithSelector(string label, string variant, ulong seed, bool install = true)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            var m = new MorningRun();
            var atDecision = new Dictionary<int, Act>();

            run.Morning.Decided = moment =>
            {
                var d = moment.Decision;
                var leading = d.Leading;
                var act = new Act
                {
                    Variant = variant,
                    Seed = seed,
                    Minute = moment.Minute,
                    Who = moment.CharacterId,
                    Want = leading?.Name,
                    WantTarget = leading?.TargetId,
                    Urgency = leading?.Urgency ?? 0.0,
                    Action = d.Chosen.Key,
                    Target = d.Chosen.TargetId,
                    Destination = d.Chosen.DestinationRoomId,
                    Room = moment.Percept.Room?.Id,
                    Answerable = moment.Mind.Beliefs.Confidence("answerable_for", new[] { moment.CharacterId, "missing_can" }),
                    Present = moment.Percept.Present.OrderBy(x => x, StringComparer.Ordinal).ToList(),
                    Competing = string.Join(", ", moment.Motives.OrderByDescending(x => x.Urgency)
                        .ThenBy(x => x.Key, StringComparer.Ordinal).Take(4)
                        .Select(x => x.Key + " " + F(x.Urgency))),
                    Beliefs = string.Join(", ", moment.Mind.Beliefs.All.Where(b => b.Confidence > 0.0)
                        .Select(b => b.Key + " " + F(b.Confidence))),
                    Feelings = string.Join(", ", moment.Mind.Emotions.Live.OrderByDescending(e => e.Intensity)
                        .Take(3).Select(e => e.Type + (e.TargetId == null ? "" : ":" + e.TargetId) + " " + F(e.Intensity))),
                    Memories = string.Join(", ", moment.Mind.Experiences
                        .Where(x => x.Day == _content.Morning.Day).Reverse().Take(3)
                        .Select(x => "m" + x.Minute + " " + x.Meaning))
                };
                act.Formed = leading == null
                    ? new Formed()
                    : Form(moment.Mind, moment.Percept, leading, _content.Morning.Day);
                atDecision[d.TraceId] = act;
                m.Acts.Add(act);
            };

            if (install)
                run.Morning.IntentOfAct = (who, action, decision) =>
                    decision != null && atDecision.TryGetValue(decision.TraceId, out var a) ? a.Formed.Intent : null;

            run.Morning.Run(_content.Morning.Minutes);
            m.Events = run.Result.Events;
            m.Fingerprint = string.Join("\n", run.Result.Actions.Select(x =>
                x.ToString() + " | " + x.Resolution + " " + x.Margin.ToString("R", CultureInfo.InvariantCulture)));
            m.IntentLine = string.Join("\n", m.Acts.Select(x => x.Minute + " " + x.Who + " " + Or(x.Want) + (x.WantTarget == null ? "" : ":" + x.WantTarget) + " -> " + Or(x.Formed.Intent)));
            return m;
        }

        static string BaselineFingerprint(string variant, ulong seed)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            run.Morning.Run(_content.Morning.Minutes);
            return string.Join("\n", run.Result.Actions.Select(x =>
                x.ToString() + " | " + x.Resolution + " " + x.Margin.ToString("R", CultureInfo.InvariantCulture)));
        }

