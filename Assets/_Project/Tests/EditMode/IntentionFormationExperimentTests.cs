        [Test]
        public void SamePlaceSameWantDifferentPeople()
        {
            var p = Stage();
            var company = new List<string> { "daniel", "elena", "leo", "mara" };

            var sb = new StringBuilder();
            sb.AppendLine("## N3. The same want, the same room, four different people");
            sb.AppendLine();
            sb.AppendLine("Everything circumstantial is held identical: the same room, the same company, the same minute, the same urgency. Only the person differs, and they differ only by what the shipped character sheets say they are.");
            sb.AppendLine();
            sb.AppendLine("| Want | daniel | elena | leo | mara | Distinct |");
            sb.AppendLine("|---|---|---|---|---|---|");

            var disagreed = 0;
            foreach (var want in Wants)
            {
                var cells = new List<string>();
                var chosen = new List<string>();
                foreach (var who in People)
                {
                    var others = company.Where(x => x != who).ToList();
                    var target = want == "look_after" ? others[0] : null;
                    var f = Form(Fresh(who), In(p, who, "kitchen", others), Want(want, 0.6, target), _content.Morning.Day);
                    cells.Add(f.Line);
                    chosen.Add(Or(f.Intent));
                }
                var distinct = chosen.Distinct().Count();
                if (distinct > 1) disagreed++;
                sb.AppendLine("| `" + want + "` | " + string.Join(" | ", cells) + " | " + distinct + " |");
            }
            sb.AppendLine();
            sb.AppendLine("**Wants on which the four disagreed: " + disagreed + " of " + Wants.Count + ".**");
            sb.AppendLine();

            sb.AppendLine("### Why they disagree, taken apart");
            sb.AppendLine();
            sb.AppendLine("`restore_standing` in company, every candidate and every term:");
            sb.AppendLine();
            foreach (var who in People)
            {
                var others = company.Where(x => x != who).ToList();
                var f = Form(Fresh(who), In(p, who, "kitchen", others), Want("restore_standing"), _content.Morning.Day);
                sb.AppendLine("**" + who + "** -> `" + Or(f.Intent) + "`");
                sb.AppendLine();
                foreach (var w in f.Considered)
                {
                    sb.AppendLine("- `" + w.Intent + "` " + F(w.Weight) + " from " + string.Join(", ", w.Rules));
                    foreach (var why in w.Why) sb.AppendLine("  - " + why);
                }
                sb.AppendLine();
            }
            Record("N3", sb.ToString());

            Assert.Greater(disagreed, 0, "P3: the person must be able to change the intention");
        }

