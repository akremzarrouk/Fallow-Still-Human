    /// <summary>
    /// The intention-formation experiment: can a plausible intention be derived
    /// from an existing want and the person's circumstances, without a universal
    /// Want -> Intention table?
    ///
    /// Three things are kept apart throughout. The **want** is what a person is
    /// driven toward; the **intention** is what they take themselves to be
    /// accomplishing; the **act** is what they do. The previous experiment showed
    /// the third is independent of the second. This one tests whether the second
    /// is independent of the first.
    ///
    /// Everything hand-authored lives in `Data/Experiments/intentions.json`,
    /// which nothing in `Fallow.Core` loads. It was written blind, from the
    /// character sheets and the vocabulary, and committed before any case ran, so
    /// every case here is held out from authoring. There is no new code in
    /// `Fallow.Core`; the selector below is thirty lines over the shipped
    /// `ScalerEval` and the shipped `SituationCondition`, and it uses no
    /// randomness of any kind.
    ///
    /// Writes `Docs/experiments/intention-formation/measurements.md`.
    /// </summary>
    public class IntentionFormationExperimentTests
    {
