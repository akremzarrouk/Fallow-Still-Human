        [Test]
        [Timeout(600000)]
        public void FiftyHeldOutMornings()
        {
            var acts = new List<Act>();
            var runs = new List<MorningRun>();
            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var m = RunWithSelector("live", v, seed);
                runs.Add(m);
                acts.AddRange(m.Acts);
            }

            var sb = new StringBuilder();
            sb.AppendLine("## N6. Fifty mornings, all of them held out from authoring");
            sb.AppendLine();
            sb.AppendLine("The candidate rules were committed before any of this ran. Every decision below is a case the rules were not written against.");
            sb.AppendLine();
            sb.AppendLine("**" + acts.Count + " decisions across " + runs.Count + " mornings.**");
            sb.AppendLine();

            var withWant = acts.Where(a => a.Want != null && a.Want != "nothing pressing").ToList();
            var withIntent = withWant.Where(a => a.Formed.Intent != null).ToList();
            sb.AppendLine("| | Count | Share |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Decisions with a leading want | " + withWant.Count + " | " + Pc(withWant.Count, acts.Count) + " |");
            sb.AppendLine("| ...that formed an intention | " + withIntent.Count + " | " + Pc(withIntent.Count, withWant.Count) + " |");
            sb.AppendLine("| ...that formed none | " + (withWant.Count - withIntent.Count) + " | " + Pc(withWant.Count - withIntent.Count, withWant.Count) + " |");
            sb.AppendLine();

            sb.AppendLine("### What each want turned into");
            sb.AppendLine();
            sb.AppendLine("| Want | Decisions | Distinct intentions | Distribution |");
            sb.AppendLine("|---|---|---|---|");
            var singleValued = new List<string>();
            foreach (var g in withWant.GroupBy(a => a.Want).OrderByDescending(g => g.Count()))
            {
                var dist = g.GroupBy(a => Or(a.Formed.Intent)).OrderByDescending(x => x.Count())
                    .ThenBy(x => x.Key, StringComparer.Ordinal).ToList();
                var distinct = dist.Count(x => x.Key != "none");
                if (distinct <= 1) singleValued.Add(g.Key);
                sb.AppendLine("| `" + g.Key + "` | " + g.Count() + " | " + distinct + " | "
                              + string.Join(", ", dist.Select(x => "`" + x.Key + "` " + x.Count() + " (" + Pc(x.Count(), g.Count()) + ")")) + " |");
