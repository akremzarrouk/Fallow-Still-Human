        [Test]
        public void WhatIsAuthored()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## N1. The whole of the hand-authored surface");
            sb.AppendLine();
            sb.AppendLine("Counted from the file, not asserted. Every rule is listed; there is nothing else.");
            sb.AppendLine();
            sb.AppendLine("| Rule | Intention | Wants it is available to | Circumstance it needs | Base | Weighed by |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var c in _candidates)
                sb.AppendLine("| `" + c.Id + "` | `" + c.Intent + "` | " + string.Join(", ", c.Motives.Select(m => "`" + m + "`"))
                              + " | " + (c.When.IsEmpty ? "any" : Describe(c.When)) + " | " + F(c.Base)
                              + " | " + string.Join("; ", c.ScaledBy.Select(s => s.Describe() + " x " + F(s.Factor))) + " |");
            sb.AppendLine();
            sb.AppendLine("**" + _candidates.Count + " rules, " + _candidates.Select(c => c.Intent).Distinct().Count()
                          + " intentions, " + Wants.Count + " wants.**");
            sb.AppendLine();

            sb.AppendLine("The test that separates a constraint from a mapping: how many intentions each want can reach at all.");
            sb.AppendLine();
            sb.AppendLine("| Want | Intentions reachable | Which |");
            sb.AppendLine("|---|---|---|");
            var single = 0;
            foreach (var w in Wants)
            {
                var reach = _candidates.Where(c => c.Motives.Contains(w, StringComparer.Ordinal))
                    .Select(c => c.Intent).Distinct().OrderBy(s => s, StringComparer.Ordinal).ToList();
                if (reach.Count < 2) single++;
                sb.AppendLine("| `" + w + "` | " + reach.Count + " | " + string.Join(", ", reach.Select(r => "`" + r + "`")) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("**Wants with only one reachable intention (which would be a lookup table): " + single + ".**");
            sb.AppendLine();
            sb.AppendLine("And the other direction, which is what P5 asks about:");
            sb.AppendLine();
            sb.AppendLine("| Intention | Wants that can express it |");
            sb.AppendLine("|---|---|");
            foreach (var i in _candidates.Select(c => c.Intent).Distinct().OrderBy(s => s, StringComparer.Ordinal))
                sb.AppendLine("| `" + i + "` | " + string.Join(", ", _candidates.Where(c => c.Intent == i)
                    .SelectMany(c => c.Motives).Distinct().OrderBy(s => s, StringComparer.Ordinal)
                    .Select(m => "`" + m + "`")) + " |");
            sb.AppendLine();
            sb.AppendLine("A circumstance can gate a candidate but can never be the reason one beats another: `SituationCondition` has six fields and none of them is a trait, a value, a feeling or a need. That is the type, not a convention. Everything about the person is in the scalers, which the shipped `ScalerEval` evaluates.");
            Record("N1", sb.ToString());

            Assert.AreEqual(0, single, "a want with one reachable intention would be a lookup table");
            foreach (var c in _candidates)
            {
                Assert.IsTrue(_content.Vocabulary.Contains("self_meanings", c.Intent), c.Id + ": invented intention");
                foreach (var m in c.Motives)
                    Assert.IsTrue(_content.Vocabulary.Contains("motives", m), c.Id + ": invented want " + m);
                foreach (var s in c.ScaledBy)
                    Assert.Contains(s.Kind, ScalerKind.All.ToList(), c.Id + ": unknown scaler kind");
            }
        }

        static string Describe(SituationCondition w)
        {
            var parts = new List<string>();
            if (w.Alone.HasValue) parts.Add(w.Alone.Value ? "alone" : "not alone");
            if (w.OthersPresentMin.HasValue) parts.Add("at least " + w.OthersPresentMin.Value + " present");
            if (w.InOwnRoom.HasValue) parts.Add(w.InOwnRoom.Value ? "in my own room" : "not in my own room");
            if (w.InSomebodyElsesRoom.HasValue) parts.Add(w.InSomebodyElsesRoom.Value ? "in somebody else's room" : "not in somebody else's room");
            if (w.RoomHoldsFood.HasValue) parts.Add(w.RoomHoldsFood.Value ? "food is kept here" : "no food here");
            if (w.SearchedThisRoomMyself.HasValue) parts.Add(w.SearchedThisRoomMyself.Value ? "I have searched here" : "I have not searched here");
            return string.Join(", ", parts);
        }

