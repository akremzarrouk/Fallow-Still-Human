        [Test]
        public void CounterfactualSensitivity()
        {
            var p = Stage();
            var sb = new StringBuilder();
            sb.AppendLine("## N4. What moves it and what does not");
            sb.AppendLine();
            sb.AppendLine("Three perturbations against the same baseline moment. Two of them change something a rule reads; one changes something no rule in the file reads at all.");
            sb.AppendLine();
            sb.AppendLine("| Person | Want | Baseline (alone, kitchen) | +company (read) | in her own room (read by no rule here) | hungry (read by no rule here) |");
            sb.AppendLine("|---|---|---|---|---|---|");

            var relevantMoved = 0;
            var irrelevantMoved = 0;
            var cells = 0;
            foreach (var who in People)
            foreach (var want in Wants)
            {
                var mind = Fresh(who);
                var day = _content.Morning.Day;
                var here = In(p, who, "kitchen", new List<string>());
                var basis = Form(mind, here, Want(want), day);

                var withCompany = Form(mind, In(p, who, "kitchen", new List<string> { "elena", "leo" }), Want(want), day);

                // The same room and the same company; only a circumstance no rule
                // in the file asks about is different.
                var elsewhere = In(p, who, p.Run.World.House.Rooms.Select(r => r.Id)
                    .FirstOrDefault(r => r != "kitchen") ?? "kitchen", new List<string>());
                var moved = Form(mind, elsewhere, Want(want), day);

                var hungry = Form(mind, Starving(here), Want(want), day);

                cells++;
                if (basis.Intent != withCompany.Intent) relevantMoved++;
                if (basis.Intent != hungry.Intent) irrelevantMoved++;

                sb.AppendLine("| " + who + " | `" + want + "` | " + basis.Line + " | " + withCompany.Line
                              + " | " + moved.Line + " | " + hungry.Line + " |");
            }
            sb.AppendLine();
            sb.AppendLine("| | Count | Share of " + cells + " |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Adding company changed the intention | " + relevantMoved + " | " + Pc(relevantMoved, cells) + " |");
            sb.AppendLine("| Making them hungry changed the intention | **" + irrelevantMoved + "** | " + Pc(irrelevantMoved, cells) + " |");
            sb.AppendLine();
            sb.AppendLine("Hunger is a real scaler kind that the shipped motivation rules use heavily. No rule in the candidate file reads it, and the measurement confirms it never moves an intention. Moving the person to another room changes the room and the tags on it; the column is there so that a circumstance which *is* structurally available but unread by these rules can be seen not to matter either, except where being in a different room changes who is present.");
            Record("N4", sb.ToString());

            Assert.AreEqual(0, irrelevantMoved, "P9: a circumstance no rule reads must never change the intention");
            Assert.Greater(relevantMoved, 0, "P9: a circumstance the rules do read must sometimes change it");
        }

        static Percept Starving(Percept p)
            => new Percept(p.CharacterId, p.Minute, p.Room, p.Present, p.Adjacent, 1.0,
                p.RoomHoldsFood, p.FoodWithinReach, p.SearchedThisRoomMyself, null,
                p.LookedInThePantryMyself, p.JustWatched, p.RoomsIHaveSearched);

