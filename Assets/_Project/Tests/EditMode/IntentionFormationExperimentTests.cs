        [Test]
        public void SameWantDifferentContext()
        {
            var p = Stage();
            var kitchen = "kitchen";
            var alone = new List<string>();
            var company = new List<string> { "elena", "leo", "mara" };

            var sb = new StringBuilder();
            sb.AppendLine("## N2. The same want, in company and alone");
            sb.AppendLine();
            sb.AppendLine("One person, one want, one room, one moment. The only difference is whether anybody else is standing there. Nothing about the person changes between the two columns.");
            sb.AppendLine();

            var moved = 0;
            var pairs = 0;
            foreach (var who in People)
            {
                var mind = Fresh(who);
                sb.AppendLine("### " + who);
                sb.AppendLine();
                sb.AppendLine("| Want | With the others in the room | Alone | Changed |");
                sb.AppendLine("|---|---|---|---|");
                foreach (var want in Wants)
                {
                    var target = want == "look_after" ? (who == "elena" ? "mara" : "elena") : null;
                    var withThem = Form(mind, In(p, who, kitchen, company), Want(want, 0.6, target), _content.Morning.Day);
                    var byHimself = Form(mind, In(p, who, kitchen, alone), Want(want, 0.6, target), _content.Morning.Day);
                    pairs++;
                    var changed = withThem.Intent != byHimself.Intent;
                    if (changed) moved++;
                    sb.AppendLine("| `" + want + "` | " + withThem.Line + " | " + byHimself.Line + " | "
                                  + (changed ? "**yes**" : "no") + " |");
                }
                sb.AppendLine();
            }

            sb.AppendLine("**" + moved + " of " + pairs + " (person, want) pairs formed a different intention with an audience than without one.**");
            sb.AppendLine();
            sb.AppendLine("The want is identical in both columns, and so is everything about the person. Where the intention moved, the only thing that moved it was who else was in the room.");
            Record("N2", sb.ToString());

            Assert.Greater(moved, 0, "P1/P2: context must be able to change the intention");
        }

