        [Test]
        [Timeout(600000)]
        public void TheControls()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## N7. Controls");
            sb.AppendLine();
            sb.AppendLine("The selector must be able to be taken away without trace, or nothing measured above is attributable to it.");
            sb.AppendLine();
            sb.AppendLine("| Condition | Seed | Selector off | Selector installed, returning null | Selector installed and forming |");
            sb.AppendLine("|---|---|---|---|---|");

            var offSame = 0;
            var nullSame = 0;
            var formedDiffered = 0;
            var total = 0;
            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var baseline = BaselineFingerprint(v, seed);
                var off = RunWithSelector("off", v, seed, install: false);
                var nulled = NullSelector(v, seed);
                var on = RunWithSelector("on", v, seed);

                total++;
                if (off.Fingerprint == baseline) offSame++;
                if (nulled == baseline) nullSame++;
                if (on.Fingerprint != baseline) formedDiffered++;

                if (off.Fingerprint != baseline || nulled != baseline || seed == 1)
                    sb.AppendLine("| `" + v + "` | " + seed + " | " + (off.Fingerprint == baseline ? "identical" : "**differs**")
                                  + " | " + (nulled == baseline ? "identical" : "**differs**")
                                  + " | " + (on.Fingerprint == baseline ? "identical" : "differs") + " |");

                Assert.AreEqual(baseline, off.Fingerprint, v + " " + seed + ": C1");
                Assert.AreEqual(baseline, nulled, v + " " + seed + ": C2");
            }
            sb.AppendLine();
            sb.AppendLine("| | Count | Share |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| C1: selector off reproduces the shipped baseline | " + offSame + " of " + total + " | " + Pc(offSame, total) + " |");
            sb.AppendLine("| C2: selector installed but returning null does too | " + nullSame + " of " + total + " | " + Pc(nullSame, total) + " |");
            sb.AppendLine("| Mornings the formed intentions changed | " + formedDiffered + " of " + total + " | " + Pc(formedDiffered, total) + " |");
            sb.AppendLine();
            sb.AppendLine("The last row is not a control but a consequence: it is how often intentions formed by this mechanism, and read by the three shipped appraisal rules that read any intention at all, went on to change what somebody did.");
            Record("N7", sb.ToString());
        }

        static string NullSelector(string variant, ulong seed)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            run.Morning.IntentOfAct = (who, action, decision) => null;
            run.Morning.Run(_content.Morning.Minutes);
            return string.Join("\n", run.Result.Actions.Select(x =>
                x.ToString() + " | " + x.Resolution + " " + x.Margin.ToString("R", CultureInfo.InvariantCulture)));
        }
