        [Test]
        public void SameStateSameIntention()
        {
            var p = Stage();
            var sb = new StringBuilder();
            sb.AppendLine("## N5. Reproducibility");
            sb.AppendLine();
            sb.AppendLine("The selector draws no random number, so this should be exact rather than probable.");
            sb.AppendLine();

            var repeats = 0;
            var stable = 0;
            foreach (var who in People)
            foreach (var want in Wants)
            {
                var first = Form(Fresh(who), In(p, who, "kitchen", new List<string> { "leo" }), Want(want), _content.Morning.Day);
                for (var i = 0; i < 5; i++)
                {
                    var again = Form(Fresh(who), In(p, who, "kitchen", new List<string> { "leo" }), Want(want), _content.Morning.Day);
                    repeats++;
                    if (again.Intent == first.Intent && Math.Abs(again.Weight - first.Weight) < 1e-12) stable++;
                    Assert.AreEqual(first.Intent, again.Intent, who + " " + want);
                }
            }
            sb.AppendLine("**" + stable + " of " + repeats + " replays identical**, intention and weight, to full precision.");
            sb.AppendLine();

            // And a whole morning, replayed with the selector installed.
            var a = RunWithSelector("replay 1", _content.Morning.Variants[0].Id, 1);
            var b = RunWithSelector("replay 2", _content.Morning.Variants[0].Id, 1);
            sb.AppendLine("A whole morning run twice with the selector installed: "
                          + (a.Fingerprint == b.Fingerprint ? "**identical**" : "**differs**")
                          + ", and the intentions formed: " + (a.IntentLine == b.IntentLine ? "**identical**" : "**differ**") + ".");
            Record("N5", sb.ToString());

            Assert.AreEqual(a.Fingerprint, b.Fingerprint);
            Assert.AreEqual(a.IntentLine, b.IntentLine);
        }

