        [Test, Timeout(3600000)]
        public void E2_TheWalksAndWhatCouldBeForeseen()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. The walks, and what could be foreseen");
            sb.AppendLine();
            sb.AppendLine("Seeds 1 to " + AuditSeeds + ", the S1.6 diagnosis instrument: at the moment somebody set out, the best thing they could have done for the walk's want on arrival, as they could imagine it.");
            sb.AppendLine();
            sb.AppendLine(Header("Measure"));
            sb.AppendLine(Row("Walks set out on", l => Walks()[l].Count.ToString()));
            sb.AppendLine(Row("... whose end was foreseeably not worth doing", l => Walks()[l].Count(w => !w.Foreseen.WorthIt) + " (" + S16.P(Walks()[l].Count(w => !w.Foreseen.WorthIt), Walks()[l].Count) + ")"));
            sb.AppendLine(Row("Walks that arrived and decided with the intention", l => Walks()[l].Count(w => w.Arrived).ToString()));
            sb.AppendLine(Row("... held", l => Walks()[l].Count(w => w.Held).ToString()));
            sb.AppendLine(Row("... given up as not worth what it costs there", l => Walks()[l].Count(w => w.Commitment == Commitment.NotWorthIt).ToString()));
            sb.AppendLine(Row("...... with somebody in the room on arrival", l => Walks()[l].Count(w => w.Commitment == Commitment.NotWorthIt && w.PresentOnArrival > 0).ToString()));
            sb.AppendLine(Row("...... foreseeable at departure", l => Walks()[l].Count(w => w.Commitment == Commitment.NotWorthIt && !w.Foreseen.WorthIt).ToString()));
            sb.AppendLine(Row("... given up: nothing there serves it", l => Walks()[l].Count(w => w.Commitment == Commitment.Impossible).ToString()));
            sb.AppendLine(Row("... given up: no longer wanted", l => Walks()[l].Count(w => w.Commitment == Commitment.NoLongerWanted).ToString()));
            foreach (var want in new[] { "find_out", "get_food", "avoid_exposure", "keep_peace", "look_after", "guard_supplies" })
                sb.AppendLine(Row("Walks for `" + want + "`: set out / given up", l => Walks()[l].Count(w => w.Want.StartsWith(want, StringComparison.Ordinal)) + " / " + Walks()[l].Count(w => w.Want.StartsWith(want, StringComparison.Ordinal) && w.Lapsed)));
            sb.AppendLine();
            foreach (var label in new[] { "B end", "B timed end" })
            {
                var lapsed = Walks()[label].Where(w => w.Lapsed).ToList();
                sb.AppendLine("**" + label + "**, every walk given up on arrival, by want, destination and who was there: " +
                              (lapsed.Count == 0 ? "none." : string.Join("; ", lapsed.GroupBy(w => w.Want.Split(':')[0] + " -> " + w.To + (w.PresentOnArrival > 0 ? ", somebody there" : ", nobody there") + ", " + w.Commitment)
                                  .OrderByDescending(g => g.Count()).Select(g => g.Key + " " + g.Count())) + "."));
                sb.AppendLine();
            }
            Record("2", sb.ToString());

            foreach (var label in new[] { "B end", "B timed end" })
                Assert.AreEqual(0, Walks()[label].Count(w => !w.Foreseen.WorthIt), label + ": no walk is set out on whose end was foreseeably not worth doing");
            foreach (var label in new[] { "B", "B timed" })
                Assert.Greater(Walks()[label].Count(w => !w.Foreseen.WorthIt), 0, label + ": the instrument still sees pointless walks where nothing stops them");
        }

