    /// <summary>
    /// S1.6: the two mechanisms, alone and together, on B, with A and A-with-M1
    /// for reference. Design conditions only. Everything is recorded whichever
    /// way it comes out; the assertions check the mechanisms, never a behavioural
    /// number. Writes Docs/slices/S1.6/experiment-results.md.
    /// </summary>
    public class S16ExperimentTests
    {
        const int AuditSeeds = 10;
        const int BatchSeeds = 40;

        static Scenario001Content _content;
        static IReadOnlyList<string> _variants;
        static Dictionary<string, Scenario001Content> _conditions;
        static Dictionary<string, S15Measured> _measured;
        static Dictionary<string, List<S16.WalkRecord>> _walks;
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        static IEnumerable<string> Labels => S16.Conditions.Select(c => c.Label);

        [OneTimeSetUp]
        public void Load()
        {
            _content = Scenario001Content.Load(TestPaths.DataRoot);
            _variants = _content.Morning.Variants.Select(v => v.Id).ToList();
            _conditions = S16.Conditions.ToDictionary(c => c.Label, c => c.Make(_content), StringComparer.Ordinal);
        }

        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# S1.6 experiment results");
            sb.AppendLine();
            sb.AppendLine("Generated by `S16ExperimentTests`. The five design conditions. **A** is the shipped rules (`standing`). **B** is traits and values as dispositions (`respond`, S1.5). **timed** is M1: the four scripted events of the lived day carry minute 0. **end** is M2: a walk is credited to a want only if something could be done for that want on arrival that would be worth doing (`means: end`). Nothing else differs between conditions.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "slices", "S1.6");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "experiment-results.md"), sb.ToString());
        }

        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static Dictionary<string, S15Measured> Measured()
        {
            if (_measured != null) return _measured;
            _measured = new Dictionary<string, S15Measured>(StringComparer.Ordinal);
            foreach (var label in Labels)
                _measured[label] = S15.Measure(_conditions[label], label, _variants, AuditSeeds, BatchSeeds);
            return _measured;
        }

        static Dictionary<string, List<S16.WalkRecord>> Walks()
        {
            if (_walks != null) return _walks;
            _walks = new Dictionary<string, List<S16.WalkRecord>>(StringComparer.Ordinal);
            foreach (var label in Labels) _walks[label] = S16.Walks(_conditions[label], _variants, 1, AuditSeeds);
            return _walks;
        }

        static string Header(string first) => "| " + first + " | " + string.Join(" | ", Labels) + " |" + Environment.NewLine + "|---|" + string.Join("|", Labels.Select(_ => "---")) + "|";
        static string Row(string name, Func<string, string> value) => "| " + name + " | " + string.Join(" | ", Labels.Select(value)) + " |";
        static string RowM(string name, Func<S15Measured, string> value) => Row(name, l => value(Measured()[l]));

        // ---- 1 ----

        [Test, Timeout(3600000)]
        public void E1_WhatPeopleDo()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 1. What people do, and where wants come from");
            sb.AppendLine();
            sb.AppendLine("Behaviour from the S1 batch (seeds 1 to " + BatchSeeds + ", 200 mornings); decisions, walks and decisive rates from the S1.2 audit (seeds 1 to " + AuditSeeds + "); sources from the S1.5 instrument on the same decisions.");
            sb.AppendLine();
            sb.AppendLine(Header("Measure"));
            sb.AppendLine(RowM("Walks completed and followed by a decision (audit)", m => m.Audit.WalksWithAPurpose.ToString()));
            sb.AppendLine(RowM("... followed by something the walk's want did not serve", m => S15.P(m.AbandonedWalks)));
            sb.AppendLine(RowM("Pacing, mean per person per morning (audit)", m => m.MeanPacing.ToString("0.00")));
            sb.AppendLine(RowM("Worst pacing (batch)", m => m.WorstPacing + " (" + m.WorstPacingWho + ")"));
            sb.AppendLine(RowM("Walks to the food given up on arrival (audit)", m => m.Audit.CommitmentsByWant.TryGetValue("get_food: " + Commitment.NotWorthIt, out var n) ? n.ToString() : "0"));
            sb.AppendLine(RowM("Standing still, share of choices (batch)", m => S15.P(m.WaitShare)));
            sb.AppendLine(RowM("Standing still on top (audit)", m => S15.P(m.WaitOnTopShare)));
            sb.AppendLine(RowM("Sitting with somebody, share of choices", m => S15.P(m.SittingShare)));
            foreach (var want in new[] { "look_after", "keep_peace", "guard_supplies", "find_out", "get_food", "restore_standing", "avoid_exposure" })
                sb.AppendLine(RowM("`" + want + "` decisive", m => S15.P(m.Decisive(want))));
            sb.AppendLine(RowM("Different people, mean gap", m => S15.F(m.MeanGap)));
            sb.AppendLine(RowM("Weakest condition, mean gap", m => S15.F(m.WorstConditionMean)));
            sb.AppendLine(RowM("Closest pair", m => S15.F(m.ClosestPair) + " (" + m.ClosestWho + ")"));
            sb.AppendLine(RowM("Ties between genuinely different actions (batch)", m => S15.P(m.RealTies)));
            sb.AppendLine(RowM("Interruptions per morning", m => (m.Audit.Interruptions / (double)Math.Max(1, m.Audit.Mornings)).ToString("0.0")));
            sb.AppendLine(RowM("Meals (batch)", m => m.Meals.ToString()));
            sb.AppendLine(RowM("Wants raised (audit)", m => m.Sources.Raised.ToString()));
            sb.AppendLine(RowM("... unsupported", m => S15.P(m.Sources.Share(Support.Unsupported))));
            sb.AppendLine(RowM("... raised on traits and values alone", m => MotivationSources.P(m.Sources.OnTraitsAndValuesAlone, m.Sources.Raised)));
            sb.AppendLine(RowM("Wants resting on something that happened (trace)", m => MotivationSources.P(m.Sources.WantsTraced, m.Sources.Raised)));
            sb.AppendLine(RowM("Urgency from traits and values", m => S15.P(m.Sources.ShareOfUrgency(Source.Disposition))));
            sb.AppendLine();
            foreach (var label in Labels)
            {
                sb.AppendLine("**" + label + "**, what each person did across every condition:");
                sb.AppendLine();
                sb.AppendLine(S15.Profiles(Measured()[label]));
            }
            sb.AppendLine("How far each person's morning moved (the total difference between action profiles):");
            sb.AppendLine();
            sb.AppendLine("| Who | A to B | B to B timed | B to B end | B to B timed end | A to B timed end |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var p in S16.People)
            {
                string Gap(string x, string y) => S15.F(BatchRunner.HowDifferent(Measured()[x].ProfileByPerson[p], Measured()[y].ProfileByPerson[p]));
                sb.AppendLine("| " + p + " | " + Gap("A", "B") + " | " + Gap("B", "B timed") + " | " + Gap("B", "B end") + " | " + Gap("B", "B timed end") + " | " + Gap("A", "B timed end") + " |");
            }
            Record("1", sb.ToString());

            Assert.AreEqual(16060, Measured()["A"].BatchDecisions, "A is the shipped morning, unchanged by S1.6");
            foreach (var label in new[] { "B end", "B timed end" })
                Assert.AreEqual(0, Measured()[label].Sources.OnTraitsAndValuesAlone, label + ": B's property that nothing is raised on traits and values alone survives");
        }

