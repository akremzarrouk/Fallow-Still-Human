        [Test]
        public void E7_OneWalkUnderEndTraced()
        {
            var content = _conditions["B timed end"];
            var run = Scenario001.Prepare(content, "daniel_ate_it", 9);
            string declined = null, taken = null;
            run.Morning.Decided = m =>
            {
                var record = run.Trace.Get(m.Decision.TraceId);
                if (!record.Data.TryGetValue("foresaw", out var foresaw)) return;
                if (declined == null && foresaw.Contains("not worth walking for") && m.CharacterId == "leo")
                    declined = "Minute " + m.Minute + ", Leo in the " + m.Percept.Room.Id + ", chose " + m.Decision.Chosen + ". Foresaw: " + foresaw + ".";
                if (taken == null && m.Decision.Chosen.Kind == ActionKind.GoTo)
                    taken = "Minute " + m.Minute + ", " + m.CharacterId + " in the " + m.Percept.Room.Id + ", chose " + m.Decision.Chosen + " for " + (m.Decision.Leading?.Key ?? "nothing") + ". Foresaw: " + foresaw + "." +
                            Environment.NewLine + Environment.NewLine + "```" + Environment.NewLine + DecisionTrace.Explain(m.Decision) + "```";
            };
            run.Morning.Run(content.Morning.Minutes);
            Record("7", "## 7. Walks under `end`, traced" + Environment.NewLine + Environment.NewLine +
                        "A walk not credited, because its end would not be worth doing:" + Environment.NewLine + Environment.NewLine + (declined ?? "none found") + Environment.NewLine + Environment.NewLine +
                        "A walk taken, because its end could be:" + Environment.NewLine + Environment.NewLine + (taken ?? "none found") + Environment.NewLine);
            Assert.IsNotNull(declined, "Leo declines a walk he would have taken under B");
            Assert.IsNotNull(taken, "somebody still walks somewhere, for an end that could be worth it");
        }

