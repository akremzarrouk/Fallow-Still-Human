        static string F(double v) => v.ToString("0.000", CultureInfo.InvariantCulture);
        static string Or(string s) => string.IsNullOrEmpty(s) ? "none" : s;
        static string Pc(double part, double whole)
            => whole == 0 ? "n/a" : (100.0 * part / whole).ToString("0.0", CultureInfo.InvariantCulture) + " %";

        static string Sha(string path)
        {
            using (var sha = SHA256.Create())
                return string.Concat(sha.ComputeHash(File.ReadAllBytes(path)).Select(b => b.ToString("x2")));
        }

        // ============================================================ the held-out people

        sealed class Declared
        {
            public string Id;
            public string Principle;
            public int Age;
            public string Role;
            public Dictionary<string, double> Traits;
            public List<string> Values;
            public List<BeliefSeed> Beliefs;
        }

        sealed class HeldOut
        {
            public List<Declared> People = new List<Declared>();
            public List<string> SweepTraits = new List<string>();
            public List<double> Levels = new List<double>();
            public List<string> ValueRing = new List<string>();
            public List<List<BeliefSeed>> BeliefSets = new List<List<BeliefSeed>>();

            public static HeldOut Load(string path)
            {
                var root = JObject.Parse(File.ReadAllText(path));
                var h = new HeldOut();
                foreach (var d in (JArray)root["declared"])
                    h.People.Add(new Declared
                    {
                        Id = d["id"].Value<string>(),
                        Principle = d["principle"].Value<string>(),
                        Age = d["age"].Value<int>(),
                        Role = d["family_role"].Value<string>(),
                        Traits = ((JObject)d["traits"]).Properties().ToDictionary(x => x.Name, x => x.Value.Value<double>()),
                        Values = ((JArray)d["values"]).Select(x => x.Value<string>()).ToList(),
                        Beliefs = Seeds(d["beliefs"] as JArray, d["id"].Value<string>())
                    });

                var s = (JObject)root["sweep"];
                h.SweepTraits = ((JArray)s["traits"]).Select(x => x.Value<string>()).ToList();
                h.Levels = ((JArray)s["levels"]).Select(x => x.Value<double>()).ToList();
                h.ValueRing = ((JArray)s["value_ring"]).Select(x => x.Value<string>()).ToList();
                foreach (var set in (JArray)s["belief_sets"])
                    h.BeliefSets.Add(Seeds(set as JArray, null));
                return h;
            }

            static List<BeliefSeed> Seeds(JArray node, string self)
            {
                var list = new List<BeliefSeed>();
                if (node == null) return list;
                foreach (var b in node)
                    list.Add(new BeliefSeed(
                        b["predicate"].Value<string>(),
                        ((JArray)b["args"]).Select(a => a.Value<string>()).ToList(),
                        b["confidence"].Value<double>()));
                return list;
            }
        }

        /// <summary>A mind from a bare specification, with `$self` in a belief resolved to them.</summary>
        static Mind Person(string id, IReadOnlyDictionary<string, double> traits,
            IReadOnlyList<string> values, IReadOnlyList<BeliefSeed> beliefs,
            int age = 30, string role = "sibling")
        {
            var profile = new Profile(id, id, age, role, traits, values, 0.5,
                new Dictionary<string, double>(), new List<BeliefSeed>());
            var mind = new Mind(profile);
            foreach (var b in beliefs ?? new List<BeliefSeed>())
                mind.Beliefs.Seed(new BeliefSeed(
                    b.Predicate, b.Args.Select(a => a == "$self" ? id : a).ToList(), b.Confidence));
            return mind;
        }

        static Mind FromDeclared(Declared d) => Person(d.Id, d.Traits, d.Values, d.Beliefs, d.Age, d.Role);

        static Mind FromCast(string who)
        {
            var mind = new Mind(_content.Cast[who]);
            foreach (var b in _content.Cast[who].InitialBeliefs) mind.Beliefs.Seed(b);
            return mind;
        }

        /// <summary>
        /// The i-th profile of the sweep: the traits are the base-3 digits of i
        /// over the seven trait names, the values are the ring rotated by i, and
        /// the beliefs are set (i mod 4). Nobody chose any of it.
        /// </summary>
        static Mind Sweep(int i)
        {
            var traits = new Dictionary<string, double>(StringComparer.Ordinal);
            var n = i;
            foreach (var name in _heldOut.SweepTraits)
            {
                traits[name] = _heldOut.Levels[n % _heldOut.Levels.Count];
                n /= _heldOut.Levels.Count;
            }
            var shift = i % _heldOut.ValueRing.Count;
            var values = _heldOut.ValueRing.Skip(shift).Concat(_heldOut.ValueRing.Take(shift)).ToList();
            return Person("p" + i, traits, values, _heldOut.BeliefSets[i % _heldOut.BeliefSets.Count]);
        }

        static int SweepSize =>
            (int)Math.Pow(_heldOut.Levels.Count, _heldOut.SweepTraits.Count);

        // ============================================================ situations

        static Percept At(string who, IReadOnlyList<string> present, double hunger = 0.3, string roomId = null)
        {
            var room = _house.Get(roomId ?? _kitchen);
            var holdsFood = room.HasTag(ActionCatalog.PantryTag);
            return new Percept(who, 10, room, present, _house.Adjacent(room.Id), hunger,
                holdsFood, holdsFood ? (bool?)true : null, false, _house, false, null, null);
        }

        static readonly IReadOnlyList<string> Nobody = new List<string>();
        static readonly IReadOnlyList<string> Others = new List<string> { "a", "b", "c" };

        static Motive Want(string key, string target = null)
            => new Motive(key, target, 0.6, new List<string>(), new List<ScalerTerm>());

        static Formed Form(IReadOnlyList<Candidate> rules, Mind mind, Percept p, string want)
            => IntentionSelector.Form(rules, mind, p, Want(want, want == "look_after" ? "a" : null),
                _content.Morning.Day, _content.Rules.Deciding.RecallHalfLife);

        static Formed Form(Mind mind, Percept p, string want) => Form(_rules, mind, p, want);

        /// <summary>The intention this person forms for each want, in order: their signature.</summary>
        static string Signature(IReadOnlyList<Candidate> rules, Mind mind, Percept p)
            => string.Join("|", Wants.Select(w => Or(Form(rules, mind, p, w).Intent)));

