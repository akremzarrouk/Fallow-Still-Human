        [Test]
        [Timeout(600000)]
        public void TheSweep()
        {
            var n = SweepSize;
            var company = At("x", Others);
            var alone = At("x", Nobody);

            var byWant = Wants.ToDictionary(w => w, w => new Dictionary<string, int>(StringComparer.Ordinal), StringComparer.Ordinal);
            var signatures = new Dictionary<string, int>(StringComparer.Ordinal);
            var flippedOnAudience = 0;
            var lookAfterEscapes = new List<string>();
            var theftInnocent = 0;
            var theftTotal = 0;

            for (var i = 0; i < n; i++)
            {
                var mind = Sweep(i);
                var p = At(mind.Id, Others);
                var a = At(mind.Id, Nobody);

                var sig = new List<string>();
                var flipped = false;
                foreach (var w in Wants)
                {
                    var inCompany = Form(mind, p, w);
                    var byThemselves = Form(mind, a, w);
                    sig.Add(Or(inCompany.Intent));

                    var key = Or(inCompany.Intent);
                    byWant[w].TryGetValue(key, out var c);
                    byWant[w][key] = c + 1;

                    if (inCompany.Intent != byThemselves.Intent) flipped = true;

                    if (w == "look_after" && inCompany.Intent != "protect" && inCompany.Intent != null)
                        lookAfterEscapes.Add(mind.Id + " in company -> " + inCompany.Intent);
                    if (w == "look_after" && byThemselves.Intent != "protect" && byThemselves.Intent != null)
                        lookAfterEscapes.Add(mind.Id + " alone -> " + byThemselves.Intent);

                    if (w == "get_food" || w == "avoid_exposure")
                    {
                        if (inCompany.Intent == "took_what_was_not_mine")
                        {
                            theftTotal++;
                            if (mind.Beliefs.Confidence("answerable_for", new[] { mind.Id, "missing_can" }) <= 0.0) theftInnocent++;
                        }
                    }
                }
                if (flipped) flippedOnAudience++;
                var s = string.Join("|", sig);
                signatures.TryGetValue(s, out var sc);
                signatures[s] = sc + 1;
            }

            var sb = new StringBuilder();
            sb.AppendLine("## G3. The sweep: " + n + " profiles nobody designed");
            sb.AppendLine();
            sb.AppendLine("Every combination of the seven shipped traits at three levels, with values and beliefs rotating by index. The frozen rules have never seen any of them.");
            sb.AppendLine();
            sb.AppendLine("| Want | Distinct intentions across the sweep | Distribution, in company |");
            sb.AppendLine("|---|---|---|");
            foreach (var w in Wants)
            {
                var dist = byWant[w].Where(k => k.Key != "none").OrderByDescending(k => k.Value)
                    .ThenBy(k => k.Key, StringComparer.Ordinal).ToList();
                sb.AppendLine("| `" + w + "` | " + dist.Count + " | "
                              + string.Join(", ", dist.Select(k => "`" + k.Key + "` " + Pc(k.Value, n))) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("| | Value |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| Profiles | " + n + " |");
            sb.AppendLine("| **Distinct signatures** (the seven intentions a profile forms, in order) | **" + signatures.Count + "** |");
            sb.AppendLine("| Most common signature, share of profiles | " + Pc(signatures.Values.Max(), n) + " |");
            sb.AppendLine("| Profiles whose intention changed on the audience alone | " + flippedOnAudience + " | ");
            sb.AppendLine();
            sb.AppendLine("A mechanism that were a table keyed on the want would produce **one** signature. " + signatures.Count + " is what a function of the person produces.");
            sb.AppendLine();
            sb.AppendLine("The five most common signatures:");
            sb.AppendLine();
            sb.AppendLine("| Share | " + string.Join(" | ", Wants.Select(w => "`" + w + "`")) + " |");
            sb.AppendLine("|---|" + string.Concat(Enumerable.Repeat("---|", Wants.Length)));
            foreach (var s in signatures.OrderByDescending(k => k.Value).Take(5))
                sb.AppendLine("| " + Pc(s.Value, n) + " | " + string.Join(" | ", s.Key.Split('|')) + " |");
            sb.AppendLine();

            sb.AppendLine("### How often the person cannot matter at all");
            sb.AppendLine();
            sb.AppendLine("An intention is chosen by comparing candidates. Where the circumstances leave only one intention with any candidate matching, there is nothing to compare and the person is irrelevant by construction, however elaborate their scalers.");
            sb.AppendLine();
            sb.AppendLine("| Want | In company | Alone |");
            sb.AppendLine("|---|---|---|");
            var uncontestedCells = 0;
            var allCells = 0;
            foreach (var w in Wants)
            {
                var cols = new List<string>();
                foreach (var present in new[] { Others, Nobody })
                {
                    var only = 0;
                    for (var i = 0; i < n; i++)
                    {
                        var mind = Sweep(i);
                        var f = Form(mind, At(mind.Id, present), w);
                        allCells++;
                        if (f.Considered.Count <= 1) { only++; uncontestedCells++; }
                    }
                    cols.Add(Pc(only, n) + " of profiles");
                }
                sb.AppendLine("| `" + w + "` | " + string.Join(" | ", cols) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("**" + Pc(uncontestedCells, allCells) + " of all " + allCells
                          + " (profile, want, context) cells had only one intention in the running.** In those, every profile in the sweep forms the same intention, and no amount of psychology could change it.");
            sb.AppendLine();

            sb.AppendLine("### The known failure, off the cast");
            sb.AppendLine();
            sb.AppendLine("`look_after` collapsed to `protect` in 851 of 851 decisions on the shipped cast. Across " + n
                          + " held-out profiles in two contexts, the number of times anything else won: **" + lookAfterEscapes.Count + "**.");
            if (lookAfterEscapes.Count > 0)
                sb.AppendLine("Examples: " + string.Join("; ", lookAfterEscapes.Take(5)) + ".");
            sb.AppendLine();
            sb.AppendLine("### The innocent theft, off the cast");
            sb.AppendLine();
            sb.AppendLine("`took_what_was_not_mine` was formed " + theftTotal + " times in company across the sweep, of which **"
                          + theftInnocent + "** (" + Pc(theftInnocent, theftTotal) + ") were by a profile holding no belief that they are answerable for anything.");
            Record("G3", sb.ToString());

            Assert.Greater(signatures.Count, 1, "P1: a table would produce one signature");
        }

