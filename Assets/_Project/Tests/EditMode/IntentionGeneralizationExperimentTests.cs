            sb.AppendLine();
            sb.AppendLine("Each held-out person is placed by a stated principle outside the region the shipped cast occupies. The cast is nowhere below 0.50 on empathetic or honest, nowhere above 0.70 on cautious, and never high on dominant and empathetic together.");
