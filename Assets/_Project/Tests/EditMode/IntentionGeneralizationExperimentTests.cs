        [Test]
        [Timeout(600000)]
        public void WhatMovesItAndWhatDoesNot()
        {
            var n = SweepSize;
            var sb = new StringBuilder();
            sb.AppendLine("## G4. Counterfactuals on held-out people");
            sb.AppendLine();
            sb.AppendLine("Each perturbation is applied to the whole sweep, one thing at a time, everything else held. A cell is one (profile, want) pair: " + (n * Wants.Length) + " of them.");
            sb.AppendLine();

            var cells = 0;
            var c1 = 0;   // relevant circumstance: company
            var c2a = 0;  // irrelevant: hunger
            var c2b = 0;  // irrelevant: food in the room
            var c3a = 0;  // belief: role_claim
            var c3b = 0;  // belief: answerable_for
            var c5 = 0;   // reachable set differs between wants

            for (var i = 0; i < n; i++)
            {
                var mind = Sweep(i);
                var basis = At(mind.Id, Nobody, hunger: 0.3);
                var withCompany = At(mind.Id, Others, hunger: 0.3);
                var hungry = At(mind.Id, Nobody, hunger: 0.95);
                var elsewhere = At(mind.Id, Nobody, hunger: 0.3,
                    roomId: _house.Rooms.First(r => !r.HasTag(ActionCatalog.PantryTag)).Id);

                var claiming = Person(mind.Id, TraitsOf(mind), mind.Profile.Values,
                    Seeds(mind).Concat(new[] { new BeliefSeed("role_claim", new[] { "$self", "leads_family" }, 0.95) }).ToList());
                var answerable = Person(mind.Id, TraitsOf(mind), mind.Profile.Values,
                    Seeds(mind).Concat(new[] { new BeliefSeed("answerable_for", new[] { "$self", "missing_can" }, 0.95) }).ToList());

                var reachable = new HashSet<string>(StringComparer.Ordinal);
                foreach (var w in Wants)
                {
                    var b = Form(mind, basis, w).Intent;
                    cells++;
                    if (b != Form(mind, withCompany, w).Intent) c1++;
                    if (b != Form(mind, hungry, w).Intent) c2a++;
                    if (b != Form(mind, elsewhere, w).Intent) c2b++;
                    if (b != Form(claiming, basis, w).Intent) c3a++;
                    if (b != Form(answerable, basis, w).Intent) c3b++;
                    reachable.Add(Or(b));
                }
                if (reachable.Count > 1) c5++;
            }

            sb.AppendLine("| Perturbation | Read by a rule | Cells whose intention changed | Share |");
            sb.AppendLine("|---|---|---|---|");
            sb.AppendLine("| C1 three others come into the room | **yes**, six rules gate on it | " + c1 + " | " + Pc(c1, cells) + " |");
            sb.AppendLine("| C3 they come to believe they lead the family (0 -> 0.95) | **yes**, two rules scale on it | " + c3a + " | " + Pc(c3a, cells) + " |");
            sb.AppendLine("| C3 they come to believe they are answerable for the can (0 -> 0.95) | **yes**, one rule scales on it | " + c3b + " | " + Pc(c3b, cells) + " |");
            sb.AppendLine("| C2 hunger 0.30 -> 0.95 | **no rule reads it** | **" + c2a + "** | " + Pc(c2a, cells) + " |");
            sb.AppendLine("| C2 moved to a room with no food | **no rule reads it** | **" + c2b + "** | " + Pc(c2b, cells) + " |");
            sb.AppendLine();
            sb.AppendLine("| C5 | the want itself | profiles for which changing the want changes the intention | " + c5 + " of " + n + ", " + Pc(c5, n) + " |");
            sb.AppendLine();

            // C4: one trait at a time, over the whole sweep.
            sb.AppendLine("### C4. One trait at a time");
            sb.AppendLine();
            sb.AppendLine("Every seventh profile in the sweep, in both contexts, with a single trait forced low and then high and nothing else touched. Both contexts matter: four of the ten rules are gated on being alone or on having company, so a trait only those rules read would look deaf if it were asked in one context only.");
            sb.AppendLine();
            sb.AppendLine("| Trait | Read by a rule | Cells changed by moving it 0.15 -> 0.85 | Share |");
            sb.AppendLine("|---|---|---|---|");
            var traitsRead = _rules.SelectMany(c => c.ScaledBy).Where(s => s.Kind == ScalerKind.Trait)
                .Select(s => s.Name).Distinct().ToList();
            var byTrait = new List<Tuple<string, int>>();
            foreach (var trait in _content.Vocabulary.Traits.OrderBy(s => s, StringComparer.Ordinal))
            {
                var moved = 0;
                var seen = 0;
                for (var i = 0; i < n; i += 7)   // every seventh profile, deterministic, for speed
                {
                    var baseMind = Sweep(i);
                    var lowTraits = TraitsOf(baseMind);
                    lowTraits[trait] = 0.15;
                    var highTraits = TraitsOf(baseMind);
                    highTraits[trait] = 0.85;
                    var low = Person(baseMind.Id, lowTraits, baseMind.Profile.Values, Seeds(baseMind));
                    var high = Person(baseMind.Id, highTraits, baseMind.Profile.Values, Seeds(baseMind));
                    foreach (var p in new[] { At(baseMind.Id, Others), At(baseMind.Id, Nobody) })
                    foreach (var w in Wants)
                    {
                        seen++;
                        if (Form(low, p, w).Intent != Form(high, p, w).Intent) moved++;
                    }
                }
                byTrait.Add(Tuple.Create(trait, moved));
                sb.AppendLine("| `" + trait + "` | " + (traitsRead.Contains(trait) ? "yes" : "**no**")
                              + " | " + moved + " | " + Pc(moved, seen) + " |");
            }
            sb.AppendLine();
            var deaf = byTrait.Where(t => t.Item2 == 0).Select(t => t.Item1).ToList();
            sb.AppendLine("**Traits that never changed an intention: " + (deaf.Count == 0 ? "none" : string.Join(", ", deaf.Select(d => "`" + d + "`"))) + ".**");
            Record("G4", sb.ToString());

            Assert.AreEqual(0, c2a, "P4: hunger is read by no rule and must never move an intention");
            Assert.AreEqual(0, c2b, "P4: a foodless room is read by no rule and must never move an intention");
            Assert.Greater(c1, 0, "P2: a circumstance the rules read must sometimes move it");
            Assert.Greater(c3a + c3b, 0, "P3: a belief the rules read must sometimes move it");
        }

        static Dictionary<string, double> TraitsOf(Mind m)
            => _content.Vocabulary.Traits.ToDictionary(t => t, t => m.Profile.Trait(t), StringComparer.Ordinal);

        static List<BeliefSeed> Seeds(Mind m)
            => m.Beliefs.All.Select(b => new BeliefSeed(b.Predicate, b.Args, b.Confidence)).ToList();

