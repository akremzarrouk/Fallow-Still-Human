        [Test]
        [Timeout(900000)]
        public void TheRuleCountExperiment()
        {
            var n = SweepSize;
            var step = 7;   // every seventh profile, deterministic
            var sb = new StringBuilder();
            sb.AppendLine("## G6. Does having more rules beat having more weight");
            sb.AppendLine();
            sb.AppendLine("This is the second question and it is not about generalization. Contributions for one intention are **summed**. So two things that look different on the page may be the same arithmetic, and the way to find out is to separate them.");
            sb.AppendLine();
            sb.AppendLine("Three conditions, same people, same wants, same circumstances, same beliefs, same traits, same values:");
            sb.AppendLine();
            sb.AppendLine("| | Rules | Total weight for that intention |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| **A** frozen | 10 | unchanged |");
            sb.AppendLine("| **B** plus an exact clone of one rule under a new id | 11 | **doubled** for that intention |");
            sb.AppendLine("| **C** with one rule split into two halves | 11 | **unchanged** |");
            sb.AppendLine();
            sb.AppendLine("Nothing on disk changes: B and C are built in memory from the frozen rules.");
            sb.AppendLine();
            sb.AppendLine("| Rule cloned or split | Intention | Cells changed by **cloning** it (B) | Cells changed by **splitting** it (C) |");
            sb.AppendLine("|---|---|---|---|");

            var cloneTotal = 0;
            var splitTotal = 0;
            var cells = 0;
            foreach (var rule in _rules)
            {
                var cloned = _rules.Concat(new[] { rule.CloneAs(rule.Id + "_again") }).ToList();
                var split = _rules.Where(r => r.Id != rule.Id)
                    .Concat(new[] { rule.CloneAs(rule.Id + "_a", 0.5), rule.CloneAs(rule.Id + "_b", 0.5) }).ToList();

                var clonedMoved = 0;
                var splitMoved = 0;
                var seen = 0;
                for (var i = 0; i < n; i += step)
                {
                    var mind = Sweep(i);
                    foreach (var p in new[] { At(mind.Id, Others), At(mind.Id, Nobody) })
                    foreach (var w in Wants)
                    {
                        var a = Form(_rules, mind, p, w).Intent;
                        seen++;
                        if (Form(cloned, mind, p, w).Intent != a) clonedMoved++;
                        if (Form(split, mind, p, w).Intent != a) splitMoved++;
                    }
                }
                cells = seen;
                cloneTotal += clonedMoved;
                splitTotal += splitMoved;
                sb.AppendLine("| `" + rule.Id + "` | `" + rule.Intent + "` | " + clonedMoved + " (" + Pc(clonedMoved, seen) + ") | "
                              + splitMoved + " (" + Pc(splitMoved, seen) + ") |");
            }
            sb.AppendLine();
            sb.AppendLine("**Over " + cells + " cells per rule and " + _rules.Count + " rules: cloning changed the intention "
                          + cloneTotal + " times; splitting changed it " + splitTotal + " times.**");
            sb.AppendLine();
            sb.AppendLine("Splitting a rule in two adds a rule and adds no weight. Cloning a rule adds a rule and doubles the weight. If the count mattered, both would move the answer. Only one does, which means **the rule count is not the bias; the sum is.** Writing a second rule for an intention and raising the first rule's numbers are the same operation as far as the mechanism can tell.");
            sb.AppendLine();

            // And the specific diagnosis for look_after, by removal rather than repair.
            sb.AppendLine("### `look_after`, diagnosed by removal");
            sb.AppendLine();
            sb.AppendLine("Not a fix. The frozen file is untouched; this asks what the collapse is made of by running the sweep with one rule withheld in memory.");
            sb.AppendLine();
            sb.AppendLine("| Rules used | Distinct intentions for `look_after` across the sweep | Distribution |");
            sb.AppendLine("|---|---|---|");
            foreach (var withheld in new[] { (string)null, "keeping_it_off_them", "standing_between_them_and_it" })
            {
                var rules = withheld == null ? _rules : _rules.Where(r => r.Id != withheld).ToList();
                var dist = new Dictionary<string, int>(StringComparer.Ordinal);
                for (var i = 0; i < n; i += step)
                {
                    var mind = Sweep(i);
                    foreach (var p in new[] { At(mind.Id, Others), At(mind.Id, Nobody) })
                    {
                        var key = Or(Form(rules, mind, p, "look_after").Intent);
                        dist.TryGetValue(key, out var c);
                        dist[key] = c + 1;
                    }
                }
                var total = dist.Values.Sum();
                sb.AppendLine("| " + (withheld == null ? "**all ten, as frozen**" : "without `" + withheld + "`") + " | "
                              + dist.Count(k => k.Key != "none") + " | "
                              + string.Join(", ", dist.OrderByDescending(k => k.Value).ThenBy(k => k.Key, StringComparer.Ordinal)
                                  .Select(k => "`" + k.Key + "` " + Pc(k.Value, total))) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("The frozen hash is checked again at the end of this test to show that none of this touched the file.");
            var shaAfter = Sha(_rulePath);
            sb.AppendLine();
            sb.AppendLine("**sha256 after the whole run: `" + shaAfter + "` — " + (shaAfter == FrozenSha ? "unchanged." : "**CHANGED**.") + "**");
            Record("G6", sb.ToString());

            Assert.AreEqual(FrozenSha, shaAfter, "the rule file must still be byte-identical after the run");
            Assert.AreEqual(0, splitTotal, "H2: splitting a rule adds no weight and must change nothing");
            Assert.Greater(cloneTotal, 0, "H2: cloning a rule doubles a weight and must change something");
        }
