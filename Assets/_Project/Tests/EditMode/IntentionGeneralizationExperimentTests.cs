    /// <summary>
    /// Does the intention-formation mechanism encode reusable relationships
    /// between a want, a person and a situation, or is it a table fitted to four
    /// people?
    ///
    /// The ten candidate rules are **frozen**: the file is hashed at the start of
    /// the run and again at the end, and nothing is added for a held-out person.
    /// The holdout is four declared people placed outside the shipped cast's
    /// trait ranges by a stated principle, and a mechanical sweep of 2,187
    /// profiles that enumerates trait space and that nobody designed.
    ///
    /// The second question is kept separate from the first. A mechanism can
    /// generalize perfectly and still rank intentions for a bad reason, so the
    /// rule-count experiment (G6) is run and reported on its own.
    ///
    /// No production change of any kind. Writes
    /// `Docs/experiments/intention-generalization/measurements.md`.
    /// </summary>
    public class IntentionGeneralizationExperimentTests
    {
