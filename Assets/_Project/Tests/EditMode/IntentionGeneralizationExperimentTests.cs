        [Test]
        public void WhatIsFrozenAndWhetherItNamesAnybody()
        {
            var sha = Sha(_rulePath);
            var sb = new StringBuilder();
            sb.AppendLine("## G1. The frozen rules, and whether they know anybody's name");
            sb.AppendLine();
            sb.AppendLine("| | |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| File | `Assets/_Project/Data/Experiments/intentions.json` |");
            sb.AppendLine("| sha256 at the start of this run | `" + sha + "` |");
            sb.AppendLine("| Expected | `" + FrozenSha + "` |");
            sb.AppendLine("| Match | " + (sha == FrozenSha ? "**yes**" : "**NO**") + " |");
            sb.AppendLine("| Rules | " + _rules.Count + " |");
            sb.AppendLine();

            var names = Cast.Concat(_heldOut.People.Select(p => p.Id)).ToList();
            var hits = new List<string>();
            foreach (var c in _rules)
            {
                var text = string.Join(" ", new[] { c.Id, c.Intent, string.Join(" ", c.Motives) }
                    .Concat(c.ScaledBy.Select(s => string.Join(" ", new[]
                    {
                        s.Kind, s.Name, s.Predicate, s.Entry, s.About, s.Topic, s.By, s.Target,
                        string.Join(" ", s.Args ?? new List<string>())
                    }.Where(x => x != null)))));
                foreach (var n in names)
                    if (text.IndexOf(n, StringComparison.OrdinalIgnoreCase) >= 0) hits.Add(c.Id + " mentions " + n);
            }
            sb.AppendLine("**Character names or ids anywhere in a rule's id, intent, wants, or any scaler's kind, name, predicate, entry, about, topic, by, target or arguments: " + hits.Count + ".** "
                          + (hits.Count == 0 ? "The only person-token any rule uses is `$self`, which is whoever is deciding."
                                             : string.Join("; ", hits)));
            sb.AppendLine();

            sb.AppendLine("### What generic state the rules actually read");
            sb.AppendLine();
            sb.AppendLine("| Kind | Names read | Names in the vocabulary that no rule reads |");
            sb.AppendLine("|---|---|---|");
            var traitsRead = _rules.SelectMany(c => c.ScaledBy).Where(s => s.Kind == ScalerKind.Trait)
                .Select(s => s.Name).Distinct().OrderBy(s => s, StringComparer.Ordinal).ToList();
            var valuesRead = _rules.SelectMany(c => c.ScaledBy).Where(s => s.Kind == ScalerKind.Value)
                .Select(s => s.Name).Distinct().OrderBy(s => s, StringComparer.Ordinal).ToList();
            var otherKinds = _rules.SelectMany(c => c.ScaledBy).Select(s => s.Kind).Distinct()
                .Where(k => k != ScalerKind.Trait && k != ScalerKind.Value)
                .OrderBy(s => s, StringComparer.Ordinal).ToList();
            sb.AppendLine("| trait | " + string.Join(", ", traitsRead) + " | **"
                          + string.Join(", ", _content.Vocabulary.Traits.Except(traitsRead).OrderBy(s => s, StringComparer.Ordinal)) + "** |");
            sb.AppendLine("| value | " + string.Join(", ", valuesRead) + " | **"
                          + string.Join(", ", _content.Vocabulary.Values.Except(valuesRead).OrderBy(s => s, StringComparer.Ordinal)) + "** |");
            sb.AppendLine("| other | " + string.Join(", ", otherKinds) + " | - |");
            sb.AppendLine();
            sb.AppendLine("Ten rules cannot read seven traits and six values evenly, and they do not. What they do not read at all is as much a fact about the mechanism as what they do.");
            Record("G1", sb.ToString());

            Assert.AreEqual(FrozenSha, sha, "the rule file must be byte-identical to the one the predictions were written against");
            Assert.AreEqual(0, hits.Count, "P6/P10: no rule may name a character");
        }

