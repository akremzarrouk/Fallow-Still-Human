        [Test]
        public void E4_TimeDoesNotWearItOff()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 4. Time does not wear it off");
            sb.AppendLine();
            sb.AppendLine("The same history, with more and more time between it and the later event. Nothing in the code decays a belief, so the prediction is that the effect is the same however long ago it was. This is the mirror image of the memory that never faded in S1.6, and it is worth stating as a defect of the same family rather than as a success.");
            sb.AppendLine();
            sb.AppendLine("| Days between | Fades between | Belief | Read it as | Chose |");
            sb.AppendLine("|---|---|---|---|---|");
            var seen = new List<string>();
            foreach (var (days, fades) in new[] { (1, 1.0), (1, Settled), (2, Settled), (3, Settled), (30, Settled * 4) })
            {
                var c = S17.Run(_content, Base("lag").With(a => { a.PriorSlights = Many; a.LagDays = days; a.LagFades = fades; }));
                seen.Add(c.Meaning + "/" + c.Chosen);
                sb.AppendLine("| " + days + " | " + fades + " | " + S17.F(c.Belief("tendency(daniel,treats_me_like_a_child)")) + " | " +
                              c.Meaning + " " + S17.F(c.Weight) + " | " + c.Chosen + " |");
            }
            sb.AppendLine();
            sb.AppendLine("A month later it lands exactly as it did the next morning.");
            Record("4", sb.ToString());

            Assert.AreEqual(1, seen.Distinct().Count(), "the effect is the same at every lag, because no belief decays");
        }

