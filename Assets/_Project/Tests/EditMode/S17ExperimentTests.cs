        [Test]
        public void E8_TheWholePathReconstructsFromTheTraceAlone()
        {
            var t = S17.Run(_content, Base("T").With(a => a.PriorSlights = Many));

            // Everything the decision rests on, walked back. The question is
            // whether the earliest thing that happened to her is in there.
            var chain = t.Trace.Chain(t.DecisionTraceId).ToList();
            var reached = chain.Where(r => r.EventId != null && t.HistoryEventIds.Contains(r.EventId)).ToList();
            var earliest = t.HistoryEventIds.First();

            var sb = new StringBuilder();
            sb.AppendLine("## 8. The whole path, from the trace alone");
            sb.AppendLine();
            sb.AppendLine("Everything the final decision rests on is walked back through its parents. The decision record has " + chain.Count +
                          " records behind it, of which " + reached.Count + " belong to one of the " + t.HistoryEventIds.Count + " earlier times.");
            sb.AppendLine();
            sb.AppendLine("The reading of the later event, written out as the trace holds it. Every `because` below is a real parent link, not a reconstruction:");
            sb.AppendLine();
            sb.AppendLine("```");
            sb.Append(t.Trace.Why(t.InterpretationTraceId));
            sb.AppendLine("```");
            sb.AppendLine();
            sb.AppendLine("Reading it from the bottom up: she went through that this morning because of what she believes about him, and she believes it because of what he did on each of those earlier days, each of which she was there for and made something of at the time. Nothing in that path is a stored conclusion; every step is the record of a stage that ran.");
            sb.AppendLine();

            var kinds = chain.GroupBy(r => r.Kind).OrderBy(g => g.Key.ToString(), StringComparer.Ordinal);
            sb.AppendLine("What the decision rests on, by kind of record: " +
                          string.Join(", ", kinds.Select(g => g.Key + " " + g.Count())) + ".");
            Record("8", sb.ToString());

            Assert.IsTrue(chain.Any(r => r.EventId == earliest),
                "the decision walks back to the first thing he ever did to her");
            Assert.IsTrue(chain.Any(r => r.Kind == TraceKind.Motive), "and through a want");
            Assert.IsTrue(chain.Any(r => r.Kind == TraceKind.Appraisal), "and through a feeling");
            Assert.IsTrue(chain.Any(r => r.Kind == TraceKind.BeliefChange), "and through a belief that moved");
            Assert.IsTrue(chain.Any(r => r.Kind == TraceKind.Interpretation), "and through a reading");
        }
