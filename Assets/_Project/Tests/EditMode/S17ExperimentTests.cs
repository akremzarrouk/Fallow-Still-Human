        // ---- 1 ----

        [Test]
        public void E1_TheFourArms()
        {
            var control = S17.Run(_content, Base("C: it never happened").With(a => a.PriorSlights = 0));
            var treatment = S17.Run(_content, Base("T: it happened, she saw it").With(a => a.PriorSlights = Many));
            var unseen = S17.Run(_content, Base("U: it happened, she did not see it").With(a => { a.PriorSlights = Many; a.SubjectSeesPriors = false; }));
            var other = S17.Run(_content, Base("P: it happened, but somebody else does it now").With(a => { a.PriorSlights = Many; a.ProbeActor = "leo"; }));

            var sb = new StringBuilder();
            sb.AppendLine("## 1. The four arms");
            sb.AppendLine();
            sb.AppendLine("Elena is the subject. The history is Daniel going through her things, " + Many + " times, on " + Many + " separate earlier days. In between she does the thing that makes her answerable for what is missing, so that two readings of the later event are live at once. The later event is always the same: somebody goes through her things while she stands there, on a later day, with the feeling of the earlier times long gone.");
            sb.AppendLine();
            sb.AppendLine(S17.ChainTable(new[] { control, treatment, unseen, other }));
            sb.AppendLine("**C against T** is the experiment. **U** is the same world with the subject out of the room for it, and is how we know the effect travels through her perceiving it rather than through it having happened. **P** is the same history with a different person doing the later thing, and is how we know the effect is about Daniel rather than about her mood.");
            sb.AppendLine();
            sb.AppendLine("What each arm read the later event as, rule by rule:");
            sb.AppendLine();
            foreach (var c in new[] { control, treatment, unseen, other })
            {
                sb.AppendLine("- **" + c.Label + "**: `" + c.Meaning + "` " + S17.F(c.Weight));
                sb.AppendLine("  - " + (c.RulesDetail ?? "no rule spoke").Replace(" | ", "\n  - "));
            }
            Record("1", sb.ToString());

            Assert.AreNotEqual(control.Meaning, treatment.Meaning, "the history changed what the later event meant");
            Assert.AreEqual(control.Meaning, unseen.Meaning, "an event she did not perceive changed nothing");
            Assert.AreEqual(0.0, unseen.Belief("tendency(daniel,treats_me_like_a_child)"), 1e-9, "and left no belief behind");
            Assert.AreEqual(control.Meaning, other.Meaning, "the history is about one person, not about everybody");
            Assert.AreNotEqual(control.Downstream, treatment.Downstream, "and the difference reached what she wants");
        }

