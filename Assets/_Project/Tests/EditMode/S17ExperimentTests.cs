        [Test, Timeout(1800000)]
        public void E7_OverAWholeMorning()
        {
            // The bench holds everything still. A morning does not: she decides
            // twenty times, and what she does changes the house, which changes
            // what everybody else does. This is the only measurement here that
            // asks whether any of it survives that.
            var sb = new StringBuilder();
            sb.AppendLine("## 7. Over a whole morning");
            sb.AppendLine();
            sb.AppendLine("The history is written into the backstory, on day 3, and the ordinary morning is run with it and without it on the same seeds. The condition is `elena_fed_mara`, so the subject is answerable for what is missing and both readings of being searched are live, exactly as on the bench. Compared against the S1.1 noise floor: two pools of twenty seeds of the *same* world, to see how much of any difference is just the dice.");
            sb.AppendLine();

            IReadOnlyDictionary<string, double> Pool(Scenario001Content content, ulong from, string who)
            {
                var counts = new Dictionary<string, double>(StringComparer.Ordinal);
                var total = 0;
                for (var seed = from; seed < from + 20; seed++)
                {
                    var run = Scenario001.Run(content, "elena_fed_mara", seed);
                    foreach (var a in run.Result.By(who))
                    {
                        counts.TryGetValue(a.Action.KindName, out var n);
                        counts[a.Action.KindName] = n + 1;
                        total++;
                    }
                }
                return counts.ToDictionary(k => k.Key, k => k.Value / Math.Max(1, total), StringComparer.Ordinal);
            }

            var withIt = S17.WithHistory(_content, Many, "daniel", "elena");
            sb.AppendLine("| Who | Effect of the history | Noise, no history | Noise, with history | Effect / noise | Above the noise |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var anyAbove = false;
            foreach (var who in S17.People)
            {
                var c1 = Pool(_content, 201, who); var c2 = Pool(_content, 221, who);
                var t1 = Pool(withIt, 201, who); var t2 = Pool(withIt, 221, who);
                var effect = (BatchRunner.HowDifferent(t1, c2) + BatchRunner.HowDifferent(t2, c1)) / 2;
                var nc = BatchRunner.HowDifferent(c1, c2);
                var nt = BatchRunner.HowDifferent(t1, t2);
                var noise = Math.Max(nc, nt);
                var above = effect > noise * 1.5;
                if (above) anyAbove = true;
                sb.AppendLine("| " + who + " | " + S17.F(effect) + " | " + S17.F(nc) + " | " + S17.F(nt) + " | " +
                              (noise == 0 ? "n/a" : (effect / noise).ToString("0.0")) + " | " + (above ? "**yes**" : "no") + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Seeds 201 to 240, which no test has used before.");
            sb.AppendLine();

            // The prediction as it was written: one earlier time, one shared seed.
            var once = S17.WithHistory(_content, 1, "daniel", "elena");
            var same = 0;
            for (ulong seed = 241; seed <= 250; seed++)
            {
                var a = Scenario001.Run(_content, "elena_fed_mara", seed).Result.By("elena").Select(x => x.Minute + ":" + x.Action.Key);
                var b = Scenario001.Run(once, "elena_fed_mara", seed).Result.By("elena").Select(x => x.Minute + ":" + x.Action.Key);
                if (a.SequenceEqual(b)) same++;
            }
            sb.AppendLine("With **one** earlier time rather than " + Many + ", on ten shared seeds, the subject's morning was identical in " + same + " of 10.");
            Record("7", sb.ToString());

            TestContext.WriteLine("any above the noise: " + anyAbove);
        }

