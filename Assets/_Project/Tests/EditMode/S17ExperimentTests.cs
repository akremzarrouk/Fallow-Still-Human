        [Test]
        public void E6_WhetherTheChangedWantEverChangesTheAction()
        {
            // Every measurement so far ended in the same act. This asks whether
            // that is a fact about the architecture or about the one room she was
            // standing in, by running the same pair of arms in every ordinary
            // circumstance the slice can put her in.
            var sb = new StringBuilder();
            sb.AppendLine("## 6. Whether the changed want ever changes the action");
            sb.AppendLine();
            sb.AppendLine("The same two arms, in twenty-seven different immediate circumstances: three rooms, three sets of people to be with, three levels of hunger. Nothing about the history or the later event changes between them.");
            sb.AppendLine();
            sb.AppendLine("| Room | With her | Hunger | Without the history | With it | Changed | Both clear |");
            sb.AppendLine("|---|---|---|---|---|---|---|");

            var changed = 0;
            var total = 0;
            var differentReason = 0;
            var clearlyMoved = 0;
            foreach (var room in new[] { "back_room", "kitchen", "living_room" })
            foreach (var present in new[] { new List<string> { "daniel" }, new List<string> { "daniel", "mara" }, new List<string>() })
            foreach (var hunger in new[] { 0.10, 0.60, 0.95 })
            {
                var c = S17.Run(_content, Base("C").With(a => { a.PriorSlights = 0; a.Room = room; a.Present = present; a.Hunger = hunger; }));
                var t2 = S17.Run(_content, Base("T").With(a => { a.PriorSlights = Many; a.Room = room; a.Present = present; a.Hunger = hunger; }));
                total++;
                var moved = c.Chosen != t2.Chosen;
                if (moved) changed++;
                if (c.LeadingWant != t2.LeadingWant) differentReason++;
                var bothClear = c.Resolution == "clear" && t2.Resolution == "clear";
                if (moved && bothClear) clearlyMoved++;
                sb.AppendLine("| " + room + " | " + (present.Count == 0 ? "nobody" : string.Join(", ", present)) + " | " + hunger.ToString("0.00") + " | " +
                              c.Chosen + " (" + c.LeadingWant + ") | " + t2.Chosen + " (" + t2.LeadingWant + ") | " + (moved ? "**yes**" : "no") + " | " + (bothClear ? "yes" : "no") + " |");
            }
            sb.AppendLine();
            sb.AppendLine("**The act she chose differed in " + changed + " of " + total + " circumstances**, and in " + clearlyMoved +
                          " of those both sides were clear rather than settled by the seed. The reason behind the act differed in " + differentReason + " of " + total + ".");
            Record("6", sb.ToString());

            TestContext.WriteLine("changed act in " + changed + " of " + total + ", changed reason in " + differentReason);
            Assert.Greater(differentReason, 0, "the history reaches the reason for what she does");
        }

