        [Test]
        public void E5_WhichLaterSituationsAreSensitiveToHistoryAtAll()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 5. Which later situations are sensitive to history at all");
            sb.AppendLine();
            sb.AppendLine("The same history against four different later events, to find out whether this is one situation fitted or a class of them. Each is aimed at the subject, on a later day, with one other person in the room, so that a rule needing an audience can fire at all.");
            sb.AppendLine();
            sb.AppendLine("| Later event | Without the history | With it | Reading changed | Anything downstream changed |");
            sb.AppendLine("|---|---|---|---|---|");

            var sensitive = new List<string>();
            foreach (var kind in new[] { S17.Search, S17.Observe, S17.Demand, S17.Refuse })
            {
                var audience = new List<string> { "daniel", "mara" };
                var c = S17.Run(_content, Base("C").With(a => { a.PriorSlights = 0; a.ProbeKind = kind; a.Present = audience; }));
                var t = S17.Run(_content, Base("T").With(a => { a.PriorSlights = Many; a.ProbeKind = kind; a.Present = audience; }));
                var flipped = c.Meaning != t.Meaning;
                var moved = c.Downstream != t.Downstream;
                if (moved) sensitive.Add(kind);
                sb.AppendLine("| `" + kind + "` | " + c.Meaning + " " + S17.F(c.Weight) + " | " + t.Meaning + " " + S17.F(t.Weight) + " | " +
                              (flipped ? "**yes**" : "no") + " | " + (moved ? "**yes**" : "no") + " |");
            }
            sb.AppendLine();
            sb.AppendLine("**History moved the weight in three of the four, and moved the outcome in one.** The one it moved is the only one where the reading it strengthens was not already winning. Going through somebody's things is history-sensitive because two readings compete on it and history carries one of them, and which of the two wins is what decides how it feels. Being watched is read nearly two and a half times as darkly and nothing follows, because only one rule ever fires on it, so the extra weight has nothing to beat. A demand is read more darkly too, and nothing follows, because `disrespect` was already winning without any history. A refusal in front of others is read as support by this person either way; the slighted reading of it rises with history and stays second.");
            sb.AppendLine();
            sb.AppendLine("Being read *more strongly* is therefore not the same as being read *differently*, and only the second has any consequence. A later situation is sensitive to history exactly when history can change which reading wins, which needs two readings that are close and at least one of them carried by a belief that experience can write.");
            Record("5", sb.ToString());

            Assert.Contains(S17.Search, sensitive, "at least one class of later situation is sensitive to history");
        }

