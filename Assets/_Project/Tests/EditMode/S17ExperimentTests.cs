        [Test]
        public void E3_TheOtherKindOfBeliefMovesBehaviourContinuously()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 3. The other kind of belief, on the same instrument");
            sb.AppendLine();
            sb.AppendLine("`supplies_short` is learned the same way, from what an event meant, and it is read by a **motivation** rule rather than only by interpretation. The same subject, the same later event, the belief set to each level in turn. If the flat stretch in section 2 were an artefact of the instrument, it would show here too.");
            sb.AppendLine();
            sb.AppendLine("| `supplies_short` | `guard_supplies` want | Chose | | `treats_me_like_a_child` | `restore_standing` want | Chose |");
            sb.AppendLine("|---|---|---|---|---|---|---|");

            var world = new List<S17Chain>();
            var person = new List<S17Chain>();
            for (var i = 0; i <= 8; i++)
            {
                var level = i / 10.0;
                world.Add(S17.Run(_content, Base("supplies " + level).With(a =>
                {
                    a.PriorSlights = 0;
                    a.ForceBeliefs = new Dictionary<string, double>(StringComparer.Ordinal) { { "supplies_short()", level } };
                })));
                person.Add(S17.Run(_content, Base("child " + level).With(a =>
                {
                    a.PriorSlights = 0;
                    a.ForceBeliefs = new Dictionary<string, double>(StringComparer.Ordinal) { { "tendency(daniel,treats_me_like_a_child)", level } };
                })));
            }

            for (var i = 0; i <= 8; i++)
            {
                var level = i / 10.0;
                sb.AppendLine("| " + S17.F(level) + " | " + S17.F(world[i].Want("guard_supplies")) + " | " + world[i].Chosen + " | | " +
                              S17.F(level) + " | " + S17.F(person[i].Want("restore_standing")) + " | " + person[i].Chosen + " |");
            }
            sb.AppendLine();
            sb.AppendLine("The left-hand belief moves the want it feeds at every step, continuously, because a motivation rule reads it directly. The right-hand belief moves nothing until the reading flips. **Two beliefs, learned by the same machinery from the same kind of event, with completely different causal reach.** That is the finding of this slice.");
            Record("3", sb.ToString());

            Assert.Greater(world.Select(c => S17.F(c.Want("guard_supplies"))).Distinct().Count(), 5,
                "a belief a motivation rule reads moves the want continuously");
        }

