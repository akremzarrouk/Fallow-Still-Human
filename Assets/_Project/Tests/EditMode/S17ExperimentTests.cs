        [Test]
        public void E2_TheResponseCurve()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## 2. The response curve: how much history it takes");
            sb.AppendLine();
            sb.AppendLine("The same arm, run again for every number of earlier times from none to fourteen. A hidden modifier would move behaviour a little at every step. The architecture predicts a flat stretch and then a step, because the only way a belief about a person can reach a feeling is by changing which reading wins.");
            sb.AppendLine();
            sb.AppendLine("| Earlier times | Belief `treats_me_like_a_child` | `disrespect` would score | Read it as | Stirred | `restore_standing` | `keep_peace` | Chose |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");

            var rows = new List<S17Chain>();
            for (var n = 0; n <= 14; n++)
            {
                var c = S17.Run(_content, Base(n + " earlier times").With(a => a.PriorSlights = n));
                rows.Add(c);
                var disrespectScore = Weight(c, "your_things_gone_through");
                sb.AppendLine("| " + n + " | " + S17.F(c.Belief("tendency(daniel,treats_me_like_a_child)")) + " | " + S17.F(disrespectScore) + " | " +
                              c.Meaning + " " + S17.F(c.Weight) + " | " +
                              string.Join(", ", c.ProbeEmotions.OrderByDescending(e => e.Value).Take(2).Select(e => e.Key + " " + S17.F(e.Value))) + " | " +
                              S17.F(c.Want("restore_standing")) + " | " + S17.F(c.Want("keep_peace")) + " | " + c.Chosen + " |");
            }

            var flip = rows.FindIndex(r => r.Meaning != rows[0].Meaning);
            sb.AppendLine();
            sb.AppendLine("**The reading changes at " + flip + " earlier times.** Below that the belief climbs at every step and *nothing else moves at all*: the same reading, the same feelings to nine decimal places, the same wants, the same choice. At " + flip + " the reading flips and everything downstream changes together.");
            sb.AppendLine();
            sb.AppendLine("Every number below the flip is identical to the one before it, downstream of the reading: " +
                          (rows.Take(flip).Select(r => r.Downstream).Distinct().Count() == 1 ? "**one distinct downstream state across all " + flip + " of them**." : "they are not all identical, which contradicts the prediction."));
            Record("2", sb.ToString());

            Assert.Greater(flip, 0, "there is a stretch where history does nothing");
            Assert.AreEqual(1, rows.Take(flip).Select(r => r.Downstream).Distinct().Count(),
                "below the flip, every downstream number is identical however much history there is");
            Assert.Greater(rows.Take(flip).Select(r => r.Belief("tendency(daniel,treats_me_like_a_child)")).Distinct().Count(), 1,
                "while the belief itself moved at every step");
            Assert.AreEqual(Many >= flip, true, "the arm used in E1 is above the flip");
        }

        static double Weight(S17Chain c, string ruleId)
        {
            if (c.RulesDetail == null) return 0.0;
            foreach (var part in c.RulesDetail.Split('|'))
            {
                var bit = part.Trim();
                if (!bit.StartsWith(ruleId + " ", StringComparison.Ordinal)) continue;
                var after = bit.Substring(bit.IndexOf("-> ", StringComparison.Ordinal) + 3);
                var number = after.Split(' ')[1];
                if (double.TryParse(number, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var v)) return v;
            }
            return 0.0;
        }

