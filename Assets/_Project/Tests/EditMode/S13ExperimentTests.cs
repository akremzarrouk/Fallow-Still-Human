        [Test]
        public void D_WithoutWhatEatingDoesToTheBodyTheUpdateIsGoneAndNothingDiffersBeforeIt()
        {
            // Same seed, same house, same people. In one morning a portion relieves
            // hunger; in the other it relieves nothing. Everything else is the same,
            // including taking the portion and being seen to.
            var without = WithoutRelief(_plenty);
            var sb = new StringBuilder();
            sb.AppendLine("| Condition, seed | First meal | Outcome with relief / without | First difference of any kind | ... in whom, and what | First difference in anybody else |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var problems = new List<string>();
            var pairs = 0;

            foreach (var v in new[] { "mara_ate_it", "daniel_ate_it", "elena_fed_mara" })
            for (ulong seed = 1; seed <= 5; seed++)
            {
                var a = Scenario001.Prepare(_plenty, v, seed);
                var b = Scenario001.Prepare(without, v, seed);
                int? firstMeal = null;
                string eater = null;
                int? firstDiff = null;
                string diffWhat = null;
                int? othersDiff = null;
                PursuitOutcome oa = null, ob = null;

                for (var i = 0; i < 90; i++)
                {
                    var seen = a.Result.Events.Count;
                    a.Morning.Step();
                    b.Morning.Step();

                    var meal = a.Result.Events.Skip(seen).FirstOrDefault(e => e.Action == "eat_portion");
                    if (meal != null && firstMeal == null)
                    {
                        firstMeal = a.World.Minute;
                        eater = meal.ActorId;
                        oa = a.Minds[eater].Outcomes.Last();
                        ob = b.Minds[eater].Outcomes.LastOrDefault();
                    }

                    foreach (var p in People)
                    {
                        var hungerDiffers = Math.Abs(a.World.HungerOf(p) - b.World.HungerOf(p)) > 1e-12;
                        var wa = new Motivator(_plenty.Rules).Raise(a.Minds[p], a.Morning.See(p), _content.Morning.Day, new TraceLog(), 0);
                        var wb = new Motivator(without.Rules).Raise(b.Minds[p], b.Morning.See(p), _content.Morning.Day, new TraceLog(), 0);
                        var wantsDiffer = wa.Count != wb.Count || wa.Zip(wb, (x, y) => x.Key != y.Key || Math.Abs(x.Urgency - y.Urgency) > 1e-12).Any(d => d);
                        var actsDiffer = !a.Result.By(p).Select(x => x.Minute + x.Action.Key).SequenceEqual(b.Result.By(p).Select(x => x.Minute + x.Action.Key));
                        if (!hungerDiffers && !wantsDiffer && !actsDiffer) continue;

                        if (firstDiff == null)
                        {
                            firstDiff = a.World.Minute;
                            diffWhat = p + ": " + string.Join(", ", new[] { hungerDiffers ? "hunger" : null, wantsDiffer ? "wants" : null, actsDiffer ? "acts" : null }.Where(x => x != null));
                            if (firstMeal == null || firstDiff < firstMeal) problems.Add(v + "/" + seed + ": something differed at minute " + firstDiff + ", before anybody ate");
                            else if (p != eater) problems.Add(v + "/" + seed + ": the first difference was in " + p + ", not the eater " + eater);
                        }
                        if (p != eater && othersDiff == null) othersDiff = a.World.Minute;
                    }
                }

                if (firstMeal == null) continue;
                pairs++;
                if (ob == null || ob.Kind != OutcomeKind.Unresolved) problems.Add(v + "/" + seed + ": without relief the meal was judged " + (ob?.Kind.ToString() ?? "nothing"));
                if (oa.Kind != OutcomeKind.PartlySatisfied && oa.Kind != OutcomeKind.Satisfied) problems.Add(v + "/" + seed + ": with relief the meal was judged " + oa.Kind);

                sb.AppendLine("| " + v + ", " + seed + " | " + eater + " at " + firstMeal + " | " + PursuitOutcome.Words(oa.Kind) + " / " + (ob == null ? "none" : PursuitOutcome.Words(ob.Kind)) + " | minute " +
                              firstDiff + " | " + diffWhat + " | " + (othersDiff == null ? "never" : "minute " + othersDiff) + " |");
            }

            sb.AppendLine();
            sb.AppendLine("Nothing differs before the first meal. The first thing to differ is always the eater, at the minute the meal is resolved. Anybody else differs only later, through what the eater then does.");
            Record("D. With and without what eating does to the body", sb.ToString());
            Assert.IsEmpty(problems, string.Join("\n", problems));
            Assert.Greater(pairs, 0, "nobody ate in any pair");
        }

