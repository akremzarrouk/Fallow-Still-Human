        [Test]
        public void A1_EatingLowersTheWantByWhatTheBodyGotAndTheWantCanBeWalkedBackToTheEating()
        {
            var meals = Meals(_plenty, _content.Morning.Variants.Select(v => v.Id), 10).Where(m => m.Event.Action == "eat_portion").ToList();
            Assert.IsNotEmpty(meals, "nobody ate even with plenty of food");

            var problems = new List<string>();
            var checkedNext = 0;
            Meal shown = null;

            foreach (var meal in meals)
            {
                var o = meal.Outcome;
                if (o == null) { problems.Add(meal.Who + " ate at minute " + meal.Event.Minute + " and has no outcome for it"); continue; }
                if (o.MotiveName != "get_food") problems.Add("the outcome was judged against " + o.MotiveName);
                if (o.Kind != OutcomeKind.PartlySatisfied && o.Kind != OutcomeKind.Satisfied) problems.Add(meal.Who + ": eating judged " + o.Kind);
                if (Math.Abs(o.Before - o.After - Math.Min(o.Before, _content.Rules.Deciding.PortionRelief)) > 1e-9)
                    problems.Add(meal.Who + ": the outcome says " + F(o.Before) + " -> " + F(o.After) + ", which is not what one portion does");

                if (meal.Next == null) continue;
                var want = FoodWant(meal.Next);
                var hunger = meal.Next.Percept.Hunger;
                if (want == null) { if (hunger > 0) problems.Add(meal.Who + ": hungry and wanting nothing"); continue; }

                checkedNext++;
                if (Math.Abs(want.Urgency - Accumulate.Knee(hunger, _content.Rules.Deciding.UrgencyKnee)) > 1e-9)
                    problems.Add(meal.Who + ": the want is not what the body says");
                var term = want.Terms.First(t => t.Description.StartsWith("hunger", StringComparison.Ordinal));
                if (!term.Drew.Contains(o.TraceId)) problems.Add(meal.Who + ": the want afterwards does not rest on the eating");
                if (!Counterfactual.ReachesCause(meal.Run.Trace, want, new[] { meal.Event.Id }))
                    problems.Add(meal.Who + ": the want afterwards cannot be walked back to the eating");
                var chose = FoodWant(meal.Chose);
                if (chose != null && want.Urgency >= chose.Urgency) problems.Add(meal.Who + ": wanted food as much after eating as when choosing to");

                if (shown == null && meal.Chose != null) shown = meal;
            }

            var sb = new StringBuilder();
            sb.AppendLine("Plenty, five conditions, seeds 1 to 10. " + meals.Count + " meals; next decision checked on " + checkedNext + ".");
            sb.AppendLine();
            sb.AppendLine("| Who | Minute | Hunger before -> after | Outcome | `get_food` when choosing | `get_food` at the next decision |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var m in meals.Take(12))
                sb.AppendLine("| " + m.Who + " | " + m.Event.Minute + " | " + F(m.Outcome.Before) + " -> " + F(m.Outcome.After) + " | " + PursuitOutcome.Words(m.Outcome.Kind) +
                              " | " + (FoodWant(m.Chose) == null ? "n/a" : F(FoodWant(m.Chose).Urgency)) + " | " + (FoodWant(m.Next) == null ? "not raised" : F(FoodWant(m.Next).Urgency) + " (minute " + m.Next.Minute + ")") + " |");
            if (shown != null)
            {
                sb.AppendLine();
                sb.AppendLine("### The whole loop, " + shown.Variant + " seed " + shown.Seed + ", " + shown.Who);
                sb.AppendLine();
                sb.AppendLine("The decision to eat:");
                sb.AppendLine();
                sb.AppendLine("```");
                sb.AppendLine(DecisionTrace.Explain(shown.Chose.Decision, 3));
                sb.AppendLine("```");
                sb.AppendLine();
                sb.AppendLine("The want for food at the next decision, and everything it rests on:");
                sb.AppendLine();
                sb.AppendLine("```");
                sb.AppendLine(Shorten(shown.Run.Trace.Why(FoodWant(shown.Next).TraceId)));
                sb.AppendLine("```");
            }
            Record("A1. Eating that works", sb.ToString());
            Assert.IsEmpty(problems, string.Join("\n", problems));
            Assert.Greater(checkedNext, 0);
        }

        [Test]
        public void A2_EatingWhenLittleHungerIsLeftSatisfiesItAndTheWantIsGone()
        {
            // The body is made less hungry part way through eating, as an
            // intervention: nobody here chooses to eat when so little is left. One
            // portion then covers all of it.
            string found = null;
            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= 10 && found == null; seed++)
            {
                var run = Scenario001.Prepare(_plenty, v.Id, seed);
                for (var i = 0; i < 90 && found == null; i++)
                {
                    run.Morning.Step();
                    var who = People.FirstOrDefault(p => run.Morning.Doing(p)?.Action.Kind == ActionKind.Eat && run.Morning.Doing(p)?.MinutesLeft == 1);
                    if (who == null) continue;

                    run.World.SetHunger(who, 0.30);
                    DecisionMoment next = null;
                    run.Morning.Decided = m => { if (m.CharacterId == who && next == null) next = m; };
                    var outcomes = run.Minds[who].Outcomes.Count;
                    run.Morning.Step();
                    if (run.Minds[who].Outcomes.Count == outcomes) { run.Morning.Decided = null; continue; }

                    var o = run.Minds[who].Outcomes.Last();
                    for (var j = 0; j < 10 && next == null; j++) run.Morning.Step();

                    Assert.AreEqual(OutcomeKind.Satisfied, o.Kind);
                    Assert.AreEqual(0.0, o.After, 0.0);
                    Assert.IsNotNull(next);
                    var hungerNow = next.Percept.Hunger;
                    var want = FoodWant(next);
                    found = who + " at minute " + o.Minute + ": " + o + ". At the next decision, minute " + next.Minute + ", hunger " + F(hungerNow) +
                            " (the body since), and `get_food` " + (want == null ? "not raised" : F(want.Urgency) + " resting on: " + want.Terms.First().Description) + ".";
                    Assert.AreEqual(Accumulate.Knee(hungerNow, _content.Rules.Deciding.UrgencyKnee), want?.Urgency ?? 0.0, 1e-9);
                    Assert.IsTrue(want == null || want.Terms.First().Drew.Contains(o.TraceId));
                }
            }

            Record("A2. Eating that covers all of it", found ?? "No case found.");
            Assert.IsNotNull(found, "nobody reached the last minute of eating");
        }

        [Test]
        public void A4_TheWholeLoopIsInTheTraceLinkByLink()
        {
            // need -> want -> decision -> eating -> consequence -> experience ->
            // outcome -> the want at the next decision. Every arrow is checked as a
            // parent link between real records, for every meal, and the first loop
            // is written out record by record.
            var meals = Meals(_plenty, _content.Morning.Variants.Select(v => v.Id), 10)
                .Where(m => m.Event.Action == "eat_portion" && m.Chose != null && FoodWant(m.Next) != null).ToList();
            Assert.IsNotEmpty(meals);

            string shown = null;
            var heldIntention = 0;
            foreach (var m in meals)
            {
                var t = m.Run.Trace;
                var wantBefore = t.Get(FoodWant(m.Chose).TraceId);
                var decision = t.Get(m.Chose.Decision.TraceId);
                var eating = t.ForEvent(m.Event.Id).First(r => r.Kind == TraceKind.Event);
                var consequence = t.ForEvent(m.Event.Id).First(r => r.Kind == TraceKind.Consequence && r.CharacterId == m.Who);
                var experience = t.Get(m.Run.Minds[m.Who].Experiences.First(x => x.EventId == m.Event.Id).TraceId);
                var outcome = t.Get(m.Outcome.TraceId);
                var wantAfter = t.Get(FoodWant(m.Next).TraceId);

                void Link(TraceRecord child, TraceRecord parent, string what)
                    => Assert.IsTrue(child.ParentIds.Contains(parent.Id), m.Variant + "/" + m.Seed + " " + m.Who + ": " + what + " is not linked");

                StringAssert.StartsWith("hunger", FoodWant(m.Chose).Terms.First().Description, "the want at the decision is not raised by hunger");
                Link(decision, wantBefore, "the decision to the want");
                Link(consequence, decision, "the consequence to the decision");
                Assert.AreEqual(m.Event.Id, consequence.EventId, "the consequence is not the eating");
                Assert.IsTrue(t.Chain(experience.Id).Contains(eating), "the experience does not rest on the eating");
                Link(outcome, consequence, "the outcome to the consequence");
                Link(outcome, experience, "the outcome to the experience");
                Link(outcome, wantBefore, "the outcome to the want it was for");
                Link(wantAfter, outcome, "the next want to the outcome");

                if (m.Chose.Decision.Commitment == Commitment.Held) heldIntention++;

                if (shown == null)
                {
                    string Line(string stage, TraceRecord r) => "| " + stage + " | #" + r.Id + " " + r.Kind + " | " + r.Summary.Replace("|", "/") + " |";
                    shown = "### " + m.Variant + ", seed " + m.Seed + ", " + m.Who + Environment.NewLine + Environment.NewLine +
                            "| Stage | Record | What it says |" + Environment.NewLine + "|---|---|---|" + Environment.NewLine +
                            "| need | the body | hunger " + F(m.Chose.Percept.Hunger) + " at minute " + m.Chose.Minute + " |" + Environment.NewLine +
                            Line("want", wantBefore) + Environment.NewLine +
                            Line("decision", decision) + Environment.NewLine +
                            Line("eating", eating) + Environment.NewLine +
                            Line("consequence", consequence) + Environment.NewLine +
                            Line("experience", experience) + Environment.NewLine +
                            Line("outcome", outcome) + Environment.NewLine +
                            Line("want again", wantAfter) + Environment.NewLine + Environment.NewLine +
                            "Each record in the table is a parent of the one below it, checked. The want at the next decision, printed by the trace tool with the decision's own reasons cut:" +
                            Environment.NewLine + Environment.NewLine + "```" + Environment.NewLine +
                            string.Join(Environment.NewLine, Shorten(t.Why(wantAfter.Id)).Split('\n').Select(l => l.TrimEnd('\r')).TakeWhile(l => !l.Contains("Deliberation"))) +
                            Environment.NewLine + "```" + Environment.NewLine;
                }
            }

            Record("A4. The loop, link by link", meals.Count + " meals checked, every link present. " + heldIntention + " of them were chosen on arrival under an intention to get food carried from a walk (S1.2)." +
                   Environment.NewLine + Environment.NewLine + shown);
        }

        [Test]
        public void A3_HavingEatenMakesEatingAgainLessWanted()
        {
            var meals = Meals(_plenty, _content.Morning.Variants.Select(v => v.Id), 10)
                .Where(m => m.Event.Action == "eat_portion" && m.Chose != null).ToList();

            var pairs = meals.Where(m => m.NextWithFoodInReach != null).ToList();
            var drops = new List<double>();
            foreach (var m in pairs)
            {
                var before = m.Chose.Decision.Ranked.First(r => r.Option.Kind == ActionKind.Eat).Appeal;
                var after = m.NextWithFoodInReach.Decision.Ranked.First(r => r.Option.Kind == ActionKind.Eat).Appeal;
                drops.Add(before - after);
                Assert.Less(after, before, m.Who + " wanted to eat again as much as before eating");
            }

            var byPerson = meals.GroupBy(m => m.Variant + "/" + m.Seed + "/" + m.Who).ToList();
            var again = byPerson.Where(g => g.Count() > 1).ToList();
            var gaps = again.SelectMany(g => g.OrderBy(x => x.Event.Minute).Zip(g.OrderBy(x => x.Event.Minute).Skip(1), (a, b) => b.Event.Minute - a.Event.Minute)).ToList();

            Record("A3. Eating again", meals.Count + " meals in " + byPerson.Count + " person-mornings. " +
                   pairs.Count + " eaters had food in reach again later; eating was worth less to every one of them than when they chose to eat, by a mean of " +
                   (drops.Count == 0 ? "n/a" : F(drops.Average())) + " (one portion is " + _content.Rules.Deciding.PortionRelief + "). " +
                   again.Count + " person-mornings had a second meal, " +
                   (gaps.Count == 0 ? "" : "the soonest " + gaps.Min() + " and on average " + gaps.Average().ToString("0") + " minutes after the first") + ".");
            Assert.IsNotEmpty(pairs, "nobody was ever near food again after eating, so this measured nothing");
        }

