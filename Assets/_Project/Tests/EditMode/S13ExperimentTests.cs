                    found = who + ", " + v.Id + " seed " + seed + ": `" + o + "`.";
                }
            }

            Record("C3. No longer relevant", found ?? "No case found.");
            Assert.IsNotNull(found, "nobody walked to the food for hunger and arrived");
        }

