            }, StringComparer.Ordinal);
            var still = new Scenario001Content(_content.Vocabulary, cast, _content.Backstory, _content.Morning, _content.Rules);

            string found = null;
            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= 10 && found == null; seed++)
            {
                var run = Scenario001.Prepare(still, v.Id, seed);
                for (var i = 0; i < 90 && found == null; i++)
                {
                    run.Morning.Step();
                    var who = People.FirstOrDefault(p => run.Morning.Intends(p)?.MotiveName == "get_food" && run.Morning.Doing(p)?.Action.Kind == ActionKind.GoTo);
                    if (who == null) continue;

                    run.World.SetHunger(who, 0.0);
                    DecisionMoment arrival = null;
                    run.Morning.Decided = m => { if (m.CharacterId == who && arrival == null) arrival = m; };
                    for (var j = 0; j < 10 && arrival == null; j++) run.Morning.Step();
