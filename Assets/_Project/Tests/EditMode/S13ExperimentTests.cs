        [Test]
        public void C2_GoingForFoodAndNotEatingIsUnresolvedAndMovesNothing()
        {
            // The scenario as written. Every walk to the food ends in not eating.
            var lapses = 0;
            var outcomes = 0;
            var wrong = new List<string>();
            PursuitOutcome example = null;

            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= 10; seed++)
            {
                var run = Scenario001.Prepare(_content, v.Id, seed);
                run.Morning.Decided = m =>
                {
                    if (m.Decision.Holding?.MotiveName != "get_food" || m.Decision.Commitment == Commitment.Held) return;
                    lapses++;
                    var o = m.Mind.Outcomes.LastOrDefault();
                    if (o == null || o.Minute != m.Minute || o.MotiveName != "get_food") { wrong.Add(m.CharacterId + " gave up at minute " + m.Minute + " with no outcome"); return; }
                    outcomes++;
                    if (o.Kind != Outcomes.OfLapse(m.Decision.Commitment)) wrong.Add("judged " + o.Kind + " for " + m.Decision.Commitment);
                    var want = FoodWant(m);
                    if (want != null && Math.Abs(want.Urgency - Accumulate.Knee(m.Percept.Hunger, _content.Rules.Deciding.UrgencyKnee)) > 1e-9) wrong.Add("the want moved");
                    example = example ?? o;
                };
                run.Morning.Run(_content.Morning.Minutes);
            }

            Record("C2. Going for food and not eating", "The scenario as written, five conditions, seeds 1 to 10: " + lapses + " walks to the food given up on arrival, " +
                   outcomes + " outcomes recorded. Example: `" + example + "`. The want is unchanged by it: still exactly what the body says, and it now says why.");
            Assert.IsEmpty(wrong, string.Join("\n", wrong));
            Assert.Greater(lapses, 0);
        }

        [Test]
        public void C3_WhenTheWantHasGoneByTheTimeYouArriveItIsNoLongerRelevant()
        {
            // An intervention: somebody walking to the food for hunger stops being
            // hungry on the way (the body is set to nothing). On arrival there is
            // nothing to serve. Metabolism would add a little back every minute
            // before they arrive, so for this test nobody's body burns anything;
            // that is a change to the circumstance, and the only one.
