        [Test]
        public void C1_ReachingForFoodThatIsGoneIsBlockedFeltAndLeavesTheWantWhereItWas()
        {
            // An intervention: in the last minute of somebody eating, the pantry is
            // emptied, as if somebody else had got there first. The same moment
            // without the intervention is the control.
            string found = null;
            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= 10 && found == null; seed++)
            {
                var probe = Scenario001.Prepare(_plenty, v.Id, seed);
                var steps = 0;
                string who = null;
                for (; steps < 90 && who == null; steps++)
                {
                    probe.Morning.Step();
                    who = People.FirstOrDefault(p => probe.Morning.Doing(p)?.Action.Kind == ActionKind.Eat && probe.Morning.Doing(p)?.MinutesLeft == 1);
                }
                if (who == null) continue;

                (Scenario001Run run, PursuitOutcome outcome, WorldEvent e, DecisionMoment next) Finish(bool drain)
                {
                    var run = Scenario001.Prepare(_plenty, v.Id, seed);
                    for (var i = 0; i < steps; i++) run.Morning.Step();
                    if (drain) while (run.World.TakePortion()) { }
                    DecisionMoment next = null;
                    run.Morning.Decided = m => { if (m.CharacterId == who && next == null) next = m; };
                    var seen = run.Result.Events.Count;
                    run.Morning.Step();
                    var e = run.Result.Events.Skip(seen).FirstOrDefault(x => x.ActorId == who && (x.Action == "eat_portion" || x.Action == "find_nothing_left"));
                    for (var j = 0; j < 10 && next == null; j++) run.Morning.Step();
                    return (run, e == null ? null : run.Minds[who].Outcomes.LastOrDefault(o => o.EventId == e.Id), e, next);
                }

                var blocked = Finish(true);
                if (blocked.e == null) continue;
                var control = Finish(false);

                Assert.AreEqual("find_nothing_left", blocked.e.Action);
                Assert.AreEqual(OutcomeKind.Blocked, blocked.outcome.Kind);
                Assert.AreEqual(blocked.outcome.Before, blocked.outcome.After, 0.0, "nothing was eaten and the need moved");
                var felt = blocked.run.Minds[who].Experiences.FirstOrDefault(x => x.EventId == blocked.e.Id);
                Assert.IsNotNull(felt, "reaching for nothing was not perceived by the person who reached");

                Assert.IsNotNull(blocked.next);
                var want = FoodWant(blocked.next);
                Assert.IsNotNull(want, "the want disappeared when the food did");
                Assert.IsTrue(Counterfactual.ReachesCause(blocked.run.Trace, want, new[] { blocked.e.Id }), "the want cannot be walked back to finding nothing");

                var controlWant = FoodWant(control.next);
                Assert.AreEqual(OutcomeKind.PartlySatisfied, control.outcome.Kind);
                Assert.Greater(want.Urgency, controlWant?.Urgency ?? 0.0, "finding nothing left the want as low as eating did");

                var witnesses = blocked.e.Witnesses.Where(w => blocked.run.Minds[w].Experiences.Any(x => x.EventId == blocked.e.Id)).ToList();
                found = "### " + v.Id + ", seed " + seed + ", " + who + ", minute " + blocked.e.Minute + Environment.NewLine + Environment.NewLine +
                        "| | Pantry emptied first | Control |" + Environment.NewLine + "|---|---|---|" + Environment.NewLine +
                        "| What happened | " + blocked.e.Summary + " | " + control.e.Summary + " |" + Environment.NewLine +
