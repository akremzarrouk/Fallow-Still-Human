        /// <summary>One act of eating and everything around it.</summary>
        sealed class Meal
        {
            public string Variant;
            public ulong Seed;
            public string Who;
            public DecisionMoment Chose;
            public DecisionMoment Next;
            public DecisionMoment NextWithFoodInReach;

            /// <summary>Every decision the eater took after the meal, in order.</summary>
            public List<DecisionMoment> After = new List<DecisionMoment>();
            public WorldEvent Event;
            public PursuitOutcome Outcome;
            public Scenario001Run Run;
        }

        /// <summary>
        /// Runs mornings and collects every completed act of eating, with the
        /// decision that chose it, the eater's next decision, the event and the
        /// outcome. Everything about a decision is read in the callback, while
        /// the mind is still in the state it decided in.
        /// </summary>
        static List<Meal> Meals(Scenario001Content content, IEnumerable<string> variants, int seeds, Action<Scenario001Run> set = null)
        {
            var meals = new List<Meal>();
            foreach (var v in variants)
            for (ulong seed = 1; seed <= (ulong)seeds; seed++)
            {
                var run = Scenario001.Prepare(content, v, seed);
                set?.Invoke(run);
                var chosen = new Dictionary<string, DecisionMoment>(StringComparer.Ordinal);
                var open = new List<Meal>();
                var seenEvents = run.Result.Events.Count;

                // A meal is resolved, and the eater may decide again, within the
                // same minute, so meals are gathered as soon as their event exists.
                void Gather()
                {
                    var events = run.Result.Events;
                    for (; seenEvents < events.Count; seenEvents++)
                    {
                        var e = events[seenEvents];
                        if (e.Action != "eat_portion" && e.Action != "find_nothing_left") continue;
                        var meal = new Meal
                        {
                            Variant = v, Seed = seed, Who = e.ActorId, Event = e, Run = run,
                            Outcome = run.Minds[e.ActorId].Outcomes.LastOrDefault(o => o.EventId == e.Id)
                        };
                        chosen.TryGetValue(e.ActorId, out var decided);
                        meal.Chose = decided;
                        meals.Add(meal);
                        open.Add(meal);
                    }
                }

                run.Morning.Decided = m =>
                {
                    Gather();
                    foreach (var meal in open.Where(x => x.Who == m.CharacterId))
                    {
                        if (meal.Next == null) meal.Next = m;
                        meal.After.Add(m);
                        if (meal.NextWithFoodInReach == null && m.Decision.Ranked.Any(r => r.Option.Kind == ActionKind.Eat)) meal.NextWithFoodInReach = m;
                    }
                    if (m.Decision.Chosen.Kind == ActionKind.Eat) chosen[m.CharacterId] = m;
                };

                for (var i = 0; i < content.Morning.Minutes; i++)
                {
                    run.Morning.Step();
                    Gather();
                }
            }
            return meals;
        }

        static Motive FoodWant(DecisionMoment m) => m?.Motives.FirstOrDefault(x => x.Name == "get_food");

