        [Test]
        public void B1_NotEnoughFoodLeavesAWantThatSaysHowMuchIsLeftAndWhy()
        {
            // One portion is not enough for anybody hungry enough to take it: every
            // meal in the house is partial. What remains has to be exactly what the
            // meal left plus what the body has added since, and has to say so.
            var meals = Meals(_plenty, _content.Morning.Variants.Select(v => v.Id), 10).Where(m => m.Event.Action == "eat_portion").ToList();
            Assert.IsNotEmpty(meals);

            var sb = new StringBuilder();
            var checkedLater = 0;
            foreach (var m in meals)
            {
                Assert.AreEqual(OutcomeKind.PartlySatisfied, m.Outcome.Kind);
                Assert.Greater(m.Outcome.After, 0.0);

                // The eater's want at a later decision, well after the meal.
                var later = LaterDecision(m, 10);
                if (later == null) continue;
                var want = FoodWant(later);
                Assert.IsNotNull(want, m.Who + " is still hungry and wants nothing");
                var elapsed = later.Minute - m.Outcome.Minute;
                var expected = Math.Min(1.0, m.Outcome.After + elapsed * _content.Rules.Deciding.HungerPerMinute * m.Run.Minds[m.Who].Profile.HungerRate);
                Assert.AreEqual(expected, later.Percept.Hunger, 1e-9, "what remains is not what the meal left plus the body since");
                Assert.AreEqual(Accumulate.Knee(expected, _content.Rules.Deciding.UrgencyKnee), want.Urgency, 1e-9);
                var term = want.Terms.First(t => t.Description.StartsWith("hunger", StringComparison.Ordinal));
                Assert.IsTrue(term.Drew.Contains(m.Outcome.TraceId), "what remains does not rest on the meal");
                checkedLater++;
                if (checkedLater <= 3)
                    sb.AppendLine("- " + m.Who + ", " + m.Variant + " seed " + m.Seed + ": ate at minute " + m.Outcome.Minute + " (" + F(m.Outcome.Before) + " -> " + F(m.Outcome.After) +
                                  "); at minute " + later.Minute + ", " + elapsed + " minutes on, `get_food` " + F(want.Urgency) + ", resting on: " + term);
            }

            sb.AppendLine();
            sb.AppendLine(meals.Count + " meals, all partly satisfied. On " + checkedLater + " of them the eater decided again at least ten minutes later; each time the want was exactly what the meal left plus the body since, and named the meal.");
            Record("B1. Not enough", sb.ToString());
            Assert.Greater(checkedLater, 0);
        }

        /// <summary>The eater's first decision at least this many minutes after the meal, read from the run's recorded decisions.</summary>
        static DecisionMoment LaterDecision(Meal m, int minutes)
        {
            var later = m.After.FirstOrDefault(x => x.Minute - m.Outcome.Minute >= minutes);
            if (later == null) return null;
            // Only if nothing else was done about the need in between.
            var between = m.Run.Minds[m.Who].Outcomes.Any(o => o.Need == m.Outcome.Need && o.Minute > m.Outcome.Minute && o.Minute <= later.Minute && o != m.Outcome);
            return between ? null : later;
        }

