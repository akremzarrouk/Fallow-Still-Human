        [Test]
        public void E_WhoEatsWhenTheHouseLetsThem()
        {
            var sb = new StringBuilder();
            sb.AppendLine("Shipped rules; only circumstances change. Every eating act and every reach for food that was gone, with how each was judged.");
            sb.AppendLine();
            sb.AppendLine("| Circumstance | Mornings | Mornings each ate: daniel / elena / leo / mara | Meals | ... chosen under an intention held from a walk | Second meals | Outcomes of meals | Reaches that found nothing |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            var problems = new List<string>();

            void Row(string label, Scenario001Content content, int seeds, Action<Scenario001Run> set = null)
            {
                var meals = Meals(content, content.Morning.Variants.Select(v => v.Id), seeds, set);
                var ate = meals.Where(m => m.Event.Action == "eat_portion").ToList();
                foreach (var m in meals.Where(m => m.Outcome == null)) problems.Add(label + ": " + m.Who + " " + m.Event.Action + " with no outcome");
                var mornings = content.Morning.Variants.Count * seeds;
                sb.AppendLine("| " + label + " | " + mornings + " | " +
                              string.Join(" / ", People.Select(p => ate.Where(m => m.Who == p).Select(m => m.Variant + m.Seed).Distinct().Count())) + " | " + ate.Count + " | " +
                              ate.Count(m => m.Chose?.Decision.Commitment == Commitment.Held) + " | " +
                              ate.GroupBy(m => m.Variant + m.Seed + m.Who).Sum(g => g.Count() - 1) + " | " +
                              string.Join(", ", ate.Where(m => m.Outcome != null).GroupBy(m => m.Outcome.Kind).Select(g => PursuitOutcome.Words(g.Key) + " " + g.Count())) + " | " +
                              meals.Count(m => m.Event.Action == "find_nothing_left") + " |");
            }

            Row("the scenario as written", _content, 20);
            Row("plenty of food, count still short", S13DiagnosisTests.Plenty(_content, 10, true), 20);
            Row("plenty of food, count not short", _plenty, 20);
            Row("two portions, count not short", S13DiagnosisTests.Plenty(_content, 2, false), 20);
            foreach (var p in People) Row(p + " starving alone, plenty, not short", _plenty, 4, r => S13DiagnosisTests.StarvingAlone(r, p));
            foreach (var p in People) Row(p + " starving alone, as written", _content, 4, r => S13DiagnosisTests.StarvingAlone(r, p));

            Record("E. Who eats", sb.ToString());
            Assert.IsEmpty(problems, string.Join("\n", problems));
        }

