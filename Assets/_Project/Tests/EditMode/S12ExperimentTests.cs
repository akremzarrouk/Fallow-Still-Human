        [Test]
        public void NothingInTheDecidingCodeNamesAWantAReadingAFeelingOrAnAct()
        {
            var names = _content.Vocabulary.Set("motives")
                .Concat(_content.Rules.Proposals.Select(p => p.Id))
                .Concat(_content.Rules.Costs.Select(c => c.Id))
                // "neutral" is also the word for a tone and a valence, which the
                // morning writes on the events it emits, so it cannot be told apart.
                .Concat(_content.Rules.Interpretation.Select(r => r.Label).Where(l => l != "neutral"))
                .Concat(_content.Vocabulary.Set("emotions"))
                .Concat(_content.Cast.Keys)
                .Concat(_content.Morning.Variants.Concat(_content.Morning.HeldOutVariants).Select(v => v.Id))
                .Distinct()
                .ToList();

            var problems = new List<string>();
            foreach (var file in new[] { "Deliberator.cs", "Motivator.cs", "ActionCatalog.cs", "SilentMorning.cs", "DecisionTrace.cs" })
            {
                var text = File.ReadAllText(Directory.GetFiles(TestPaths.CoreSources, file, SearchOption.AllDirectories).Single());
                foreach (var n in names)
                    if (text.Contains("\"" + n + "\"")) problems.Add(file + " names \"" + n + "\"");
            }

            Assert.IsEmpty(problems, string.Join("\n", problems));
        }
