        static void Record(string key, string text)
        {
            _findings[key] = text;
            TestContext.WriteLine(text);
        }

        static IReadOnlyList<WorldEvent> Night(string variant) => _content.Morning.Variant(variant).NightEvents;
        static IReadOnlyList<string> Causes(string variant) => Night(variant).Select(e => e.Id).ToList();

        sealed class Paired
        {
            public Scenario001Run Control;
            public Scenario001Run Treatment;
            public List<DecisionMoment> C = new List<DecisionMoment>();
            public List<DecisionMoment> T = new List<DecisionMoment>();
        }

        /// <summary>
        /// Both mornings, run side by side. Anything that needs to weigh a
        /// decision again must do it in <paramref name="atTheMoment"/>, while the
        /// mind is still in the state it decided in; afterwards it has moved on.
        /// </summary>
        static Paired RunPaired(Scenario001Content content, string variant, IReadOnlyList<WorldEvent> control,
            IReadOnlyList<WorldEvent> treatment, ulong seed, string who, int? minutes = null,
            Action<DecisionMoment, bool> atTheMoment = null)
        {
            var p = new Paired
            {
                Control = Scenario001.PrepareWith(content, variant + "/control", control, seed),
                Treatment = Scenario001.PrepareWith(content, variant + "/treatment", treatment, seed)
            };
            p.Control.Morning.Decided = m => { if (who == null || m.CharacterId == who) { p.C.Add(m); atTheMoment?.Invoke(m, false); } };
            p.Treatment.Morning.Decided = m => { if (who == null || m.CharacterId == who) { p.T.Add(m); atTheMoment?.Invoke(m, true); } };
            p.Control.Morning.Run(minutes ?? content.Morning.Minutes);
            p.Treatment.Morning.Run(minutes ?? content.Morning.Minutes);
            return p;
        }

        /// <summary>Everything a person can know about where they stand, the same in both worlds.</summary>
        static bool SameSituation(DecisionMoment a, DecisionMoment b)
        {
            var x = a.Percept;
            var y = b.Percept;
            return a.Minute == b.Minute
                   && x.Room?.Id == y.Room?.Id
                   && x.Present.SequenceEqual(y.Present)
                   && x.JustWatched.OrderBy(s => s).SequenceEqual(y.JustWatched.OrderBy(s => s))
                   && x.RoomsIHaveSearched.SequenceEqual(y.RoomsIHaveSearched)
                   && x.LookedInThePantryMyself == y.LookedInThePantryMyself
                   && x.SearchedThisRoomMyself == y.SearchedThisRoomMyself
                   && x.FoodWithinReach == y.FoodWithinReach
                   && Math.Abs(x.Hunger - y.Hunger) < 1e-9
                   && a.Decision.Holding?.MotiveKey == b.Decision.Holding?.MotiveKey;
        }

        static string Shorten(string why)
            => string.Join(Environment.NewLine, why.Split('\n')
                .Select(l => l.TrimEnd('\r'))
                .Select(l => l.Length > 200 ? l.Substring(0, 197) + "..." : l));

        static Dictionary<string, double> Profile(IEnumerable<Scenario001Run> runs, string who)
        {
            var counts = new Dictionary<string, double>(StringComparer.Ordinal);
            var total = 0;
            foreach (var run in runs)
            foreach (var a in run.Result.By(who))
            {
                counts.TryGetValue(a.Action.KindName, out var n);
                counts[a.Action.KindName] = n + 1;
                total++;
            }
            return counts.ToDictionary(k => k.Key, k => k.Value / Math.Max(1, total), StringComparer.Ordinal);
        }

        static List<Scenario001Run> Pool(Scenario001Content content, string variant, bool night, ulong from, int count)
        {
            var runs = new List<Scenario001Run>();
            for (var seed = from; seed < from + (ulong)count; seed++)
            {
                var run = Scenario001.PrepareWith(content, variant, night ? Night(variant) : new List<WorldEvent>(), seed);
                run.Morning.Run(content.Morning.Minutes);
                runs.Add(run);
            }
            return runs;
        }

