        [Test]
        public void T5_NoTwoPeopleAreAsAlikeAsOnePersonIsToThemself()
        {
            // Collapse measured against the only scale that is not chosen: how
            // different the same person's mornings are from one set of seeds to
            // another. Two people closer than that are indistinguishable.
            const string variant = "mara_ate_it";
            var a = Pool(_content, variant, true, 1, 20);
            var b = Pool(_content, variant, true, 21, 20);
            var people = _content.Cast.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();

            var noise = people.Max(p => BatchRunner.HowDifferent(Profile(a, p), Profile(b, p)));
            var both = a.Concat(b).ToList();
            var gaps = new List<(string, double)>();
            for (var i = 0; i < people.Count; i++)
            for (var j = i + 1; j < people.Count; j++)
                gaps.Add((people[i] + "/" + people[j], BatchRunner.HowDifferent(Profile(both, people[i]), Profile(both, people[j]))));

            var closest = gaps.OrderBy(g => g.Item2).First();
            Record("5. People stay themselves", "`" + variant + "`, 40 mornings. The same person across two twenty-seed pools differs by at most **" +
                   noise.ToString("0.000") + "**. Two different people differ by a mean of **" + gaps.Average(g => g.Item2).ToString("0.00") +
                   "**; the closest pair is " + closest.Item1 + " at **" + closest.Item2.ToString("0.00") + "**." +
                   Environment.NewLine + Environment.NewLine + string.Join(", ", gaps.Select(g => g.Item1 + " " + g.Item2.ToString("0.00"))));

            Assert.Greater(closest.Item2, noise * 2, closest.Item1 + " are as alike as one person is to themself");
        }

