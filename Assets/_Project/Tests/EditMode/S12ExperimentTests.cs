        [Test]
        public void T1a_AChangedWantChangesWhatTheOptionsAreWorthAndLeadsBackToTheNight()
        {
            var sb = new StringBuilder();
            sb.AppendLine("First decision of the morning, where both worlds are identical apart from the person. An option counts as moved when its appeal changed by more than " + Moved + ".");
            sb.AppendLine();
            sb.AppendLine("| Condition | Who | Options moved (mean per seed) | Of those, traceable to the night | Largest mean move | Best option changed |");
            sb.AppendLine("|---|---|---|---|---|---|");

            var maraTraced = 0.0;
            var maraMoved = 0;

            foreach (var (variant, who) in Culprits)
            {
                var moved = 0;
                var traced = 0;
                var topChanged = 0;
                var shifts = new Dictionary<string, List<double>>(StringComparer.Ordinal);

                for (ulong seed = 1; seed <= Seeds; seed++)
                {
                    var p = RunPaired(_content, variant, new List<WorldEvent>(), Night(variant), seed, who, minutes: 1);
                    var c = p.C[0].Decision;
                    var t = p.T[0].Decision;
                    if (!c.Considered[0].Option.SameAs(t.Considered[0].Option)) topChanged++;
                    var memo = new Dictionary<int, bool>();

                    foreach (var option in t.Ranked)
                    {
                        var was = c.Ranked.First(r => r.Option.SameAs(option.Option));
                        var shift = option.Appeal - was.Appeal;
                        if (!shifts.TryGetValue(option.Option.Key, out var l)) shifts[option.Option.Key] = l = new List<double>();
                        l.Add(shift);
                        if (Math.Abs(shift) <= Moved) continue;

                        moved++;
                        var rests = option.Contributions.Any(k =>
                        {
                            var motive = t.Motives.First(m => m.Key == k.MotiveKey);
                            return Counterfactual.ReachesCause(p.Treatment.Trace, motive, Causes(variant), memo);
                        });
                        if (rests) traced++;
                    }
                }

                var biggest = shifts.OrderByDescending(s => Math.Abs(s.Value.Average())).First();
                sb.AppendLine("| " + variant + " | " + who + " | " + (moved / (double)Seeds).ToString("0.0") + " | " +
                              (moved == 0 ? "n/a" : (traced / (double)moved).ToString("P0")) + " | `" + biggest.Key + "` " +
                              biggest.Value.Average().ToString("+0.000;-0.000") + " | " + topChanged + " of " + Seeds + " |");

                if (who == "mara") { maraMoved = moved; maraTraced = moved == 0 ? 0 : traced / (double)moved; }
            }

            Record("1a. Changed want, changed candidate appeal", sb.ToString());
            Assert.Greater(maraMoved, 0, "her night moved no option's appeal");
            Assert.AreEqual(1.0, maraTraced, 1e-9, "an option moved for a reason that does not lead back to her night");
        }

        [Test]
        public void T1b_SameSituationSamePersonADifferentChoiceBecauseOfTheNight()
        {
            // The strictest form of the claim. Pairs of decisions taken at the
            // same minute, in the same room, with the same people, the same
            // hunger, the same knowledge of the house and the same intention
            // carried in. Where both are settled clearly, nothing was left to the
            // seed, so a different choice can only be the person, and the want
            // behind the treatment choice must lead back to the night. Where the
            // seed settled either one, the night can only have moved the odds.
            var sb = new StringBuilder();
            sb.AppendLine("| Condition | Who | Same situation, both clear | Different choice | ... led by a want resting on the night | Same situation, seed settled one or both | Different choice |");
            sb.AppendLine("|---|---|---|---|---|---|---|");

            var examples = new Dictionary<string, string>(StringComparer.Ordinal);
            var maraCaused = 0;
            var anyCaused = 0;

            foreach (var (variant, who) in Culprits)
            {
                var same = 0;
                var different = 0;
                var caused = 0;
                var sameOpen = 0;
                var differentOpen = 0;

                for (ulong seed = 1; seed <= Seeds; seed++)
                {
                    var p = RunPaired(_content, variant, new List<WorldEvent>(), Night(variant), seed, who);
                    var memo = new Dictionary<int, bool>();

                    foreach (var t in p.T)
                    {
                        var c = p.C.FirstOrDefault(x => x.Minute == t.Minute);
                        if (c == null || !SameSituation(c, t)) continue;

                        if (c.Decision.Resolution != Resolution.Clear || t.Decision.Resolution != Resolution.Clear)
                        {
                            sameOpen++;
                            if (!c.Decision.Chosen.SameAs(t.Decision.Chosen)) differentOpen++;
                            continue;
                        }

                        same++;
                        if (c.Decision.Chosen.SameAs(t.Decision.Chosen)) continue;
                        different++;

                        var leading = t.Decision.Leading;
                        if (leading == null || !Counterfactual.ReachesCause(p.Treatment.Trace, leading, Causes(variant), memo)) continue;
                        caused++;

                        if (!examples.ContainsKey(who))
                            examples[who] = "### " + variant + ", " + who + ", seed " + seed + ", minute " + t.Minute + Environment.NewLine + Environment.NewLine +
                                            "Without the night:" + Environment.NewLine + Environment.NewLine + "```" + Environment.NewLine +
                                            DecisionTrace.Explain(c.Decision, 4) + "```" + Environment.NewLine + Environment.NewLine +
                                            "With the night:" + Environment.NewLine + Environment.NewLine + "```" + Environment.NewLine +
                                            DecisionTrace.Explain(t.Decision, 4) + "```" + Environment.NewLine + Environment.NewLine +
                                            "The want that led the changed choice, and what it rests on:" + Environment.NewLine + Environment.NewLine +
                                            "```" + Environment.NewLine + Shorten(p.Treatment.Trace.Why(leading.TraceId)) + Environment.NewLine + "```" + Environment.NewLine;
                    }
                }

                sb.AppendLine("| " + variant + " | " + who + " | " + same + " | " + different + " | " + caused + " | " + sameOpen + " | " + differentOpen + " |");
                if (who == "mara") maraCaused = caused;
                anyCaused += caused;
            }

            sb.AppendLine();
            foreach (var e in examples.Values) sb.AppendLine(e);
            if (examples.Count == 0) sb.AppendLine("No example: no clear choice in an identical situation was changed by a night.");
            Record("1b. Same situation, different choice", sb.ToString());

            // The first version of this test asserted it for Mara, and failed: in
            // twenty seeds her night never changed a clear choice she made in an
            // identical situation. That miss is pinned here rather than softened,
            // in the way S1.1 pinned its held-out miss. The claim that it happens
            // for somebody is asserted separately, and was added after the miss,
            // which the S1.2 report says.
            Assert.AreEqual(0, maraCaused,
                "RECORDED MISS. If this starts failing, her night has started changing clear choices in identical situations; turn it round");
            Assert.Greater(anyCaused, 0, "no night ever changed a clear choice made in an identical situation");
        }

        [Test]
        public void T1c_BehaviourAgainstTheNoiseOnSeedsNeverUsedBefore()
        {
            // Seeds 81 to 120 had not been used by any test when this was written.
            // The gate was set before they were run and is the S1.1 gate unchanged:
            // Mara's night-versus-no-night difference must be more than one and a
            // half times the larger of the two same-condition differences.
            var sb = new StringBuilder();
            sb.AppendLine("Twenty-seed pools, seeds 81 to 100 and 101 to 120.");
            sb.AppendLine();
            sb.AppendLine("| Condition | Who | Night vs no night | No night vs no night | Night vs night | Above the noise |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var maraAbove = false;

            foreach (var (variant, who) in Culprits)
            {
                var t1 = Profile(Pool(_content, variant, true, 81, 20), who);
                var t2 = Profile(Pool(_content, variant, true, 101, 20), who);
                var c1 = Profile(Pool(_content, variant, false, 81, 20), who);
                var c2 = Profile(Pool(_content, variant, false, 101, 20), who);

                var effect = (BatchRunner.HowDifferent(t1, c2) + BatchRunner.HowDifferent(t2, c1)) / 2;
                var noiseC = BatchRunner.HowDifferent(c1, c2);
                var noiseT = BatchRunner.HowDifferent(t1, t2);
                var above = effect > Math.Max(noiseC, noiseT) * 1.5;
                if (who == "mara") maraAbove = above;

                sb.AppendLine("| " + variant + " | " + who + " | " + effect.ToString("0.000") + " | " + noiseC.ToString("0.000") +
                              " | " + noiseT.ToString("0.000") + " | " + (above ? "yes" : "no") + " |");
            }

            Record("1c. Behaviour against the noise floor, fresh seeds", sb.ToString());
            Assert.IsTrue(maraAbove, "her night no longer changes her morning by more than the seeds do");
        }

        // ---- 2. remove the cause ----

        [Test]
        public void T2_RemovingTheNightRemovesEveryDecisionItChanged()
        {
            var problems = new List<string>();
            var compared = 0;

            foreach (var (variant, _) in Culprits)
            for (ulong seed = 1; seed <= 3; seed++)
            {
                var p = RunPaired(_content, variant, new List<WorldEvent>(),
                    Counterfactual.Without(Night(variant), Causes(variant).ToArray()), seed, null);

                if (p.C.Count != p.T.Count) { problems.Add(variant + "/" + seed + ": different number of decisions"); continue; }

                for (var i = 0; i < p.C.Count; i++)
                {
                    var c = p.C[i].Decision;
                    var t = p.T[i].Decision;
                    compared++;

                    if (p.C[i].Minute != p.T[i].Minute || c.CharacterId != t.CharacterId || !c.Chosen.SameAs(t.Chosen) ||
                        c.Commitment != t.Commitment || c.Forms?.MotiveKey != t.Forms?.MotiveKey ||
                        c.Ranked.Count != t.Ranked.Count ||
                        c.Ranked.Zip(t.Ranked, (x, y) => x.Option.SameAs(y.Option) && x.Score == y.Score && x.Contributions.Count == y.Contributions.Count).Any(ok => !ok))
                    {
                        problems.Add(variant + "/" + seed + ": decision " + i + " (" + c.CharacterId + ", minute " + p.C[i].Minute + ") differs");
                        break;
                    }
                }
            }

            Record("2. Removing the cause", problems.Count == 0
                ? "With the night event removed, " + compared + " decisions across all four design conditions on seeds 1 to 3 are identical to the control: same options, same score for every option to the last bit, same contributions, same intention carried in and formed, same choice."
                : string.Join(Environment.NewLine, problems));
            Assert.IsEmpty(problems, string.Join("\n", problems));
        }

