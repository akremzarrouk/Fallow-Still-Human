        [Test]
        public void T3b_RemovingAWantChangesTheChoicesItMatteredToAndNoOthers()
        {
            // At every one of Mara's decisions, the same moment is weighed again
            // with the want taken out. Every option must lose exactly what that
            // want added to it and nothing else, and the choice may change only
            // where the want was part of what put the winner ahead.
            const string variant = "mara_ate_it";
            var sb = new StringBuilder();
            var deliberator = new Deliberator(_content.Rules);
            var maraMattered = 0;

            sb.AppendLine("| Want removed | Mara's decisions | Where it added to any option considered | Where the best option changed |");
            sb.AppendLine("|---|---|---|---|");

            string example = null;

            foreach (var want in new[] { "avoid_exposure", "find_out", "look_after", "keep_peace" })
            {
                var decisions = 0;
                var present = 0;
                var changed = 0;

                for (ulong seed = 1; seed <= 10; seed++)
                {
                    RunPaired(_content, variant, new List<WorldEvent>(), Night(variant), seed, "mara", atTheMoment: (m, isTreatment) =>
                    {
                        if (!isTreatment) return;
                        decisions++;
                        var d = m.Decision;
                        var removed = m.Motives.Where(x => x.Name != want).ToList();
                        var again = deliberator.Decide(m.Mind, m.Percept, removed, _content.Morning.Day, new Rng(1), new TraceLog(), 0, d.Holding);

                        foreach (var option in d.Ranked)
                        {
                            var after = again.Ranked.First(r => r.Option.SameAs(option.Option));
                            var lost = option.Contributions.Where(c => c.MotiveName == want).Sum(c => c.Amount);
                            Assert.AreEqual(option.Score - lost, after.Score, 1e-9, option.Option.Key + " lost something other than " + want);
                        }

                        var contributed = d.Considered.Any(o => o.Contributions.Any(c => c.MotiveName == want));
                        if (contributed) present++;

                        var before = d.Considered[0].Option;
                        var now = again.Considered[0].Option;
                        if (before.SameAs(now)) return;

                        if (d.Commitment == again.Commitment)
                            Assert.IsTrue(contributed, "the best option changed at a decision " + want + " added nothing to");
                        changed++;
                        if (want == "avoid_exposure") maraMattered++;

                        if (example == null && want == "avoid_exposure" && d.Commitment == Commitment.None)
                            example = "### Seed " + seed + ", minute " + m.Minute + ", with `avoid_exposure`" + Environment.NewLine + Environment.NewLine +
                                      "```" + Environment.NewLine + DecisionTrace.Explain(d, 4) + "```" + Environment.NewLine + Environment.NewLine +
                                      "### The same moment, without it" + Environment.NewLine + Environment.NewLine +
                                      "```" + Environment.NewLine + DecisionTrace.Explain(again, 4) + "```" + Environment.NewLine;
                    });
                }

                sb.AppendLine("| `" + want + "` | " + decisions + " | " + present + " | " + changed + " |");
            }

            sb.AppendLine();
            sb.AppendLine(example ?? "No decision where removing `avoid_exposure` changed her choice.");
            Record("3b. Removing a want, at the decision", sb.ToString());
            Assert.Greater(maraMattered, 0, "taking away her wish to be elsewhere never changed a single choice");
        }

