    /// <summary>
    /// The S1.2 experiment: does a changed want now reach the choice?
    ///
    /// changed circumstance -> changed motivation -> changed candidate appeal ->
    /// changed intention or action. Each link is tested on its own, against a
    /// control that differs in one thing, on the same seed. Every test records
    /// what it measured whether it passes or not.
    /// </summary>
    public class S12ExperimentTests
    {
        const int Seeds = 20;
        const double Moved = 0.02;

        static Scenario001Content _content;
        static readonly SortedDictionary<string, string> _findings = new SortedDictionary<string, string>(StringComparer.Ordinal);

        static readonly (string Variant, string Who)[] Culprits =
        {
            ("mara_ate_it", "mara"),
            ("elena_fed_mara", "elena"),
            ("daniel_ate_it", "daniel"),
            ("daniel_hid_it", "daniel")
        };

