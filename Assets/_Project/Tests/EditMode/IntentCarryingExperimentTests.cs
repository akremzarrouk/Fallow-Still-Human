    /// <summary>
    /// The intent-carrying experiment: if what a person took themselves to be
    /// doing survives onto the event their act becomes, does anything about them
    /// afterwards differ?
    ///
    /// One physical act (searching a room), one character, one morning, one
    /// seed, and the only difference between arms is the intent carried on the
    /// event. Everything else is identical by construction: the same content,
    /// the same seed, the same random streams (forked per person and minute), the
    /// same world, and the same act with the same physical outcome.
    ///
    /// The two meanings are the shipped ones, and both are defensible from the
    /// data as it stands (see the report). Nothing about wants, rules, numbers,
    /// appraisal or interpretation was changed; the only new code in
    /// `Fallow.Core` is the hook that carries the intent and the event field it
    /// fills, which is null unless an experiment sets it.
    ///
    /// Writes `Docs/experiments/intent-carrying/results.md`.
    /// </summary>
    public class IntentCarryingExperimentTests
    {
        const string TakeResponsibility = "take_responsibility";
        const string AssertAuthority = "assert_authority";
        const int Seeds = 10;

        static Scenario001Content _content;
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        [OneTimeSetUp]
        public void Load() => _content = Baselines.Primary();

        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Intent-carrying action: results");
            sb.AppendLine();
            sb.AppendLine("Generated by `IntentCarryingExperimentTests` on the primary baseline. Each arm is a whole morning run from the same content with the same seed; the only difference between arms is the intent carried onto the event that one act becomes (or, in part 3, that every search becomes). The random stream is forked per person and minute from the seed, so it cannot shift between arms.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "experiments", "intent-carrying");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "results.md"), sb.ToString());
        }

        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static string F(double v) => v.ToString("0.000", CultureInfo.InvariantCulture);
        static string Or(string s) => string.IsNullOrEmpty(s) ? "null" : s;

        // ------------------------------------------------------------------ watching a run

        /// <summary>One decision, and the state it was taken in.</summary>
        sealed class Snap
        {
            public int Minute;
            public string Who;
            public string Chosen;
            public string Leading;
            public double Margin;
            public bool Ambiguous;
            public string Options;
            public Dictionary<string, double> Wants = new Dictionary<string, double>(StringComparer.Ordinal);
            public string Feelings;
            public string World;

            public string Line => "m" + Minute + " " + Who + " " + Chosen + " for " + (Leading ?? "nothing");
        }

        sealed class Watch
        {
            public string Label;
            public string Intent;
            public List<Snap> Decisions = new List<Snap>();
            public IReadOnlyList<ActionRecord> Actions;
            public IReadOnlyList<WorldEvent> Events;
            public IReadOnlyDictionary<string, Mind> Minds;
            public TraceLog Trace;
            public string Fingerprint;

            public Snap After(string who, int minute)
                => Decisions.FirstOrDefault(d => d.Who == who && d.Minute >= minute);

            public WorldEvent ActEvent(string who, string action, int notBefore)
                => Events.FirstOrDefault(e => e.ActorId == who && e.Action == action && e.Minute >= notBefore);
        }

        static Watch Run(string label, string variant, ulong seed, Func<Scenario001Run, Func<string, ActionOption, Decision, string>> intends, string intentLabel = null)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            if (intends != null) run.Morning.IntentOfAct = intends(run);
            var w = new Watch { Label = label, Intent = intentLabel };
            run.Morning.Decided = m =>
            {
                var d = m.Decision;
                var s = new Snap
                {
                    Minute = m.Minute, Who = m.CharacterId, Chosen = d.Chosen.Key, Leading = d.Leading?.Key,
                    Margin = d.Margin, Ambiguous = d.Resolution == Resolution.Ambiguous,
                    Options = string.Join("; ", d.Considered.Take(4).Select(r => r.Option.Key + " " + r.Score.ToString("+0.000;-0.000", CultureInfo.InvariantCulture))),
                    Feelings = string.Join(", ", m.Mind.Emotions.Live.OrderBy(e => e.Type, StringComparer.Ordinal)
                        .Select(e => e.Type + (e.TargetId == null ? "" : ":" + e.TargetId) + " " + F(e.Intensity))),
                    World = "portions " + run.World.Portions + "; " + string.Join(", ", S16.People.Select(p => p + " in " + run.World.RoomOf(p) + " hunger " + F(run.World.HungerOf(p))))
                };
                foreach (var x in m.Motives) s.Wants[x.Key] = x.Urgency;
                w.Decisions.Add(s);
            };
            run.Morning.Run(_content.Morning.Minutes);
            w.Actions = run.Result.Actions;
            w.Events = run.Result.Events;
            w.Minds = run.Minds;
            w.Trace = run.Trace;
            w.Fingerprint = string.Join("\n", w.Actions.Select(a => a.ToString() + " | " + a.Resolution + " " + a.Margin.ToString("R", CultureInfo.InvariantCulture)));
            return w;
        }

        /// <summary>
        /// Carries one intent onto one person's search, the one that finishes at
        /// a given minute, and onto nothing else. The minute identifies the act
        /// exactly: an act makes its event when it finishes, and the arms run
        /// identically up to that point.
        /// </summary>
        static Func<Scenario001Run, Func<string, ActionOption, Decision, string>> OnTheSearchFinishingAt(string who, int minute, string intent)
            => run => (actor, action, decision) =>
                actor == who && action.Kind == ActionKind.SearchRoom && run.World.Minute == minute ? intent : null;

        /// <summary>A hook that carries nothing, to show the hook itself changes nothing.</summary>
        static readonly Func<Scenario001Run, Func<string, ActionOption, Decision, string>> CarriesNothing =
            run => (actor, action, decision) => null;

        // ------------------------------------------------------------------ the case

        /// <summary>A real search act, found by running the baseline.</summary>
        sealed class Case
        {
            public string Variant;
            public ulong Seed;
            public string Who;
            public int Minute;
            public int Finished;
            public string Leading;
            public double Urgency;
            public Watch Baseline;
        }

        /// <summary>The first search led by the given want, over the design conditions in order.</summary>
        static Case FindSearch(string leadingWant)
        {
            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var w = Run("baseline", v, seed, null);
                foreach (var a in w.Actions.Where(a => a.Action.Kind == ActionKind.SearchRoom))
                {
                    if (a.LeadingMotive != leadingWant) continue;
                    // Only a search that ran its course and became an event, at
                    // the minute it was due to finish.
                    var finished = a.Minute + a.Action.Duration;
                    var e = w.Events.FirstOrDefault(x => x.ActorId == a.CharacterId && x.Action == "search_belongings" && x.Minute == finished);
                    if (e == null) continue;
                    return new Case
                    {
                        Variant = v, Seed = seed, Who = a.CharacterId, Minute = a.Minute, Finished = finished,
                        Leading = a.LeadingMotive, Urgency = a.LeadingUrgency, Baseline = w
                    };
                }
            }
            return null;
        }

        static string ReadingOf(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "no event";
            var x = w.Minds[who].Experiences.LastOrDefault(k => k.EventId == e.Id);
            if (x == null) return "nothing kept";
            return x.Meaning + (x.FromOwnIntent ? " (own intention)" : " (" + x.Access.ToString().ToLowerInvariant() + ")") +
                   ", salience " + F(x.Salience) + ", felt " + (x.DominantEmotion ?? "nothing");
        }

        static string StirredBy(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var records = w.Trace.ForEvent(e.Id).Where(r => r.CharacterId == who).ToList();
            var appraisals = records.Where(r => r.Kind == TraceKind.Appraisal).Select(r => r.Summary).ToList();
            return appraisals.Count == 0 ? "nothing" : string.Join("; ", appraisals);
        }

        static string InterpretationOf(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var r = w.Trace.ForEvent(e.Id).FirstOrDefault(x => x.CharacterId == who && x.Kind == TraceKind.Interpretation);
            if (r == null) return "-";
            var weight = r.Data.TryGetValue("weight", out var wt) ? wt : "1.00";
            var runner = r.Data.TryGetValue("runner_up", out var ru) ? ru : "none";
            return r.Summary + " (weight " + weight + ", runner-up " + runner + ")";
        }

        /// <summary>Whether what the act stirred became visible in the room afterwards, and to whom.</summary>
        static string Showed(Watch w, string who, int from)
        {
            var shown = w.Events.Where(e => e.Action == "show_distress" && e.TargetId == who && e.Minute >= from).ToList();
            if (shown.Count == 0) return "no";
            return string.Join("; ", shown.Take(3).Select(e => "m" + e.Minute + ", seen by " + string.Join(", ", e.Witnesses)))
                   + (shown.Count > 3 ? "; and " + (shown.Count - 3) + " more" : "");
        }

        /// <summary>Everything else the actor perceived between their act becoming an event and their next decision.</summary>
        static string Between(Watch w, string who, WorldEvent act, int until)
        {
            var others = w.Events
                .Where(e => e.Id != act.Id && e.Minute >= act.Minute && e.Minute <= until)
                .Where(e => e.Witnesses.Contains(who) || e.Overhearers.Contains(who) || e.ActorId == who || e.TargetId == who)
                .ToList();
            if (others.Count == 0) return "nothing";
            return string.Join("; ", others.Select(e =>
            {
                var x = w.Minds[who].Experiences.LastOrDefault(k => k.EventId == e.Id);
                var how = x == null ? "not perceived" : x.Meaning;
                return "m" + e.Minute + " " + e.Action + (e.ActorId == null ? "" : " by " + e.ActorId) + (e.TargetId == null ? "" : " to " + e.TargetId) + " -> " + how;
            }));
        }

        static string FirstDifference(Watch a, Watch b)
        {
            var x = a.Actions.Select(r => r.ToString()).ToList();
            var y = b.Actions.Select(r => r.ToString()).ToList();
            for (var i = 0; i < Math.Min(x.Count, y.Count); i++)
                if (x[i] != y[i]) return "act " + (i + 1) + ": " + x[i] + "  ->  " + y[i];
            return x.Count == y.Count ? "none" : "the runs differ in length only";
        }

        static int DecisionsDiffering(Watch a, Watch b)
        {
            var x = a.Decisions.Select(d => d.Line).ToList();
            var y = b.Decisions.Select(d => d.Line).ToList();
            var n = 0;
            for (var i = 0; i < Math.Min(x.Count, y.Count); i++) if (x[i] != y[i]) n++;
            return n + Math.Abs(x.Count - y.Count);
        }

