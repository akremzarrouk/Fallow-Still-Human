        [Test, Timeout(1800000)]
        public void I3_EverySearchInFiftyMornings()
        {
            // The same two meanings, carried on every search in fifty mornings,
            // by the want that led the search. This is a stipulation of the
            // experiment, not a rule of the simulation: it exists to count how
            // far the difference reaches, not to propose a mapping.
            string Map(Decision d)
            {
                var lead = d?.Leading?.Name;
                if (lead == "find_out") return TakeResponsibility;
                if (lead == "restore_standing") return AssertAuthority;
                return null;
            }

            int carried = 0, recovered = 0, meaningChanged = 0, salienceChanged = 0, feelingsChanged = 0,
                beliefsChanged = 0, wantsChanged = 0, actsChanged = 0, morningsChanged = 0, witnessChanged = 0;
            var byIntent = new SortedDictionary<string, int>(StringComparer.Ordinal);
            var firstChanges = new List<string>();
            var mornings = 0;

            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var b = Run("baseline", v, seed, null);
                var i = Run("intent", v, seed, run => (who, act, d) => act.Kind == ActionKind.SearchRoom ? Map(d) : null);
                var removed = Run("removed", v, seed, CarriesNothing);
                Assert.AreEqual(b.Fingerprint, removed.Fingerprint, v + " seed " + seed + ": the hook alone changes nothing");
                mornings++;

                foreach (var e in i.Events.Where(e => e.Intent != null))
                {
                    carried++;
                    byIntent.TryGetValue(e.Intent, out var n);
                    byIntent[e.Intent] = n + 1;

                    var mine = i.Minds[e.ActorId].Experiences.LastOrDefault(x => x.EventId == e.Id);
                    var theirs = b.Minds[e.ActorId].Experiences.LastOrDefault(x => x.EventId == e.Id);
                    if (mine != null && mine.FromOwnIntent && mine.Meaning == e.Intent) recovered++;
                    if (mine != null && theirs != null)
                    {
                        if (mine.Meaning != theirs.Meaning) meaningChanged++;
                        if (Math.Abs(mine.Salience - theirs.Salience) > 1e-9) salienceChanged++;
                    }

                    // what everybody else made of the same search
                    foreach (var p in e.Witnesses.Concat(e.Overhearers))
                    {
                        var m1 = i.Minds[p].Experiences.LastOrDefault(x => x.EventId == e.Id);
                        var m0 = b.Minds[p].Experiences.LastOrDefault(x => x.EventId == e.Id);
                        if (m1?.Meaning != m0?.Meaning) witnessChanged++;
                    }

                    // the actor's next decision after that act
                    var after1 = i.Decisions.FirstOrDefault(d => d.Who == e.ActorId && d.Minute >= e.Minute);
                    var after0 = b.Decisions.FirstOrDefault(d => d.Who == e.ActorId && d.Minute >= e.Minute);
                    if (after1 != null && after0 != null)
                    {
                        if (after1.Feelings != after0.Feelings) feelingsChanged++;
                        if (string.Join(",", after1.Wants.Select(x => x.Key + "=" + F(x.Value))) !=
                            string.Join(",", after0.Wants.Select(x => x.Key + "=" + F(x.Value)))) wantsChanged++;
                        if (after1.Chosen != after0.Chosen) actsChanged++;
                    }

                    var beliefs1 = string.Join(",", i.Minds[e.ActorId].Beliefs.All.Select(x => x.Key + "=" + F(x.Confidence)));
                    var beliefs0 = string.Join(",", b.Minds[e.ActorId].Beliefs.All.Select(x => x.Key + "=" + F(x.Confidence)));
                    if (beliefs1 != beliefs0) beliefsChanged++;
                }

                if (b.Fingerprint != i.Fingerprint)
                {
                    morningsChanged++;
                    if (firstChanges.Count < 6) firstChanges.Add(v + " seed " + seed + ": " + FirstDifference(b, i));
                }
            }

            var sb = new StringBuilder();
            sb.AppendLine("## 3. Every search in fifty mornings");
            sb.AppendLine();
            sb.AppendLine("The five design conditions, seeds 1-" + Seeds + ". Every search carries the meaning of the want that led it: `find_out` -> `take_responsibility`, `restore_standing` -> `assert_authority`, nothing otherwise. **This mapping is a stipulation of the experiment**, made to count how far a carried meaning reaches; it is not proposed as a rule.");
            sb.AppendLine();
            sb.AppendLine("| | Count |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| Mornings | " + mornings + " |");
            sb.AppendLine("| Searches carrying an intent | " + carried + " (" + string.Join(", ", byIntent.Select(x => x.Key + " " + x.Value)) + ") |");
