        [Test, Timeout(1800000)]
        public void I2_OneActThreeMeanings()
        {
            var cases = new List<Case>();
            var a = FindSearch("find_out");
            if (a != null) cases.Add(a);
            var b = FindSearch("restore_standing");
            if (b != null) cases.Add(b);

            var sb = new StringBuilder();
            sb.AppendLine("## 2. The same search, three meanings");
            sb.AppendLine();
            sb.AppendLine("For each case: the baseline (no intent), the same act carrying `take_responsibility`, and the same act carrying `assert_authority`. Nothing else differs.");
            sb.AppendLine();

            foreach (var c in cases)
            {
                var arms = new List<Watch> { c.Baseline };
                foreach (var intent in new[] { TakeResponsibility, AssertAuthority })
                    arms.Add(Run(intent, c.Variant, c.Seed, OnTheSearchFinishingAt(c.Who, c.Finished, intent), intent));

                sb.AppendLine("### " + c.Who + ", " + c.Variant + " seed " + c.Seed + ", searching from minute " + c.Minute + " to " + c.Finished + " (led by " + c.Leading + " " + F(c.Urgency) + ")");
                sb.AppendLine();
                sb.AppendLine("| | baseline (no intent) | `take_responsibility` | `assert_authority` |");
                sb.AppendLine("|---|---|---|---|");

                var events = arms.Select(w => w.ActEvent(c.Who, "search_belongings", c.Finished)).ToList();
                for (var i = 1; i < arms.Count; i++)
                    Assert.AreEqual(arms[i].Intent, events[i].Intent, "the act carried the intent meant for it");
                var afters = arms.Select((w, i) => w.After(c.Who, events[i].Minute)).ToList();
                var bases = afters[0];

                sb.AppendLine("| **Event** carried | " + string.Join(" | ", events.Select(e => "intent " + Or(e.Intent))) + " |");
                sb.AppendLine("| **Interpretation** by the actor | " + string.Join(" | ", arms.Select((w, i) => InterpretationOf(w, c.Who, events[i]))) + " |");
                sb.AppendLine("| **Appraisal** for the actor | " + string.Join(" | ", arms.Select((w, i) => StirredBy(w, c.Who, events[i]))) + " |");
                sb.AppendLine("| **Memory** kept | " + string.Join(" | ", arms.Select((w, i) => ReadingOf(w, c.Who, events[i]))) + " |");
                sb.AppendLine("| **Feelings** at the next decision (m" + bases.Minute + ") | " + string.Join(" | ", afters.Select(s => s.Feelings.Length == 0 ? "nothing" : s.Feelings)) + " |");
                sb.AppendLine("| **Wants** there | " + string.Join(" | ", afters.Select(s => string.Join(", ", s.Wants.OrderByDescending(x => x.Value).Select(x => x.Key + " " + F(x.Value))))) + " |");
                sb.AppendLine("| **Options** there | " + string.Join(" | ", afters.Select(s => s.Options)) + " |");
                sb.AppendLine("| **Chose** there | " + string.Join(" | ", afters.Select(s => s.Chosen + " for " + (s.Leading ?? "nothing") + (s.Ambiguous ? ", the seed settled it" : ", clear by " + F(s.Margin)))) + " |");
                sb.AppendLine("| **Did what it stirred become visible?** | " + string.Join(" | ", arms.Select((w, i) => Showed(w, c.Who, events[i].Minute))) + " |");
                sb.AppendLine("| **What else reached the actor in the same minute** | " + string.Join(" | ", arms.Select((w, i) => Between(w, c.Who, events[i], afters[i].Minute))) + " |");
                sb.AppendLine("| **What others made of the search** | " + string.Join(" | ", arms.Select((w, i) => string.Join("; ", events[i].Witnesses.Concat(events[i].Overhearers).Select(p => p + ": " + ReadingOf(w, p, events[i]).Split(',')[0])))) + " |");
                sb.AppendLine("| **The rest of the morning** | - | " + string.Join(" | ", arms.Skip(1).Select(w => FirstDifference(c.Baseline, w) == "none" ? "identical to the baseline" : DecisionsDiffering(c.Baseline, w) + " of " + c.Baseline.Decisions.Count + " decisions differ; first at " + FirstDifference(c.Baseline, w))) + " |");
                sb.AppendLine();

                // What the actor recovered must be what was carried.
                for (var i = 1; i < arms.Count; i++)
                {
                    var x = arms[i].Minds[c.Who].Experiences.Last(k => k.EventId == events[i].Id);
                    Assert.AreEqual(events[i].Intent, x.Meaning, "the actor recovers the carried meaning");
                    Assert.IsTrue(x.FromOwnIntent);
                }
                var baseline = c.Baseline.Minds[c.Who].Experiences.Last(k => k.EventId == events[0].Id);
                Assert.IsFalse(baseline.FromOwnIntent, "the baseline actor reads their own act as a witness would");
            }
            Record("2", sb.ToString());
        }

