        [Test, Timeout(1800000)]
        public void I1_TheCaseAndTheControls()
        {
            var found = FindSearch("find_out");
            Assert.IsNotNull(found, "some search is led by find_out");
            var other = FindSearch("restore_standing");

            var sb = new StringBuilder();
            sb.AppendLine("## 1. The act, and the controls");
            sb.AppendLine();
            sb.AppendLine("The act is a **room search**, chosen because it is the one act the shipped data already carries an intent for: `p02` of the backstory is `search_belongings` with intent `take_responsibility`. Two real searches were found by running the baseline and taking the first search led by each want, in condition and seed order:");
            sb.AppendLine();
            sb.AppendLine("| Case | Who | Condition, seed | Minute | Led by | Urgency |");
            sb.AppendLine("|---|---|---|---|---|---|");
            sb.AppendLine("| A | " + found.Who + " | " + found.Variant + ", seed " + found.Seed + " | " + found.Minute + " | " + found.Leading + " | " + F(found.Urgency) + " |");
            if (other != null)
                sb.AppendLine("| B | " + other.Who + " | " + other.Variant + ", seed " + other.Seed + " | " + other.Minute + " | " + other.Leading + " | " + F(other.Urgency) + " |");
            sb.AppendLine();

            // Control 1: the baseline reproduces itself.
            var again = Run("baseline again", found.Variant, found.Seed, null);
            Assert.AreEqual(found.Baseline.Fingerprint, again.Fingerprint);

            // Control 3: the hook, returning nothing, is the baseline.
            var removed = Run("intent removed", found.Variant, found.Seed, CarriesNothing);
            Assert.AreEqual(found.Baseline.Fingerprint, removed.Fingerprint);

            // Control 3b: an intent on an act, then taken away again.
            var carried = Run("take_responsibility", found.Variant, found.Seed, OnTheSearchFinishingAt(found.Who, found.Finished, TakeResponsibility));
            var takenAway = Run("removed again", found.Variant, found.Seed, OnTheSearchFinishingAt(found.Who, found.Finished, null));
            Assert.AreEqual(found.Baseline.Fingerprint, takenAway.Fingerprint);

            // Control 5: the world, at the actor's next decision, is the same.
            var e0 = found.Baseline.ActEvent(found.Who, "search_belongings", found.Finished);
            var e1 = carried.ActEvent(found.Who, "search_belongings", found.Finished);
            Assert.IsNotNull(e0);
            Assert.IsNotNull(e1);
            Assert.AreEqual(TakeResponsibility, e1.Intent, "the act carried the intent");
            Assert.IsNull(e0.Intent, "and the baseline act carried none");
            var after0 = found.Baseline.After(found.Who, e0.Minute);
            var after1 = carried.After(found.Who, e1.Minute);
            Assert.AreEqual(after0.World, after1.World, "the house is the same after the act");
            Assert.AreEqual(after0.Minute, after1.Minute, "the act took the same time");

            // Control 4: the same decisions, in the same order, up to any divergence.
            var sameOrder = found.Baseline.Decisions.Zip(carried.Decisions, (x, y) => x.Minute == y.Minute && x.Who == y.Who).All(ok => ok);
            Assert.IsTrue(sameOrder, "the same people decide at the same minutes");

            sb.AppendLine("| Control | What was checked | Result |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| 1. Repeat | the baseline run twice, same seed | **identical**, act for act (" + found.Baseline.Actions.Count + " acts) |");
            sb.AppendLine("| 3. Intent removed | the hook set, returning nothing | **identical to the baseline** |");
            sb.AppendLine("| 3b. Intent taken away again | the same hook shape, carrying null on the same act | **identical to the baseline** |");
            sb.AppendLine("| 4. Randomness | every decision in both arms at the same minute by the same person | **held**; the stream is forked from the seed by person and minute, so an arm cannot shift it |");
            sb.AppendLine("| 5. Physical outcome | the house at the actor's next decision: portions, everybody's room and hunger | **identical**: " + after0.World + " |");
            sb.AppendLine("| 5b. The act's own event | every field but the intent | " + (e0.Action == e1.Action && e0.Topic == e1.Topic && e0.Valence == e1.Valence && e0.TargetId == e1.TargetId && e0.Summary == e1.Summary && e0.Minute == e1.Minute ? "**identical**" : "DIFFERENT") + ": `" + e0.Action + "`, topic `" + Or(e0.Topic) + "`, valence `" + e0.Valence + "`, target `" + Or(e0.TargetId) + "`, minute " + e0.Minute + " |");
            sb.AppendLine("| 5c. The intent itself | the event's `intent` | baseline `" + Or(e0.Intent) + "`, carrying arm `" + Or(e1.Intent) + "` |");
            Record("1", sb.ToString());
        }

