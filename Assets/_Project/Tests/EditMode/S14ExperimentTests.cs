                              (answered ? "yes, having seen them come right later" : "no") + " |");
            }

            Record("D. No interaction", sb.ToString());
            Assert.IsEmpty(fabricated, string.Join("\n", fabricated));
            Assert.Greater(cases, 0);
        }

