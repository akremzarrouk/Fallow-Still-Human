        // ---- what happened at the end of each sitting ----

        internal enum Ending { CameRight, StillNotAllRight, NothingShowing, TheyHadGone }

        internal sealed class Sitting
        {
            public string Variant;
            public ulong Seed;
            public int Minute;
            public string Who;
            public string Whom;
            public Ending Ending;
            public WorldEvent Comfort;
            public WorldEvent Steady;
            public DecisionMoment Chose;
            public DecisionMoment Next;
            public Scenario001Run Run;
            public int SittingsWithThemWithin20;
        }

        internal static List<Sitting> Sittings(Scenario001Content content, IEnumerable<string> variants, int seeds, ulong firstSeed = 1)
        {
            var all = new List<Sitting>();
            foreach (var v in variants)
            for (var seed = firstSeed; seed < firstSeed + (ulong)seeds; seed++)
            {
                var run = Scenario001.Prepare(content, v, seed);
                var chosen = new Dictionary<string, DecisionMoment>(StringComparer.Ordinal);
                var open = new List<Sitting>();
                var finishing = new Dictionary<string, string>(StringComparer.Ordinal);
                var showingBefore = new Dictionary<string, bool>(StringComparer.Ordinal);
                var seenTrace = run.Trace.Count;
                var gathered = false;

                void Gather()
                {
                    if (gathered) return;
                    gathered = true;
                    var fresh = run.Trace.All.Skip(seenTrace).ToList();
                    foreach (var pair in finishing)
                    {
                        var who = pair.Key;
                        var whom = pair.Value;
                        var comfort = run.Result.Events.LastOrDefault(e => e.Action == "comfort" && e.ActorId == who && e.TargetId == whom && e.Minute == run.World.Minute);
                        var gone = fresh.Any(r => r.Kind == TraceKind.Consequence && r.CharacterId == who && r.Summary.StartsWith("could not sit with " + whom, StringComparison.Ordinal));
                        if (comfort == null && !gone) continue;

                        var steady = run.Result.Events.LastOrDefault(e => e.Action == "steady" && e.TargetId == whom && e.Minute == run.World.Minute);
                        var s = new Sitting
                        {
                            Variant = v, Seed = seed, Minute = run.World.Minute, Who = who, Whom = whom, Comfort = comfort, Steady = steady, Run = run,
                            Chose = chosen.TryGetValue(who, out var c) ? c : null,
                            Ending = gone ? Ending.TheyHadGone
                                : !showingBefore[whom] ? Ending.NothingShowing
                                : steady != null && steady.Witnesses.Contains(who) ? Ending.CameRight
                                : Ending.StillNotAllRight
                        };
                        foreach (var earlier in all.Where(x => x.Run == run && x.Who == who && x.Whom == whom && s.Minute - x.Minute <= 20 && s.Minute > x.Minute))
                            earlier.SittingsWithThemWithin20++;
                        all.Add(s);
                        open.Add(s);
                    }
                }

                run.Morning.Decided = m =>
                {
                    Gather();
                    foreach (var s in open.Where(x => x.Who == m.CharacterId && x.Next == null))
                        if (m.Motives.Any(x => x.Key == "look_after:" + s.Whom)) s.Next = m;
                    if (m.Decision.Chosen.Kind == ActionKind.Comfort) chosen[m.CharacterId] = m;
                };

                for (var i = 0; i < content.Morning.Minutes; i++)
                {
                    finishing.Clear();
                    foreach (var p in People)
                    {
                        var d = run.Morning.Doing(p);
                        if (d.HasValue && d.Value.Action.Kind == ActionKind.Comfort && d.Value.MinutesLeft == 1) finishing[p] = d.Value.Action.TargetId;
                        showingBefore[p] = S14DiagnosisTests.Showing(run.Minds[p], content);
                    }
                    seenTrace = run.Trace.Count;
                    gathered = false;
                    run.Morning.Step();
                    Gather();
                }
            }
            return all;
        }

        static Motive Want(DecisionMoment m, string whom) => m?.Motives.FirstOrDefault(x => x.Key == "look_after:" + whom);

        static IEnumerable<ScalerTerm> MemoryTerms(Motive w) => w.Terms.Where(t => t.Description.StartsWith("memory", StringComparison.Ordinal));

        static double MemoryPart(Motive w) => MemoryTerms(w).Sum(t => t.Amount);

