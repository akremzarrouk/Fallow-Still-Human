        [Test]
        public void F_OnlyThoseInTheRoomSeeSomebodyComeRightAndOnlyTheyHaveTheirConcernAnswered()
        {
            var steadies = 0;
            var holders = 0;
            var problems = new List<string>();
            var answeredTerms = 0;

            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var run = Scenario001.Prepare(_content, v.Id, seed);
                run.Morning.Decided = m =>
                {
                    foreach (var w in m.Motives.Where(x => x.Name == "look_after"))
                    foreach (var t in w.Terms.Where(t => t.Answered))
                    {
                        answeredTerms++;
                        var answer = run.Trace.Get(t.Drew.Single());
                        var experience = m.Mind.Experiences.FirstOrDefault(x => x.TraceId == answer.Id);
                        if (experience == null || experience.Meaning != "reassurance" || experience.TargetId != w.TargetId)
                            problems.Add(m.CharacterId + ": a concern about " + w.TargetId + " was answered by something that is not their own sight of them coming right");
                    }
                };
                run.Morning.Run(_content.Morning.Minutes);

                foreach (var e in run.Result.Events.Where(e => e.Action == "steady"))
                {
                    steadies++;
                    if (e.Overhearers.Count > 0) problems.Add(e.Id + " was heard through a wall");
                    foreach (var p in People)
                    {
                        var holds = run.Minds[p].Experiences.Any(x => x.EventId == e.Id);
                        if (holds) holders++;
                        if (holds && !e.Witnesses.Contains(p)) problems.Add(p + " holds " + e.Id + " without being in the room");
                        if (!holds && e.Witnesses.Contains(p)) problems.Add(p + " was in the room for " + e.Id + " and kept nothing");
                        if (p == e.TargetId && holds) problems.Add(p + " saw their own face come right");
                    }
                }
            }

            Record("F. Knowledge locality", steadies + " moments of somebody coming right in front of others, " + holders + " memories of them, every one held by somebody in the room and nobody else; " +
                   answeredTerms + " answered concerns, every one resting on the holder's own sight of that person coming right.");
            Assert.IsEmpty(problems, string.Join("\n", problems.Take(20)));
            Assert.Greater(steadies, 0);
        }

