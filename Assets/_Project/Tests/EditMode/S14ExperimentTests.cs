        [Test]
        public void D_WithoutTheSittingThereIsNoAnswerUnlessTheyAreSeenToComeRightAnyway()
        {
            // The same moment twice. In one, the helper sits with them as chosen. In
            // the other, the helper is taken out of the room before the sitting can
            // finish, so they do not interact and do not see how it ends.
            var sb = new StringBuilder();
            sb.AppendLine("| Condition, seed | Helper, person | Sat, and saw them come right | Did not interact: concern at the helper's next decision with them | ... answered |");
            sb.AppendLine("|---|---|---|---|---|");
            var cases = 0;
            var fabricated = new List<string>();

            foreach (var s in Sittings(_content, _content.Morning.Variants.Select(x => x.Id), Seeds).Where(x => x.Ending == Ending.CameRight).Take(12))
            {
                var run = Scenario001.Prepare(_content, s.Variant, s.Seed);
                while (run.World.Minute < s.Minute - 1) run.Morning.Step();
                var elsewhere = run.World.RoomOf(s.Who) == "hallway" ? "bathroom" : "hallway";
                run.World.Place(s.Who, elsewhere);

                DecisionMoment next = null;
                run.Morning.Decided = m => { if (m.CharacterId == s.Who && next == null && m.Motives.Any(x => x.Key == "look_after:" + s.Whom)) next = m; };
                for (var i = 0; i < 40 && next == null; i++) run.Morning.Step();
                if (next == null) continue;

                cases++;
                var want = Want(next, s.Whom);
                var answered = MemoryTerms(want).Any(t => t.Answered);
                var saw = run.Minds[s.Who].Experiences.Any(x => x.Meaning == "reassurance" && x.TargetId == s.Whom && x.Minute <= next.Minute);
                if (answered && !saw) fabricated.Add(s.Variant + "/" + s.Seed + ": answered without being seen");
