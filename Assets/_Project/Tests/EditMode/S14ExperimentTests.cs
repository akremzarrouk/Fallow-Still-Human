        [Test]
        public void Natural_HowSittingsEndedAndWhatThatDidToTheConcern()
        {
            var sittings = Sittings(_content, _content.Morning.Variants.Select(x => x.Id), Seeds);
            var problems = new List<string>();
            var sb = new StringBuilder();
            sb.AppendLine(sittings.Count + " sittings finished.");
            sb.AppendLine();
            sb.AppendLine("| How it ended | Sittings | ... helper decided again with them there | Memory terms answered at that decision | Mean change in wanting to look after them (memory part) | Mean further sittings with them within 20 minutes |");
            sb.AppendLine("|---|---|---|---|---|---|");

            foreach (var ending in new[] { Ending.CameRight, Ending.StillNotAllRight, Ending.TheyHadGone, Ending.NothingShowing })
            {
                var group = sittings.Where(s => s.Ending == ending).ToList();
                var decided = group.Where(s => s.Chose != null && s.Next != null && Want(s.Chose, s.Whom) != null).ToList();
                var answered = 0;
                var changes = new List<double>();
                foreach (var s in decided)
                {
                    var before = Want(s.Chose, s.Whom);
                    var after = Want(s.Next, s.Whom);
                    changes.Add(MemoryPart(after) - MemoryPart(before));
                    var wasAnswered = MemoryTerms(after).Any(t => t.Answered);
                    if (wasAnswered) answered++;

                    // No sight of them coming right means no answer, however it ended.
                    var sawThemComeRight = s.Run.Minds[s.Who].Experiences.Any(x => x.Meaning == "reassurance" && x.TargetId == s.Whom && x.Minute <= s.Next.Minute);
                    if (wasAnswered && !sawThemComeRight) problems.Add(s.Who + " had concern about " + s.Whom + " answered without ever seeing them come right");
                    if (ending == Ending.TheyHadGone && s.Comfort != null) problems.Add("a sitting with somebody who had gone still made a comfort event");
                }
                if (ending == Ending.CameRight)
                    foreach (var s in decided)
                    {
                        var after = Want(s.Next, s.Whom);
                        var freshDistressSince = s.Run.Result.Events.Any(e => e.Action == "show_distress" && e.TargetId == s.Whom && e.Minute >= s.Minute && e.Minute <= s.Next.Minute && e.Witnesses.Contains(s.Who));
                        if (!freshDistressSince && MemoryPart(after) != 0.0) problems.Add(s.Variant + "/" + s.Seed + " " + s.Who + ": saw " + s.Whom + " come right and the concern still presses");
                    }

                sb.AppendLine("| " + ending + " | " + group.Count + " | " + decided.Count + " | " + answered + " | " + (changes.Count == 0 ? "n/a" : F(changes.Average())) + " | " +
                              (group.Count == 0 ? "n/a" : group.Average(s => s.SittingsWithThemWithin20).ToString("0.00")) + " |");
            }

            var example = sittings.FirstOrDefault(s => s.Ending == Ending.CameRight && s.Chose != null && s.Next != null && Want(s.Next, s.Whom) != null && MemoryTerms(Want(s.Next, s.Whom)).Any(t => t.Answered));
            if (example != null)
            {
                sb.AppendLine();
                sb.AppendLine("### Came right: " + example.Variant + ", seed " + example.Seed + ", " + example.Who + " with " + example.Whom + ", minute " + example.Minute);
                sb.AppendLine();
                sb.AppendLine("- When choosing to sit, minute " + example.Chose.Minute + ": `look_after:" + example.Whom + "` " + F(Want(example.Chose, example.Whom).Urgency) + " because " + Want(example.Chose, example.Whom).Because);
                sb.AppendLine("- Next decision, minute " + example.Next.Minute + ": `look_after:" + example.Whom + "` " + F(Want(example.Next, example.Whom).Urgency) + " because " + Want(example.Next, example.Whom).Because);
                sb.AppendLine("- Memory terms at the next decision: " + string.Join("; ", MemoryTerms(Want(example.Next, example.Whom)).Select(t => t.ToString())));
            }

            var still = sittings.FirstOrDefault(s => s.Ending == Ending.StillNotAllRight && s.Chose != null && s.Next != null && Want(s.Next, s.Whom) != null);
            if (still != null)
            {
                sb.AppendLine();
                sb.AppendLine("### Still not all right: " + still.Variant + ", seed " + still.Seed + ", " + still.Who + " with " + still.Whom + ", minute " + still.Minute);
                sb.AppendLine();
                sb.AppendLine("- Next decision, minute " + still.Next.Minute + ": `look_after:" + still.Whom + "` " + F(Want(still.Next, still.Whom).Urgency) + " because " + Want(still.Next, still.Whom).Because);
            }

            sb.AppendLine();
            sb.AppendLine("\"Memory terms answered\" counts any sight of the person coming right up to that decision, not only at the end of this sitting.");
            sb.AppendLine("No sitting in these mornings ended with the other person still visibly not all right. Being sat with is perceived by them as support and felt as gratitude, which in every case became a stronger feeling than whatever distress was showing. So partial help does not occur on its own here, and is built by intervention in the next test.");
            Record("A B C D (natural). How sittings ended, and what that did to the concern", sb.ToString());
            Assert.IsEmpty(problems, string.Join("\n", problems));
            Assert.IsTrue(sittings.Any(s => s.Ending == Ending.CameRight), "nobody ever saw somebody they sat with come right");
        }

        [Test]
        public void ABCD_TheSameMomentEndedFourWays()
        {
            // Real moments: somebody in the last minute of sitting with a person
            // whose distress is showing, having seen that person go to pieces. From
            // the identical state, four endings, three of them interventions:
            //   A as it happens
            //   B the person also carries shame, which being sat with does not settle
            //   C the person has left the room
            //   D the helper has left the room, so there is no interaction
            var moments = new List<(string v, ulong seed, int steps, string who, string whom)>();
            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= (ulong)Seeds && moments.Count < 12; seed++)
            {
                var run = Scenario001.Prepare(_content, v.Id, seed);
                for (var i = 1; i <= 90 && moments.Count(m => m.v == v.Id && m.seed == seed) == 0; i++)
                {
                    run.Morning.Step();
                    foreach (var p in People)
                    {
                        var d = run.Morning.Doing(p);
                        if (!d.HasValue || d.Value.Action.Kind != ActionKind.Comfort || d.Value.MinutesLeft != 1) continue;
                        var whom = d.Value.Action.TargetId;
                        if (!S14DiagnosisTests.Showing(run.Minds[whom], _content)) continue;
                        if (!run.Minds[p].Experiences.Any(x => x.Meaning == "concern" && x.TargetId == whom)) continue;
                        moments.Add((v.Id, seed, i, p, whom));
                        break;
                    }
                }
            }
            Assert.IsNotEmpty(moments, "never found somebody finishing sitting with a person whose distress was showing");

            var table = new Dictionary<string, List<(double memory, bool answered, bool rests, int minutes, bool satAgain20, bool steadyAtEnd)>>
            {
                { "A as it happens", new List<(double, bool, bool, int, bool, bool)>() },
                { "B shame being sat with does not settle", new List<(double, bool, bool, int, bool, bool)>() },
                { "C they had left", new List<(double, bool, bool, int, bool, bool)>() },
                { "D the helper had left", new List<(double, bool, bool, int, bool, bool)>() }
            };
            var problems = new List<string>();

            foreach (var (v, seed, steps, who, whom) in moments)
            foreach (var ending in table.Keys.ToList())
            {
                var run = Scenario001.Prepare(_content, v, seed);
                for (var i = 0; i < steps; i++) run.Morning.Step();
                var end = run.World.Minute + 1;
                var elsewhere = run.World.RoomOf(who) == "hallway" ? "bathroom" : "hallway";
                if (ending.StartsWith("B")) run.Minds[whom].Emotions.Add("shame", null, "respect", 0.95, 0, "experiment");
                if (ending.StartsWith("C")) run.World.Place(whom, elsewhere);
                if (ending.StartsWith("D")) run.World.Place(who, elsewhere);

                DecisionMoment next = null;
                var satAgain = false;
                run.Morning.Decided = m =>
                {
                    if (m.CharacterId != who) return;
                    if (next == null && m.Minute >= end && m.Motives.Any(x => x.Key == "look_after:" + whom)) next = m;
                    if (m.Minute > end && m.Minute <= end + 20 && m.Decision.Chosen.Kind == ActionKind.Comfort && m.Decision.Chosen.TargetId == whom) satAgain = true;
                };
                run.Morning.Step();
                var steadyAtEnd = run.Result.Events.Any(e => e.Action == "steady" && e.TargetId == whom && e.Minute == end && e.Witnesses.Contains(who));
                var satThrough = run.Result.Events.Any(e => e.Action == "comfort" && e.ActorId == who && e.TargetId == whom && e.Minute == end);
                if ((ending.StartsWith("A") || ending.StartsWith("B")) && !satThrough) continue;
                for (var i = 0; i < 40 && (next == null || run.World.Minute < end + 20); i++) run.Morning.Step();
                if (next == null) continue;

                if (ending.StartsWith("B") && steadyAtEnd) { problems.Add(v + "/" + seed + ": the shame did not keep " + whom + " showing, so B was not built"); continue; }

                var want = Want(next, whom);
                var memory = MemoryPart(want);
                var answered = MemoryTerms(want).Any(t => t.Answered);
                var sawComeRight = run.Minds[who].Experiences.Where(x => x.Meaning == "reassurance" && x.TargetId == whom && x.Minute <= next.Minute).ToList();
                var rests = sawComeRight.Any(x => run.Trace.Get(want.TraceId).ParentIds.Contains(x.TraceId));
                table[ending].Add((memory, answered, rests, next.Minute - end, satAgain, steadyAtEnd));

                if (answered && sawComeRight.Count == 0) problems.Add(ending + " " + v + "/" + seed + ": answered without seeing them come right");
                if (!ending.StartsWith("A") && steadyAtEnd) problems.Add(ending + " " + v + "/" + seed + ": " + who + " saw " + whom + " come right at the end");
            }

            var sb = new StringBuilder();
            sb.AppendLine(moments.Count + " moments, each ended four ways from the same state.");
            sb.AppendLine();
            sb.AppendLine("| Ending | Cases | Helper saw them come right at the end | Concern answered at the helper's next decision with them | Want rests on that sight | Mean memory part of the want then | Mean minutes to that decision | Sat with them again within 20 minutes |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (var k in table)
            {
                var r = k.Value;
                if (r.Count == 0) { sb.AppendLine("| " + k.Key + " | 0 | | | | | | |"); continue; }
                sb.AppendLine("| " + k.Key + " | " + r.Count + " | " + r.Count(x => x.steadyAtEnd) + " | " + r.Count(x => x.answered) + " | " + r.Count(x => x.rests) + " | " +
                              F(r.Average(x => x.memory)) + " | " + r.Average(x => x.minutes).ToString("0.0") + " | " + r.Count(x => x.satAgain20) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("B, C and D are interventions. B adds shame 0.95 to the person being sat with in the last minute; C and D move one of the two into another room in the last minute.");
            Record("A B C D (controlled). The same moment ended four ways", sb.ToString());

            Assert.IsEmpty(problems, string.Join("\n", problems));
            var a = table["A as it happens"];
            Assert.IsNotEmpty(a);
            Assert.AreEqual(a.Count, a.Count(x => x.steadyAtEnd), "as it happens, the helper did not always see them come right");
            foreach (var k in table.Keys.Where(k => !k.StartsWith("A")))
                Assert.Greater(table[k].Count(x => !x.answered), 0, k + " never left the concern unanswered");
        }

        [Test]
        public void A_TheWholeChainIsInTheTraceLinkByLink()
        {
            // circumstance -> perception -> reading -> want -> decision -> sitting
            // -> what it did to them -> what the helper saw -> memory -> answered
            // want. Each arrow is a parent link between real records.
            var sittings = Sittings(_content, _content.Morning.Variants.Select(x => x.Id), Seeds)
                .Where(s => s.Ending == Ending.CameRight && s.Chose != null && s.Next != null && Want(s.Next, s.Whom) != null && MemoryTerms(Want(s.Next, s.Whom)).Any(t => t.Answered))
                .ToList();
            Assert.IsNotEmpty(sittings, "no sitting ended with the helper seeing them come right and still caring enough to want to look after them");

            string shown = null;
            foreach (var s in sittings)
            {
                var t = s.Run.Trace;
                var before = Want(s.Chose, s.Whom);
                var concernTerm = MemoryTerms(before).First(x => x.Amount > 0 || x.Answered);
                var concernMemory = t.Get(concernTerm.Drew.First());
                var distressEvent = t.Chain(concernMemory.Id).FirstOrDefault(r => r.Kind == TraceKind.Event);
                var wantBefore = t.Get(before.TraceId);
                var decision = t.Get(s.Chose.Decision.TraceId);
                var sitting = t.ForEvent(s.Comfort.Id).First(r => r.Kind == TraceKind.Event);
                var settled = t.All.First(r => r.Kind == TraceKind.Consequence && r.CharacterId == s.Whom && r.ParentIds.Contains(decision.Id));
                var steady = t.ForEvent(s.Steady.Id).First(r => r.Kind == TraceKind.Event);
                var seen = t.Get(s.Run.Minds[s.Who].Experiences.First(x => x.EventId == s.Steady.Id).TraceId);
                var after = Want(s.Next, s.Whom);
                var wantAfter = t.Get(after.TraceId);

                void Link(TraceRecord child, TraceRecord parent, string what)
                    => Assert.IsTrue(child.ParentIds.Contains(parent.Id), s.Variant + "/" + s.Seed + " " + s.Who + ": " + what + " is not linked");

                Assert.IsNotNull(distressEvent, "the concern does not rest on anything that happened");
                Assert.IsTrue(wantBefore.ParentIds.Contains(concernMemory.Id), "the want does not rest on the concern");
                Link(decision, wantBefore, "the decision to the want");
                Link(settled, decision, "what the sitting did to them, to the decision");
                Link(steady, settled, "what could be seen, to what the sitting did");
                var theirReading = t.Get(s.Run.Minds[s.Whom].Experiences.First(x => x.EventId == s.Comfort.Id).TraceId);
                Link(steady, theirReading, "what could be seen, to what the person made of being sat with");
                Assert.IsTrue(t.Chain(seen.Id).Contains(steady), "what the helper made of it does not rest on what could be seen");
                Link(wantAfter, seen, "the want afterwards, to what the helper saw");
                Assert.AreEqual(s.Comfort.Minute, s.Steady.Minute);
                Assert.IsNotNull(sitting);

                if (shown == null)
                {
                    string Line(string stage, TraceRecord r) => "| " + stage + " | #" + r.Id + " " + r.Kind + (r.CharacterId == null ? "" : " [" + r.CharacterId + "]") + " | " + r.Summary.Replace("|", "/") + " |";
                    shown = "### " + s.Variant + ", seed " + s.Seed + ", " + s.Who + " and " + s.Whom + Environment.NewLine + Environment.NewLine +
                            "| Stage | Record | What it says |" + Environment.NewLine + "|---|---|---|" + Environment.NewLine +
                            Line("social circumstance", distressEvent) + Environment.NewLine +
                            Line("perception, reading, memory", concernMemory) + Environment.NewLine +
                            Line("want", wantBefore) + Environment.NewLine +
                            Line("decision", decision) + Environment.NewLine +
                            Line("action", sitting) + Environment.NewLine +
                            Line("social consequence (their reading)", theirReading) + Environment.NewLine +
                            Line("social consequence (the settling)", settled) + Environment.NewLine +
                            Line("what could be seen", steady) + Environment.NewLine +
                            Line("experience, memory", seen) + Environment.NewLine +
                            Line("changed want", wantAfter) + Environment.NewLine + Environment.NewLine +
                            "The want afterwards, printed by the trace tool down to what the helper saw:" + Environment.NewLine + Environment.NewLine +
                            "```" + Environment.NewLine + string.Join(Environment.NewLine, Shorten(t.Why(wantAfter.Id)).Split('\n').Select(l => l.TrimEnd('\r')).Take(12)) + Environment.NewLine + "```" + Environment.NewLine;
                }
            }

            Record("A. The chain, link by link", sittings.Count + " sittings checked, every link present." + Environment.NewLine + Environment.NewLine + shown);
        }

