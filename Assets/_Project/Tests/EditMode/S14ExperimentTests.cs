        [Test]
        public void E_RemovingTheConsequenceOrWhatReadsItChangesNothingUntilItCouldMatter()
        {
            var sb = new StringBuilder();
            sb.AppendLine("| Counterfactual | Condition, seed | First sitting that did something / first answered concern | First difference in anybody's wants | In whom | Why it is them |");
            sb.AppendLine("|---|---|---|---|---|---|");
            var problems = new List<string>();

            foreach (var (label, other) in new (string, Scenario001Content)[]
                     {
                         ("sitting soothes nothing", With(_content, SittingSoothesNothing)),
                         ("nothing reads seeing them come right", With(_content, NothingIsAnswered))
                     })
            foreach (var v in new[] { "mara_ate_it", "elena_fed_mara", "daniel_ate_it" })
            for (ulong seed = 1; seed <= 4; seed++)
            {
                var a = Scenario001.Prepare(_content, v, seed);
                var b = Scenario001.Prepare(other, v, seed);
                int? firstMatters = null;
                int? firstDiff = null;
                string whoDiff = null, why = null;

                for (var i = 0; i < 90 && firstDiff == null; i++)
                {
                    var seenA = a.Result.Events.Count;
                    a.Morning.Step();
                    b.Morning.Step();

                    // When the consequence could first matter in the shipped morning.
                    if (firstMatters == null)
                    {
                        if (label.StartsWith("sitting") && a.Result.Events.Skip(seenA).Any(e => e.Action == "comfort")) firstMatters = a.World.Minute;
                        if (label.StartsWith("nothing") && People.Any(p => new Motivator(_content.Rules).Raise(a.Minds[p], a.Morning.See(p), _content.Morning.Day, new TraceLog(), 0)
                                .Any(w => w.Name == "look_after" && w.Terms.Any(t => t.Answered)))) firstMatters = a.World.Minute;
                    }

                    foreach (var p in People)
                    {
                        var wa = new Motivator(_content.Rules).Raise(a.Minds[p], a.Morning.See(p), _content.Morning.Day, new TraceLog(), 0);
                        var wb = new Motivator(other.Rules).Raise(b.Minds[p], b.Morning.See(p), _content.Morning.Day, new TraceLog(), 0);
                        var differ = wa.Count != wb.Count || wa.Zip(wb, (x, y) => x.Key != y.Key || Math.Abs(x.Urgency - y.Urgency) > 1e-12).Any(d => d);
                        if (!differ) continue;
                        firstDiff = a.World.Minute;
                        whoDiff = p;
                        var satWith = a.Result.Events.Any(e => e.Action == "comfort" && e.TargetId == p);
                        var sawSteady = a.Minds[p].Experiences.Any(x => x.Meaning == "reassurance");
                        why = satWith ? "was sat with" : sawSteady ? "saw somebody come right" : "neither";
                        if (firstMatters == null || firstDiff < firstMatters) problems.Add(label + " " + v + "/" + seed + ": wants differed at minute " + firstDiff + " before the consequence could matter");
                        if (why == "neither") problems.Add(label + " " + v + "/" + seed + ": " + p + " differed without being sat with or seeing anybody come right");
                        break;
                    }
                }

                sb.AppendLine("| " + label + " | " + v + ", " + seed + " | " + (firstMatters?.ToString() ?? "never") + " | " + (firstDiff?.ToString() ?? "never") + " | " + (whoDiff ?? "") + " | " + (why ?? "") + " |");
            }

            Record("E. Causality", sb.ToString());
            Assert.IsEmpty(problems, string.Join("\n", problems));
        }

