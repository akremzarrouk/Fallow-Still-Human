        [Test]
        public void C_WhenTheyLeaveBeforeItFinishesTheyAreNotSoothedAndNothingIsTreatedAsHelp()
        {
            // An intervention: the person being sat with is moved out of the room in
            // the last minute. The control is the same moment without the move.
            string found = null;
            foreach (var v in _content.Morning.Variants)
            for (ulong seed = 1; seed <= (ulong)Seeds && found == null; seed++)
            {
                var probe = Scenario001.Prepare(_content, v.Id, seed);
                var steps = 0;
                string who = null, whom = null;
                for (; steps < 90 && who == null; steps++)
                {
                    probe.Morning.Step();
                    foreach (var p in People)
                    {
                        var d = probe.Morning.Doing(p);
                        if (d.HasValue && d.Value.Action.Kind == ActionKind.Comfort && d.Value.MinutesLeft == 1 &&
                            probe.Minds[d.Value.Action.TargetId].Emotions.IntensityAny("fear") > 0.1) { who = p; whom = d.Value.Action.TargetId; break; }
                    }
                }
                if (who == null) continue;

                (Scenario001Run run, double fearBefore, double fearAfter, bool comforted, bool couldNot) Finish(bool move)
                {
                    var run = Scenario001.Prepare(_content, v.Id, seed);
                    for (var i = 0; i < steps; i++) run.Morning.Step();
                    if (move) run.World.Place(whom, run.World.RoomOf(who) == "hallway" ? "bathroom" : "hallway");
                    var fear = run.Minds[whom].Emotions.IntensityAny("fear");
                    var seen = run.Trace.Count;
                    var events = run.Result.Events.Count;
                    run.Morning.Step();
                    return (run, fear, run.Minds[whom].Emotions.IntensityAny("fear"),
                        run.Result.Events.Skip(events).Any(e => e.Action == "comfort" && e.ActorId == who),
                        run.Trace.All.Skip(seen).Any(r => r.Kind == TraceKind.Consequence && r.CharacterId == who && r.Summary.StartsWith("could not sit with", StringComparison.Ordinal)));
                }

                var gone = Finish(true);
                var stayed = Finish(false);
                if (!stayed.comforted) continue;

                Assert.IsTrue(gone.couldNot, "the world did not notice they had gone");
                Assert.IsFalse(gone.comforted, "sitting with somebody who had gone still happened");
                Assert.Greater(gone.fearAfter, stayed.fearAfter, "they were soothed from another room");
                Assert.IsFalse(gone.run.Minds[who].Outcomes.Any(o => o.Kind == OutcomeKind.Satisfied || o.Kind == OutcomeKind.PartlySatisfied), "it was treated as help");
                Assert.IsFalse(gone.run.Minds[who].Experiences.Any(x => x.Meaning == "reassurance" && x.TargetId == whom && x.Minute == gone.run.World.Minute));

                found = v.Id + ", seed " + seed + ": " + who + " sitting with " + whom + ". Moved out in the last minute: no sitting happened, `" + whom + "` fear " + F(gone.fearBefore) + " -> " + F(gone.fearAfter) +
                        ". Left where they were: sat with, fear " + F(stayed.fearBefore) + " -> " + F(stayed.fearAfter) + ".";
            }

