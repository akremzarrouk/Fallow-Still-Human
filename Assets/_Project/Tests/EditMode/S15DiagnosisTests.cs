            sb.AppendLine();
            sb.AppendLine("Each term of a want is sorted by what it read. **Circumstance:** the body, a memory of today, a live feeling. **History:** a belief with evidence behind it, a ledger entry. **Authored:** a belief written into the person with no evidence. **Disposition:** a trait, a value. A want is **FromCircumstance** when circumstance and history carry at least half of it, **MostlyDisposition** when they carry something but less than half, and **Unsupported** when nothing that happened is behind it at all.");
