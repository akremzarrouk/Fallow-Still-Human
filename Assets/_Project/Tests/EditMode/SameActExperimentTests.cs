    /// <summary>
    /// The same-act experiment: several wants reach for the same physical act.
    /// When one of them does, can the simulation keep hold of *which* one, and
    /// does anything read it?
    ///
    /// Three questions, kept apart: whether the distinction can be represented,
    /// whether it survives act -> event -> perception -> appraisal, and whether
    /// it ever reaches behaviour. A failure at the third is not a failure at the
    /// first.
    ///
    /// The act is `check_pantry`, which four wants propose. It is held fixed:
    /// the arms run identically up to the minute the act finishes, and the only
    /// difference between them is the intention carried onto the event it
    /// becomes, through the `IntentOfAct` hook the intent-carrying experiment
    /// added. The hook stays unset everywhere else, and nothing about wants,
    /// rules, numbers, appraisal, interpretation or the action model was
    /// changed for this. There is no new code in `Fallow.Core` at all.
    ///
    /// Writes `Docs/experiments/same-act-different-reason/measurements.md`.
    /// </summary>
    public class SameActExperimentTests
    {
        const int Seeds = 10;

        /// <summary>The wants that propose `check_pantry`, in the order the file lists them.</summary>
        static readonly string[] ReachForIt = { "get_food", "guard_supplies", "find_out", "restore_standing" };

        static Scenario001Content _content;
        static IReadOnlyList<string> _intentions;

        /// <summary>Baseline mornings, kept so that four tests do not each run fifty of them.</summary>
        static readonly Dictionary<string, Watch> _cache = new Dictionary<string, Watch>(StringComparer.Ordinal);
        static readonly SortedDictionary<string, string> _results = new SortedDictionary<string, string>(StringComparer.Ordinal);

        [OneTimeSetUp]
        public void Load()
        {
            _content = Baselines.Primary();
            _intentions = _content.Vocabulary.SelfMeanings.OrderBy(s => s, StringComparer.Ordinal).ToList();
        }

        [OneTimeTearDown]
        public void Write()
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Same act, different reason: measurements");
            sb.AppendLine();
            sb.AppendLine("Generated by `SameActExperimentTests` on the primary baseline. One physical act is held fixed and only the intention carried onto the event it becomes is varied, through the `IntentOfAct` hook, which is unset in every baseline arm. The random stream is forked per person and minute from the seed, so it cannot shift between arms.");
            sb.AppendLine();
            foreach (var r in _results.Values) sb.AppendLine(r);
            var dir = Path.Combine(TestPaths.ProjectRoot, "Docs", "experiments", "same-act-different-reason");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "measurements.md"), sb.ToString());
        }

        static void Record(string key, string text)
        {
            _results[key] = text;
            TestContext.WriteLine(text);
        }

        static string F(double v) => v.ToString("0.000", CultureInfo.InvariantCulture);
        static string Or(string s) => string.IsNullOrEmpty(s) ? "none" : s;

        static string Pc(double part, double whole)
            => whole == 0 ? "n/a" : (100.0 * part / whole).ToString("0.0", CultureInfo.InvariantCulture) + " %";

        // ------------------------------------------------------------------ watching a run

        sealed class Snap
        {
            public int Minute;
            public string Who;
            public string Chosen;
            public string Leading;
            public double Urgency;
            public double Margin;
            public string Commitment;
            public Resolution Resolution;
            public string Options;
            public Dictionary<string, double> Wants = new Dictionary<string, double>(StringComparer.Ordinal);

            public string Line => "m" + Minute + " " + Who + " " + Chosen + " for " + Or(Leading);
        }

        sealed class Watch
        {
            public string Label;
            public string Intent;
            public List<Snap> Decisions = new List<Snap>();
            public IReadOnlyList<ActionRecord> Actions;
            public IReadOnlyList<WorldEvent> Events;
            public IReadOnlyDictionary<string, Mind> Minds;
            public TraceLog Trace;
            public string Fingerprint;

            public Snap NextAfter(string who, int minute)
                => Decisions.FirstOrDefault(d => d.Who == who && d.Minute >= minute);

            public WorldEvent ActEvent(string who, string action, int minute)
                => Events.FirstOrDefault(e => e.ActorId == who && e.Action == action && e.Minute == minute);
        }

        static Watch Run(string label, string variant, ulong seed,
            Func<Scenario001Run, Func<string, ActionOption, Decision, string>> intends, string intentLabel = null)
        {
            var run = Scenario001.Prepare(_content, variant, seed);
            if (intends != null) run.Morning.IntentOfAct = intends(run);
            var w = new Watch { Label = label, Intent = intentLabel };
            run.Morning.Decided = m =>
            {
                var d = m.Decision;
                var s = new Snap
                {
                    Minute = m.Minute,
                    Who = m.CharacterId,
                    Chosen = d.Chosen.Key,
                    Leading = d.Leading?.Key,
                    Urgency = d.Leading?.Urgency ?? 0.0,
                    Margin = d.Margin,
                    Commitment = d.Commitment,
                    Resolution = d.Resolution,
                    Options = string.Join("; ", d.Considered.Take(4).Select(r =>
                        r.Option.Key + " " + r.Score.ToString("+0.000;-0.000", CultureInfo.InvariantCulture)))
                };
                foreach (var x in m.Motives) s.Wants[x.Key] = x.Urgency;
                w.Decisions.Add(s);
            };
            run.Morning.Run(_content.Morning.Minutes);
            w.Actions = run.Result.Actions;
            w.Events = run.Result.Events;
            w.Minds = run.Minds;
            w.Trace = run.Trace;
            w.Fingerprint = string.Join("\n", w.Actions.Select(a =>
                a.ToString() + " | " + a.Resolution + " " + a.Margin.ToString("R", CultureInfo.InvariantCulture)));
            return w;
        }

        /// <summary>
        /// Carries one intention onto one person's pantry-check, the one that
        /// finishes at a given minute, and onto nothing else. The minute
        /// identifies the act exactly: an act makes its event when it finishes,
        /// and the arms run identically up to that point.
        /// </summary>
        static Func<Scenario001Run, Func<string, ActionOption, Decision, string>> OnTheCheckFinishingAt(
            string who, int minute, string intent)
            => run => (actor, action, decision) =>
                actor == who && action.Kind == ActionKind.CheckPantry && run.World.Minute == minute ? intent : null;

        /// <summary>A hook that carries nothing, to show the hook itself changes nothing.</summary>
        static readonly Func<Scenario001Run, Func<string, ActionOption, Decision, string>> CarriesNothing =
            run => (actor, action, decision) => null;

        // ------------------------------------------------------------------ the case

        sealed class Case
        {
            public string Variant;
            public ulong Seed;
            public string Who;
            public int Started;
            public int Finished;
            public string Leading;
            public double Urgency;
            public ActionRecord Record;
            public Watch Baseline;
            public WorldEvent Event;
            public IReadOnlyList<string> Witnesses;
        }

        static Case At(Watch w, string variant, ulong seed, ActionRecord a)
        {
            var finished = a.Minute + a.Action.Duration;
            var e = w.ActEvent(a.CharacterId, "count_supplies", finished);
            if (e == null) return null;
            return new Case
            {
                Variant = variant,
                Seed = seed,
                Who = a.CharacterId,
                Started = a.Minute,
                Finished = finished,
                Leading = a.LeadingMotive,
                Urgency = a.LeadingUrgency,
                Record = a,
                Baseline = w,
                Event = e,
                Witnesses = e.Witnesses.Where(x => x != a.CharacterId).OrderBy(x => x, StringComparer.Ordinal).ToList()
            };
        }

        /// <summary>Every pantry-check in the design conditions that ran its course and became an event.</summary>
        static List<Case> AllChecks()
        {
            var found = new List<Case>();
            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var key = v + "#" + seed;
                if (!_cache.TryGetValue(key, out var w)) _cache[key] = w = Run("baseline", v, seed, null);
                foreach (var a in w.Actions.Where(x => x.Action.Kind == ActionKind.CheckPantry))
                {
                    var c = At(w, v, seed, a);
                    if (c != null) found.Add(c);
                }
            }
            return found;
        }

        /// <summary>
        /// The case the rest of the experiment holds fixed: a real pantry-check,
        /// led by one of the wants the brief names, and seen by somebody, so that
        /// the witness question can be asked of the same act.
        /// </summary>
        static Case Fixed()
        {
            var all = AllChecks();
            foreach (var want in new[] { "find_out", "restore_standing", "get_food", "guard_supplies" })
            {
                var c = all.FirstOrDefault(x => x.Leading == want && x.Witnesses.Count > 0);
                if (c != null) return c;
            }
            foreach (var want in new[] { "find_out", "restore_standing", "get_food", "guard_supplies" })
            {
                var c = all.FirstOrDefault(x => x.Leading == want);
                if (c != null) return c;
            }
            return all.FirstOrDefault();
        }

        // ------------------------------------------------------------------ reading one arm

        static string ReadingOf(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "no event";
            var x = w.Minds[who].Experiences.LastOrDefault(k => k.EventId == e.Id);
            if (x == null) return "nothing kept";
            return x.Meaning + (x.FromOwnIntent ? " (own intention)" : " (" + x.Access.ToString().ToLowerInvariant() + ")");
        }

        static string KeptAs(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var x = w.Minds[who].Experiences.LastOrDefault(k => k.EventId == e.Id);
            return x == null ? "nothing kept" : x.Meaning + ", salience " + F(x.Salience) + ", felt " + Or(x.DominantEmotion);
        }

        static string InterpretationOf(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var r = w.Trace.ForEvent(e.Id).FirstOrDefault(x => x.CharacterId == who && x.Kind == TraceKind.Interpretation);
            if (r == null) return "-";
            var weight = r.Data.TryGetValue("weight", out var wt) ? wt : "1.00";
            var runner = r.Data.TryGetValue("runner_up", out var ru) ? ru : "none";
            return r.Summary + " (weight " + weight + ", runner-up " + runner + ")";
        }

        static string AccessOf(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var r = w.Trace.ForEvent(e.Id).FirstOrDefault(x => x.CharacterId == who && x.Kind == TraceKind.Access);
            return r == null ? "-" : r.Summary;
        }

        static string StirredBy(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var appraisals = w.Trace.ForEvent(e.Id)
                .Where(r => r.CharacterId == who && r.Kind == TraceKind.Appraisal)
                .Select(r => r.Data.TryGetValue("rules", out var rules)
                    ? r.Data["emotion"] + " " + r.Data["intensity"] + " [" + rules.Split(' ')[0] + "]"
                    : r.Summary)
                .ToList();
            return appraisals.Count == 0 ? "nothing" : string.Join("; ", appraisals);
        }

        static string FeelingsAt(Watch w, string who)
            => string.Join(", ", w.Minds[who].Emotions.Live.OrderBy(e => e.Type, StringComparer.Ordinal)
                   .Select(e => e.Type + (e.TargetId == null ? "" : ":" + e.TargetId) + " " + F(e.Intensity)));

        static string BeliefsOf(Watch w, string who)
            => string.Join(", ", w.Minds[who].Beliefs.All.Where(b => b.Confidence > 0.0)
                   .Select(b => b.Key + " " + F(b.Confidence)));

        static string NudgesFrom(Watch w, string who, WorldEvent e)
        {
            if (e == null) return "-";
            var nudges = w.Trace.ForEvent(e.Id)
                .Where(r => r.CharacterId == who && r.Kind == TraceKind.BeliefChange)
                .Select(r => r.Summary).ToList();
            return nudges.Count == 0 ? "none" : string.Join("; ", nudges);
        }

        static string WantsLine(Snap s)
            => s == null ? "-" : string.Join(", ", s.Wants.OrderByDescending(k => k.Value)
                   .ThenBy(k => k.Key, StringComparer.Ordinal).Select(k => k.Key + " " + F(k.Value)));

        /// <summary>The first decision anywhere in the morning that differs from the baseline.</summary>
        static string FirstDivergence(Watch baseline, Watch arm)
        {
            var n = Math.Min(baseline.Decisions.Count, arm.Decisions.Count);
            for (var i = 0; i < n; i++)
            {
                var b = baseline.Decisions[i];
                var a = arm.Decisions[i];
                if (b.Minute == a.Minute && b.Who == a.Who && b.Chosen == a.Chosen && b.Leading == a.Leading) continue;
                return "m" + a.Minute + " " + a.Who + ": " + b.Chosen + " for " + Or(b.Leading)
                     + " -> " + a.Chosen + " for " + Or(a.Leading);
            }
            if (baseline.Decisions.Count != arm.Decisions.Count)
                return "same decisions, different count (" + baseline.Decisions.Count + " -> " + arm.Decisions.Count + ")";
            return "none";
        }

