        [Test]
        public void WhatTheWitnessGets()
        {
            var c = Fixed();
            Assert.IsNotNull(c);

            var sb = new StringBuilder();
            sb.AppendLine("## M4. The witness");
            sb.AppendLine();

            var witness = c.Witnesses.FirstOrDefault();
            if (witness == null)
            {
                sb.AppendLine("Nobody was in the room for the fixed act, so there is no witness to ask.");
                Record("M4", sb.ToString());
                Assert.Ignore("no witness to the fixed act");
                return;
            }

            sb.AppendLine("The actor is " + c.Who + "; the witness is " + witness
                          + ". Neither is told anything by the experiment. The witness responds only to what the existing perception system hands them.");
            sb.AppendLine();
            sb.AppendLine("| Arm | Witness access | Witness interpretation | Kept as | Appraisal | Belief nudges | Their next decision |");
            sb.AppendLine("|---|---|---|---|---|---|---|");

            var rows = new List<Watch> { Run("baseline", c.Variant, c.Seed, null) };
            foreach (var intent in _intentions)
                rows.Add(Run("intent `" + intent + "`", c.Variant, c.Seed,
                    OnTheCheckFinishingAt(c.Who, c.Finished, intent), intent));

            var readings = new List<string>();
            foreach (var w in rows)
            {
                var e = w.ActEvent(c.Who, "count_supplies", c.Finished);
                var next = w.NextAfter(witness, c.Finished);
                var line = AccessOf(w, witness, e) + " | " + InterpretationOf(w, witness, e) + " | " + KeptAs(w, witness, e)
                           + " | " + StirredBy(w, witness, e) + " | " + NudgesFrom(w, witness, e);
                readings.Add(line);
                sb.AppendLine("| " + w.Label + " | " + line + " | " + (next == null ? "none" : next.Line) + " |");
