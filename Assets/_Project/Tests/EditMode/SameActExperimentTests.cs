            sb.AppendLine();
            sb.AppendLine("(The interpretation column means something different in the two tables: for a meaning it is the number of rules that can *produce* it, since no rule is keyed on a meaning to produce another. For an intention it is the number keyed on it, which is what a reader is.)");
            sb.AppendLine();

