        [Test]
        public void FourWantsReachForTheSamePhysicalAct()
        {
            var all = AllChecks();

            var sb = new StringBuilder();
            sb.AppendLine("## M1. Four wants, one physical act");
            sb.AppendLine();
            sb.AppendLine("Every proposal in the shipped file that asks for `check_pantry`, and then the first real act in a live morning led by each of those wants.");
            sb.AppendLine();
            sb.AppendLine("| Proposal | Want | Fit |");
            sb.AppendLine("|---|---|---|");
            foreach (var p in _content.Rules.Proposals.Where(p => p.Action == "check_pantry"))
                sb.AppendLine("| `" + p.Id + "` | `" + p.Motive + "` | " + F(p.Fit) + " |");
            sb.AppendLine();

            sb.AppendLine("| Want | Found | Who | Minute | Urgency | Chosen | Margin | Resolution | Commitment | Target | Destination | What was considered |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|");
            var found = 0;
            foreach (var want in ReachForIt)
            {
                var c = all.FirstOrDefault(x => x.Leading == want);
                if (c == null)
                {
                    sb.AppendLine("| `" + want + "` | **no** | - | - | - | - | - | - | - | - | - | led no pantry-check in "
                                  + (_content.Morning.Variants.Count * Seeds) + " mornings |");
                    continue;
                }
                found++;
                var snap = c.Baseline.Decisions.FirstOrDefault(d => d.Who == c.Who && d.Minute == c.Started);
                sb.AppendLine("| `" + want + "` | yes | " + c.Who + " | m" + c.Started + " | " + F(c.Urgency)
                              + " | " + c.Record.Action.Key + " | " + F(c.Record.Margin) + " | " + c.Record.Resolution
                              + " | " + Or(snap?.Commitment) + " | " + Or(c.Record.Action.TargetId)
                              + " | " + Or(c.Record.Action.DestinationRoomId) + " | " + Or(snap?.Options) + " |");
            }
            sb.AppendLine();

            sb.AppendLine("And the event each act became:");
            sb.AppendLine();
            sb.AppendLine("| Want | Event action | Actor | Target | Topic | Valence | Intent | Witnesses | Summary |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|");
            foreach (var want in ReachForIt)
            {
                var c = all.FirstOrDefault(x => x.Leading == want);
                if (c == null) continue;
                sb.AppendLine("| `" + c.Leading + "` | `" + c.Event.Action + "` | " + c.Event.ActorId + " | "
                              + Or(c.Event.TargetId) + " | " + Or(c.Event.Topic) + " | " + c.Event.Valence + " | **"
                              + Or(c.Event.Intent) + "** | " + (c.Witnesses.Count == 0 ? "nobody" : string.Join(", ", c.Witnesses))
                              + " | " + c.Event.Summary + " |");
            }
            sb.AppendLine();

            var shapes = all.Select(c => c.Event.Action + "|" + Or(c.Event.TargetId) + "|" + Or(c.Event.Topic) + "|" + Or(c.Event.Intent))
                .Distinct().Count();
            sb.AppendLine("**" + all.Count + " real pantry-checks across " + (_content.Morning.Variants.Count * Seeds)
                          + " mornings, led by " + all.Select(c => c.Leading).Distinct().Count()
                          + " different wants. Distinct event shapes, ignoring valence and the sentence: " + shapes + ".**");
            sb.AppendLine();
            sb.AppendLine("Valence is `bad` when the count is low and `neutral` otherwise, so it reports the state of the shelf and not the reason for looking. The sentence is about the shelf for the same reason. Nothing on the event says which want sent him.");
            Record("M1", sb.ToString());

            Assert.GreaterOrEqual(found, 3, "at least three wants must really lead this act for the experiment to mean anything");
            foreach (var c in all)
            {
                Assert.AreEqual("count_supplies", c.Event.Action);
                Assert.IsNull(c.Event.Intent, "no act carries an intent on the baseline");
            }
            Assert.AreEqual(1, shapes, "every pantry-check makes the same shape of event");
        }

