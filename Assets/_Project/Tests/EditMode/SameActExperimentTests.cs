        [Test]
        public void RemovingTheIntentionRestoresTheBaselineExactly()
        {
            var sb = new StringBuilder();
            sb.AppendLine("## M3. Taking the intention away");
            sb.AppendLine();
            sb.AppendLine("The null condition has to reproduce the existing behaviour exactly, or nothing else here means anything. Two ways of having no intention, over every condition and every seed, against the morning with no hook at all.");
            sb.AppendLine();
            sb.AppendLine("| Condition | Seed | Hook set, carries nothing | Hook set, then removed |");
            sb.AppendLine("|---|---|---|---|");

            var same = 0;
            var total = 0;
            foreach (var v in _content.Morning.Variants.Select(x => x.Id))
            for (ulong seed = 1; seed <= (ulong)Seeds; seed++)
            {
                var a = Run("no hook", v, seed, null);
                var b = Run("inert hook", v, seed, CarriesNothing);

                var run = Scenario001.Prepare(_content, v, seed);
                run.Morning.IntentOfAct = (actor, action, decision) => "assert_authority";
                run.Morning.IntentOfAct = null;
                run.Morning.Run(_content.Morning.Minutes);
                var removed = string.Join("\n", run.Result.Actions.Select(x =>
                    x.ToString() + " | " + x.Resolution + " " + x.Margin.ToString("R", CultureInfo.InvariantCulture)));

                var ok1 = a.Fingerprint == b.Fingerprint;
                var ok2 = a.Fingerprint == removed;
                total++;
                if (ok1 && ok2) same++;
                if (!ok1 || !ok2 || seed == 1)
                    sb.AppendLine("| `" + v + "` | " + seed + " | " + (ok1 ? "identical" : "**differs**")
                                  + " | " + (ok2 ? "identical" : "**differs**") + " |");

                Assert.AreEqual(a.Fingerprint, b.Fingerprint, v + " seed " + seed + ": an inert hook must change nothing");
                Assert.AreEqual(a.Fingerprint, removed, v + " seed " + seed + ": removing the hook must restore the baseline");
                Assert.IsTrue(a.Events.All(e => e.Intent == null || e.Minute < 0),
                    v + " seed " + seed + ": no morning event carries an intent on the baseline");
            }
            sb.AppendLine();
            sb.AppendLine("**" + same + " of " + total + " mornings identical on both.** Every act, every margin to full precision, every resolution. Only the first seed of each condition is listed; a difference anywhere would have been listed and would have failed the test.");
            Record("M3", sb.ToString());
        }

