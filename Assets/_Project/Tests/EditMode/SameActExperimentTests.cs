        [Test]
        public void OneActUnderEveryShippedIntention()
        {
            var c = Fixed();
            Assert.IsNotNull(c, "no pantry-check to hold fixed");

            var arms = new List<Watch>
            {
                Run("baseline: no hook", c.Variant, c.Seed, null),
                Run("control: hook set, carries nothing", c.Variant, c.Seed, CarriesNothing)
            };
            foreach (var intent in _intentions)
                arms.Add(Run("intent `" + intent + "`", c.Variant, c.Seed,
                    OnTheCheckFinishingAt(c.Who, c.Finished, intent), intent));

            var sb = new StringBuilder();
            sb.AppendLine("## M2. One act, every intention the vocabulary has");
            sb.AppendLine();
            sb.AppendLine("**The act.** " + c.Who + " checks the pantry, decided at m" + c.Started + " and finishing at m"
                          + c.Finished + ", led by `" + c.Leading + "` at urgency " + F(c.Urgency)
                          + ". Condition `" + c.Variant + "`, seed " + c.Seed + ". Witnessed by "
                          + (c.Witnesses.Count == 0 ? "nobody" : string.Join(", ", c.Witnesses)) + ".");
            sb.AppendLine();
            sb.AppendLine("Every arm is the same morning with the same seed, and the arms are identical up to m" + c.Finished
                          + " by construction: the intention is attached at the moment the act becomes an event, and nothing before that can see it.");
            sb.AppendLine();

            sb.AppendLine("### The event");
            sb.AppendLine();
            sb.AppendLine("| Arm | Event | Action | Target | Topic | Valence | **Intent on the event** | Same sentence |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (var w in arms)
            {
                var e = w.ActEvent(c.Who, "count_supplies", c.Finished);
                sb.AppendLine("| " + w.Label + " | " + (e == null ? "**missing**" : "yes") + " | " + (e == null ? "-" : e.Action)
                              + " | " + (e == null ? "-" : Or(e.TargetId)) + " | " + (e == null ? "-" : Or(e.Topic))
                              + " | " + (e == null ? "-" : e.Valence) + " | " + (e == null ? "-" : "`" + Or(e.Intent) + "`")
                              + " | " + (e == null ? "-" : (e.Summary == c.Event.Summary ? "yes" : "**no**")) + " |");
            }
            sb.AppendLine();

            sb.AppendLine("### What the actor made of his own act");
            sb.AppendLine();
            sb.AppendLine("| Arm | Access | Interpretation | Kept as | Appraisal rules that fired | Belief nudges |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var w in arms)
            {
                var e = w.ActEvent(c.Who, "count_supplies", c.Finished);
                sb.AppendLine("| " + w.Label + " | " + AccessOf(w, c.Who, e) + " | " + InterpretationOf(w, c.Who, e)
                              + " | " + KeptAs(w, c.Who, e) + " | " + StirredBy(w, c.Who, e) + " | " + NudgesFrom(w, c.Who, e) + " |");
            }
            sb.AppendLine();

            sb.AppendLine("### And what came of it");
            sb.AppendLine();
            sb.AppendLine("| Arm | Feelings at the end of the morning | Next decision after the act | Wants at that decision |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var w in arms)
            {
                var next = w.NextAfter(c.Who, c.Finished);
                sb.AppendLine("| " + w.Label + " | " + Or(FeelingsAt(w, c.Who)) + " | " + (next == null ? "none" : next.Line)
                              + " | " + WantsLine(next) + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Beliefs at the end of the morning, for the same person:");
            sb.AppendLine();
            sb.AppendLine("| Arm | Beliefs |");
            sb.AppendLine("|---|---|");
            foreach (var w in arms)
                sb.AppendLine("| " + w.Label + " | " + Or(BeliefsOf(w, c.Who)) + " |");
            sb.AppendLine();

            var carried = _intentions.Count(i => arms.First(x => x.Intent == i)
                .ActEvent(c.Who, "count_supplies", c.Finished)?.Intent == i);
            sb.AppendLine("**The intention survived execution onto the event in " + carried + " of " + _intentions.Count
                          + " arms.** The two control arms carry none, as they should.");
            Record("M2", sb.ToString());

            foreach (var intent in _intentions)
            {
                var w = arms.First(x => x.Intent == intent);
                var e = w.ActEvent(c.Who, "count_supplies", c.Finished);
                Assert.IsNotNull(e, intent + ": the act must still become an event");
                Assert.AreEqual(intent, e.Intent, intent + ": the intention must reach the event");
                Assert.AreEqual(c.Event.Summary, e.Summary, intent + ": the physical act must be unchanged");
                Assert.AreEqual(c.Event.Action, e.Action);
                Assert.AreEqual(c.Event.Valence, e.Valence);
                Assert.AreEqual(c.Event.TargetId, e.TargetId);
            }
        }

