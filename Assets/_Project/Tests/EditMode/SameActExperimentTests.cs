            sb.AppendLine();
            sb.AppendLine("The witness sees the act. What the actor took himself to be doing is carried on the event, and the interpreter hands somebody their own intention only when the event's actor is the perceiver themselves. So the witness reads the act by rule, as they would anybody else's. That is knowledge locality working, not a defect. Whether they are given any evidence from which to infer more is a separate question, taken up in the report.");
            Record("M4", sb.ToString());

            Assert.AreEqual(1, distinct, "the witness must get the same thing in every arm: the intention is private");
        }

