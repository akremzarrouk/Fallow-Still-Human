        /// <summary>
        /// One case, every intention, against what the person would have made of
        /// the act with no intention at all. Returns how many arms left him with
        /// less than the baseline and how many gave him something it did not.
        /// </summary>
        static void Displacement(Case c, StringBuilder sb, out int lost, out int gained)
        {
            var baseline = Run("baseline", c.Variant, c.Seed, null);
            var e0 = baseline.ActEvent(c.Who, "count_supplies", c.Finished);
            var x0 = baseline.Minds[c.Who].Experiences.LastOrDefault(k => k.EventId == e0.Id);
            var baseStirred = StirredBy(baseline, c.Who, e0);

            sb.AppendLine("| Arm | Actor's reading | Rules consulted | Feelings from this act | Meaning kept in memory | Against baseline |");
            sb.AppendLine("|---|---|---|---|---|---|");
            sb.AppendLine("| baseline, no intention | " + ReadingOf(baseline, c.Who, e0) + " | yes | " + baseStirred
                          + " | `" + (x0 == null ? "-" : x0.Meaning) + "` | - |");

            lost = 0;
            gained = 0;
            foreach (var intent in _intentions)
            {
                var w = Run(intent, c.Variant, c.Seed, OnTheCheckFinishingAt(c.Who, c.Finished, intent), intent);
                var e = w.ActEvent(c.Who, "count_supplies", c.Finished);
                var x = w.Minds[c.Who].Experiences.LastOrDefault(k => k.EventId == e.Id);
                var stirred = StirredBy(w, c.Who, e);
                string verdict;
                if (stirred == baseStirred) verdict = "same";
                else if (stirred == "nothing") { verdict = "**less**: the reading the rules gave, and what it stirred, are gone"; lost++; }
                else if (baseStirred == "nothing") { verdict = "**more**"; gained++; }
                else { verdict = "**different**"; gained++; }
                sb.AppendLine("| `" + intent + "` | " + ReadingOf(w, c.Who, e) + " | no | " + stirred
                              + " | `" + (x == null ? "-" : x.Meaning) + "` | " + verdict + " |");
            }
        }

        [Test]
        public void AnIntentionReplacesTheReadingTheRulesWouldHaveGiven()
        {
            var all = AllChecks();
            var c = Fixed();
            Assert.IsNotNull(c);

            var sb = new StringBuilder();
            sb.AppendLine("## M6. An intention does not only add");
            sb.AppendLine();
            sb.AppendLine("The interpreter hands an actor their own intention *instead of* running the rules, not as well as. So carrying an intention can leave a person with **less** than carrying none: whatever reading the rules would have given is gone, and so is the memory of it. Whether that costs anything depends on whether the rules had anything to say about the act, which for a pantry-check depends on how much food is left.");
            sb.AppendLine();
            sb.AppendLine("### A count that found enough");
            sb.AppendLine();
            sb.AppendLine("The fixed act: " + c.Who + " at m" + c.Finished + " in `" + c.Variant + "` seed " + c.Seed
                          + ", event valence `" + c.Event.Valence + "`.");
            sb.AppendLine();
            int lostA, gainedA;
            Displacement(c, sb, out lostA, out gainedA);
            sb.AppendLine();
            sb.AppendLine("**Arms that left him with less than no intention at all: " + lostA + " of " + _intentions.Count
                          + ". Arms that gave him something the baseline did not: " + gainedA + ".**");
            sb.AppendLine();

            var bad = all.FirstOrDefault(x => x.Event.Valence == "bad");
            sb.AppendLine("### A count that found the shelf nearly empty");
            sb.AppendLine();
            if (bad == null)
            {
                var ate = _cache.Values.Sum(w => w.Events.Count(e => e.Action == "eat_portion" && e.Minute >= 0));
                var mornings = _cache.Values.Count(w => w.Events.Any(e => e.Action == "eat_portion" && e.Minute >= 0));
                sb.AppendLine("No pantry-check in " + (_content.Morning.Variants.Count * Seeds)
                              + " mornings found the shelf low enough for the event to carry a bad valence, so the displacing case does not arise here. The morning starts with "
                              + _content.Morning.Portions + " portions and the rule that would have been displaced (`bad_news_reads_as_a_problem`) needs the count to fall to "
                              + _content.Rules.Deciding.LowPortions + " or below, which takes somebody eating: " + ate
                              + " portions were eaten in the whole set, across " + mornings + " of "
                              + (_content.Morning.Variants.Count * Seeds) + " mornings, and no check followed one.");
                sb.AppendLine();
                sb.AppendLine("So the displacement is real in the code and costs nothing here, because for this act the rules had nothing to say in the first place. **On the baseline a man counting the family's food reads it as `neutral` at weight 0.00: no interpretation rule matches `count_supplies` at all unless the shelf is nearly bare.** Carrying an intention is the only way this act means anything to anybody.");
            }
            else
            {
                sb.AppendLine("Here the event carries valence `bad`, so `bad_news_reads_as_a_problem` matches and the baseline reading is not empty. The act: " + bad.Who
                              + " at m" + bad.Finished + " in `" + bad.Variant + "` seed " + bad.Seed + ", led by `" + bad.Leading + "`.");
                sb.AppendLine();
                int lostB, gainedB;
                Displacement(bad, sb, out lostB, out gainedB);
                sb.AppendLine();
                sb.AppendLine("**Arms that left him with less than no intention at all: " + lostB + " of " + _intentions.Count
                              + ". Arms that gave him something the baseline did not: " + gainedB + ".**");
            }
            sb.AppendLine();
            sb.AppendLine("The meaning kept in memory is the intention in every intention arm, which is the representation working. Whether that memory is ever read again is M5's question, and the answer there is no.");
            Record("M6", sb.ToString());
        }

