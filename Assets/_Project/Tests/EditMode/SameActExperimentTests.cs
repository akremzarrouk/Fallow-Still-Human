        [Test]
        [Timeout(900000)]
        public void DoesAnythingLaterMove()
        {
            var cases = AllChecks();

            var sb = new StringBuilder();
            sb.AppendLine("## M7. Whether it ever reaches behaviour");
            sb.AppendLine();
            sb.AppendLine("Every real pantry-check in the design conditions, under every intention, against its own baseline. A divergence is the first decision anywhere in the house that differs.");
            sb.AppendLine();
            sb.AppendLine("| Condition | Seed | Who | m | Led by | Intention | Feelings differ at the end | A decision differs | First divergence |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|");

            var arms = 0;
            var feelingsMoved = 0;
            var decisionsMoved = 0;
            var byIntent = _intentions.ToDictionary(i => i, i => 0, StringComparer.Ordinal);
            var feelingsByIntent = _intentions.ToDictionary(i => i, i => 0, StringComparer.Ordinal);

            foreach (var c in cases)
            foreach (var intent in _intentions)
            {
                var w = Run(intent, c.Variant, c.Seed, OnTheCheckFinishingAt(c.Who, c.Finished, intent), intent);
                var baseFeel = FeelingsAt(c.Baseline, c.Who);
                var armFeel = FeelingsAt(w, c.Who);
                var diverged = FirstDivergence(c.Baseline, w);
                arms++;
                if (baseFeel != armFeel) { feelingsMoved++; feelingsByIntent[intent]++; }
                if (diverged != "none") { decisionsMoved++; byIntent[intent]++; }

                if (diverged != "none" || baseFeel != armFeel)
                    sb.AppendLine("| `" + c.Variant + "` | " + c.Seed + " | " + c.Who + " | " + c.Finished + " | `" + c.Leading
                                  + "` | `" + intent + "` | " + (baseFeel != armFeel ? "**yes**" : "no")
                                  + " | " + (diverged != "none" ? "**yes**" : "no") + " | " + diverged + " |");
            }
            sb.AppendLine();
            sb.AppendLine("Rows where nothing moved at all are left out. **" + cases.Count + " real pantry-checks x "
                          + _intentions.Count + " intentions = " + arms + " arms.**");
            sb.AppendLine();
            sb.AppendLine("| | Count | Share |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Arms where the actor's feelings still differed at the end of the morning | " + feelingsMoved + " | " + Pc(feelingsMoved, arms) + " |");
