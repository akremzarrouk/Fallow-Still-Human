            sb.AppendLine();
            sb.AppendLine("Feelings are read at the end of the morning, so a `no` there does not mean nothing was ever felt: a feeling can move a decision and then fade before the morning ends, which is why the second column is larger than the first for every intention that has a reader.");
            sb.AppendLine();
            sb.AppendLine("| Intention | Appraisal readers | Arms where feelings still differed at the end | Arms where a decision moved |");
