                                                                    && r.When.Meanings.Contains(i, StringComparer.Ordinal))
                              + " | " + feelingsByIntent[i] + " of " + cases.Count
                              + " | " + byIntent[i] + " of " + cases.Count + " |");
            Record("M7", sb.ToString());

            Assert.Greater(cases.Count, 0, "there must be real pantry-checks to test");
        }
