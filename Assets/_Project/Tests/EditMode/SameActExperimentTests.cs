            var rules = _content.Rules;
            var sb = new StringBuilder();
            sb.AppendLine("## M5. Who reads an intention");
            sb.AppendLine();
            sb.AppendLine("Counted from the loaded rules, not from memory. A rule *reads* a label if it is keyed on it (`when.meanings`) or scales on a memory of it (`kind: memory`, `name: <label>`).");
            sb.AppendLine();
            sb.AppendLine("| Intention | Interpretation rules | Belief nudges | Appraisal rules | Memory scalers anywhere | Total readers |");
