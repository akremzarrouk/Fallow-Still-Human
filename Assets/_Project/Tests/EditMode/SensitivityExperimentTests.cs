        /// <summary>The share of random streams that choose a given act at one urgency.</summary>
        static double Share(Scenario001Content c, Moment m, WantSweep w, double u, string act, int streams)
        {
            var motives = Sensitivity.With(m.Motives, w.Name, w.Target, u);
            var hits = 0;
            var d = new Deliberator(c.Rules);
            for (var k = 0; k < streams; k++)
            {
                var rng = new Rng(m.Seed).Fork(m.Who + "@" + m.Minute + "#" + k);
                var decision = d.Decide(m.Mind, m.Percept, motives, m.Day, rng, new TraceLog(), 0, m.Holding);
                if (decision.Chosen.Key == act) hits++;
            }
            return hits / (double)streams;
        }

