        /// <summary>
        /// The first decision each person takes in a morning. Before anybody has
        /// decided anything, every architecture has produced the same mind in the
        /// same room: the backstory, the night and the opening are the same, and
        /// at minute 0 a memory stamped minute 0 is exactly as fresh as one with
        /// no minute. Only the wants the architecture raises from that mind, and
        /// how it credits a walk, differ. That makes it the one moment at which
        /// the architectures can be compared under identical circumstances.
        /// </summary>
        static List<T> FirstDecisions<T>(Scenario001Content c, string label, string variant, ulong seed, Func<Moment, Scenario001Run, T> look)
        {
            // Everything is done inside the callback, while the mind is in the
            // state it decided in: later in the same minute somebody else's act
            // can reach it.
            var list = new List<T>();
            var run = Scenario001.Prepare(c, variant, seed);
            var taken = new HashSet<string>(StringComparer.Ordinal);
            run.Morning.Decided = m =>
            {
                if (!taken.Add(m.CharacterId)) return;
                list.Add(look(Moment.Of(m, label, variant, seed, c.Morning.Day), run));
            };
            run.Morning.Step();
            return list;
        }

