        [Test]
        public void X7_WhatEachWantCanAskFor()
        {
            // Read straight from the proposals: for each want, the fit with which
            // it credits each kind of act. Two wants with the same row can differ
            // in the mind and never in what is done.
            var rules = _primary.Rules;
            var wants = rules.Motivation.Select(r => r.Motive).Distinct().OrderBy(x => x, StringComparer.Ordinal).ToList();
            var kinds = ActionOption.AllNames.ToList();
            double Fit(string want, string kind)
                => rules.Proposals.Where(p => p.Motive == want && p.Action == kind).Select(p => p.Fit).DefaultIfEmpty(0.0).Max();

            var sb = new StringBuilder();
            sb.AppendLine("## 7. What each want can ask for");
            sb.AppendLine();
            sb.AppendLine("From the proposals in `decisions.json`, unchanged: the fit with which each want credits each kind of act (the largest, where a want has several proposals for one kind, with different targets or conditions). A want's change of urgency reaches an act only through these numbers, and reaches the choice between two acts only through their difference.");
            sb.AppendLine();
            sb.AppendLine("| Want | " + string.Join(" | ", kinds) + " |");
            sb.AppendLine("|---|" + string.Concat(kinds.Select(_ => "---|")));
            foreach (var w in wants)
                sb.AppendLine("| " + w + " | " + string.Join(" | ", kinds.Select(k => { var f = Fit(w, k); return f == 0.0 ? "" : f.ToString("0.00", CultureInfo.InvariantCulture); })) + " |");
            sb.AppendLine("| **wants that credit it** | " + string.Join(" | ", kinds.Select(k => "**" + wants.Count(w => Fit(w, k) > 0.0) + "**")) + " |");
            sb.AppendLine("| **what it costs** (cost rules) | " + string.Join(" | ", kinds.Select(k => { var n = rules.Costs.Count(c => c.Action == k); return n == 0 ? "nothing" : n + " rule" + (n == 1 ? "" : "s"); })) + " |");
            sb.AppendLine();

            // How alike two wants are in what they ask for: the cosine of their rows.
            sb.AppendLine("How alike two wants are in what they ask for (the cosine of their rows; 1.00 is the same acts in the same proportions):");
            sb.AppendLine();
            sb.AppendLine("| | " + string.Join(" | ", wants) + " |");
            sb.AppendLine("|---|" + string.Concat(wants.Select(_ => "---|")));
            var pairs = new List<(string A, string B, double Cos)>();
            foreach (var a in wants)
            {
                var cells = new List<string>();
                foreach (var b in wants)
                {
                    var dot = kinds.Sum(k => Fit(a, k) * Fit(b, k));
                    var na = Math.Sqrt(kinds.Sum(k => Fit(a, k) * Fit(a, k)));
                    var nb = Math.Sqrt(kinds.Sum(k => Fit(b, k) * Fit(b, k)));
                    var cos = na == 0 || nb == 0 ? 0.0 : dot / (na * nb);
                    cells.Add(a == b ? "" : cos.ToString("0.00", CultureInfo.InvariantCulture));
                    if (string.CompareOrdinal(a, b) < 0) pairs.Add((a, b, cos));
                }
                sb.AppendLine("| " + a + " | " + string.Join(" | ", cells) + " |");
            }
            sb.AppendLine();
            var closest = pairs.OrderByDescending(x => x.Cos).First();
            sb.AppendLine("The two most alike are **" + closest.A + "** and **" + closest.B + "** (" + closest.Cos.ToString("0.00", CultureInfo.InvariantCulture) + "). Moving urgency from one to the other, which is what S1.7's history did, changes what is wanted and barely changes what any act is worth.");
            Record("7", sb.ToString());

            Assert.AreEqual(7, kinds.Count);
        }

