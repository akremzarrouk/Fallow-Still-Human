        sealed class Census
        {
            public string Label;
            public readonly List<MomentSweep> Moments = new List<MomentSweep>();
            public double Seconds;
            public int Decides;
            public IEnumerable<WantSweep> Pairs => Moments.Where(m => m.Faithful).SelectMany(m => m.Wants);
        }

        static Census RunCensus(string label, Scenario001Content c, IEnumerable<string> variants, IEnumerable<ulong> seeds)
        {
            var sweeper = new Sweeper(c, CensusStep) { LocateChosen = false };
            var census = new Census { Label = label };
            var clock = Stopwatch.StartNew();
            foreach (var v in variants)
            foreach (var seed in seeds)
            {
                var run = Scenario001.Prepare(c, v, seed);
                run.Morning.Decided = m =>
                {
                    var swept = sweeper.Sweep(Moment.Of(m, label, v, seed, c.Morning.Day));
                    // Only the numbers are kept: a whole decision per point would not fit.
                    foreach (var w in swept.Wants)
                    foreach (var p in w.Points) p.Decision = null;
                    swept.Moment.Mind = null;
                    census.Moments.Add(swept);
                };
                run.Morning.Run(c.Morning.Minutes);
            }
            census.Seconds = clock.Elapsed.TotalSeconds;
            census.Decides = sweeper.Decides;
            return census;
        }

        static readonly Dictionary<string, Census> _censuses = new Dictionary<string, Census>(StringComparer.Ordinal);

        static Census CensusOf(string label)
        {
            if (_censuses.TryGetValue(label, out var c)) return c;
            var content = Conditions().Single(x => x.Label == label).Content;
            c = RunCensus(label, content, Design, new[] { CensusSeed });
            _censuses[label] = c;
            return c;
        }

        static readonly string[] ClassOrder =
        {
            Sweeper.Classes.Moves, Sweeper.Classes.AlreadyItsAct, Sweeper.Classes.OutweighedWithinScale,
            Sweeper.Classes.OutweighedAlways, Sweeper.Classes.Committed, Sweeper.Classes.NoCandidate, Sweeper.Classes.CandidateOnlyPastReach
        };

        static readonly (string Label, double Max)[] DeltaBins =
        {
            ("at most 0.05", 0.05), ("0.05 to 0.10", 0.10), ("0.10 to 0.25", 0.25), ("0.25 to 0.50", 0.50), ("more than 0.50", 10.0)
        };

        static string Quantiles(IReadOnlyList<double> xs)
        {
            if (xs.Count == 0) return "none";
            var s = xs.OrderBy(x => x).ToList();
            double Q(double q) => s[(int)Math.Min(s.Count - 1, Math.Floor(q * (s.Count - 1) + 0.5))];
            return "median " + F(Q(0.5)) + " (quartiles " + F(Q(0.25)) + " to " + F(Q(0.75)) + ")";
        }

